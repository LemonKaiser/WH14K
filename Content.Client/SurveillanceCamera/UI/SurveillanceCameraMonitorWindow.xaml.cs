    public void SetEntity(EntityUid uid)
    {
        var metaData = _entityManager.GetComponent<MetaDataComponent>(uid);
        _titleText = metaData.EntityName;
        _subtitleText = string.IsNullOrWhiteSpace(metaData.EntityDescription)
            ? Loc.GetString("surveillance-camera-monitor-ui-header-subtitle-fallback")
            : metaData.EntityDescription;
        _theme = SurveillanceCameraMonitorStyles.ResolveTheme(metaData.EntityPrototype?.ID);

        ApplyTheme();
        RefreshAllReadouts();
    }

    public void UpdateState(IEye? eye, HashSet<string> subnets, string activeAddress, string activeSubnet, Dictionary<string, string> cameras)
    {
        _currentAddress = activeAddress;
        _currentSubnet = activeSubnet;

        CameraMap.SetActiveCameraAddress(activeAddress);
        CameraMap.SetAvailableSubnets(subnets);

        RebuildSubnetSelector(subnets, activeSubnet);

        if (subnets.Count > 0 && string.IsNullOrEmpty(activeSubnet))
        {
            PopulateCameraEntries(Array.Empty<KeyValuePair<string, string>>());
            SetCameraView(eye);
            RefreshAllReadouts();
            SubnetOpened?.Invoke(subnets.OrderBy(ResolveSubnetDisplayName).First());
            return;
        }

        PopulateCameraEntries(cameras);
        SetCameraView(eye);
        RefreshAllReadouts();
    }

    public void OnSwitchTimerComplete()
    {
        _isSwitching = false;
        CameraView.Visible = CameraView.Eye != _defaultEye;
        CameraViewBackground.Visible = CameraView.Eye == _defaultEye;
        RefreshAllReadouts();
    }

