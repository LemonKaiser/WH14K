    private void RefreshAllReadouts()
    {
        RefreshStatusPanel();
        RefreshSummaryCards();
        RefreshFeedPane();
        RefreshFooter();
    }

    private void RefreshStatusPanel()
    {
        var state = GetFeedState();
        var color = GetFeedStateColor(state);
        var changed = _lastStatusFlashState != state;
        _lastStatusFlashState = state;

        StatusPanel.PanelOverride = SurveillanceCameraMonitorStyles.CreatePanelStyle(_theme.PanelAltBackground, color.WithAlpha(0.82f), 0);
        StatusValueLabel.Text = Loc.GetString(GetFeedStateLocKey(state));
        StatusValueLabel.FontColorOverride = color;
        SetWrappedText(StatusHintLabel, Loc.GetString(GetFeedStateHintLocKey(state)), _theme.SecondaryText);
        if (changed)
            WH40KUiChrome.PlayHoverFlash(StatusPanel, "status-flash", new Color(0.86f, 0.86f, 0.9f, 1f), 0.18f);
    }

    private void RefreshSummaryCards()
    {
        SubnetValueLabel.Text = _subnetMap.Count.ToString();
        CameraValueLabel.Text = _allCameraEntries.Count.ToString();
        ActiveSubnetValueLabel.Text = string.IsNullOrWhiteSpace(_currentSubnet)
            ? Loc.GetString("surveillance-camera-monitor-ui-active-subnet-none")
            : ResolveSubnetDisplayName(_currentSubnet);

        var stateLoc = Loc.GetString(GetFeedStateLocKey(GetFeedState()));
        FeedValueLabel.Text = stateLoc;
        FeedValueLabel.FontColorOverride = GetFeedStateColor(GetFeedState());

        RoutingValueLabel.Text = string.IsNullOrWhiteSpace(_currentSubnet)
            ? Loc.GetString("surveillance-camera-monitor-ui-active-subnet-none")
            : ResolveSubnetDisplayName(_currentSubnet);
    }

    private void RefreshFeedPane()
    {
        var state = GetFeedState();
        var stateColor = GetFeedStateColor(state);
        var hasCamera = !string.IsNullOrWhiteSpace(_currentAddress);
        var cameraName = ResolveActiveCameraName();
        var changed = _lastFeedFlashState != state ||
                      !string.Equals(_lastFeedFlashAddress, _currentAddress, StringComparison.Ordinal) ||
                      !string.Equals(_lastFeedFlashSubnet, _currentSubnet, StringComparison.Ordinal);

        _lastFeedFlashState = state;
        _lastFeedFlashAddress = _currentAddress;
        _lastFeedFlashSubnet = _currentSubnet;

        FeedTitleLabel.Text = hasCamera
            ? WH40KUiChrome.DecorateIfMissing(Loc.GetString("surveillance-camera-monitor-ui-feed-title"), WH40KUiChrome.Blade)
            : WH40KUiChrome.DecorateIfMissing(Loc.GetString("surveillance-camera-monitor-ui-feed-title-offline"), WH40KUiChrome.Blade);
        FeedTitleLabel.FontColorOverride = _theme.Accent;

        SetWrappedText(
            FeedSubtitleLabel,
            hasCamera
                ? Loc.GetString("surveillance-camera-monitor-ui-feed-subtitle", ("camera", cameraName))
                : Loc.GetString("surveillance-camera-monitor-ui-feed-subtitle-offline"),
            hasCamera ? _theme.PrimaryText : _theme.SecondaryText);

        LinkValueLabel.Text = Loc.GetString(GetFeedStateLocKey(state));
        LinkValueLabel.FontColorOverride = stateColor;
        AddressValueLabel.Text = hasCamera
            ? _currentAddress
            : Loc.GetString("surveillance-camera-monitor-ui-feed-address-none");
        FeedSubnetValueLabel.Text = string.IsNullOrWhiteSpace(_currentSubnet)
            ? Loc.GetString("surveillance-camera-monitor-ui-active-subnet-none")
            : ResolveSubnetDisplayName(_currentSubnet);
        if (changed)
            WH40KUiChrome.PlayHoverFlash(FeedHeaderPanel, "feed-flash", new Color(0.86f, 0.86f, 0.9f, 1f), 0.18f);
    }

    private void RefreshFooter()
    {
        var footerKey = GetFeedState() == CameraFeedState.Disconnected
            ? "surveillance-camera-monitor-ui-footer-offline"
            : _viewMode == MonitorViewMode.Map
                ? "surveillance-camera-monitor-ui-footer-map"
                : "surveillance-camera-monitor-ui-footer-roster";

        SetWrappedText(FooterLabel, Loc.GetString(footerKey), _theme.SecondaryText);
    }

    private CameraFeedState GetFeedState()
    {
        if (CameraView.Eye == _defaultEye)
            return CameraFeedState.Disconnected;

        return _isSwitching
            ? CameraFeedState.Connecting
            : CameraFeedState.Live;
    }

    private Color GetFeedStateColor(CameraFeedState state)
    {
        return state switch
        {
            CameraFeedState.Live => _theme.SuccessAccent,
            CameraFeedState.Connecting => _theme.WarningAccent,
            _ => _theme.DangerAccent,
        };
    }

    private string ResolveActiveCameraName()
    {
        if (string.IsNullOrWhiteSpace(_currentAddress))
            return Loc.GetString("surveillance-camera-monitor-ui-feed-subtitle-offline");

        return _cameraNames.TryGetValue(_currentAddress, out var cameraName)
            ? cameraName
            : _currentAddress;
    }

    private string ResolveSubnetDisplayName(string subnet)
    {
        if (_prototypeManager.TryIndex<DeviceFrequencyPrototype>(subnet, out var frequency) &&
            frequency.Name != null)
        {
            return Loc.GetString(frequency.Name);
        }

        return subnet;
    }

    private static string GetFeedStateLocKey(CameraFeedState state)
    {
        return state switch
        {
            CameraFeedState.Live => "surveillance-camera-monitor-ui-status-ready-card",
            CameraFeedState.Connecting => "surveillance-camera-monitor-ui-status-connecting-card",
            _ => "surveillance-camera-monitor-ui-status-offline-card",
        };
    }

    private static string GetFeedStateHintLocKey(CameraFeedState state)
    {
        return state switch
        {
            CameraFeedState.Live => "surveillance-camera-monitor-ui-status-hint-ready",
            CameraFeedState.Connecting => "surveillance-camera-monitor-ui-status-hint-connecting",
            _ => "surveillance-camera-monitor-ui-status-hint-offline",
        };
    }

    private void OnCameraMapSelected(NetEntity netEntity)
    {
        if (_mapUid is null || !_entityManager.TryGetComponent<SurveillanceCameraMapComponent>(_mapUid.Value, out var mapComp))
            return;

        if (!mapComp.Cameras.TryGetValue(netEntity, out var marker) || !marker.Active)
            return;

        if (!string.IsNullOrEmpty(marker.Address))
            CameraSelected?.Invoke(marker.Address, marker.Subnet);
        else
            _entityManager.RaisePredictiveEvent(new RequestCameraMarkerUpdateMessage(netEntity));
    }

    private static void SetWrappedText(RichTextLabel label, string text, Color color)
