    private void GenerateCameraButton(ListData data, ListContainerButton button)
    {
        if (data is not CameraRosterListData entry)
            return;

        var control = new SurveillanceCameraMonitorEntry();
        control.ApplyState(entry.CameraName, entry.Address, entry.IsCurrent, _theme);

        button.AddChild(control);
        button.MinSize = new Vector2(0f, 68f);
        var normalStyle = SurveillanceCameraMonitorStyles.CreatePanelStyle(
            entry.IsCurrent ? _theme.SurfaceBackground : _theme.PanelAltBackground,
            entry.IsCurrent ? _theme.Accent.WithAlpha(0.82f) : _theme.BorderColor,
            0);
        var hoverStyle = SurveillanceCameraMonitorStyles.CreatePanelStyle(
            _theme.SurfaceBackground,
            _theme.Accent.WithAlpha(0.88f),
            0);
        button.StyleBoxOverride = normalStyle;
        button.ToolTip = $"{entry.CameraName}\n{entry.Address}";
        button.OnMouseEntered += _ =>
        {
            button.StyleBoxOverride = hoverStyle;
            WH40KUiChrome.PlayHoverFlash(control, "hover-flash");
        };
        button.OnMouseExited += _ => button.StyleBoxOverride = normalStyle;
    }

    private void RebuildSubnetSelector(HashSet<string> subnets, string activeSubnet)
    {
        if (subnets.Count == 0)
        {
            if (!SubnetSelector.Disabled || SubnetSelector.ItemCount != 1)
            {
                SubnetSelector.Clear();
                SubnetSelector.AddItem(Loc.GetString("surveillance-camera-monitor-ui-no-subnets"), 0);
                SubnetSelector.Disabled = true;
            }

            _subnetMap.Clear();
            return;
        }

        var orderedSubnets = subnets.OrderBy(ResolveSubnetDisplayName).ToList();
        var knownSubnetsMatch = _subnetMap.Count == orderedSubnets.Count &&
                                new HashSet<string>(_subnetMap.Keys).SetEquals(orderedSubnets);

        if (SubnetSelector.Disabled || !knownSubnetsMatch)
        {
            SubnetSelector.Clear();
            SubnetSelector.Disabled = false;
            _subnetMap.Clear();

            foreach (var subnet in orderedSubnets)
            {
                var id = AddSubnet(subnet);
                _subnetMap[subnet] = id;
            }
        }

        if (!string.IsNullOrEmpty(activeSubnet) && _subnetMap.TryGetValue(activeSubnet, out var subnetId))
            SubnetSelector.SelectId(subnetId);
    }

    private int AddSubnet(string subnet)
    {
        var id = _subnetMap.Count;
        SubnetSelector.AddItem(ResolveSubnetDisplayName(subnet), id);
        SubnetSelector.SetItemMetadata(id, subnet);
        return id;
    }

    private void PopulateCameraEntries(IEnumerable<KeyValuePair<string, string>> cameras)
    {
        _allCameraEntries.Clear();
        _cameraNames.Clear();

        foreach (var (address, name) in cameras
                     .OrderBy(pair => pair.Value, StringComparer.CurrentCultureIgnoreCase)
                     .ThenBy(pair => pair.Key, StringComparer.CurrentCultureIgnoreCase))
        {
            var displayName = string.IsNullOrWhiteSpace(name)
                ? address
                : name;

            _cameraNames[address] = displayName;
            _allCameraEntries.Add(new CameraRosterListData(address)
            {
                CameraName = displayName,
                SearchText = $"{displayName} {address}",
                IsCurrent = address == _currentAddress,
                SortIndex = _allCameraEntries.Count,
            });
        }

        ApplyCameraFilter();
    }

    private void ApplyCameraFilter()
    {
        var search = CameraSearchBar.Text.Trim();
        var filtered = string.IsNullOrWhiteSpace(search)
            ? _allCameraEntries
            : _allCameraEntries
                .Where(entry => entry.SearchText.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                .ToList();

        _visibleCameraCount = filtered.Count;
        CameraList.PopulateList(filtered.Cast<ListData>().ToList());

        CameraListEmptyLabel.Visible = filtered.Count == 0;
        CameraList.Visible = filtered.Count > 0;
        CameraListEmptyLabel.Text = Loc.GetString(string.IsNullOrWhiteSpace(search)
            ? "surveillance-camera-monitor-ui-roster-empty"
            : "surveillance-camera-monitor-ui-roster-empty-search");

        CameraListSubtitleLabel.SetMessage(
            Loc.GetString(
                "surveillance-camera-monitor-ui-roster-subtitle",
                ("visible", _visibleCameraCount),
                ("total", _allCameraEntries.Count)),
            defaultColor: _theme.SecondaryText);

        VisibleValueLabel.Text = Loc.GetString(
            "surveillance-camera-monitor-ui-feed-visible-value",
            ("visible", _visibleCameraCount),
            ("total", _allCameraEntries.Count));

        RefreshAllReadouts();
    }

    private void SetCameraView(IEye? eye)
    {
        var eyeChanged = eye != CameraView.Eye || CameraView.Eye == null;
        CameraView.Eye = eye ?? _defaultEye;
        CameraDisconnectButton.Disabled = eye == null;

        if (eye == null)
        {
            _isSwitching = false;
            CameraView.Visible = false;
            CameraViewBackground.Visible = true;
            return;
        }

        if (eyeChanged)
        {
            _isSwitching = true;
            CameraView.Visible = false;
            CameraViewBackground.Visible = true;
            CameraSwitchTimer?.Invoke();
            return;
        }

        CameraView.Visible = !_isSwitching;
        CameraViewBackground.Visible = _isSwitching;
    }

