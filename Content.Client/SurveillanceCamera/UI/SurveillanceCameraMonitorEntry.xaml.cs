using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client._WH40K.Interface;

namespace Content.Client.SurveillanceCamera.UI;

[GenerateTypedNameReferences]
public sealed partial class SurveillanceCameraMonitorEntry : BoxContainer
{
    public SurveillanceCameraMonitorEntry()
    {
        RobustXamlLoader.Load(this);
    }

    public void ApplyState(string name, string address, bool active, SurveillanceCameraMonitorTheme theme)
    {
        var accent = active ? theme.Accent : theme.BorderStrongColor;
        var badgeColor = active ? theme.SuccessAccent : theme.SecondaryText;

        AccentBar.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = accent,
        };

        StateBadge.PanelOverride = SurveillanceCameraMonitorStyles.CreateBadgeStyle(
            active ? theme.PanelBackground : theme.PanelAltBackground,
            badgeColor.WithAlpha(0.82f),
            10,
            6);

        CameraNameLabel.SetMessage(
            $"{(active ? WH40KUiChrome.Eye : WH40KUiChrome.DiamondOutline)} {name}",
            defaultColor: active ? theme.PrimaryText : theme.SecondaryText);
        CameraAddressLabel.SetMessage($"{WH40KUiChrome.Arrow} {address}", defaultColor: theme.LabelText);
        StateLabel.Text = Loc.GetString(active
            ? "surveillance-camera-monitor-ui-entry-state-active"
            : "surveillance-camera-monitor-ui-entry-state-standby");
        StateLabel.FontColorOverride = badgeColor;
    }
}
