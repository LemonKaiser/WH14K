namespace Content.Client.Construction.UI
{
    public interface IConstructionMenuView : IDisposable
    {
        string[] Categories { get; set; }
        ThemedOptionButton OptionCategories { get; }

        bool EraseButtonPressed { get; set; }
        bool GridViewButtonPressed { get; set; }
        bool BuildButtonPressed { get; set; }

        ListContainer Recipes { get; }
        ItemList RecipeStepList { get; }
        ScrollContainer RecipesGridScrollContainer { get; }
        GridContainer RecipesGrid { get; }

        event EventHandler<(string search, string catagory)> PopulateRecipes;
        event EventHandler<ConstructionMenu.ConstructionMenuListData?> RecipeSelected;
        event EventHandler RecipeFavorited;
        event EventHandler<bool> BuildButtonToggled;
        event EventHandler<bool> EraseButtonToggled;
        event EventHandler ClearAllGhosts;

        void ApplyWh40KTheme(string? teamId);
        void SetCatalogSummary(int count, string categoryName, bool gridView);
        void ClearRecipeInfo();
        void SetRecipeInfo(
            string name,
            string description,
            EntityPrototype? targetPrototype,
            bool usesGhostPlacement,
            bool canAddToFavorites,
            string categoryName,
            int stepCount);
        void ResetPlacement();

        event Action? OnClose;
        bool IsOpen { get; }
        void OpenCentered();
        void MoveToFront();
        bool IsAtFront();
        void Close();
    }

    [GenerateTypedNameReferences]
    public sealed partial class ConstructionMenu : DefaultWindow, IConstructionMenuView
    {
        private const int RecipeGridColumns = 3;
        private const float RecipeGridCellSpacing = 8f;
        private const float RecipeGridMinCellWidth = 78f;
        private const float RecipeGridCellHeight = 104f;
        private static readonly Color BuildDangerAccent = WH40KCommandUiStyles.DangerBadge.WithAlpha(0.64f);
        private readonly Dictionary<ContainerButton, (Label Title, Label Meta)> _listButtonLabels = new();
        private Color _accent = WH40KCommandUiStyles.DefaultAccent;
        private bool _chaosTheme;

        public bool BuildButtonPressed
        {
            get => BuildButton.Pressed;
            set
            {
                BuildButton.Pressed = value;
                RefreshButtonThemes();
            }
        }

        public string[] Categories { get; set; } = Array.Empty<string>();

        public bool EraseButtonPressed
        {
            get => EraseButton.Pressed;
            set
            {
                EraseButton.Pressed = value;
                RefreshButtonThemes();
            }
        }

        public bool GridViewButtonPressed
        {
            get => MenuGridViewButton.Pressed;
            set
            {
                MenuGridViewButton.Pressed = value;
                UpdateLayoutButtonText();
                RefreshButtonThemes();
            }
        }

        public ConstructionMenu()
        {
            SetSize = new Vector2(856, 690);
            MinSize = new Vector2(733, 598);

            RobustXamlLoader.Load(this);

            Title = Loc.GetString("construction-menu-title");
            RecipeStepList.ItemSeparation = 6;
            RecipesGridScrollContainer.OnResized += UpdateRecipeGridColumns;
            OnResized += UpdateRecipeGridColumns;

            BuildButton.Text = Loc.GetString("construction-menu-place-ghost");
            Recipes.ItemPressed += (_, data) => RecipeSelected?.Invoke(this, data as ConstructionMenuListData);
            Recipes.NoItemSelected += () => RecipeSelected?.Invoke(this, null);
            Recipes.GenerateItem += (_, button) =>
            {
                if (button.Data is not ConstructionMenuListData(var prototype, var targetPrototype, var stepCount))
                    return;

                var entityView = new EntityPrototypeView
                {
                    SetSize = new Vector2(34f),
                    Stretch = SpriteView.StretchMode.Fill,
                    Scale = new Vector2(1.65f),
                    Margin = new Thickness(0, 2, 8, 2),
                };
                entityView.SetPrototype(targetPrototype);

                var titleLabel = new Label
                {
                    Text = prototype.Name,
                    StyleClasses = { "LabelBig" },
                    ClipText = true,
                    ModulateSelfOverride = WH40KCommandUiStyles.ResolveSoftText(_chaosTheme)
                };

                var metaLabel = new Label
                {
                    Text = BuildRecipeMetaTextDisplay(prototype, stepCount),
                    StyleClasses = { "LabelSubText" },
                    ClipText = true,
                    ModulateSelfOverride = WH40KCommandUiStyles.ResolveMutedText(_chaosTheme)
                };

                var textBox = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    SeparationOverride = 1,
                    HorizontalExpand = true
                };
                textBox.AddChild(titleLabel);
                textBox.AddChild(metaLabel);

                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    SeparationOverride = 0,
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Center
                };
                row.AddChild(entityView);
                row.AddChild(textBox);

                button.AddChild(row);
                button.ToolTip = prototype.Description;
                button.AddStyleClass(ListContainer.StyleClassListContainerButton);

                if (button is ContainerButton containerButton)
                {
                    _listButtonLabels[containerButton] = (titleLabel, metaLabel);
                    ApplyRecipeItemTheme(containerButton, false);
                    WH40KUiChrome.PlayFadeIn(containerButton, $"construction-list-appear-{prototype.ID}", 0.16f);
                    containerButton.OnToggled += args =>
                    {
                        RefreshRecipeListSelectionTheme();
                    };
                }
            };

            SearchBar.OnTextChanged += _ =>
                PopulateRecipes?.Invoke(this, (SearchBar.Text, Categories[OptionCategories.SelectedId]));
            OptionCategories.OnItemSelected += args =>
            {
                OptionCategories.SelectId(args.Id);
                SearchBar.SetText(string.Empty);
                PopulateRecipes?.Invoke(this, (SearchBar.Text, Categories[args.Id]));
            };

            BuildButton.OnToggled += args =>
            {
                RefreshButtonThemes();
                if (args.Pressed)
                {
                    PlayActionButtonFeedback(BuildButton, "construction-build-toggle-flash");
                }

                BuildButtonToggled?.Invoke(this, args.Pressed);
            };
            ClearButton.OnPressed += _ =>
            {
                PlayActionButtonFeedback(ClearButton, "construction-clear-flash", danger: true);
                ClearAllGhosts?.Invoke(this, EventArgs.Empty);
            };
            EraseButton.OnToggled += args =>
            {
                RefreshButtonThemes();
                if (args.Pressed)
                {
                    PlayActionButtonFeedback(EraseButton, "construction-erase-toggle-flash", danger: true);
                }

                EraseButtonToggled?.Invoke(this, args.Pressed);
            };
            FavoriteButton.OnPressed += _ => RecipeFavorited?.Invoke(this, EventArgs.Empty);
            MenuGridViewButton.OnToggled += args =>
            {
                UpdateLayoutButtonText();
                UpdateRecipeGridColumns();
                RefreshButtonThemes();
                if (args.Pressed != GridViewButtonPressed)
                    return;
                PopulateRecipes?.Invoke(this, (SearchBar.Text, Categories[OptionCategories.SelectedId]));
            };

            ApplyWh40KTheme(null);
            RelocalizeStatic();
            ClearRecipeInfo();
            SetCatalogSummary(0, Loc.GetString("construction-category-all"), false);
            UpdateRecipeGridColumns();

            HeaderPanel.Modulate = new Color(1f, 1f, 1f, 0f);
            RecipeStepPanel.Modulate = new Color(1f, 1f, 1f, 0f);
        }

        public event EventHandler? ClearAllGhosts;
        public event EventHandler<(string search, string catagory)>? PopulateRecipes;
        public event EventHandler<ConstructionMenuListData?>? RecipeSelected;
        public event EventHandler? RecipeFavorited;
        public event EventHandler<bool>? BuildButtonToggled;
        public event EventHandler<bool>? EraseButtonToggled;

        public void ApplyWh40KTheme(string? teamId)
        {
            _accent = string.IsNullOrWhiteSpace(teamId)
                ? WH40KCommandUiStyles.DefaultAccent
                : WH40KTeamIdentityClientResolver.ResolveAccentColor(teamId, WH40KCommandUiStyles.DefaultAccent);
            _chaosTheme = !string.IsNullOrWhiteSpace(teamId) &&
                          WH40KTeamIdentityClientResolver.UsesHereticsDoctrinePresentation(teamId);

            RootPanel.PanelOverride = WH40KCommandUiStyles.CreateBorderPanelStyle(
                WH40KCommandUiStyles.ResolvePanelBackgroundAlt(_chaosTheme),
                WH40KCommandUiStyles.ResolveStrongBorder(_chaosTheme),
                1);
            HeaderPanel.PanelOverride = WH40KCommandUiStyles.CreateBorderPanelStyle(
                WH40KCommandUiStyles.ResolveHeaderBackground(_chaosTheme),
                _accent,
                2);
            HeaderStatsBadge.PanelOverride = WH40KCommandUiStyles.CreateBadgeStyle(
                WH40KCommandUiStyles.ResolveBadgeBackground(_chaosTheme),
                _accent);

            CatalogPanel.PanelOverride = WH40KCommandUiStyles.CreateBorderPanelStyle(
                WH40KCommandUiStyles.ResolvePanelBackground(_chaosTheme),
                WH40KCommandUiStyles.ResolveStrongBorder(_chaosTheme),
                2);
            SearchPanel.PanelOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme),
                WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme));
            RecipeListPanel.PanelOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme));

            DetailsHeroPanel.PanelOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme),
                _accent);
            PreviewFramePanel.PanelOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme));
            RecipeStepPanel.PanelOverride = WH40KCommandUiStyles.CreateBorderPanelStyle(
                WH40KCommandUiStyles.ResolvePanelBackground(_chaosTheme),
                WH40KCommandUiStyles.ResolveStrongBorder(_chaosTheme),
                2);
            BuildActionsPanel.PanelOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme),
                WH40KCommandUiStyles.ResolveStrongBorder(_chaosTheme));

            TargetCategoryBadgePanel.PanelOverride = WH40KCommandUiStyles.CreateBadgeStyle(
                WH40KCommandUiStyles.ResolveBadgeBackground(_chaosTheme),
                _accent.WithAlpha(0.92f));

            SearchBar.StyleBoxOverride = WH40KCommandUiStyles.CreateInputStyle(WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme), _chaosTheme);
            OptionCategories.StyleBoxOverride = WH40KCommandUiStyles.CreateCardStyle(
                WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme));
            OptionCategories.ModulateSelfOverride = Color.White;
            ApplyCategoryPopupTheme();

            HeaderTitleLabel.ModulateSelfOverride = _accent;
            HeaderSubtitleLabel.ModulateSelfOverride = WH40KCommandUiStyles.ResolveMutedText(_chaosTheme);
            HeaderStatsLabel.ModulateSelfOverride = WH40KCommandUiStyles.ResolveSoftText(_chaosTheme);

            var sectionHeading = _chaosTheme
                ? WH40KCommandUiStyles.ResolveSoftText(true)
                : _accent;
            CatalogTitleLabel.ModulateSelfOverride = sectionHeading;
            RequirementsTitleLabel.ModulateSelfOverride = sectionHeading;
            StepSummaryLabel.ModulateSelfOverride = WH40KCommandUiStyles.ResolveMutedText(_chaosTheme);
            ActionHintLabel.ModulateSelfOverride = WH40KCommandUiStyles.ResolveMutedText(_chaosTheme);
            TargetCategoryBadgeLabel.ModulateSelfOverride = WH40KCommandUiStyles.ResolveSoftText(_chaosTheme);

            RefreshRecipeListSelectionTheme();
            RefreshButtonThemes();
        }

        protected override void Opened()
        {
            base.Opened();

            HeaderPanel.Modulate = new Color(1f, 1f, 1f, 0f);
            RecipeStepPanel.Modulate = new Color(1f, 1f, 1f, 0f);

            WH40KUiChrome.PlayFadeIn(HeaderPanel, "construction-menu-header-appear", 0.12f);
            WH40KUiChrome.PlayFadeIn(RecipeStepPanel, "construction-menu-steps-appear", 0.18f, 0.08f);
        }

        public void SetCatalogSummary(int count, string categoryName, bool gridView)
        {
            HeaderStatsLabel.Text = Loc.GetString("construction-menu-header-badge", ("count", count));
            UpdateLayoutButtonText();
        }

        public void ResetPlacement()
        {
            BuildButton.Pressed = false;
            EraseButton.Pressed = false;
            RefreshButtonThemes();
        }

        public void SetRecipeInfo(
            string name,
            string description,
            EntityPrototype? targetPrototype,
            bool usesGhostPlacement,
            bool canAddToFavorites,
            string categoryName,
            int stepCount)
        {
            BuildButton.Disabled = false;
            BuildButton.Text = Loc.GetString(usesGhostPlacement
                ? "construction-menu-place-ghost"
                : "construction-menu-craft");

            TargetCategoryBadgePanel.Visible = true;
            FavoriteButton.Visible = true;

            TargetCategoryBadgeLabel.Text = categoryName;

            WH40KCommandUiStyles.SetWrappedText(TargetName, name, _accent);
            WH40KCommandUiStyles.SetWrappedText(TargetDesc, description, WH40KCommandUiStyles.ResolveMutedText(_chaosTheme));
            TargetTexture.SetPrototype(targetPrototype?.ID);

            FavoriteButton.Text = Loc.GetString(canAddToFavorites
                ? "construction-menu-favorite-add"
                : "construction-menu-favorite-remove");
            StepSummaryLabel.Text = Loc.GetString(
                stepCount > 0
                    ? "construction-menu-requirements-summary"
                    : "construction-menu-requirements-summary-empty",
                ("count", stepCount));
            ActionHintLabel.Text = Loc.GetString(usesGhostPlacement
                ? "construction-menu-action-hint-structure"
                : "construction-menu-action-hint-item");

            RefreshButtonThemes();
        }

        public void ClearRecipeInfo()
        {
            BuildButton.Disabled = true;
            BuildButton.Text = Loc.GetString("construction-menu-place-ghost");
            WH40KCommandUiStyles.SetWrappedText(
                TargetName,
                Loc.GetString("construction-menu-details-placeholder-title"),
                _accent);
            WH40KCommandUiStyles.SetWrappedText(
                TargetDesc,
                Loc.GetString("construction-menu-details-placeholder-description"),
                WH40KCommandUiStyles.ResolveMutedText(_chaosTheme));
            TargetTexture.SetPrototype(null);
            TargetCategoryBadgePanel.Visible = false;
            FavoriteButton.Visible = false;
            StepSummaryLabel.Text = Loc.GetString("construction-menu-requirements-summary-idle");
            ActionHintLabel.Text = Loc.GetString("construction-menu-action-hint-idle");
            RecipeStepList.Clear();
            RefreshButtonThemes();
        }

        public sealed record ConstructionMenuListData(ConstructionPrototype Prototype, EntityPrototype TargetPrototype, int StepCount) : ListData;

        private void RelocalizeStatic()
        {
            Title = Loc.GetString("construction-menu-title");
            HeaderTitleLabel.Text = Loc.GetString("construction-menu-title");
            HeaderSubtitleLabel.Text = Loc.GetString("construction-menu-header-subtitle");
            CatalogTitleLabel.Text = Loc.GetString("construction-menu-catalog-title");
            RequirementsTitleLabel.Text = Loc.GetString("construction-menu-requirements-title");

            SearchBar.PlaceHolder = Loc.GetString("construction-menu-search");
            ClearButton.Text = Loc.GetString("construction-menu-clear-all");
            EraseButton.Text = Loc.GetString("construction-menu-eraser-mode");
            UpdateLayoutButtonText();
        }

        private void UpdateLayoutButtonText()
        {
            MenuGridViewButton.Text = Loc.GetString(GridViewButtonPressed
                ? "construction-menu-layout-grid"
                : "construction-menu-layout-list");
        }

        private void RefreshButtonThemes()
        {
            WH40KCommandUiStyles.ApplyButtonTheme(
                MenuGridViewButton,
                WH40KCommandUiStyles.CreateCardStyle(
                    GridViewButtonPressed
                        ? WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme)
                        : WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    GridViewButtonPressed
                        ? _accent.WithAlpha(0.72f)
                        : WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme)),
                WH40KCommandUiStyles.ResolveSoftText(_chaosTheme));
            MenuGridViewButton.ModulateSelfOverride = Color.White;
            WH40KCommandUiStyles.ApplyButtonTheme(
                FavoriteButton,
                WH40KCommandUiStyles.CreateCardStyle(
                    FavoriteButton.Disabled
                        ? WH40KCommandUiStyles.ResolveCardBackgroundMuted(_chaosTheme)
                        : WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    FavoriteButton.Disabled
                        ? WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme)
                        : _accent.WithAlpha(0.68f)),
                FavoriteButton.Disabled
                    ? WH40KCommandUiStyles.ResolveMutedText(_chaosTheme)
                    : WH40KCommandUiStyles.ResolveSoftText(_chaosTheme));
            FavoriteButton.ModulateSelfOverride = Color.White;
            WH40KCommandUiStyles.ApplyButtonTheme(
                BuildButton,
                WH40KCommandUiStyles.CreateCardStyle(
                    BuildButton.Disabled
                        ? WH40KCommandUiStyles.ResolveCardBackgroundMuted(_chaosTheme)
                        : BuildButton.Pressed
                            ? WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme)
                        : WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    BuildButton.Disabled
                        ? WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme)
                        : BuildButton.Pressed
                            ? _accent.WithAlpha(0.94f)
                            : _accent.WithAlpha(0.62f)),
                BuildButton.Disabled
                    ? WH40KCommandUiStyles.ResolveMutedText(_chaosTheme)
                    : WH40KCommandUiStyles.ResolveSoftText(_chaosTheme));
            BuildButton.ModulateSelfOverride = Color.White;
            WH40KCommandUiStyles.ApplyButtonTheme(
                EraseButton,
                WH40KCommandUiStyles.CreateCardStyle(
                    EraseButton.Pressed
                        ? WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme)
                        : WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    EraseButton.Pressed
                        ? BuildDangerAccent.WithAlpha(0.96f)
                        : WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme)),
                WH40KCommandUiStyles.ResolveSoftText(_chaosTheme));
            EraseButton.ModulateSelfOverride = Color.White;
            WH40KCommandUiStyles.ApplyButtonTheme(
                ClearButton,
                WH40KCommandUiStyles.CreateCardStyle(
                    WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    BuildDangerAccent),
                WH40KCommandUiStyles.ResolveSoftText(_chaosTheme));
            ClearButton.ModulateSelfOverride = Color.White;
        }

        private void ApplyCategoryPopupTheme()
        {
            if (OptionCategories is not ThemedOptionButton themed)
                return;

            themed.PopupButtonStyleOverride = WH40KCommandUiStyles.CreatePopupListButtonStyle(_accent, _chaosTheme);
            themed.PopupSelectedButtonStyleOverride = WH40KCommandUiStyles.CreatePopupListSelectedButtonStyle(_accent, _chaosTheme);
            themed.PopupButtonFontColorOverride = WH40KCommandUiStyles.ResolveSoftText(_chaosTheme);
            themed.PopupSelectedButtonFontColorOverride = WH40KCommandUiStyles.ResolveSoftText(_chaosTheme);
            themed.RefreshPopupItemTheme();
        }

        private void UpdateRecipeGridColumns()
        {
            RecipesGrid.Columns = RecipeGridColumns;

            var availableWidth = RecipesGridScrollContainer.Width;
            if (availableWidth <= 0)
                return;

            var innerWidth = MathF.Max(
                RecipeGridMinCellWidth * RecipeGridColumns + RecipeGridCellSpacing * (RecipeGridColumns - 1),
                availableWidth - 12f);
            var cellWidth = MathF.Max(
                RecipeGridMinCellWidth,
                MathF.Floor((innerWidth - RecipeGridCellSpacing * (RecipeGridColumns - 1)) / RecipeGridColumns));

            foreach (var child in RecipesGrid.Children)
            {
                child.MinWidth = cellWidth;
                child.SetWidth = cellWidth;
                child.MinHeight = RecipeGridCellHeight;
                child.SetHeight = RecipeGridCellHeight;
                child.HorizontalExpand = false;
                child.VerticalExpand = false;
            }
        }

        public void RefreshRecipeGridLayout()
        {
            UpdateRecipeGridColumns();
        }

        private string BuildRecipeMetaTextDisplay(ConstructionPrototype prototype, int stepCount)
        {
            var category = ResolveCategoryDisplayName(prototype.Category);
            return Loc.GetString("construction-menu-list-meta", ("category", category), ("count", stepCount));
        }

        private string BuildRecipeMetaText(ConstructionPrototype prototype, int stepCount)
        {
            var category = ResolveCategoryDisplayName(prototype.Category);
            return Loc.GetString("construction-menu-list-meta", ("category", category), ("count", stepCount));
        }

        private static string ResolveCategoryDisplayName(string? category)
        {
            return string.IsNullOrWhiteSpace(category)
                ? Loc.GetString("construction-category-misc")
                : Loc.GetString(category);
        }

        private void ApplyRecipeItemTheme(ContainerButton button, bool selected)
        {
            button.StyleBoxOverride = selected
                ? WH40KCommandUiStyles.CreateCardStyle(
                    WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme),
                    _accent.WithAlpha(0.76f))
                : WH40KCommandUiStyles.CreateCardStyle(
                    WH40KCommandUiStyles.ResolveCardBackground(_chaosTheme),
                    WH40KCommandUiStyles.ResolveMutedBorder(_chaosTheme));
            button.ModulateSelfOverride = Color.White;
        }

        public void RefreshRecipeListSelectionTheme()
        {
            foreach (var (button, labels) in _listButtonLabels.ToArray())
            {
                if (button.Disposed)
                {
                    _listButtonLabels.Remove(button);
                    continue;
                }

                ApplyRecipeItemTheme(button, button.Pressed);
                labels.Title.ModulateSelfOverride = button.Pressed
                    ? Color.White
                    : WH40KCommandUiStyles.ResolveSoftText(_chaosTheme);
                labels.Meta.ModulateSelfOverride = button.Pressed
                    ? WH40KCommandUiStyles.ResolveSoftText(_chaosTheme)
                    : WH40KCommandUiStyles.ResolveMutedText(_chaosTheme);
            }
        }

        private void PlayActionButtonFeedback(Button button, string key, bool danger = false)
        {
            var accent = danger ? WH40KCommandUiStyles.DangerBadge : _accent;
            button.StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = WH40KCommandUiStyles.ResolveCardBackgroundAlt(_chaosTheme),
                BorderColor = accent.WithAlpha(1f),
                BorderThickness = new Thickness(2),
                ContentMarginLeftOverride = 8,
                ContentMarginTopOverride = 8,
                ContentMarginRightOverride = 8,
                ContentMarginBottomOverride = 8,
            };
            button.Label.FontColorOverride = Color.White;
            button.ModulateSelfOverride = Color.White;

            Timer.Spawn(150, () =>
            {
                if (Disposed || button.Disposed)
                    return;

                RefreshButtonThemes();
            });
        }
    }
