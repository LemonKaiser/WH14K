using System;
using System.Linq;
using Content.Client._WH40K.Command;
using Content.Client.Localization;
using Content.Client.UserInterface.Controls;
using Content.Shared._WH40K.Squads;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Localization;
using Robust.Shared.Maths;

namespace Content.Client._WH40K.Squads.UI;

[GenerateTypedNameReferences]
public sealed partial class WH40KSquadWindow : FancyWindow, ILocalizedControl
{
    private static readonly Color DefaultAccent = Color.FromHex("#5F8FB8".AsSpan());
    private static readonly Color ReadyBadgeColor = Color.FromHex("#5FA27E".AsSpan());
    private static readonly Color WarningBadgeColor = Color.FromHex("#D5A356".AsSpan());
    private static readonly Color DangerBadgeColor = Color.FromHex("#C97070".AsSpan());
    private static readonly Color MutedBorderColor = Color.FromHex("#324459".AsSpan());
    private static readonly Color CardBackground = Color.FromHex("#121C28".AsSpan());
    private static readonly Color EmptyCardBackground = Color.FromHex("#101821".AsSpan());

    private WH40KSquadBuiState? _latestState;

    public event Action? CreatePressed;
    public event Action? DisbandPressed;
    public event Action? RefreshPressed;
    public event Action<NetEntity>? AssignPressed;
    public event Action<byte>? RemovePressed;

    public WH40KSquadWindow()
    {
        RobustXamlLoader.Load(this);

        CreateSquadButton.OnPressed += _ => CreatePressed?.Invoke();
        DisbandSquadButton.OnPressed += _ => DisbandPressed?.Invoke();
        RefreshButton.OnPressed += _ => RefreshPressed?.Invoke();
        FilterBar.OnTextChanged += args => ApplyCandidateFilter(args.Text);
        Relocalize();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("wh40k-squad-window-title");
        CommandTitleLabel.Text = Loc.GetString("wh40k-squad-command-title");
        CommandSubtitleLabel.Text = Loc.GetString("wh40k-squad-command-subtitle");
        LeaderTitleLabel.Text = Loc.GetString("wh40k-squad-leader-title");
        OverviewTitleLabel.Text = Loc.GetString("wh40k-squad-overview-title");
        ActionsTitleLabel.Text = Loc.GetString("wh40k-squad-actions-title");
        SlotsTitleLabel.Text = Loc.GetString("wh40k-squad-slots-title");
        RosterTitleLabel.Text = Loc.GetString("wh40k-squad-roster-title");
        RosterSubtitleLabel.Text = Loc.GetString("wh40k-squad-roster-subtitle");
        CreateSquadButton.Text = Loc.GetString("wh40k-squad-action-create");
        DisbandSquadButton.Text = Loc.GetString("wh40k-squad-action-disband");
        RefreshButton.Text = Loc.GetString("wh40k-squad-action-refresh");
        FilterBar.PlaceHolder = Loc.GetString("wh40k-squad-filter-placeholder");

        if (_latestState != null)
        {
            UpdateState(_latestState);
            return;
        }

        HeaderTitleLabel.Text = Loc.GetString("wh40k-squad-header-title");
        HeaderSubtitleLabel.Text = Loc.GetString("wh40k-squad-header-subtitle");
        TeamBadgeLabel.Text = Loc.GetString("wh40k-squad-team-badge-idle");
        AvailabilityBadgeLabel.Text = Loc.GetString("wh40k-squad-roster-badge-inactive");
        LeaderStateLabel.Text = Loc.GetString("wh40k-squad-leader-status-ready");
        InstructionLabel.Text = Loc.GetString("wh40k-squad-command-instruction-idle");
        FooterLabel.Text = Loc.GetString("wh40k-squad-footer-idle");
    }

    public void UpdateState(WH40KSquadBuiState state)
    {
        _latestState = state;

        var accent = ParseAccent(state.AccentHex);
        var nextFreeSlot = state.Slots.FirstOrDefault(slot => !slot.Occupied)?.SlotIndex ?? (byte) 0;
        var squadFull = state.MemberCount >= state.MaxMembers;
        var teamLabel = ResolveTeamLabel(state.TeamId);

        HeaderTitleLabel.Text = Loc.GetString("wh40k-squad-header-title");
        HeaderSubtitleLabel.Text = state.SquadActive
            ? Loc.GetString("wh40k-squad-header-subtitle-active", ("team", teamLabel))
            : Loc.GetString("wh40k-squad-header-subtitle-idle", ("team", teamLabel));

        TeamBadgeLabel.Text = string.IsNullOrWhiteSpace(state.TeamId)
            ? Loc.GetString("wh40k-squad-team-badge-idle")
            : Loc.GetString("wh40k-squad-team-badge", ("team", teamLabel));

        AvailabilityBadgeLabel.Text = state.SquadActive
            ? Loc.GetString("wh40k-squad-roster-badge-active", ("count", state.MemberCount), ("max", state.MaxMembers))
            : Loc.GetString("wh40k-squad-roster-badge-inactive");

        LeaderNameLabel.Text = state.LeaderName;
        LeaderRoleLabel.Text = string.IsNullOrWhiteSpace(state.LeaderRoleName)
            ? Loc.GetString("wh40k-squad-role-unknown")
            : WH40KCommandUiStyles.ResolveLocalizedOrRaw(state.LeaderRoleName);
        LeaderStateLabel.Text = state.LeaderAlive
            ? Loc.GetString("wh40k-squad-leader-status-ready")
            : Loc.GetString("wh40k-squad-leader-status-kia");

        SquadSummaryLabel.Text = state.SquadActive
            ? Loc.GetString("wh40k-squad-summary-active", ("count", state.MemberCount), ("max", state.MaxMembers))
            : Loc.GetString("wh40k-squad-summary-idle");
        RosterSummaryLabel.Text = Loc.GetString("wh40k-squad-roster-summary", ("count", state.AvailableCount));
        InstructionLabel.Text = !state.SquadActive
            ? Loc.GetString("wh40k-squad-command-instruction-idle")
            : squadFull
                ? Loc.GetString("wh40k-squad-command-instruction-full")
                : nextFreeSlot == 0
                    ? Loc.GetString("wh40k-squad-command-instruction-full")
                    : Loc.GetString("wh40k-squad-command-instruction-active", ("slot", nextFreeSlot));

        AvailableCountLabel.Text = state.AvailableCount.ToString();
        FooterLabel.Text = !state.SquadActive
            ? Loc.GetString("wh40k-squad-footer-idle")
            : squadFull
                ? Loc.GetString("wh40k-squad-footer-full")
                : Loc.GetString("wh40k-squad-footer-active", ("slot", nextFreeSlot));

        CreateSquadButton.Disabled = state.SquadActive || string.IsNullOrWhiteSpace(state.TeamId);
        DisbandSquadButton.Disabled = !state.SquadActive;

        ApplyAccent(accent, state.SquadActive, squadFull);
        RebuildSlots(state, accent);
        RebuildCandidates(state, nextFreeSlot, squadFull);
    }

    private void RebuildSlots(WH40KSquadBuiState state, Color accent)
    {
        SlotList.Children.Clear();

        foreach (var slot in state.Slots)
        {
            var panel = new PanelContainer
            {
                PanelOverride = CreateCardStyle(slot.Occupied ? CardBackground : EmptyCardBackground,
                    slot.Occupied ? accent : MutedBorderColor),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 6,
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            header.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-squad-slot-title", ("slot", slot.SlotIndex)),
                StyleClasses = { "LabelHeading" },
                HorizontalExpand = true,
            });

            var statusBadge = new PanelContainer
            {
                PanelOverride = CreateBadgeStyle(
                    slot.Occupied
                        ? slot.Alive ? Color.FromHex("#223B2F".AsSpan()) : Color.FromHex("#3A2A2A".AsSpan())
                        : Color.FromHex("#22313B".AsSpan()),
                    slot.Occupied
                        ? slot.Alive ? ReadyBadgeColor : DangerBadgeColor
                        : DefaultAccent),
            };
            statusBadge.AddChild(new Label
            {
                Text = !slot.Occupied
                    ? Loc.GetString("wh40k-squad-slot-empty")
                    : slot.Alive
                        ? Loc.GetString("wh40k-squad-slot-assigned")
                        : Loc.GetString("wh40k-squad-slot-kia"),
            });

            header.AddChild(statusBadge);
            content.AddChild(header);

            if (slot.Occupied)
            {
                content.AddChild(new Label
                {
                    Text = slot.Name,
                    StyleClasses = { "LabelBig" },
                    ClipText = true,
                });
                content.AddChild(new Label
                {
                    Text = string.IsNullOrWhiteSpace(slot.RoleName)
                        ? Loc.GetString("wh40k-squad-role-unknown")
                        : WH40KCommandUiStyles.ResolveLocalizedOrRaw(slot.RoleName),
                    StyleClasses = { "LabelSubText" },
                    ClipText = true,
                });

                var removeButton = new Button
                {
                    Text = Loc.GetString("wh40k-squad-action-remove"),
                    HorizontalExpand = true,
                    StyleClasses = { "ButtonColorRed" },
                };
                var capturedSlot = slot.SlotIndex;
                removeButton.OnPressed += _ => RemovePressed?.Invoke(capturedSlot);
                content.AddChild(removeButton);
            }
            else
            {
                content.AddChild(new Label
                {
                    Text = Loc.GetString("wh40k-squad-slot-empty-detail"),
                    StyleClasses = { "LabelSubText" },
                    ClipText = true,
                });
            }

            panel.AddChild(content);
            SlotList.AddChild(panel);
        }
    }

    private void RebuildCandidates(WH40KSquadBuiState state, byte nextFreeSlot, bool squadFull)
    {
        CandidateList.Children.Clear();

        var filtered = state.Candidates
            .Where(candidate => MatchesFilter(candidate, FilterBar.Text))
            .ToList();

        if (filtered.Count == 0)
        {
            CandidateList.AddChild(BuildEmptyCandidateCard(state));
            return;
        }

        foreach (var candidate in filtered)
        {
            var panel = new PanelContainer
            {
                PanelOverride = CreateCardStyle(CardBackground, MutedBorderColor),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 8,
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            var info = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 2,
                HorizontalExpand = true,
            };
            info.AddChild(new Label
            {
                Text = candidate.Name,
                StyleClasses = { "LabelBig" },
                ClipText = true,
            });
            info.AddChild(new Label
            {
                Text = string.IsNullOrWhiteSpace(candidate.RoleName)
                    ? Loc.GetString("wh40k-squad-role-unknown")
                    : WH40KCommandUiStyles.ResolveLocalizedOrRaw(candidate.RoleName),
                StyleClasses = { "LabelSubText" },
                ClipText = true,
            });

            var statusBadge = new PanelContainer
            {
                PanelOverride = CreateBadgeStyle(Color.FromHex("#223B2F".AsSpan()), ReadyBadgeColor),
            };
            statusBadge.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-squad-candidate-ready"),
            });

            header.AddChild(info);
            header.AddChild(statusBadge);
            content.AddChild(header);

            var assignButton = new Button
            {
                HorizontalExpand = true,
                Text = !state.SquadActive
                    ? Loc.GetString("wh40k-squad-action-create-first")
                    : squadFull || nextFreeSlot == 0
                        ? Loc.GetString("wh40k-squad-action-full")
                        : Loc.GetString("wh40k-squad-action-assign", ("slot", nextFreeSlot)),
            };
            assignButton.Disabled = !state.SquadActive || squadFull || nextFreeSlot == 0;
            var capturedEntity = candidate.Entity;
            assignButton.OnPressed += _ => AssignPressed?.Invoke(capturedEntity);
            content.AddChild(assignButton);

            panel.AddChild(content);
            CandidateList.AddChild(panel);
        }
    }

    private Control BuildEmptyCandidateCard(WH40KSquadBuiState state)
    {
        var panel = new PanelContainer
        {
            PanelOverride = CreateCardStyle(EmptyCardBackground, MutedBorderColor),
        };

        panel.AddChild(new Label
        {
            Text = string.IsNullOrWhiteSpace(FilterBar.Text)
                ? state.SquadActive
                    ? Loc.GetString("wh40k-squad-roster-empty")
                    : Loc.GetString("wh40k-squad-roster-empty-idle")
                : Loc.GetString("wh40k-squad-roster-no-filter-match"),
            StyleClasses = { "LabelSubText" },
        });

        return panel;
    }

    private void ApplyCandidateFilter(string _)
    {
        if (_latestState == null)
            return;

        var nextFreeSlot = _latestState.Slots.FirstOrDefault(slot => !slot.Occupied)?.SlotIndex ?? (byte) 0;
        RebuildCandidates(_latestState, nextFreeSlot, _latestState.MemberCount >= _latestState.MaxMembers);
    }

    private void ApplyAccent(Color accent, bool squadActive, bool squadFull)
    {
        HeaderPanel.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#0D1520".AsSpan()), accent, 2);
        RailHeaderPanel.PanelOverride = CreateHeaderStripStyle(accent);
        RosterHeaderPanel.PanelOverride = CreateHeaderStripStyle(accent);
        FooterPanel.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#0E141C".AsSpan()), MutedBorderColor, 1);
        TeamBadge.PanelOverride = CreateBadgeStyle(Color.FromHex("#203227".AsSpan()), accent);
        AvailabilityBadge.PanelOverride = CreateBadgeStyle(
            squadActive
                ? squadFull ? Color.FromHex("#3A2E1D".AsSpan()) : Color.FromHex("#223B2F".AsSpan())
                : Color.FromHex("#26314A".AsSpan()),
            squadActive
                ? squadFull ? WarningBadgeColor : ReadyBadgeColor
                : DefaultAccent);
        RosterCountBadge.PanelOverride = CreateBadgeStyle(Color.FromHex("#22313B".AsSpan()), accent);
        CommandRail.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#111924".AsSpan()), MutedBorderColor, 2);
        RosterPanel.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#0D141D".AsSpan()), MutedBorderColor, 2);
        FilterPanel.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#121C28".AsSpan()), MutedBorderColor, 1);
        CandidatePanel.PanelOverride = CreateBorderPanelStyle(Color.FromHex("#0F1822".AsSpan()), MutedBorderColor, 1);
        LeaderPanel.PanelOverride = CreateBorderPanelStyle(CardBackground, accent, 1);
        OverviewPanel.PanelOverride = CreateBorderPanelStyle(CardBackground, MutedBorderColor, 1);
        ActionPanel.PanelOverride = CreateBorderPanelStyle(CardBackground, MutedBorderColor, 1);
        SlotsPanel.PanelOverride = CreateBorderPanelStyle(CardBackground, MutedBorderColor, 1);
    }

    private static bool MatchesFilter(WH40KSquadMemberEntry candidate, string filter)
    {
        if (string.IsNullOrWhiteSpace(filter))
            return true;

        return candidate.Name.Contains(filter, StringComparison.OrdinalIgnoreCase) ||
               candidate.RoleName.Contains(filter, StringComparison.OrdinalIgnoreCase);
    }

    private static string ResolveTeamLabel(string teamId)
    {
        return string.Equals(teamId, "Heretics", StringComparison.OrdinalIgnoreCase)
            ? Loc.GetString("wh40k-squad-team-heretics")
            : string.Equals(teamId, "Imperium", StringComparison.OrdinalIgnoreCase)
                ? Loc.GetString("wh40k-squad-team-imperium")
                : Loc.GetString("wh40k-squad-team-unknown");
    }

    private static Color ParseAccent(string hex)
    {
        if (!string.IsNullOrWhiteSpace(hex))
        {
            var normalized = hex.StartsWith('#') ? hex : $"#{hex}";
            return Color.FromHex(normalized.AsSpan());
        }

        return DefaultAccent;
    }

    private static StyleBoxFlat CreateCardStyle(Color background, Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 10,
            ContentMarginTopOverride = 10,
            ContentMarginRightOverride = 10,
            ContentMarginBottomOverride = 10,
        };
    }

    private static StyleBoxFlat CreateBadgeStyle(Color background, Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 10,
            ContentMarginTopOverride = 4,
            ContentMarginRightOverride = 10,
            ContentMarginBottomOverride = 4,
        };
    }

    private static StyleBoxFlat CreateBorderPanelStyle(Color background, Color border, int thickness)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(thickness),
            ContentMarginLeftOverride = thickness == 1 ? 6 : 0,
            ContentMarginTopOverride = thickness == 1 ? 6 : 0,
            ContentMarginRightOverride = thickness == 1 ? 6 : 0,
            ContentMarginBottomOverride = thickness == 1 ? 6 : 0,
        };
    }

    private static StyleBoxFlat CreateHeaderStripStyle(Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#162231".AsSpan()),
            BorderColor = border,
            BorderThickness = new Thickness(0, 0, 0, 1),
            ContentMarginLeftOverride = 12,
            ContentMarginTopOverride = 10,
            ContentMarginRightOverride = 12,
            ContentMarginBottomOverride = 10,
        };
    }
}
