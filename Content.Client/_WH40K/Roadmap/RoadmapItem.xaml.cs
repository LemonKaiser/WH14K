using System;
using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Roadmap;

[GenerateTypedNameReferences]
public sealed partial class RoadmapItem : Control
{
    private const float PulseBase = 0.72f;
    private const float PulseAmplitude = 0.28f;
    private const float PulseFrequency = 2.7f;
    private const float PulseUpdateInterval = 1f / 12f;

    private RoadmapItemState _itemState;
    private Color _baseStateColor = Color.Red;
    private float _pulse;
    private float _pulseAccumulator;
    private bool _stateVisualDirty;

    public RoadmapItemState ItemState
    {
        get => _itemState;
        set
        {
            _itemState = value;
            _baseStateColor = _itemState switch
            {
                RoadmapItemState.Planned => Color.FromHex("#B25B4E"),
                RoadmapItemState.InProgress => Color.FromHex("#C4A14A"),
                RoadmapItemState.Complete => Color.FromHex("#779260"),
                _ => Color.FromHex("#B25B4E")
            };

            StateText.Text = _itemState switch
            {
                RoadmapItemState.Planned => Loc.GetString("roadmap-item-tag-planned"),
                RoadmapItemState.InProgress => Loc.GetString("roadmap-item-tag-in-progress"),
                RoadmapItemState.Complete => Loc.GetString("roadmap-item-tag-complete"),
                _ => string.Empty
            };

            StatusLabel.Text = _itemState switch
            {
                RoadmapItemState.Planned => Loc.GetString("roadmap-item-status-planned"),
                RoadmapItemState.InProgress => Loc.GetString("roadmap-item-status-in-progress"),
                RoadmapItemState.Complete => Loc.GetString("roadmap-item-status-complete"),
                _ => string.Empty
            };

            _pulse = 0f;
            _pulseAccumulator = 0f;
            _stateVisualDirty = true;
            ApplyStateVisual(1f);
        }
    }

    public string? HeaderText
    {
        get => HeaderButton.Text;
        set => HeaderButton.Text = value;
    }

    public string? Text
    {
        get => Contents.GetMessage();
        set => Contents.SetMarkup($"[font size=11]{FormattedMessage.EscapeText(value ?? string.Empty)}[/font]");
    }

    public RoadmapItem()
    {
        RobustXamlLoader.Load(this);
        HeaderButton.OnPressed += _ => ContentsContainer.Visible = !ContentsContainer.Visible;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!VisibleInTree)
            return;

        if (_itemState == RoadmapItemState.Complete)
        {
            if (_stateVisualDirty)
            {
                ApplyStateVisual(1f);
                _stateVisualDirty = false;
            }

            return;
        }

        _pulse += args.DeltaSeconds;
        _pulseAccumulator += args.DeltaSeconds;
        if (_pulseAccumulator < PulseUpdateInterval && !_stateVisualDirty)
            return;

        _pulseAccumulator = 0f;
        var t = PulseBase + PulseAmplitude * MathF.Sin(_pulse * PulseFrequency);
        ApplyStateVisual(t);
        _stateVisualDirty = false;
    }

    private void ApplyStateVisual(float pulse)
    {
        var stripe = (StyleBoxFlat) StateColor.PanelOverride!;
        stripe.BackgroundColor = _baseStateColor.WithAlpha(0.72f + 0.28f * pulse);
        StateText.ModulateSelfOverride = _baseStateColor.WithAlpha(0.78f + 0.22f * pulse);
        StatusLabel.ModulateSelfOverride = _baseStateColor.WithAlpha(0.78f + 0.22f * pulse);
    }
}
