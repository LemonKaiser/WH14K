using System;
using Content.Client.UserInterface.Controls;
using Content.Shared._WH40K.SupplyDrop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.SupplyDrop;

[GenerateTypedNameReferences]
public sealed partial class WH40KSupplyDropWindow : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;

    private WH40KSupplyDropBuiState? _state;

    public WH40KSupplyDropWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void ApplyState(WH40KSupplyDropBuiState state)
    {
        _state = state;
        Refresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Refresh();
    }

    private void Refresh()
    {
        if (_state == null)
            return;

        TeamLabel.Text = Loc.GetString("wh40k-supplydrop-ui-team", ("team", _state.TeamName));
        AccountLabel.Text = Loc.GetString("wh40k-supplydrop-ui-account", ("account", _state.AccountId));
        BalanceLabel.Text = Loc.GetString("wh40k-supplydrop-ui-balance", ("amount", _state.Balance));
        CostLabel.Text = Loc.GetString("wh40k-supplydrop-ui-cost", ("amount", _state.Cost));
        EtaLabel.Text = Loc.GetString("wh40k-supplydrop-ui-eta", ("seconds", _state.DropDelaySeconds));

        var cooldown = _state.NextLaunchAt - _timing.CurTime;
        if (cooldown > TimeSpan.Zero)
        {
            LaunchButton.Disabled = true;
            CooldownLabel.Text = Loc.GetString(
                "wh40k-supplydrop-ui-cooldown",
                ("seconds", (int) Math.Ceiling(cooldown.TotalSeconds)));
            return;
        }

        if (_state.Balance < _state.Cost)
        {
            LaunchButton.Disabled = true;
            CooldownLabel.Text = Loc.GetString("wh40k-supplydrop-ui-not-enough-funds");
            return;
        }

        LaunchButton.Disabled = false;
        CooldownLabel.Text = Loc.GetString("wh40k-supplydrop-ui-ready");
    }
}
