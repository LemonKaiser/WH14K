using Content.Client.Localization;
using Content.Shared._WH40K.Mortar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;

namespace Content.Client._WH40K.Mortar;

[GenerateTypedNameReferences]
public sealed partial class WH40KMortarWindow : DefaultWindow, ILocalizedControl
{
    private WH40KMortarBuiState? _latestState;

    public WH40KMortarWindow()
    {
        RobustXamlLoader.Load(this);

        TargetXInput.IsValid = IsSignedInt;
        TargetYInput.IsValid = IsSignedInt;
        DialXInput.IsValid = IsSignedInt;
        DialYInput.IsValid = IsSignedInt;
        LaserDesignatorIdInput.IsValid = IsSignedInt;
        Relocalize();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("wh40k-mortar-interface-title");
        SetLaserDesignatorButton.Text = Loc.GetString("wh40k-mortar-laser-link-button");
        TargetTitleLabel.Text = Loc.GetString("wh40k-mortar-target-title");
        TargetXTitleLabel.Text = Loc.GetString("wh40k-mortar-target-short-x");
        TargetYTitleLabel.Text = Loc.GetString("wh40k-mortar-target-short-y");
        SetTargetButton.Text = Loc.GetString("wh40k-mortar-target-set-button-short");
        DialTitleLabel.Text = Loc.GetString("wh40k-mortar-dial-title");
        DialXTitleLabel.Text = Loc.GetString("wh40k-mortar-target-short-x");
        DialYTitleLabel.Text = Loc.GetString("wh40k-mortar-target-short-y");
        SetDialButton.Text = Loc.GetString("wh40k-mortar-dial-set-button-short");
        FireButton.Text = Loc.GetString("wh40k-mortar-fire-button");

        if (_latestState != null)
            ApplyState(_latestState);
        else
            ToggleLaserModeButton.Text = Loc.GetString("wh40k-mortar-laser-toggle-button");
    }

    public void ApplyState(WH40KMortarBuiState state)
    {
        _latestState = state;
        if (!TargetXInput.HasKeyboardFocus())
            TargetXInput.Text = state.Target.X.ToString();

        if (!TargetYInput.HasKeyboardFocus())
            TargetYInput.Text = state.Target.Y.ToString();

        if (!DialXInput.HasKeyboardFocus())
            DialXInput.Text = state.Dial.X.ToString();

        if (!DialYInput.HasKeyboardFocus())
            DialYInput.Text = state.Dial.Y.ToString();

        RangeLabel.Text = Loc.GetString(
            "wh40k-mortar-interface-range",
            ("min", state.MinimumRange),
            ("max", state.MaximumRange));

        CooldownLabel.Text = state.CooldownRemainingSeconds > 0
            ? Loc.GetString(
                "wh40k-mortar-interface-cooldown-reloading",
                ("remaining", state.CooldownRemainingSeconds),
                ("total", state.FireDelaySeconds))
            : Loc.GetString(
                "wh40k-mortar-interface-cooldown-ready",
                ("total", state.FireDelaySeconds));

        PositionLabel.Text = Loc.GetString(
            "wh40k-mortar-interface-position",
            ("x", state.Position.X),
            ("y", state.Position.Y));

        LaserModeLabel.Text = state.LaserTargetingMode
            ? Loc.GetString("wh40k-mortar-interface-laser-mode-enabled")
            : Loc.GetString("wh40k-mortar-interface-laser-mode-disabled");

        LaserStatusLabel.Text = GetLaserStatusText(state);

        LoadStateLabel.Text = state.Loaded
            ? Loc.GetString("wh40k-mortar-interface-loaded-yes")
            : Loc.GetString("wh40k-mortar-interface-loaded-no");
        ShellTypeLabel.Text = state.Loaded
            ? Loc.GetString("wh40k-mortar-interface-shell-type", ("type", GetShellTypeText(state.LoadedShellType)))
            : Loc.GetString("wh40k-mortar-interface-shell-type-none");

        if (!LaserDesignatorIdInput.HasKeyboardFocus())
            LaserDesignatorIdInput.Text = state.LinkedDesignatorAssigned
                ? state.LinkedDesignatorId.ToString()
                : string.Empty;

        ToggleLaserModeButton.Text = state.LaserTargetingMode
            ? Loc.GetString("wh40k-mortar-laser-switch-to-coordinates")
            : Loc.GetString("wh40k-mortar-laser-switch-to-designator");

        SetTargetButton.Disabled = !state.Deployed || state.LaserTargetingMode;
        SetDialButton.Disabled = !state.Deployed;
        FireButton.Disabled = !state.Deployed || !state.Loaded || state.CooldownRemainingSeconds > 0;
        SetLaserDesignatorButton.Disabled = !state.Deployed;
        ToggleLaserModeButton.Disabled = !state.Deployed;

        TargetXInput.Editable = state.Deployed && !state.LaserTargetingMode;
        TargetYInput.Editable = state.Deployed && !state.LaserTargetingMode;
        DialXInput.Editable = state.Deployed;
        DialYInput.Editable = state.Deployed;
        LaserDesignatorIdInput.Editable = state.Deployed;
    }

    private static bool IsSignedInt(string text)
    {
        if (string.IsNullOrEmpty(text) || text == "-")
            return true;

        return int.TryParse(text, out _);
    }

    private static string GetShellTypeText(string rawType)
    {
        return rawType.ToLowerInvariant() switch
        {
            "he" => Loc.GetString("wh40k-mortar-shell-type-he"),
            "flare" => Loc.GetString("wh40k-mortar-shell-type-flare"),
            "smoke" => Loc.GetString("wh40k-mortar-shell-type-smoke"),
            "incendiary" => Loc.GetString("wh40k-mortar-shell-type-incendiary"),
            "emp" => Loc.GetString("wh40k-mortar-shell-type-emp"),
            _ => Loc.GetString("wh40k-mortar-shell-type-unknown"),
        };
    }

    private static string GetLaserStatusText(WH40KMortarBuiState state)
    {
        if (!state.LinkedDesignatorAssigned)
            return Loc.GetString("wh40k-mortar-interface-laser-status-none");

        if (!state.HasLinkedTarget)
            return Loc.GetString("wh40k-mortar-interface-laser-status-no-target", ("id", state.LinkedDesignatorId));

        if (!state.LinkedTargetSameGrid)
            return Loc.GetString("wh40k-mortar-interface-laser-status-other-grid", ("id", state.LinkedDesignatorId));

        return Loc.GetString(
            "wh40k-mortar-interface-laser-status-target",
            ("id", state.LinkedDesignatorId),
            ("x", state.LinkedTarget.X),
            ("y", state.LinkedTarget.Y));
    }
}
