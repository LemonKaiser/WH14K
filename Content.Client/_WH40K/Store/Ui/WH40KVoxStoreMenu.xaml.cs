using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Numerics;
using Content.Client.Actions;
using Content.Client.UserInterface.Controls;
using Content.Shared.FixedPoint;
using Content.Shared.Store;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._WH40K.Store.Ui;

[GenerateTypedNameReferences]
public sealed partial class WH40KVoxStoreMenu : FancyWindow
{
    private const char PurchaseCurrencySymbol = '\u20AE';

    [Dependency] private  IEntityManager _entityManager = default!;
    [Dependency] private  IPrototypeManager _prototype = default!;
    [Dependency] private  IGameTiming _timing = default!;

    private readonly SpriteSystem _spriteSystem;
    private readonly ActionsSystem _actionsSystem;

    private readonly StyleBoxFlat _tileDefaultStyle = new()
    {
        BackgroundColor = Color.FromHex("#1A201B"),
        BorderColor = Color.FromHex("#3C4A3F"),
        BorderThickness = new Thickness(1),
        ContentMarginBottomOverride = 4,
        ContentMarginLeftOverride = 4,
        ContentMarginRightOverride = 4,
        ContentMarginTopOverride = 4
    };

    private readonly StyleBoxFlat _tileSelectedStyle = new()
    {
        BackgroundColor = Color.FromHex("#2A332C"),
        BorderColor = Color.FromHex("#8BAA77"),
        BorderThickness = new Thickness(2),
        ContentMarginBottomOverride = 3,
        ContentMarginLeftOverride = 3,
        ContentMarginRightOverride = 3,
        ContentMarginTopOverride = 3
    };

    private readonly StyleBoxFlat _tileUnavailableStyle = new()
    {
        BackgroundColor = Color.FromHex("#291B1B"),
        BorderColor = Color.FromHex("#704A4A"),
        BorderThickness = new Thickness(1),
        ContentMarginBottomOverride = 4,
        ContentMarginLeftOverride = 4,
        ContentMarginRightOverride = 4,
        ContentMarginTopOverride = 4
    };

    private readonly Dictionary<ListingDataWithCostModifiers, TextureButton> _listingButtons = new();
    private readonly Dictionary<ListingDataWithCostModifiers, PanelContainer> _listingPanels = new();
    private readonly Dictionary<ListingDataWithCostModifiers, Texture?> _listingTextures = new();
    private Dictionary<ProtoId<ListingPrototype>, int> _listingDropAmounts = new();

    private List<ListingDataWithCostModifiers> _listings = new();

    private ListingDataWithCostModifiers? _selectedListing;
    private string? _selectedListingId;
    private TimeSpan _nextLaunchAt;

    public event Action<BaseButton.ButtonEventArgs, ListingDataWithCostModifiers>? OnPurchasePressed;

    public Dictionary<ProtoId<CurrencyPrototype>, FixedPoint2> Balance = new();

    public WH40KVoxStoreMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _spriteSystem = _entityManager.System<SpriteSystem>();
        _actionsSystem = _entityManager.System<ActionsSystem>();

        BuyButton.OnButtonDown += OnBuyButtonDown;
        SetEmptySelectionState();
    }

    public void UpdateBalance(Dictionary<ProtoId<CurrencyPrototype>, FixedPoint2> balance)
    {
        Balance = balance;

        var balanceLines = balance.Select(pair =>
        {
            return Loc.GetString(
                "wh40k-vox-supplydrop-balance-line",
                ("amount", FormatFundsWithPurchaseSymbol(pair.Value)));
        });

        BalanceInfo.SetMessage(string.Join("\n", balanceLines));
        RefreshListingVisualState();
        RefreshSelectedListing();
    }

    public void UpdateSupplyDropCooldown(TimeSpan nextLaunchAt)
    {
        _nextLaunchAt = nextLaunchAt;
        RefreshListingVisualState();
        RefreshSelectedListing();
    }

    public void UpdateListingDropAmounts(Dictionary<ProtoId<ListingPrototype>, int> listingDropAmounts)
    {
        _listingDropAmounts = listingDropAmounts;
        RefreshSelectedListing();
    }

    public void UpdateListings(List<ListingDataWithCostModifiers> listings)
    {
        _listings = listings
            .OrderBy(listing => listing.Priority)
            .ThenBy(listing => listing.Cost.Values.Sum())
            .ThenBy(listing => ListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _prototype))
            .ToList();

        if (_selectedListingId != null)
            _selectedListing = _listings.FirstOrDefault(listing => listing.ID == _selectedListingId);

        if (_selectedListing == null)
            _selectedListing = _listings.FirstOrDefault();

        _selectedListingId = _selectedListing?.ID;

        RebuildListingTiles();
        RefreshSelectedListing();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        RefreshListingVisualState();
        RefreshSelectedListing();
    }

    private void RebuildListingTiles()
    {
        ListingGrid.Children.Clear();
        _listingButtons.Clear();
        _listingPanels.Clear();
        _listingTextures.Clear();

        var group = new ButtonGroup();

        foreach (var listing in _listings)
        {
            var texture = ResolveListingTexture(listing);
            _listingTextures[listing] = texture;

            var button = new TextureButton
            {
                MinSize = new Vector2(64, 64),
                MaxSize = new Vector2(64, 64),
                Group = group,
                ToggleMode = true,
                ToolTip = ListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _prototype),
                TextureNormal = texture,
            };

            button.OnPressed += _ => SelectListing(listing);

            var panel = new PanelContainer
            {
                MinSize = new Vector2(72, 72),
                MaxSize = new Vector2(72, 72),
            };
            panel.AddChild(button);

            ListingGrid.AddChild(panel);
            _listingButtons[listing] = button;
            _listingPanels[listing] = panel;
        }

        RefreshListingVisualState();
    }

    private void SelectListing(ListingDataWithCostModifiers listing)
    {
        _selectedListing = listing;
        _selectedListingId = listing.ID;
        RefreshListingVisualState();
        RefreshSelectedListing();
    }

    private void RefreshListingVisualState()
    {
        foreach (var listing in _listings)
        {
            if (!_listingButtons.TryGetValue(listing, out var button) ||
                !_listingPanels.TryGetValue(listing, out var panel))
            {
                continue;
            }

            var selected = _selectedListingId != null && listing.ID == _selectedListingId;
            var canBuy = CanBuy(listing);

            button.Pressed = selected;
            button.Modulate = canBuy ? Color.White : Color.FromHex("#8F8F8F");

            panel.PanelOverride = selected
                ? _tileSelectedStyle
                : canBuy
                    ? _tileDefaultStyle
                    : _tileUnavailableStyle;
        }
    }

    private void RefreshSelectedListing()
    {
        if (_selectedListing == null)
        {
            SetEmptySelectionState();
            return;
        }

        var listing = _selectedListing;
        var now = _timing.CurTime;
        var onCooldown = _nextLaunchAt > now;
        var hasBalance = listing.CanBuyWith(Balance);
        var canBuy = !onCooldown && hasBalance;
        var dropAmount = GetDropAmount(listing);
        var baseName = ListingLocalisationHelpers.GetLocalisedNameOrEntityName(listing, _prototype);

        SelectedIcon.Texture = GetListingTexture(listing);
        SelectedName.Text = Loc.GetString(
            "wh40k-vox-supplydrop-selected-name-with-amount",
            ("name", baseName),
            ("amount", dropAmount));
        SelectedDescription.SetMessage(ListingLocalisationHelpers.GetLocalisedDescriptionOrEntityDescription(listing, _prototype));

        var price = GetListingPriceString(listing);
        var status = string.Empty;

        if (onCooldown)
        {
            var left = _nextLaunchAt - now;
            BuyButton.Text = FormatTime(left);
        }
        else if (!hasBalance)
        {
            status = Loc.GetString("wh40k-vox-supplydrop-status-not-enough-funds");
            BuyButton.Text = Loc.GetString("wh40k-vox-supplydrop-buy-button");
        }
        else
        {
            BuyButton.Text = Loc.GetString("wh40k-vox-supplydrop-buy-button");
        }

        var discount = GetDiscountString(listing);
        if (discount.Length > 0)
            status = status.Length > 0 ? $"{status}\n{discount}" : discount;

        var priceInfo = price.Length > 0 ? price : Loc.GetString("store-currency-free");
        if (status.Length > 0)
            priceInfo += $"\n{status}";

        priceInfo += $"\n{Loc.GetString("wh40k-vox-supplydrop-quantity-line", ("amount", dropAmount))}";

        SelectedPrice.SetMessage(priceInfo);
        BuyButton.Disabled = !canBuy;
    }

    private void SetEmptySelectionState()
    {
        SelectedIcon.Texture = null;
        SelectedName.Text = Loc.GetString("wh40k-vox-supplydrop-empty-title");
        SelectedDescription.SetMessage(Loc.GetString("wh40k-vox-supplydrop-empty-description"));
        SelectedPrice.SetMessage(string.Empty);
        BuyButton.Text = Loc.GetString("wh40k-vox-supplydrop-buy-button");
        BuyButton.Disabled = true;
    }

    private Texture? ResolveListingTexture(ListingDataWithCostModifiers listing)
    {
        if (listing.Icon != null)
            return _spriteSystem.Frame0(listing.Icon);

        if (listing.ProductEntity != null)
            return _spriteSystem.GetPrototypeIcon(listing.ProductEntity).Default;

        if (listing.ProductAction != null)
        {
            var actionId = _entityManager.Spawn(listing.ProductAction);
            Texture? texture = null;
            if (_actionsSystem.GetAction(actionId)?.Comp?.Icon is { } icon)
                texture = _spriteSystem.Frame0(icon);

            _entityManager.DeleteEntity(actionId);
            return texture;
        }

        return null;
    }

    private Texture? GetListingTexture(ListingDataWithCostModifiers listing)
    {
        if (_listingTextures.TryGetValue(listing, out var texture))
            return texture;

        texture = ResolveListingTexture(listing);
        _listingTextures[listing] = texture;
        return texture;
    }

    private string GetListingPriceString(ListingDataWithCostModifiers listing)
    {
        if (listing.Cost.Count < 1)
            return Loc.GetString("store-currency-free");

        var lines = listing.Cost.Select(cost =>
            Loc.GetString(
                "wh40k-vox-supplydrop-price-line",
                ("amount", FormatFundsWithPurchaseSymbol(cost.Value))));

        return string.Join("\n", lines);
    }

    private string GetDiscountString(ListingDataWithCostModifiers listing)
    {
        if (!listing.IsCostModified)
            return string.Empty;

        var modifiers = listing.GetModifiersSummaryRelative();
        if (modifiers.Count < 1)
            return string.Empty;

        if (modifiers.Count == 1)
        {
            var amount = modifiers.First().Value;
            return Loc.GetString("store-ui-discount-display", ("amount", amount.ToString("P0", CultureInfo.InvariantCulture)));
        }

        var parts = modifiers.Select(modifier =>
        {
            var currency = _prototype.Index(modifier.Key);
            return Loc.GetString(
                "store-ui-discount-display-with-currency",
                ("amount", modifier.Value.ToString("P0", CultureInfo.InvariantCulture)),
                ("currency", Loc.GetString(currency.DisplayName)));
        });

        return $"({string.Join(", ", parts)})";
    }

    private bool CanBuy(ListingDataWithCostModifiers listing)
    {
        if (!listing.CanBuyWith(Balance))
            return false;

        return _nextLaunchAt <= _timing.CurTime;
    }

    private void OnBuyButtonDown(BaseButton.ButtonEventArgs args)
    {
        if (_selectedListing == null || !CanBuy(_selectedListing))
            return;

        OnPurchasePressed?.Invoke(args, _selectedListing);
    }

    private static string FormatTime(TimeSpan time)
    {
        if (time.TotalHours >= 1)
            return time.ToString(@"hh\:mm\:ss");

        return time.ToString(@"mm\:ss");
    }

    private static string FormatFundsWithPurchaseSymbol(FixedPoint2 amount)
    {
        var wholeAmount = Math.Max(0, (int) Math.Ceiling(amount.Double()));
        return $"{PurchaseCurrencySymbol}{wholeAmount}";
    }

    private int GetDropAmount(ListingDataWithCostModifiers listing)
    {
        if (!_listingDropAmounts.TryGetValue(listing.ID, out var amount))
            return 1;

        return Math.Max(1, amount);
    }
}
