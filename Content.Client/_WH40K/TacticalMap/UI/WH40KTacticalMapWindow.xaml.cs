    public event Action<WH40KTacticalMapSaveAnnotationsMessage>? SaveAnnotationsPressed;

    public WH40KTacticalMapWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        BuildColorPalette();

        FilterBar.OnTextChanged += bar => OnFilterChanged(bar.Text);
        ToggleAlliesButton.OnPressed += _ =>
        {
            TacticalMapScreen.ShowAllies = !TacticalMapScreen.ShowAllies;
            RefreshOverlayUi();
        };
        ToggleAllyNamesButton.OnPressed += _ =>
        {
            TacticalMapScreen.ShowAllyNames = !TacticalMapScreen.ShowAllyNames;
            RefreshOverlayUi();
        };
        ToggleGridButton.OnPressed += _ =>
        {
            TacticalMapScreen.ShowChunkGrid = !TacticalMapScreen.ShowChunkGrid;
            RefreshOverlayUi();
        };
        ToggleCoordinatesButton.OnPressed += _ =>
        {
            TacticalMapScreen.ShowCursorCoordinates = !TacticalMapScreen.ShowCursorCoordinates;
            RefreshOverlayUi();
        };
        PanToolButton.OnPressed += _ => SetActiveTool(WH40KTacticalMapAnnotationTool.Pan);
        BrushToolButton.OnPressed += _ => SetActiveTool(WH40KTacticalMapAnnotationTool.Brush);
        EraserToolButton.OnPressed += _ => SetActiveTool(WH40KTacticalMapAnnotationTool.Eraser);
        RecenterButton.OnPressed += _ => TacticalMapScreen.ResetView();
        ReloadSavedButton.OnPressed += _ =>
        {
            TacticalMapScreen.ReloadSavedAnnotations();
            RefreshAnnotationUi();
        };
        ClearAnnotationsButton.OnPressed += _ =>
        {
            TacticalMapScreen.ClearWorkingAnnotations();
            RefreshAnnotationUi();
        };
        SaveAnnotationsButton.OnPressed += _ =>
        {
            if (!TacticalMapScreen.CanSaveAnnotations || !TacticalMapScreen.HasUnsavedAnnotations || TacticalMapScreen.IsSavePending)
                return;

            TacticalMapScreen.MarkSaveRequested();
            SaveAnnotationsPressed?.Invoke(TacticalMapScreen.BuildSaveMessage());
            RefreshAnnotationUi();
        };

        ThicknessSlider.OnValueChanged += _ => UpdateThickness((float) ThicknessSlider.Value);
        TacticalMapScreen.AnnotationStateChanged += RefreshAnnotationUi;
        TacticalMapScreen.ViewChanged += RefreshViewUi;

        UpdateThickness((float) ThicknessSlider.Value);
        SetAnnotationColor(Color.Red);
        SetActiveTool(WH40KTacticalMapAnnotationTool.Pan);
        ConfigureAnnotationMode(true);
        Relocalize();
        RefreshAnnotationUi();
        RefreshOverlayUi();
        RefreshViewUi();
    }

