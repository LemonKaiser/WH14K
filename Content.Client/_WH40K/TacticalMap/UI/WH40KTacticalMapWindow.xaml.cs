    public void Set(string gridName, EntityUid? mapUid, EntityUid tacticalMapUid, EntityUid? trackedEntity)
    {
        _latestGridName = gridName;
        var mapChanged = TacticalMapScreen.MapUid != mapUid;

        TacticalMapScreen.MapUid = mapUid;
        TacticalMapScreen.TacticalMapUid = tacticalMapUid;
        TacticalMapScreen.TrackedCoordinates.Clear();

        if (trackedEntity != null)
            TacticalMapScreen.TrackedCoordinates.Add(new EntityCoordinates(trackedEntity.Value, Vector2.Zero), (true, Color.Cyan));

        RefreshStationLabel();

        if (mapChanged)
        {
            TacticalMapScreen.ResetView();
            UpdateCapturePointList(mapUid, Array.Empty<WH40KTacticalMapCapturePointMarker>());
        }

        RefreshAnnotationUi();
        RefreshOverlayUi();
        RefreshViewUi();
    }

    public void ApplyState(WH40KTacticalMapBuiState state)
    {
        var mapUid = state.TargetGrid != NetEntity.Invalid ? _entMan.GetEntity(state.TargetGrid) : (EntityUid?) null;
        var trackedEntity = state.TrackedEntity != NetEntity.Invalid ? _entMan.GetEntity(state.TrackedEntity) : (EntityUid?) null;

        if (!string.IsNullOrWhiteSpace(state.SnapshotTexturePath))
            TacticalMapScreen.SnapshotTexturePath = new ResPath(state.SnapshotTexturePath);

        if (TacticalMapScreen.TacticalMapUid is { } tacticalMapUid)
            Set(state.GridName, mapUid, tacticalMapUid, trackedEntity);

        TacticalMapScreen.ApplyState(state);
        ConfigureAnnotationMode(state.CanAnnotate);
        UpdateCapturePointList(mapUid, state.CapturePoints);
        RefreshAnnotationUi();
        RefreshOverlayUi();
        RefreshViewUi();
    }

    public void ApplyOverlayState(WH40KTacticalMapOverlayState state)
    {
        TacticalMapScreen.ApplyOverlayState(state);
        UpdateCapturePointList(TacticalMapScreen.MapUid, state.CapturePoints);
        RefreshOverlayUi();
    }

    public void ApplyLiveRefreshState(WH40KTacticalMapLiveRefreshState state)
    {
        TacticalMapScreen.ApplyLiveRefreshState(state);
    }

    public void OnFilterChanged(string newFilter)
    {
        var visible = 0;

        foreach (var entry in _signalEntries)
        {
            entry.Visible = string.IsNullOrEmpty(newFilter) || (
                !string.IsNullOrEmpty(entry.SearchText) &&
                entry.SearchText.Contains(newFilter, StringComparison.OrdinalIgnoreCase));

            if (entry.Visible)
                visible++;
        }

        BeaconCountLabel.Text = visible.ToString();
    }

    public void UpdateCapturePointList(EntityUid? mapUid, IReadOnlyList<WH40KTacticalMapCapturePointMarker> capturePoints)
    {
        _latestMapUid = mapUid;
        _latestCapturePoints = new List<WH40KTacticalMapCapturePointMarker>(capturePoints);
        BeaconButtons.Children.Clear();
        _signalEntries.Clear();

        if (!mapUid.HasValue || capturePoints.Count == 0)
        {
            BeaconCountLabel.Text = "0";
            return;
        }

        foreach (var point in capturePoints)
        {
            var entry = new WH40KTacticalMapSignalEntry(mapUid.Value, point);
            entry.OnPressed += TacticalMapScreen.CenterToCoordinates;
            _signalEntries.Add(entry);
        }

        _signalEntries.Sort();

        foreach (var entry in _signalEntries)
        {
            BeaconButtons.AddChild(entry);
        }

        OnFilterChanged(FilterBar.Text);
    }

    private void BuildColorPalette()
    {
        foreach (var color in Palette)
        {
            var swatch = new ContainerButton
            {
                Group = _colorGroup,
                ToggleMode = true,
                MinSize = new Vector2(46f, 28f),
                HorizontalExpand = true,
                MuteSounds = true,
                StyleBoxOverride = CreateSwatchBorderStyle(false),
            };
            swatch.AddChild(new PanelContainer
            {
                PanelOverride = CreateSwatchFillStyle(color),
            });

            var capturedColor = color;
            swatch.OnToggled += args =>
            {
                if (!args.Pressed)
                    return;

                SetAnnotationColor(capturedColor);
            };

            ColorSwatches.AddChild(swatch);
            _colorButtons.Add((swatch, capturedColor));
        }
    }

    private void SetActiveTool(WH40KTacticalMapAnnotationTool tool)
    {
        if (!_annotationsEnabled)
            tool = WH40KTacticalMapAnnotationTool.Pan;

        PanToolButton.Pressed = tool == WH40KTacticalMapAnnotationTool.Pan;
        BrushToolButton.Pressed = tool == WH40KTacticalMapAnnotationTool.Brush;
        EraserToolButton.Pressed = tool == WH40KTacticalMapAnnotationTool.Eraser;
        TacticalMapScreen.SetAnnotationTool(tool);

        ToolSummaryLabel.Text = !_annotationsEnabled
            ? Loc.GetString("wh40k-tactical-map-tool-readonly-summary")
            : tool switch
        {
            WH40KTacticalMapAnnotationTool.Brush => Loc.GetString("wh40k-tactical-map-tool-brush-summary"),
            WH40KTacticalMapAnnotationTool.Eraser => Loc.GetString("wh40k-tactical-map-tool-eraser-summary"),
            _ => Loc.GetString("wh40k-tactical-map-tool-pan-summary")
        };

        MapModeBadgeLabel.Text = !_annotationsEnabled
            ? Loc.GetString("wh40k-tactical-map-mode-readonly")
            : tool switch
        {
            WH40KTacticalMapAnnotationTool.Brush => Loc.GetString("wh40k-tactical-map-mode-brush"),
            WH40KTacticalMapAnnotationTool.Eraser => Loc.GetString("wh40k-tactical-map-mode-eraser"),
            _ => Loc.GetString("wh40k-tactical-map-mode-active")
        };
    }

    private void UpdateThickness(float thickness)
    {
        TacticalMapScreen.SetAnnotationThickness(thickness);
        ThicknessValue.Text = $"{thickness:0.00}";
    }

    private void SetAnnotationColor(Color color)
    {
        TacticalMapScreen.SetAnnotationColor(color);
        CurrentColorLabel.Text = color.ToHexNoAlpha();
        CurrentColorPreview.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = color,
            BorderColor = AccentBorderBrightColor,
            BorderThickness = new Thickness(1),
        };

        UpdateColorPaletteSelection(color);
    }

    private void UpdateColorPaletteSelection(Color selectedColor)
    {
        foreach (var (button, color) in _colorButtons)
        {
            var selected = color.Equals(selectedColor);
            button.Pressed = selected;
            button.StyleBoxOverride = CreateSwatchBorderStyle(selected);
        }
    }

    private void RefreshAnnotationUi()
    {
        if (!_annotationsEnabled)
        {
            SaveAnnotationsButton.Disabled = true;
            ClearAnnotationsButton.Disabled = true;
            ReloadSavedButton.Disabled = true;

            AnnotationsStatus.Text = Loc.GetString("wh40k-tactical-map-annotations-view-only");
            OverlaySyncLabel.Text = Loc.GetString("wh40k-tactical-map-sync-view-only");
            SyncBadgeLabel.Text = Loc.GetString("wh40k-tactical-map-sync-badge-view");
            DraftBadgeLabel.Text = string.Empty;
            SyncBadge.PanelOverride = CreateBadgeStyle(
                OriginalViewOnlyPanelColor,
                OriginalViewOnlyBorderColor);
            return;
        }

        var canSave = TacticalMapScreen.CanSaveAnnotations;
        var dirty = TacticalMapScreen.HasUnsavedAnnotations;
        var remoteDirty = TacticalMapScreen.HasRemoteAnnotationChanges;
        var savePending = TacticalMapScreen.IsSavePending;

        SaveAnnotationsButton.Disabled = !canSave || !dirty || savePending;
        ClearAnnotationsButton.Disabled = !TacticalMapScreen.HasAnyWorkingAnnotations;
        ReloadSavedButton.Disabled = !dirty && !TacticalMapScreen.HasSavedAnnotations && !remoteDirty;

        AnnotationsStatus.Text = !canSave
            ? Loc.GetString("wh40k-tactical-map-annotations-local-only")
            : savePending
                ? Loc.GetString("wh40k-tactical-map-annotations-save-pending")
                : remoteDirty && dirty
                    ? Loc.GetString("wh40k-tactical-map-annotations-server-changed")
                    : dirty
                        ? Loc.GetString("wh40k-tactical-map-annotations-unsaved")
                        : Loc.GetString("wh40k-tactical-map-annotations-saved");

        OverlaySyncLabel.Text = canSave
            ? Loc.GetString("wh40k-tactical-map-sync-ready")
            : Loc.GetString("wh40k-tactical-map-sync-missing");
        SyncBadgeLabel.Text = canSave
            ? Loc.GetString("wh40k-tactical-map-sync-badge-team")
            : Loc.GetString("wh40k-tactical-map-sync-badge-local");
        DraftBadgeLabel.Text = savePending
            ? Loc.GetString("wh40k-tactical-map-draft-badge-pending")
            : remoteDirty
                ? Loc.GetString("wh40k-tactical-map-draft-badge-server")
                : dirty
                    ? Loc.GetString("wh40k-tactical-map-draft-badge-dirty")
                    : Loc.GetString("wh40k-tactical-map-draft-badge-saved");

        SyncBadge.PanelOverride = CreateBadgeStyle(
            canSave ? OriginalSuccessPanelColor : OriginalLocalOnlyPanelColor,
            canSave ? OriginalSuccessBorderColor : OriginalLocalOnlyBorderColor);

        DraftBadge.PanelOverride = CreateBadgeStyle(
            savePending
                ? OriginalPendingPanelColor
                : remoteDirty
                    ? OriginalRemotePanelColor
                    : dirty
                        ? OriginalDirtyPanelColor
                        : OriginalSuccessPanelColor,
            savePending
                ? OriginalPendingBorderColor
                : remoteDirty
                    ? OriginalRemoteBorderColor
                    : dirty
                        ? OriginalDirtyBorderColor
                        : OriginalSuccessBorderColor);
    }

    private void ConfigureAnnotationMode(bool canAnnotate)
    {
        _annotationsEnabled = canAnnotate;
        TacticalMapScreen.AnnotationsEnabled = canAnnotate;

        LeftRail.SetWidth = LeftRailWidth;
        HeaderTitleLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-header-title"
            : "wh40k-tactical-map-header-title-readonly");
        HeaderSubtitleLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-header-subtitle"
            : "wh40k-tactical-map-header-subtitle-readonly");
        LeftTitleLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-left-title"
            : "wh40k-tactical-map-left-title-readonly");
        LeftSubtitleLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-left-subtitle"
            : "wh40k-tactical-map-left-subtitle-readonly");
        ViewportSubtitleLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-viewport-subtitle"
            : "wh40k-tactical-map-viewport-subtitle-readonly");
        FooterLeftLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-footer-left"
            : "wh40k-tactical-map-footer-left-readonly");
        FooterRightLabel.Text = Loc.GetString(canAnnotate
            ? "wh40k-tactical-map-footer-right"
            : "wh40k-tactical-map-footer-right-readonly");
        AnnotationControlsStack.Visible = canAnnotate;
        AnnotationActionsPanel.Visible = canAnnotate;
        ToolsPanel.Visible = canAnnotate;
        ColorPanel.Visible = canAnnotate;
        ThicknessPanel.Visible = canAnnotate;
        ReloadSavedButton.Visible = canAnnotate;
        ClearAnnotationsButton.Visible = canAnnotate;
        SaveAnnotationsButton.Visible = canAnnotate;
        DraftBadge.Visible = canAnnotate;

        SetActiveTool(canAnnotate ? TacticalMapScreen.AnnotationTool : WH40KTacticalMapAnnotationTool.Pan);
    }

    private void RefreshOverlayUi()
    {
        var allyCount = TacticalMapScreen.AlliedMarkerCount;
        ToggleAlliesButton.Text = TacticalMapScreen.ShowAllies
            ? Loc.GetString("wh40k-tactical-map-toggle-allies-on", ("count", allyCount))
            : Loc.GetString("wh40k-tactical-map-toggle-allies-off", ("count", allyCount));
        ToggleAllyNamesButton.Text = TacticalMapScreen.ShowAllyNames
            ? Loc.GetString("wh40k-tactical-map-toggle-ally-names-on")
            : Loc.GetString("wh40k-tactical-map-toggle-ally-names-off");

        var chunkSize = Math.Max(1, TacticalMapScreen.FogChunkSize);
        ToggleGridButton.Text = TacticalMapScreen.ShowChunkGrid
            ? Loc.GetString("wh40k-tactical-map-toggle-grid-on", ("size", chunkSize))
            : Loc.GetString("wh40k-tactical-map-toggle-grid-off", ("size", chunkSize));
        ToggleCoordinatesButton.Text = TacticalMapScreen.ShowCursorCoordinates
            ? Loc.GetString("wh40k-tactical-map-toggle-coordinates-on")
            : Loc.GetString("wh40k-tactical-map-toggle-coordinates-off");
    }

    private void RefreshViewUi()
    {
        ZoomValueLabel.Text = $"{TacticalMapScreen.ZoomFactor:0.00}x";
        RecenterButton.Disabled = TacticalMapScreen.MapUid == null;
    }

    private void RefreshStationLabel()
    {
        StationName.Text = string.IsNullOrWhiteSpace(_latestGridName)
            ? Loc.GetString("station-map-unknown-station")
            : _latestGridName;
    }

    private static StyleBoxFlat CreateBadgeStyle(Color background, Color border)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 10,
            ContentMarginTopOverride = 4,
            ContentMarginRightOverride = 10,
            ContentMarginBottomOverride = 4,
        };
    }

    private static StyleBoxFlat CreateSwatchBorderStyle(bool selected)
    {
        var borderThickness = selected ? 2 : 1;
        var inset = selected ? 2 : 1;
        return new StyleBoxFlat
        {
            BackgroundColor = Color.Transparent,
            BorderColor = selected ? AccentBorderBrightColor : AccentBorderSoftColor,
            BorderThickness = new Thickness(borderThickness),
            ContentMarginLeftOverride = inset,
            ContentMarginTopOverride = inset,
            ContentMarginRightOverride = inset,
            ContentMarginBottomOverride = inset,
        };
    }

    private static StyleBoxFlat CreateSwatchFillStyle(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
            BorderColor = Color.Transparent,
            BorderThickness = new Thickness(0),
            ContentMarginLeftOverride = 0,
            ContentMarginTopOverride = 0,
            ContentMarginRightOverride = 0,
            ContentMarginBottomOverride = 0,
        };
    }

    [Obsolete]
    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            TacticalMapScreen.AnnotationStateChanged -= RefreshAnnotationUi;
            TacticalMapScreen.ViewChanged -= RefreshViewUi;
        }

#pragma warning disable CS0618
        base.Dispose(disposing);
#pragma warning restore CS0618
    }
}
