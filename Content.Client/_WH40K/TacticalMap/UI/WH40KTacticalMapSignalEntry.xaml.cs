using System;
using Content.Shared._WH40K.TacticalMap;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Map;
using Robust.Shared.Maths;

namespace Content.Client._WH40K.TacticalMap.UI;

[GenerateTypedNameReferences]
public sealed partial class WH40KTacticalMapSignalEntry : Control, IComparable<WH40KTacticalMapSignalEntry>
{
    public readonly EntityCoordinates TargetCoordinates;
    public Action<EntityCoordinates>? OnPressed;
    public string SearchText { get; }
    public string? Label => TitleLabel.Text;

    public WH40KTacticalMapSignalEntry(EntityUid mapUid, WH40KTacticalMapCapturePointMarker marker)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var title = WH40KTacticalMapLoc.LocalizeStrategicLabel(marker);
        var ownerName = WH40KTacticalMapLoc.LocalizeTeamName(marker.OwnerTeamId, marker.OwnerDisplayName);
        var capturingName = WH40KTacticalMapLoc.LocalizeTeamName(marker.CapturingTeamId, marker.CapturingDisplayName);

        TargetCoordinates = new EntityCoordinates(mapUid, marker.Position);
        SearchText = $"{title} {marker.Label} {ownerName} {capturingName} {marker.OwnerDisplayName} {marker.CapturingDisplayName}".Trim();

        AccentPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = ResolveAccentColor(marker),
        };

        TitleLabel.Text = title.ToUpperInvariant();
        StatusLabel.Text = BuildStatusText(marker, ownerName, capturingName);
        MainButton.OnPressed += _ => OnPressed?.Invoke(TargetCoordinates);
    }

    public int CompareTo(WH40KTacticalMapSignalEntry? other)
    {
        if (other == null)
            return 1;

        return string.Compare(Label, other.Label, StringComparison.OrdinalIgnoreCase);
    }

    private static string BuildStatusText(
        WH40KTacticalMapCapturePointMarker marker,
        string ownerName,
        string capturingName)
    {
        var rewardText = marker.FrontReward > 0
            ? Loc.GetString("wh40k-tactical-map-front-reward-short", ("reward", marker.FrontReward))
            : string.Empty;

        if (marker.Kind == WH40KTacticalMapStrategicMarkerKind.CommandNode)
        {
            var teamName = string.IsNullOrWhiteSpace(ownerName)
                ? marker.OwnerDisplayName
                : ownerName;

            return marker.Relation switch
            {
                WH40KTacticalMapStrategicRelation.Allied => Loc.GetString(
                    "wh40k-tactical-map-command-node-status-allied",
                    ("reward", rewardText)),
                WH40KTacticalMapStrategicRelation.Hostile => Loc.GetString(
                    "wh40k-tactical-map-command-node-status-hostile",
                    ("team", teamName),
                    ("reward", rewardText)),
                _ => Loc.GetString(
                    "wh40k-tactical-map-command-node-status-neutral",
                    ("reward", rewardText))
            };
        }

        if (!string.IsNullOrWhiteSpace(marker.CapturingTeamId) && marker.CaptureProgress > 0f)
        {
            var progressPercent = (int) MathF.Round(marker.CaptureProgress * 100f);
            var teamName = string.IsNullOrWhiteSpace(capturingName)
                ? marker.CapturingDisplayName
                : capturingName;

            return marker.Contested
                ? Loc.GetString(
                    "wh40k-tactical-map-point-status-contested",
                    ("team", teamName),
                    ("progress", progressPercent),
                    ("reward", rewardText))
                : Loc.GetString(
                    "wh40k-tactical-map-point-status-capturing",
                    ("team", teamName),
                    ("progress", progressPercent),
                    ("reward", rewardText));
        }

        if (!string.IsNullOrWhiteSpace(marker.OwnerTeamId))
        {
            var teamName = string.IsNullOrWhiteSpace(ownerName)
                ? marker.OwnerDisplayName
                : ownerName;

            return Loc.GetString(
                "wh40k-tactical-map-point-status-held",
                ("team", teamName),
                ("reward", rewardText));
        }

        return Loc.GetString("wh40k-tactical-map-point-status-neutral", ("reward", rewardText));
    }

    private static Color ResolveAccentColor(WH40KTacticalMapCapturePointMarker marker)
    {
        if (!string.IsNullOrWhiteSpace(marker.CapturingTeamId))
            return marker.CapturingColor;

        if (!string.IsNullOrWhiteSpace(marker.OwnerTeamId))
            return marker.OwnerColor;

        return Color.FromHex("#B7C1CF".AsSpan());
    }
}
