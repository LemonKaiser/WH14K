    private void RefreshState()
    {
        if (_state == null)
            return;

        var state = _state;

        StatusValueLabel.Text = Loc.GetString(GetStatusLocKey(state.Status));
        TierValueLabel.Text = Loc.GetString(
            "wh40k-ore-extractor-ui-tier-card-value",
            ("tier", state.CurrentTier),
            ("level", state.EffectiveLevel));
        YieldValueLabel.Text = Loc.GetString(
            "wh40k-ore-extractor-ui-cycle-card-value",
            ("count", state.SpawnCount),
            ("seconds", FormatSeconds(state.SpawnIntervalSeconds)));

        SetWrappedText(StatusHintLabel, Loc.GetString(GetStatusHintLocKey(state.Status)), _theme.SecondaryText);
        SetWrappedText(TierHintLabel, BuildTierHintText(state), ResolveTierHintColor(state));
        SetWrappedText(YieldHintLabel, BuildYieldHintText(state), ResolveYieldHintColor(state));
        SetWrappedText(ModeValueLabel, BuildModeText(state), state.SelectedOreId == null ? _theme.Accent : _theme.PrimaryText);
        ModeBadge.PanelOverride = WH40KOreExtractorStyles.CreateBadgeStyle(
            _theme.PanelAltBackground,
            (state.SelectedOreId == null ? _theme.Accent : _theme.SuccessAccent).WithAlpha(0.8f),
            10,
            6);

        ApplyStatusCard(state.Status);
        ApplyMetricCards(state);
        RefreshActionButtons(state);
        RebuildOreButtons(state);
    }

    private void ApplyStatusCard(WH40KOreExtractorUiStatus status)
    {
        var accent = ResolveStatusColor(status);
        StatusCard.PanelOverride = WH40KOreExtractorStyles.CreatePanelStyle(_theme.PanelAltBackground, accent.WithAlpha(0.82f), 0);
        StatusValueLabel.FontColorOverride = accent;
    }

    private void ApplyMetricCards(WH40KOreExtractorBuiState state)
    {
        var tierAccent = state.NextTierLevel > 0 ? _theme.Accent : _theme.SuccessAccent;
        TierCard.PanelOverride = WH40KOreExtractorStyles.CreatePanelStyle(_theme.PanelAltBackground, tierAccent.WithAlpha(0.8f), 0);

        var yieldAccent = state.Status == WH40KOreExtractorUiStatus.Ready
            ? _theme.SuccessAccent
            : ResolveStatusColor(state.Status);
        YieldCard.PanelOverride = WH40KOreExtractorStyles.CreatePanelStyle(_theme.PanelAltBackground, yieldAccent.WithAlpha(0.78f), 0);

        OrePanel.PanelOverride = WH40KOreExtractorStyles.CreatePanelStyle(_theme.PanelBackground, tierAccent.WithAlpha(0.7f), 0);
    }

    private void RefreshActionButtons(WH40KOreExtractorBuiState? state)
    {
        var enabled = state?.Enabled ?? false;
        var hasOres = (state?.OreEntries.Length ?? 0) > 0;

        ToggleExtractionButton.Text = Loc.GetString(enabled
            ? "wh40k-ore-extractor-ui-button-stop"
            : "wh40k-ore-extractor-ui-button-start");
        WH40KOreExtractorStyles.ApplyButtonTheme(
            ToggleExtractionButton,
            enabled
                ? WH40KOreExtractorStyles.CreateDangerButtonStyle(_theme)
                : WH40KOreExtractorStyles.CreatePrimaryButtonStyle(_theme),
            _theme.PrimaryText);

        SetRandomModeButton.Disabled = !hasOres;
        WH40KOreExtractorStyles.ApplyButtonTheme(
            SetRandomModeButton,
            state?.SelectedOreId == null
                ? WH40KOreExtractorStyles.CreatePrimaryButtonStyle(_theme)
                : WH40KOreExtractorStyles.CreateSecondaryButtonStyle(_theme),
            SetRandomModeButton.Disabled ? _theme.SecondaryText : _theme.PrimaryText);
    }

    private void RebuildOreButtons(WH40KOreExtractorBuiState state)
    {
        OreButtonsGrid.RemoveAllChildren();

        var hasOres = state.OreEntries.Length > 0;
        OreEmptyLabel.Visible = !hasOres;
        OreScrollContainer.Visible = hasOres;

        if (!hasOres)
            return;

        foreach (var oreEntry in state.OreEntries)
        {
            var oreName = GetOreDisplayName(oreEntry.OreId);
            var isLocked = oreEntry.UnlockTier > state.CurrentTier;
            var isSelected = !isLocked && string.Equals(state.SelectedOreId, oreEntry.OreId, StringComparison.Ordinal);

            var oreButton = new Button
            {
                HorizontalExpand = true,
                MinHeight = 40,
                Text = oreName,
                ToolTip = BuildOreTooltip(oreEntry, oreName, isLocked, isSelected),
            };

            oreButton.Label.ClipText = true;

            if (!isLocked)
                oreButton.OnPressed += _ => OnOreSelected?.Invoke(oreEntry.OreId);

            if (isSelected)
            {
                WH40KOreExtractorStyles.ApplyButtonTheme(
                    oreButton,
                    WH40KOreExtractorStyles.CreatePrimaryButtonStyle(_theme),
                    _theme.PrimaryText);
            }
            else if (isLocked)
            {
                WH40KOreExtractorStyles.ApplyButtonTheme(
                    oreButton,
                    WH40KOreExtractorStyles.CreateLockedButtonStyle(_theme),
                    _theme.SecondaryText);
            }
            else
            {
                WH40KOreExtractorStyles.ApplyButtonTheme(
                    oreButton,
                    WH40KOreExtractorStyles.CreateSecondaryButtonStyle(_theme),
                    _theme.PrimaryText);
            }

            OreButtonsGrid.AddChild(oreButton);
        }
    }

    private string BuildModeText(WH40KOreExtractorBuiState state)
    {
        return state.SelectedOreId == null
            ? Loc.GetString("wh40k-ore-extractor-ui-selected-ore-random")
            : Loc.GetString("wh40k-ore-extractor-ui-mode-focused", ("ore", GetOreDisplayName(state.SelectedOreId)));
    }

    private string BuildTierHintText(WH40KOreExtractorBuiState state)
    {
        if (state.NextTierLevel <= 0)
            return Loc.GetString("wh40k-ore-extractor-ui-tier-next-max");

        return Loc.GetString(
            "wh40k-ore-extractor-ui-tier-next-value",
            ("tier", state.CurrentTier + 1),
            ("level", state.NextTierLevel),
            ("remaining", state.RemainingToNextTier));
    }

    private string BuildYieldHintText(WH40KOreExtractorBuiState state)
    {
        if (state.Status != WH40KOreExtractorUiStatus.Ready)
            return Loc.GetString(GetStatusHintLocKey(state.Status));

        return state.NextSpawnSeconds <= 0
            ? Loc.GetString("wh40k-ore-extractor-ui-next-cycle-ready")
            : Loc.GetString("wh40k-ore-extractor-ui-next-cycle-value", ("seconds", state.NextSpawnSeconds));
    }

    private string BuildOreTooltip(WH40KOreExtractorUiOreEntry oreEntry, string oreName, bool isLocked, bool isSelected)
    {
        string tooltip;

        if (isLocked)
        {
            tooltip = Loc.GetString(
                "wh40k-ore-extractor-ui-ore-button-tooltip-locked",
                ("ore", oreName),
                ("tier", oreEntry.UnlockTier));
        }
        else if (isSelected)
        {
            tooltip = Loc.GetString("wh40k-ore-extractor-ui-ore-button-tooltip-selected", ("ore", oreName));
        }
        else
        {
            tooltip = Loc.GetString("wh40k-ore-extractor-ui-ore-button-tooltip", ("ore", oreName));
        }

        return NormalizeMultilineText(tooltip);
    }

    private string GetOreDisplayName(string oreId)
    {
        if (!_prototype.TryIndex<OrePrototype>(oreId, out var ore) ||
            ore.OreEntity is not { } oreEntity ||
            !_prototype.TryIndex<EntityPrototype>(oreEntity, out var oreEntityPrototype))
        {
            return oreId;
        }

        return ResolveLocalizedOrRaw(oreEntityPrototype.Name);
    }

    private string ResolveLocalizedOrRaw(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return string.Empty;

        if (_localization.TryGetString(value, out var localized) && !string.IsNullOrWhiteSpace(localized))
            return localized!;

        return value;
    }

    private Color ResolveStatusColor(WH40KOreExtractorUiStatus status)
    {
        return status switch
        {
            WH40KOreExtractorUiStatus.Ready => _theme.SuccessAccent,
            WH40KOreExtractorUiStatus.Disabled => _theme.WarningAccent,
            WH40KOreExtractorUiStatus.OutputBlocked => _theme.WarningAccent,
            WH40KOreExtractorUiStatus.OutputSaturated => _theme.WarningAccent,
            WH40KOreExtractorUiStatus.Unpowered => _theme.DangerAccent,
            WH40KOreExtractorUiStatus.NoOutput => _theme.DangerAccent,
            WH40KOreExtractorUiStatus.NoConfiguredOres => _theme.DangerAccent,
            _ => _theme.PrimaryText,
        };
    }

    private Color ResolveTierHintColor(WH40KOreExtractorBuiState state)
    {
        return state.NextTierLevel > 0
            ? _theme.SecondaryText
            : _theme.SuccessAccent;
    }

    private Color ResolveYieldHintColor(WH40KOreExtractorBuiState state)
    {
        if (state.Status != WH40KOreExtractorUiStatus.Ready)
            return ResolveStatusColor(state.Status);

        return state.NextSpawnSeconds <= 0
            ? _theme.Accent
            : _theme.SecondaryText;
    }

