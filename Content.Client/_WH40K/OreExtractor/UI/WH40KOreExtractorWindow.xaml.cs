    {
        return status switch
        {
            WH40KOreExtractorUiStatus.Ready => "wh40k-ore-extractor-ui-status-ready",
            WH40KOreExtractorUiStatus.Disabled => "wh40k-ore-extractor-ui-status-disabled",
            WH40KOreExtractorUiStatus.Unpowered => "wh40k-ore-extractor-ui-status-unpowered",
            WH40KOreExtractorUiStatus.OutputBlocked => "wh40k-ore-extractor-ui-status-output-blocked",
            WH40KOreExtractorUiStatus.OutputSaturated => "wh40k-ore-extractor-ui-status-output-saturated",
            WH40KOreExtractorUiStatus.NoOutput => "wh40k-ore-extractor-ui-status-no-output",
            WH40KOreExtractorUiStatus.NoConfiguredOres => "wh40k-ore-extractor-ui-status-no-ores",
            _ => "wh40k-ore-extractor-ui-status-disabled",
        };
    }

    private static string GetStatusHintLocKey(WH40KOreExtractorUiStatus status)
    {
        return status switch
        {
            WH40KOreExtractorUiStatus.Ready => "wh40k-ore-extractor-ui-status-hint-ready",
            WH40KOreExtractorUiStatus.Disabled => "wh40k-ore-extractor-ui-status-hint-disabled",
            WH40KOreExtractorUiStatus.Unpowered => "wh40k-ore-extractor-ui-status-hint-unpowered",
            WH40KOreExtractorUiStatus.OutputBlocked => "wh40k-ore-extractor-ui-status-hint-output-blocked",
            WH40KOreExtractorUiStatus.OutputSaturated => "wh40k-ore-extractor-ui-status-hint-output-saturated",
            WH40KOreExtractorUiStatus.NoOutput => "wh40k-ore-extractor-ui-status-hint-no-output",
            WH40KOreExtractorUiStatus.NoConfiguredOres => "wh40k-ore-extractor-ui-status-hint-no-ores",
            _ => "wh40k-ore-extractor-ui-status-hint-disabled",
        };
    }

    private static string FormatSeconds(float seconds)
    {
        return Math.Max(0.1f, seconds).ToString("0.#", CultureInfo.InvariantCulture);
    }

    private static void SetWrappedText(RichTextLabel label, string text, Color color)
    {
        label.SetMessage(NormalizeMultilineText(text), defaultColor: color);
    }

    private static string NormalizeMultilineText(string text)
    {
        return text.Replace("\\n", "\n", StringComparison.Ordinal);
    }

    private static Color Blend(Color from, Color to, float amount)
    {
        amount = Math.Clamp(amount, 0f, 1f);
        return new Color(
            from.R + (to.R - from.R) * amount,
            from.G + (to.G - from.G) * amount,
            from.B + (to.B - from.B) * amount,
            from.A + (to.A - from.A) * amount);
    }
