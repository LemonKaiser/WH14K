    public WH40KOreExtractorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ToggleExtractionButton.OnPressed += _ => OnSetEnabledPressed?.Invoke(!(_state?.Enabled ?? false));
        SetRandomModeButton.OnPressed += _ => OnSetRandomModePressed?.Invoke();

        ApplyTheme();
    }

    public void Relocalize()
    {
        ApplyTheme();
        if (_state != null)
            RefreshState();
    }

    public void ApplyState(WH40KOreExtractorBuiState state)
    {
        var previousState = _state;
        _state = state;

        var resolvedTheme = WH40KOreExtractorStyles.ResolveTheme(state.ThemeTeamId);
        var themeChanged = !resolvedTheme.Equals(_theme);
        if (themeChanged)
        {
            _theme = resolvedTheme;
            ApplyTheme();
        }

        if (previousState == null || themeChanged)
        {
            RefreshState();
            return;
        }

        if (HasNonTimerUiChanges(previousState, state))
        {
            RefreshState();
            return;
        }

        if (previousState.NextSpawnSeconds != state.NextSpawnSeconds)
            RefreshYieldHint(state);
    }

    private static bool HasNonTimerUiChanges(WH40KOreExtractorBuiState previous, WH40KOreExtractorBuiState next)
    {
        return !string.Equals(previous.ThemeTeamId, next.ThemeTeamId, StringComparison.Ordinal) ||
               !string.Equals(previous.OutputDirectionLocKey, next.OutputDirectionLocKey, StringComparison.Ordinal) ||
               !string.Equals(previous.SelectedOreId, next.SelectedOreId, StringComparison.Ordinal) ||
               previous.Status != next.Status ||
               previous.Enabled != next.Enabled ||
               previous.Powered != next.Powered ||
               previous.RequirePowered != next.RequirePowered ||
               previous.HasOutputTile != next.HasOutputTile ||
               previous.OutputOccupancy != next.OutputOccupancy ||
               previous.MaxItemsOnOutputTile != next.MaxItemsOnOutputTile ||
               previous.CurrentTier != next.CurrentTier ||
               previous.EffectiveLevel != next.EffectiveLevel ||
               previous.NodeUpgradeBonus != next.NodeUpgradeBonus ||
               previous.NextTierLevel != next.NextTierLevel ||
               previous.RemainingToNextTier != next.RemainingToNextTier ||
               !AreNearlyEqual(previous.SpawnIntervalSeconds, next.SpawnIntervalSeconds) ||
               previous.SpawnCount != next.SpawnCount ||
               !AreEquivalent(previous.TrackedTeamIds, next.TrackedTeamIds) ||
               !AreEquivalent(previous.AllowedOreIds, next.AllowedOreIds) ||
               !AreEquivalent(previous.OreEntries, next.OreEntries);
    }

    private static bool AreEquivalent(string[] left, string[] right)
    {
        if (ReferenceEquals(left, right))
            return true;

        if (left.Length != right.Length)
            return false;

        for (var i = 0; i < left.Length; i++)
        {
            if (!string.Equals(left[i], right[i], StringComparison.Ordinal))
                return false;
        }

        return true;
    }

    private static bool AreEquivalent(WH40KOreExtractorUiOreEntry[] left, WH40KOreExtractorUiOreEntry[] right)
    {
        if (ReferenceEquals(left, right))
            return true;

        if (left.Length != right.Length)
            return false;

        for (var i = 0; i < left.Length; i++)
        {
            if (!string.Equals(left[i].OreId, right[i].OreId, StringComparison.Ordinal) ||
                left[i].UnlockTier != right[i].UnlockTier)
            {
                return false;
            }
        }

        return true;
    }

    private static bool AreNearlyEqual(float left, float right)
    {
        return Math.Abs(left - right) <= FloatComparisonEpsilon;
    }

    private void RefreshYieldHint(WH40KOreExtractorBuiState state)
    {
        SetWrappedText(YieldHintLabel, BuildYieldHintText(state), ResolveYieldHintColor(state));
    }

