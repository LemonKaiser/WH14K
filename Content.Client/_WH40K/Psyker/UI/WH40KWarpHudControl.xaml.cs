using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WH40K.Psyker.UI;

[GenerateTypedNameReferences]
public sealed partial class WH40KWarpHudControl : Control
{
    private readonly StyleBoxFlat _warpChargeBarStyle = new();
    private readonly StyleBoxFlat _warpInstabilityBarStyle = new();
    private readonly StyleBoxFlat _barBackgroundStyle = new();

    public WH40KWarpHudControl()
    {
        RobustXamlLoader.Load(this);

        LayoutContainer.SetAnchorPreset(WarpChargeBar, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(WarpChargeValueLabel, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(WarpInstabilityBar, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetAnchorPreset(WarpInstabilityValueLabel, LayoutContainer.LayoutPreset.Wide);

        _barBackgroundStyle.BackgroundColor = Color.FromHex("#161b2a");
        _barBackgroundStyle.BorderThickness = new Thickness(0f);

        WarpChargeBar.BackgroundStyleBoxOverride = _barBackgroundStyle;
        WarpInstabilityBar.BackgroundStyleBoxOverride = _barBackgroundStyle;

        _warpChargeBarStyle.BackgroundColor = Color.FromHex("#2f77dc");
        _warpInstabilityBarStyle.BackgroundColor = Color.FromHex("#2f77dc");
        _warpChargeBarStyle.BorderThickness = new Thickness(0f);
        _warpInstabilityBarStyle.BorderThickness = new Thickness(0f);
        WarpChargeBar.ForegroundStyleBoxOverride = _warpChargeBarStyle;
        WarpInstabilityBar.ForegroundStyleBoxOverride = _warpInstabilityBarStyle;

        WarpChargeValueLabel.Align = Label.AlignMode.Center;
        WarpInstabilityValueLabel.Align = Label.AlignMode.Center;
    }

    public void ApplyState(WH40KWarpHudViewState state)
    {
        Visible = state.Visible;
        if (!Visible)
            return;

        WarpChargeValueLabel.Text = state.WarpChargeText;
        WarpInstabilityValueLabel.Text = state.WarpInstabilityText;

        WarpChargeBar.Value = state.WarpChargeFraction;
        WarpInstabilityBar.Value = state.WarpInstabilityFraction;

        var roleColor = state.ChaosTheme
            ? Color.FromHex("#c23c3c")
            : Color.FromHex("#2f77dc");

        _warpChargeBarStyle.BackgroundColor = roleColor;
        _warpInstabilityBarStyle.BackgroundColor = roleColor;
    }
}
