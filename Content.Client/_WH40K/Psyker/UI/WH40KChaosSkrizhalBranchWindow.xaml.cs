    private WH40KChaosSkrizhalPatronBranchBuiState? _state;
    private int _activeUpgradeSlot = 4;

    public event Action<int>? SelectPrimaryRequested;
    public event Action<int>? UnlockRequested;
    public event Action<int, WH40KChaosGiftUpgradePath, int>? UpgradeTierRequested;
    public event Action<int>? UnlockExRequested;

    public WH40KChaosSkrizhalBranchWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entityManager.System<SpriteSystem>();

        LevelProgressBar.BackgroundStyleBoxOverride = _progressBackgroundStyle;
        LevelProgressBar.ForegroundStyleBoxOverride = _progressForegroundStyle;

        AbilitiesHeaderLabel.Text = Loc.GetString("wh40k-chaos-branch-abilities-header");
        TreeHeaderLabel.Text = Loc.GetString("wh40k-chaos-branch-tree-header");
        TreeEmptyLabel.Text = Loc.GetString("wh40k-chaos-branch-tree-empty");

        GiftOneCardButton.OnPressed += _ => OnGiftCardPressed(1);
        GiftTwoCardButton.OnPressed += _ => OnGiftCardPressed(2);
        GiftThreeCardButton.OnPressed += _ => OnGiftCardPressed(3);
        PassiveCardButton.OnPressed += _ => OnPassiveCardPressed();
        GiftTreeControl.UpgradeNodePressed += OnUpgradeNodePressed;
        GiftTreeControl.UpgradeExPressed += OnUpgradeExPressed;
    }

    public void ApplyState(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        _state = state;

        if (_activeUpgradeSlot is > 0 and <= 3 && !IsGiftSlotUnlocked(state, _activeUpgradeSlot))
            _activeUpgradeSlot = 0;

        var patronLoc = Loc.GetString(GetPatronLocKey(state.Patron));
        var xpProgress = state.NextLevelXp <= 0f
            ? 1f
            : Math.Clamp(state.LevelXp / state.NextLevelXp, 0f, 1f);

        PatronLabel.Text = Loc.GetString("wh40k-chaos-branch-patron", ("patron", patronLoc));
        BranchTitleLabel.Text = Loc.GetString(GetBranchTitleKey(state.Patron));
        LevelLabel.Text = Loc.GetString("wh40k-chaos-branch-level", ("level", state.Level), ("max", state.MaxLevel));
        XpLabel.Text = Loc.GetString("wh40k-chaos-branch-xp", ("current", MathF.Round(state.LevelXp, 1)), ("next", MathF.Round(state.NextLevelXp, 1)));
        DevelopmentPointsLabel.Text = Loc.GetString("wh40k-chaos-branch-dev-points", ("points", state.DevelopmentPoints));
        SoulsOfferedLabel.Text = Loc.GetString("wh40k-chaos-branch-souls", ("patron", patronLoc), ("count", state.PatronSoulOfferCount));
        PassiveIncomeLabel.Text = Loc.GetString(
            "wh40k-chaos-branch-passive-income",
            ("xp", MathF.Round(state.PassiveXpPerTick, 1)),
            ("seconds", state.PassiveXpIntervalSeconds));
        LevelProgressBar.Value = xpProgress;
        UpdateProgressAccent(state.Patron);

        ApplyGiftCardState(1, state, GiftOneTitleLabel, GiftOneDescriptionLabel, GiftOneStatusLabel, GiftOneCardButton, GiftOneIcon);
        ApplyGiftCardState(2, state, GiftTwoTitleLabel, GiftTwoDescriptionLabel, GiftTwoStatusLabel, GiftTwoCardButton, GiftTwoIcon);
        ApplyGiftCardState(3, state, GiftThreeTitleLabel, GiftThreeDescriptionLabel, GiftThreeStatusLabel, GiftThreeCardButton, GiftThreeIcon);
        ApplyPassiveCardState(state);

        RefreshUpgradeWorkspace(state);
    }

    private void OnGiftCardPressed(int slot)
    {
        if (_state is not { } state || !IsGiftSlotValid(slot))
            return;

        if (state.PrimaryGiftSlot == 0)
        {
            SelectPrimaryRequested?.Invoke(slot);
            return;
        }

        if (IsGiftSlotUnlocked(state, slot))
        {
            _activeUpgradeSlot = slot;
            RefreshUpgradeWorkspace(state);
            return;
        }

        if (state.DevelopmentPoints < state.GiftUnlockCost)
            return;

        UnlockRequested?.Invoke(slot);
    }

    private void OnPassiveCardPressed()
    {
        if (_state is not { } state)
            return;

        _activeUpgradeSlot = 4;
        RefreshUpgradeWorkspace(state);
    }

    private void OnUpgradeNodePressed(int pathIndex, int tier)
    {
        if (_state is not { } state)
            return;

        if (_activeUpgradeSlot == 0 || !CanUpgradeSlot(state, _activeUpgradeSlot))
            return;

        var path = pathIndex switch
        {
            0 => WH40KChaosGiftUpgradePath.Power,
            1 => WH40KChaosGiftUpgradePath.Cooldown,
            2 => WH40KChaosGiftUpgradePath.Utility,
            _ => WH40KChaosGiftUpgradePath.Power,
        };

        UpgradeTierRequested?.Invoke(_activeUpgradeSlot, path, tier);
    }

    private void OnUpgradeExPressed()
    {
        if (_state is not { } state)
            return;

        if (_activeUpgradeSlot == 0 || !CanUpgradeSlot(state, _activeUpgradeSlot))
            return;

        UnlockExRequested?.Invoke(_activeUpgradeSlot);
    }

    private void ApplyGiftCardState(
        int slot,
        WH40KChaosSkrizhalPatronBranchBuiState state,
        Label titleLabel,
        RichTextLabel descriptionLabel,
        Label statusLabel,
        Button actionButton,
        TextureRect iconRect)
    {
        titleLabel.Text = Loc.GetString(GetGiftTitleKey(state.Patron, slot));
        descriptionLabel.Text = Loc.GetString(GetGiftDescriptionKey(state.Patron, slot));
        iconRect.Texture = ResolveGiftTexture(state.Patron, slot);

        var (statusText, actionText, actionDisabled) = ResolveGiftCardVisualState(slot, state);
        statusLabel.Text = statusText;
        actionButton.Text = actionText;
        actionButton.Disabled = actionDisabled;
    }

    private void ApplyPassiveCardState(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        PassiveIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, GetPatronIconState(state.Patron)));
        PassiveTitleLabel.Text = Loc.GetString("wh40k-chaos-branch-passive-title");
        PassiveDescriptionLabel.Text = Loc.GetString("wh40k-chaos-branch-passive-description");
        PassiveStatusLabel.Text = Loc.GetString("wh40k-chaos-branch-passive-status-open");
        PassiveCardButton.Text = Loc.GetString("wh40k-chaos-branch-card-button-upgrade");
        PassiveCardButton.Disabled = false;
    }

    private void RefreshUpgradeWorkspace(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        if (_activeUpgradeSlot == 0 || !IsGiftSlotUnlocked(state, _activeUpgradeSlot))
        {
            if (_activeUpgradeSlot == 4)
            {
                ShowPassiveUpgradeWorkspace(state);
                return;
            }

            GiftTreeControl.Visible = false;
            TreeEmptyLabel.Visible = true;
            TreeHeaderLabel.Text = Loc.GetString("wh40k-chaos-branch-tree-header");
            SelectedGiftTitleLabel.Text = Loc.GetString("wh40k-chaos-branch-upgrade-none-title");
            SelectedGiftDescriptionLabel.Text = Loc.GetString("wh40k-chaos-branch-upgrade-none-description");
            SelectedGiftStatusLabel.Text = Loc.GetString("wh40k-chaos-branch-upgrade-none-status");
            GiftTreeControl.ClearFocus();
            return;
        }

        var slot = _activeUpgradeSlot;
        var giftTitle = Loc.GetString(GetGiftTitleKey(state.Patron, slot));
        var giftDescription = Loc.GetString(GetGiftDescriptionKey(state.Patron, slot));
        var giftTexture = ResolveGiftTexture(state.Patron, slot);
        var accent = ResolvePatronAccent(state.Patron);
        var (powerTier, cooldownTier, utilityTier, exUnlocked) = GetUpgradeSnapshot(state, slot);
        var pathKeys = ResolvePathKeys(state.Patron, slot);

        TreeHeaderLabel.Text = Loc.GetString("wh40k-chaos-branch-tree-header-focus", ("gift", giftTitle));
        TreeEmptyLabel.Visible = false;
        GiftTreeControl.Visible = true;
        GiftTreeControl.SetFocus(giftTexture, giftTitle, accent);
        GiftTreeControl.SetPathLabels(
            pathKeys.PowerShort,
            pathKeys.CooldownShort,
            pathKeys.UtilityShort,
            pathKeys.PowerLong,
            pathKeys.CooldownLong,
            pathKeys.UtilityLong);
        GiftTreeControl.SetUpgradeProgress(powerTier, cooldownTier, utilityTier, exUnlocked);

        SelectedGiftTitleLabel.Text = Loc.GetString("wh40k-chaos-branch-upgrade-selected-title", ("gift", giftTitle));
        SelectedGiftDescriptionLabel.Text = BuildUpgradeDescription(
            giftDescription,
            pathKeys.PowerLong,
            pathKeys.CooldownLong,
            pathKeys.UtilityLong);
        SelectedGiftStatusLabel.Text = Loc.GetString(
            "wh40k-chaos-branch-upgrade-selected-status-tiered",
            ("power", powerTier),
            ("cooldown", cooldownTier),
            ("utility", utilityTier),
            ("ex", exUnlocked ? "ON" : "OFF"),
            ("tierCost", UpgradeTierCost),
            ("exCost", UpgradeExCost));
    }

    private void ShowPassiveUpgradeWorkspace(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        var passiveTitle = Loc.GetString("wh40k-chaos-branch-passive-title");
        var passiveDescription = Loc.GetString("wh40k-chaos-branch-passive-description");
        var passiveTexture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, GetPatronIconState(state.Patron)));
        var accent = ResolvePatronAccent(state.Patron);
        var pathKeys = ResolvePathKeys(state.Patron, 4);

        TreeHeaderLabel.Text = Loc.GetString("wh40k-chaos-branch-tree-header-focus", ("gift", passiveTitle));
        TreeEmptyLabel.Visible = false;
        GiftTreeControl.Visible = true;
        GiftTreeControl.SetFocus(passiveTexture, passiveTitle, accent);
        GiftTreeControl.SetPathLabels(
            pathKeys.PowerShort,
            pathKeys.CooldownShort,
            pathKeys.UtilityShort,
            pathKeys.PowerLong,
            pathKeys.CooldownLong,
            pathKeys.UtilityLong);
        GiftTreeControl.SetUpgradeProgress(
            state.PassiveSpeedTier,
            state.PassiveHealthTier,
            state.PassiveMeleeTier,
            state.PassiveExUnlocked);

        SelectedGiftTitleLabel.Text = Loc.GetString("wh40k-chaos-branch-upgrade-selected-title", ("gift", passiveTitle));
        SelectedGiftDescriptionLabel.Text = BuildUpgradeDescription(
            passiveDescription,
            pathKeys.PowerLong,
            pathKeys.CooldownLong,
            pathKeys.UtilityLong);
        SelectedGiftStatusLabel.Text = Loc.GetString(
            "wh40k-chaos-branch-upgrade-selected-status-tiered",
            ("power", state.PassiveSpeedTier),
            ("cooldown", state.PassiveHealthTier),
            ("utility", state.PassiveMeleeTier),
            ("ex", state.PassiveExUnlocked ? "ON" : "OFF"),
            ("tierCost", UpgradeTierCost),
            ("exCost", UpgradeExCost));
    }

    private static string BuildUpgradeDescription(
        string giftDescription,
        string powerKey,
        string cooldownKey,
        string utilityKey)
    {
        var power = Loc.GetString(powerKey);
        var cooldown = Loc.GetString(cooldownKey);
        var utility = Loc.GetString(utilityKey);
        var summary = Loc.GetString(
            "wh40k-chaos-branch-upgrade-paths-summary",
            ("power", power),
            ("cooldown", cooldown),
            ("utility", utility));
        var costs = Loc.GetString(
            "wh40k-chaos-branch-upgrade-costs-summary",
            ("tierCost", UpgradeTierCost),
            ("exCost", UpgradeExCost));

        return $"{giftDescription}\n\n{summary}\n{costs}";
    }

    private static (string StatusText, string ActionText, bool ActionDisabled) ResolveGiftCardVisualState(
        int slot,
        WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        if (state.PrimaryGiftSlot == 0)
        {
            return (
                Loc.GetString("wh40k-chaos-branch-card-status-primary-choice"),
                Loc.GetString("wh40k-chaos-branch-card-button-select"),
                false);
        }

        if (IsGiftSlotUnlocked(state, slot))
        {
            var status = slot == state.PrimaryGiftSlot
                ? Loc.GetString("wh40k-chaos-branch-card-status-primary-selected")
                : Loc.GetString("wh40k-chaos-branch-card-status-opened");

            return (
                status,
                Loc.GetString("wh40k-chaos-branch-card-button-upgrade"),
                false);
        }

        var cost = Math.Max(1, state.GiftUnlockCost);
        var canAfford = state.DevelopmentPoints >= cost;
        return (
            Loc.GetString("wh40k-chaos-branch-card-status-cost", ("cost", cost), ("points", state.DevelopmentPoints)),
            Loc.GetString("wh40k-chaos-branch-card-button-unlock-short", ("cost", cost)),
            !canAfford);
    }

    private Texture ResolveGiftTexture(WH40KChaosPatron patron, int slot)
    {
        var specifier = GetGiftIconSpecifier(patron, slot);
        return _sprite.Frame0(specifier);
    }

