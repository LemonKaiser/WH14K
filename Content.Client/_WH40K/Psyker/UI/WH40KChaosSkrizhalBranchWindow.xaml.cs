    }

    private void UpdateProgressAccent(WH40KChaosPatron patron)
    {
        _progressForegroundStyle.BackgroundColor = ResolvePatronAccent(patron);
    }

    private static Color ResolvePatronAccent(WH40KChaosPatron patron)
    {
        return patron switch
        {
            WH40KChaosPatron.Khorne => Color.FromHex("#C14B53"),
            WH40KChaosPatron.Nurgle => Color.FromHex("#4FA95E"),
            WH40KChaosPatron.Slaanesh => Color.FromHex("#9A63C8"),
            WH40KChaosPatron.Tzeentch => Color.FromHex("#5DA8D8"),
            _ => Color.FromHex("#7B88A6"),
        };
    }

    private static bool IsGiftSlotValid(int slot)
    {
        return slot is >= 1 and <= 3;
    }

    private static bool IsGiftSlotUnlocked(WH40KChaosSkrizhalPatronBranchBuiState state, int slot)
    {
        return slot switch
        {
            1 => state.GiftSlotOneUnlocked,
            2 => state.GiftSlotTwoUnlocked,
            3 => state.GiftSlotThreeUnlocked,
            _ => false,
        };
    }

    private static bool CanUpgradeSlot(WH40KChaosSkrizhalPatronBranchBuiState state, int slot)
    {
        return slot switch
        {
            1 => state.GiftSlotOneUnlocked,
            2 => state.GiftSlotTwoUnlocked,
            3 => state.GiftSlotThreeUnlocked,
            4 => true,
            _ => false,
        };
    }

    private static (byte power, byte cooldown, byte utility, bool exUnlocked) GetUpgradeSnapshot(
        WH40KChaosSkrizhalPatronBranchBuiState state,
        int slot)
    {
        return slot switch
        {
            1 => (state.GiftOnePowerTier, state.GiftOneCooldownTier, state.GiftOneUtilityTier, state.GiftOneExUnlocked),
            2 => (state.GiftTwoPowerTier, state.GiftTwoCooldownTier, state.GiftTwoUtilityTier, state.GiftTwoExUnlocked),
            3 => (state.GiftThreePowerTier, state.GiftThreeCooldownTier, state.GiftThreeUtilityTier, state.GiftThreeExUnlocked),
            4 => (state.PassiveSpeedTier, state.PassiveHealthTier, state.PassiveMeleeTier, state.PassiveExUnlocked),
            _ => (0, 0, 0, false),
        };
    }

