using Content.Client.Localization;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WH40K.Psyker.UI;

[GenerateTypedNameReferences]
public sealed partial class WH40KPsykerProgressionWindow : FancyWindow, ILocalizedControl
{
    private WH40KPsykerProgressionViewState? _latestState;

    public WH40KPsykerProgressionWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void Relocalize()
    {
        // State text is fully built by WH40KWarpUiController;
        // if we have a cached state, re-apply it (controller will push fresh strings next frame).
        if (_latestState != null)
            ApplyState(_latestState.Value);
    }

    public void ApplyState(WH40KPsykerProgressionViewState state)
    {
        _latestState = state;
        RoleLabel.Text = state.RoleText;
        WarpChargeLabel.Text = state.WarpChargeText;
        WarpInstabilityLabel.Text = state.WarpInstabilityText;
        LevelLabel.Text = state.LevelText;
        XpLabel.Text = state.XpText;
        MeditationLabel.Text = state.MeditationText;
        CastXpLabel.Text = state.CastText;
        RepeatLabel.Text = state.RepeatText;
        HintLabel.Text = state.HintText;
        LevelProgressBar.Value = state.LevelProgress;
    }
}
