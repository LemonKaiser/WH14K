            var phase = _animationTime * (0.58f + i * 0.11f) + i * 0.9f + GetCardPhase(_previewPatron);
            var spreadX = WarpRippleInset + i * 16f + (MathF.Sin(phase) + 1f) * 10f;
            var spreadY = WarpRippleInset * 0.7f + i * 12f + (MathF.Cos(phase * 1.12f) + 1f) * 7f;
