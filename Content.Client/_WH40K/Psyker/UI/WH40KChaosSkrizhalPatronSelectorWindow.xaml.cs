using System;
using Content.Client.UserInterface.Controls;
using Content.Shared._WH40K.Psyker;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WH40K.Psyker.UI;

[GenerateTypedNameReferences]
public sealed partial class WH40KChaosSkrizhalPatronSelectorWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entityManager = default!;
    private readonly SpriteSystem _sprite;

    private static readonly ResPath SkrizhalRsi = new("_WH40K/Interface/Abilities/skrizhali_runes.rsi");

    public event Action<WH40KChaosPatron>? PatronSelected;

    public WH40KChaosSkrizhalPatronSelectorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entityManager.System<SpriteSystem>();

        InitCardContent();

        KhorneSelectButton.OnPressed += _ => PatronSelected?.Invoke(WH40KChaosPatron.Khorne);
        NurgleSelectButton.OnPressed += _ => PatronSelected?.Invoke(WH40KChaosPatron.Nurgle);
        SlaaneshSelectButton.OnPressed += _ => PatronSelected?.Invoke(WH40KChaosPatron.Slaanesh);
        TzeentchSelectButton.OnPressed += _ => PatronSelected?.Invoke(WH40KChaosPatron.Tzeentch);
    }

    public void ApplyState(WH40KChaosSkrizhalPatronSelectorBuiState state)
    {
        var locked = state.SelectionLocked;
        SetSelectionEnabled(!locked);

        SelectorStatusLabel.Text = locked
            ? Loc.GetString(
                "wh40k-chaos-selector-status-locked",
                ("patron", Loc.GetString(GetPatronLocKey(state.CurrentPatron))))
            : Loc.GetString("wh40k-chaos-selector-status-open");
    }

    private void InitCardContent()
    {
        SelectorHeaderLabel.Text = Loc.GetString("wh40k-chaos-selector-header");

        KhorneTitleLabel.Text = Loc.GetString("wh40k-chaos-selector-khorne-title");
        NurgleTitleLabel.Text = Loc.GetString("wh40k-chaos-selector-nurgle-title");
        SlaaneshTitleLabel.Text = Loc.GetString("wh40k-chaos-selector-slaanesh-title");
        TzeentchTitleLabel.Text = Loc.GetString("wh40k-chaos-selector-tzeentch-title");

        KhorneDescriptionLabel.Text = Loc.GetString("wh40k-chaos-selector-khorne-desc");
        NurgleDescriptionLabel.Text = Loc.GetString("wh40k-chaos-selector-nurgle-desc");
        SlaaneshDescriptionLabel.Text = Loc.GetString("wh40k-chaos-selector-slaanesh-desc");
        TzeentchDescriptionLabel.Text = Loc.GetString("wh40k-chaos-selector-tzeentch-desc");

        var selectText = Loc.GetString("wh40k-chaos-selector-select-button");
        KhorneSelectButton.Text = selectText;
        NurgleSelectButton.Text = selectText;
        SlaaneshSelectButton.Text = selectText;
        TzeentchSelectButton.Text = selectText;

        KhorneIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, "skrizhal_khorn"));
        NurgleIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, "skrizhal_nurgk"));
        SlaaneshIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, "skrizhal_slaanesh"));
        TzeentchIcon.Texture = _sprite.Frame0(new SpriteSpecifier.Rsi(SkrizhalRsi, "skrizhal_tzinch"));
    }

    private void SetSelectionEnabled(bool enabled)
    {
        KhorneSelectButton.Disabled = !enabled;
        NurgleSelectButton.Disabled = !enabled;
        SlaaneshSelectButton.Disabled = !enabled;
        TzeentchSelectButton.Disabled = !enabled;
    }

    private static string GetPatronLocKey(WH40KChaosPatron patron)
    {
        return patron switch
        {
            WH40KChaosPatron.Khorne => "wh40k-chaos-patron-khorne",
            WH40KChaosPatron.Nurgle => "wh40k-chaos-patron-nurgle",
            WH40KChaosPatron.Slaanesh => "wh40k-chaos-patron-slaanesh",
            WH40KChaosPatron.Tzeentch => "wh40k-chaos-patron-tzeentch",
            WH40KChaosPatron.Undivided => "wh40k-chaos-patron-undivided",
            _ => "wh40k-chaos-window-patron-none",
        };
    }
}
