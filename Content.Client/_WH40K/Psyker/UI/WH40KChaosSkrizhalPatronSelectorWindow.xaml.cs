    private bool IsPointInsideControl(Control control, Vector2 point)
    {
        var topLeft = Vector2.Zero;

        for (Control? current = control; current != null && current != this; current = current.Parent)
        {
            topLeft += current.Position;
        }

        return point.X >= topLeft.X && point.X <= topLeft.X + control.Size.X &&
               point.Y >= topLeft.Y && point.Y <= topLeft.Y + control.Size.Y;
    }

