    private static Color MixColor(Color from, Color to, float amount)
    {
        amount = Math.Clamp(amount, 0f, 1f);
        return new Color(
            from.R + (to.R - from.R) * amount,
            from.G + (to.G - from.G) * amount,
            from.B + (to.B - from.B) * amount,
            from.A + (to.A - from.A) * amount);
    }

    private static Color LightenColor(Color color, float amount)
    {
        amount = Math.Clamp(amount, 0f, 1f);
        return new Color(
            color.R + (1f - color.R) * amount,
            color.G + (1f - color.G) * amount,
            color.B + (1f - color.B) * amount,
            color.A);
    }

    private bool TryGetCardFormationBounds(out Vector2 topLeft, out Vector2 size, out Vector2 center)
    {
        topLeft = Vector2.Zero;
        size = Vector2.Zero;
        center = Vector2.Zero;

        var initialized = false;
        var minX = 0f;
        var minY = 0f;
        var maxX = 0f;
        var maxY = 0f;

        foreach (var patron in CardOrder)
        {
            if (!_entryPanels.TryGetValue(patron, out var panel) || panel.Width <= 0f || panel.Height <= 0f)
                continue;

            var panelMinX = panel.Position.X;
            var panelMinY = panel.Position.Y;
            var panelMaxX = panel.Position.X + panel.Size.X;
            var panelMaxY = panel.Position.Y + panel.Size.Y;

            if (!initialized)
            {
                minX = panelMinX;
                minY = panelMinY;
                maxX = panelMaxX;
                maxY = panelMaxY;
                initialized = true;
                continue;
            }

            minX = MathF.Min(minX, panelMinX);
            minY = MathF.Min(minY, panelMinY);
            maxX = MathF.Max(maxX, panelMaxX);
            maxY = MathF.Max(maxY, panelMaxY);
        }

        if (!initialized)
            return false;

        topLeft = new Vector2(minX, minY);
        size = new Vector2(maxX - minX, maxY - minY);
        center = topLeft + size * 0.5f;
        return true;
    }

    private static float EaseOutCubic(float value)
    {
        value = Math.Clamp(value, 0f, 1f);
        var inv = 1f - value;
        return 1f - inv * inv * inv;
    }

