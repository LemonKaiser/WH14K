    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        SyncOverlayBounds();

        if (args.DeltaSeconds <= 0f)
            return;

        _animationTime += args.DeltaSeconds;
        ArrangeFloatingCards();
        RefreshEntryStyles();
        UpdateArcaneEffects();
    }

    protected override void Resized()
    {
        base.Resized();
        ArrangeFloatingCards();
    }

    protected override void ExitedTree()
    {
        StopHoverTheme();
        base.ExitedTree();
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Handled || args.Function != EngineKeyFunctions.UIClick)
            return;

        foreach (var patron in CardOrder)
        {
            if (!_entryPanels.TryGetValue(patron, out var panel) || !IsPointInsideControl(panel, args.RelativePosition))
                continue;

            CommitPatron(patron);
            args.Handle();
            return;
        }

        Close();
        args.Handle();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
