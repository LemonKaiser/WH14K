            ripple.SetWidth = formationSize.X + spreadX * 2f;
            ripple.SetHeight = formationSize.Y + spreadY * 2f;
            LayoutContainer.SetPosition(ripple, formationTopLeft - new Vector2(spreadX, spreadY) + drift);
        }
