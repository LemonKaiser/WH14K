    private void PreviewPatron(WH40KChaosPatron patron, bool playFlash)
    {
        _previewPatron = patron;
        UpdateHoverTheme(patron);

        if (playFlash)
        {
            var accent = ResolvePatronAccent(patron);
            WH40KUiChrome.PlayHoverFlash(_entryAccentBars[patron], $"chaos-selector-bar-hover-{patron}", accent.WithAlpha(0.92f), 0.16f);
        }

        RefreshEntryStyles();
        RefreshFooter();
    }

    private void OnWindowVisibilityChanged(Control control)
    {
        if (!Visible)
            StopHoverTheme();
    }

    private void OnCardMouseExited()
    {
        if (IsMouseOverAnyPatronCard())
            return;

        StopHoverTheme();
    }

    private bool IsMouseOverAnyPatronCard()
    {
        if (Parent == null || !Visible)
            return false;

        var mousePoint = UserInterfaceManager.MousePositionScaled.Position;
        foreach (var patron in CardOrder)
        {
            if (_entryPanels.TryGetValue(patron, out var panel) && IsPointInsideControl(panel, mousePoint))
                return true;

            if (_entryButtons.TryGetValue(patron, out var button) && IsPointInsideControl(button, mousePoint))
                return true;
        }

        return false;
    }

    private void UpdateHoverTheme(WH40KChaosPatron patron)
    {
        if (_hoverThemePatron == patron && _hoverThemeStream != null)
            return;

        StopHoverTheme();

        ResolvedSoundSpecifier? themePath = ResolvePatronThemePath(patron);
        if (themePath == null)
            return;

        _hoverThemeStream = _audio.PlayGlobal((ResolvedSoundSpecifier?) themePath, Filter.Local(), true, PatronThemeAudioParams)?.Entity;
        _hoverThemePatron = _hoverThemeStream != null ? patron : WH40KChaosPatron.None;
    }

    private void StopHoverTheme()
    {
        _hoverThemeStream = _audio.Stop(_hoverThemeStream);
        _hoverThemePatron = WH40KChaosPatron.None;
    }

    private static ResolvedSoundSpecifier? ResolvePatronThemePath(WH40KChaosPatron patron)
    {
        return patron switch
        {
            WH40KChaosPatron.Khorne => new ResolvedPathSpecifier(new ResPath("/Audio/_WH40K/ChaosGods/Khorne.ogg")),
            WH40KChaosPatron.Nurgle => new ResolvedPathSpecifier(new ResPath("/Audio/_WH40K/ChaosGods/Nurgle.ogg")),
            WH40KChaosPatron.Slaanesh => new ResolvedPathSpecifier(new ResPath("/Audio/_WH40K/ChaosGods/Slaanesh.ogg")),
            WH40KChaosPatron.Tzeentch => new ResolvedPathSpecifier(new ResPath("/Audio/_WH40K/ChaosGods/Tzeentch.ogg")),
            _ => null,
        };
    }

    private void CommitPatron(WH40KChaosPatron patron)
    {
        _previewPatron = patron;

        if (!IsSelectionLocked())
            PatronSelected?.Invoke(patron);

        RefreshEntryStyles();
        RefreshFooter();
    }

    private void RefreshFooter()
    {
        var patronLoc = Loc.GetString(GetPatronLocKey(_previewPatron));
        PreviewPatronLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Eye, patronLoc);
        UpdateFocusSigilTextures();

        var accent = ResolvePatronAccent(_previewPatron);
        _cardStageStyle.BackgroundColor = accent.WithAlpha(0.015f);
        _cardStageStyle.BorderColor = Color.Transparent;
        _focusSigilStyle.BackgroundColor = Color.Transparent;
        _focusSigilStyle.BorderColor = Color.Transparent;

        WH40KUiChrome.StartLoopingPulse(
            FocusSigilPanel,
            "chaos-selector-focus-pulse",
            accent.WithAlpha(0.72f),
            Color.White,
            2.8f);

        var locked = IsSelectionLocked();
        var currentPatron = _latestState?.CurrentPatron ?? WH40KChaosPatron.None;
        PreviewStatusLabel.Text = locked
            ? Loc.GetString(
                _previewPatron == currentPatron
                    ? "wh40k-chaos-selector-preview-status-locked-current"
                    : "wh40k-chaos-selector-preview-status-locked-other",
                ("patron", Loc.GetString(GetPatronLocKey(currentPatron))))
            : Loc.GetString("wh40k-chaos-selector-preview-status-open", ("patron", patronLoc));
        PreviewCommitNoteLabel.Text = locked
            ? Loc.GetString("wh40k-chaos-selector-preview-note-locked")
            : Loc.GetString("wh40k-chaos-selector-preview-note-open");
    }

    private void RefreshEntryStyles()
    {
        var currentPatron = _latestState?.CurrentPatron ?? WH40KChaosPatron.None;
        var locked = IsSelectionLocked();

        foreach (var patron in CardOrder)
        {
            var style = _entryStyles[patron];
            var accentStyle = _entryAccentStyles[patron];
            var haloStyle = _entryHaloStyles[patron];
            var giftPanelStyles = _entryGiftPanelStyles[patron];
            var leaderPanelStyle = _entryLeaderPanelStyles[patron];
            var buttonStyle = _entryButtonStyles[patron];
            var shadowStyle = _entryShadowStyles[patron];
            var button = _entryButtons[patron];
            var giftIcons = _entryGiftIcons[patron];
            var giftSummaryLabel = _entryGiftSummaryLabels[patron];
            var statusLabel = _entryStatusLabels[patron];
            var panel = _entryPanels[patron];

            var accent = ResolvePatronAccent(patron);
            var baseBackground = ResolveEntryBackground(patron);
            var previewed = patron == _previewPatron;
            var selected = locked && patron == currentPatron;
            var buttonHovered = previewed;
            var haloPulse = 0.5f + 0.5f * MathF.Sin(_animationTime * (1.45f + GetCardPhase(patron) * 0.08f) + GetCardPhase(patron));
            var leaderName = ResolveLeaderName(patron);
            var hasLeader = leaderName != Loc.GetString("wh40k-chaos-selector-no-leader");

            style.BackgroundColor = selected
                ? LightenColor(baseBackground, 0.16f)
                : previewed
