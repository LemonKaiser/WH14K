    private void UpdateAmbientMotes(Vector2 focusCenter, Vector2 cardCenter, Color accent)
    {
        for (var i = 0; i < _ambientMotes.Length; i++)
        {
            var mote = _ambientMotes[i];
            var orbitAngle = GetCardPhase(_previewPatron) + i * (Tau / _ambientMotes.Length) + _animationTime * (0.6f + i * 0.05f) * (i % 2 == 0 ? 1f : -1f);
            var radius = 46f + i * 5f + MathF.Sin(_animationTime * 1.3f + i) * 6f;
            var centerBias = i % 2 == 0 ? focusCenter : Vector2.Lerp(focusCenter, cardCenter, 0.34f);
            var offset = new Vector2(
                MathF.Cos(orbitAngle) * radius,
                MathF.Sin(orbitAngle) * (18f + i * 1.5f));
            var shimmer = 0.2f + (MathF.Sin(_animationTime * 2.1f + i * 0.9f) + 1f) * 0.18f;

            mote.FontColorOverride = LightenColor(accent, 0.18f + i * 0.03f);
            mote.Modulate = Color.White.WithAlpha(shimmer);
            mote.Visible = true;
            LayoutContainer.SetPosition(mote, centerBias + offset - new Vector2(6f, 8f));
        }
    }

    private void UpdateSelectionBurst(Color accent)
    {
        var elapsed = _animationTime - _burstStartedAt;
        if (_burstPatron == WH40KChaosPatron.None || elapsed < 0f || elapsed > BurstDuration || !_entryPanels.TryGetValue(_burstPatron, out var burstPanel))
        {
            _selectionBurstRing.Visible = false;

            foreach (var mote in _burstMotes)
            {
                mote.Visible = false;
                mote.Modulate = Color.Transparent;
            }

            return;
        }

        var progress = Math.Clamp(elapsed / BurstDuration, 0f, 1f);
        var eased = EaseOutCubic(progress);
        var expansion = (26f + 48f * eased) * _burstIntensity;
        var ringPosition = burstPanel.Position - new Vector2(expansion * 0.5f, expansion * 0.5f);
        var ringSize = burstPanel.Size + new Vector2(expansion, expansion);
        var ringAlpha = (1f - progress) * (0.85f + _burstIntensity * 0.1f);

        _selectionBurstRingStyle.BorderColor = accent.WithAlpha(ringAlpha);
        _selectionBurstRingStyle.BackgroundColor = accent.WithAlpha((1f - progress) * 0.035f * _burstIntensity);
        _selectionBurstRingStyle.BorderThickness = new Thickness(2f + (1f - progress) * _burstIntensity);
        _selectionBurstRing.Visible = true;
        _selectionBurstRing.Modulate = Color.White.WithAlpha(ringAlpha);
        _selectionBurstRing.SetWidth = ringSize.X;
        _selectionBurstRing.SetHeight = ringSize.Y;
        LayoutContainer.SetPosition(_selectionBurstRing, ringPosition);

        var burstCenter = burstPanel.Position + burstPanel.Size * new Vector2(0.5f, 0.42f);
        for (var i = 0; i < _burstMotes.Length; i++)
        {
            var mote = _burstMotes[i];
            var angle = GetCardPhase(_burstPatron) + _burstSerial * 0.31f + i * (Tau / _burstMotes.Length);
            var direction = new Vector2(MathF.Cos(angle), MathF.Sin(angle) * 0.62f);
            var travel = (16f + 82f * eased) * _burstIntensity;
            var rise = (1f - progress) * 12f;
            var moteAlpha = (1f - progress) * (0.92f - i * 0.04f);

            mote.FontColorOverride = i % 2 == 0 ? LightenColor(accent, 0.34f) : accent;
            mote.Modulate = Color.White.WithAlpha(Math.Max(0f, moteAlpha));
            mote.Visible = moteAlpha > 0.02f;
            LayoutContainer.SetPosition(mote, burstCenter + direction * travel + new Vector2(0f, -rise) - new Vector2(8f, 8f));
        }
    }

    private void ArrangeFloatingCards()
    {
        if (CardCanvas.Width <= 0f || CardCanvas.Height <= 0f)
            return;

        var usableWidth = Math.Max(320f, CardCanvas.Width - CardHorizontalPadding * 2f - CardGap * 3f);
        var cardWidth = usableWidth / 4f;
        var cardHeight = MathF.Min(600f, Math.Max(436f, CardCanvas.Height - CardTopPadding - CardBottomPadding - 112f));
        var stageTop = MathF.Max(CardTopPadding, (CardCanvas.Height - cardHeight) * 0.5f - 10f);

        for (var i = 0; i < CardOrder.Length; i++)
        {
            var patron = CardOrder[i];
            var panel = _entryPanels[patron];
            panel.SetWidth = cardWidth;
            panel.SetHeight = cardHeight;

            var lift = MathF.Sin(_animationTime * 0.92f + GetCardPhase(patron)) * GetCardAmplitude(patron);
            if (patron == _previewPatron)
                lift -= 12f;

            var x = CardHorizontalPadding + i * (cardWidth + CardGap);
            var y = stageTop + GetCardBaseOffset(patron) + lift;
            LayoutContainer.SetPosition(panel, new Vector2(x, y));

            var shadow = _entryShadowPanels[patron];
            var shadowWidth = cardWidth + 30f;
            var shadowHeight = cardHeight + 42f;
            shadow.SetWidth = shadowWidth;
            shadow.SetHeight = shadowHeight;

            var shadowDrift = new Vector2(
                MathF.Cos(_animationTime * 0.34f + GetCardPhase(patron)) * 6f,
                MathF.Sin(_animationTime * 0.28f + GetCardPhase(patron)) * 8f);
            LayoutContainer.SetPosition(
                shadow,
                new Vector2(x - 15f, y + 18f) + shadowDrift);
        }

        var focusWidth = 62f;
        var focusHeight = 62f;
        FocusSigilPanel.SetWidth = focusWidth;
        FocusSigilPanel.SetHeight = focusHeight;
        var focusIndex = Array.IndexOf(CardOrder, _previewPatron);
        if (focusIndex >= 0)
        {
            var focusX = CardHorizontalPadding + focusIndex * (cardWidth + CardGap) + cardWidth * 0.5f - focusWidth * 0.5f;
            var focusY = stageTop + GetCardBaseOffset(_previewPatron) + MathF.Sin(_animationTime * 1.12f + GetCardPhase(_previewPatron)) * 4f - 34f;
            LayoutContainer.SetPosition(FocusSigilPanel, new Vector2(focusX, focusY));
        }
    }

