    private FormattedMessage BuildGiftSummary(WH40KChaosPatron patron)
    {
        var message = new FormattedMessage();

        for (var slot = 1; slot <= 3; slot++)
        {
            if (slot > 1)
                message.AddText("\n");

            message.PushColor(Color.FromHex("#D7BC72"));
            message.AddText($"{slot}. {Loc.GetString(GetGiftTitleKey(patron, slot))}");
            message.Pop();
            message.AddText("  ");
            message.PushColor(Color.FromHex("#CFD3DD"));
            message.AddText(Loc.GetString(GetGiftBriefKey(patron, slot)));
            message.Pop();
        }

        return message;
    }

