    private void UpdateStageRunes(Vector2 focusCenter, Vector2 cardCenter, Color accent)
    {
        if (CardCanvas.Width <= 0f || CardCanvas.Height <= 0f)
            return;

        var highlightCenter = Vector2.Lerp(focusCenter, cardCenter, 0.5f);
        var heightStep = (CardCanvas.Height - 84f) / Math.Max(1, _stageRunes.Length - 1);
        var travelWidth = CardCanvas.Width + 120f;

        for (var i = 0; i < _stageRunes.Length; i++)
        {
            var rune = _stageRunes[i];
            var travel = (_animationTime * (18f + i * 3.2f) + i * 91f) % travelWidth;
            var x = i % 2 == 0
                ? travel - 60f
                : CardCanvas.Width - travel + 60f;
            var baseY = 42f + i * heightStep;
            var y = baseY
                + MathF.Sin(_animationTime * (0.7f + i * 0.04f) + i * 0.8f) * 20f
                + MathF.Sin(_animationTime * 0.35f + i * 1.1f) * 8f;
            var position = new Vector2(x, y);
            var influence = 1f - Math.Clamp(Vector2.Distance(position, highlightCenter) / 420f, 0f, 1f);
            var alpha = 0.06f + (MathF.Sin(_animationTime * 1.15f + i * 0.6f) + 1f) * 0.04f + influence * 0.08f;

            rune.FontColorOverride = i % 2 == 0
                ? LightenColor(accent, 0.16f + influence * 0.14f)
                : MixColor(Color.FromHex("#8A7442"), accent, 0.5f + influence * 0.25f);
            rune.Modulate = Color.White.WithAlpha(alpha);
            LayoutContainer.SetPosition(rune, position);
        }
    }

