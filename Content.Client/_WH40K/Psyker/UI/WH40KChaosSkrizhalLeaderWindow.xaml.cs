    private void UpdateCardStyle(
        StyleBoxFlat style,
        WH40KChaosPatron patron,
        bool active,
        bool unlocked,
        bool primary)
    {
        var accent = WH40KChaosUiShared.ResolvePatronAccent(patron);
        var brass = Color.FromHex("#9A7446");
        var baseColor = Color.FromHex("#191315");
        var background = active
            ? WH40KChaosUiShared.MixColor(baseColor, accent, unlocked ? 0.25f : 0.10f)
            : unlocked
                ? WH40KChaosUiShared.MixColor(baseColor, Color.FromHex("#231A19"), 0.35f)
                : baseColor;

        style.BackgroundColor = background;
        style.BorderColor = active
            ? WH40KChaosUiShared.LightenColor(accent, 0.15f).WithAlpha(0.98f)
            : unlocked
                ? brass.WithAlpha(0.52f)
                : Color.FromHex("#554537");
        style.BorderThickness = new Thickness(active ? 2f : 1f);
    }

