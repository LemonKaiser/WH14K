    private static string BuildCardPreviewText(string description, int maxLength = 92)
    {
        var normalized = string.Join(' ', description.Split(new[] { ' ', '\t', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries));
        if (normalized.Length <= maxLength)
            return normalized;

        return $"{normalized[..Math.Max(0, maxLength - 3)].TrimEnd()}...";
    }

    private static (string StatusText, string ActionText, bool ActionDisabled) ResolveGiftCardVisualState(
        int slot,
        WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        if (!state.CanEdit)
        {
            var status = state.PrimaryGiftSlot == slot
                ? Loc.GetString("w40k-ch-card-status-primary-selected-readonly")
                : IsGiftSlotUnlocked(state, slot)
                    ? Loc.GetString("w40k-ch-card-status-opened-readonly")
                    : Loc.GetString("w40k-ch-card-status-cost", ("cost", Math.Max(1, state.GiftUnlockCost)), ("points", state.DevelopmentPoints));

            return (
                status,
                Loc.GetString("w40k-ch-card-button-review"),
                false);
        }

        if (state.PrimaryGiftSlot == 0)
        {
            return (
                Loc.GetString("w40k-ch-card-status-primary-choice"),
                Loc.GetString("w40k-ch-card-button-select"),
                false);
        }

        if (IsGiftSlotUnlocked(state, slot))
        {
            var status = slot == state.PrimaryGiftSlot
                ? Loc.GetString("w40k-ch-card-status-primary-selected")
                : Loc.GetString("w40k-ch-card-status-opened");

            return (
                status,
                Loc.GetString("w40k-ch-card-button-upgrade"),
                false);
        }

        var cost = Math.Max(1, state.GiftUnlockCost);
        var canAfford = state.DevelopmentPoints >= cost;
        return (
            Loc.GetString("w40k-ch-card-status-cost", ("cost", cost), ("points", state.DevelopmentPoints)),
            Loc.GetString("w40k-ch-card-button-unlock-short", ("cost", cost)),
            !canAfford);
    }

