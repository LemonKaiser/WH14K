    private void RefreshLiveTelemetry(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        var patron = state.Patron;
        var progression = default(WH40KChaosGiftProgressionComponent?);
        var warp = default(WH40KWarpResourceComponent?);
        var instability = default(WH40KWarpInstabilityComponent?);

        if (_player.LocalEntity is { Valid: true } uid)
        {
            progression = _entityManager.GetComponentOrNull<WH40KChaosGiftProgressionComponent>(uid);
            warp = _entityManager.GetComponentOrNull<WH40KWarpResourceComponent>(uid);
            instability = _entityManager.GetComponentOrNull<WH40KWarpInstabilityComponent>(uid);
            if (progression != null && progression.AttunedPatron != WH40KChaosPatron.None)
                patron = progression.AttunedPatron;
        }

        var warpCurrent = warp?.CurrentCharge ?? 0f;
        var warpMax = Math.Max(1f, warp?.MaxCharge ?? 100f);
        var instabilityCurrent = instability?.CurrentInstability ?? 0f;
        var instabilityMax = Math.Max(1f, instability?.MaxInstability ?? 100f);
        var warpFraction = Math.Clamp(warpCurrent / warpMax, 0f, 1f);
        var instabilityFraction = Math.Clamp(instabilityCurrent / instabilityMax, 0f, 1f);
        var attunementMultiplier = progression?.AttunementXpMultiplier ?? 1f;

        WarpChargeTitleLabel.Text = Loc.GetString("w40k-ch-telemetry-warp-short");
        WarpChargeValueLabel.Text = FormatRatio(warpCurrent, warpMax);
        WarpInstabilityTitleLabel.Text = Loc.GetString("w40k-ch-telemetry-instability-short");
        WarpInstabilityValueLabel.Text = FormatRatio(instabilityCurrent, instabilityMax);
        AttunementLabel.Text = Loc.GetString("w40k-ch-telemetry-attunement", ("multiplier", WH40KChaosUiShared.FormatNumber(attunementMultiplier, 2)));

        WarpChargeBar.Value = warpFraction;
        WarpInstabilityBar.Value = instabilityFraction;

        UpdateProgressAccent(patron, instabilityFraction);
    }

    private void RefreshUpgradeWorkspace(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        if (_activeUpgradeSlot == 4)
        {
            ShowPassiveUpgradeWorkspace(state);
            return;
        }

        if (_activeUpgradeSlot == 0 || !IsGiftSlotUnlocked(state, _activeUpgradeSlot))
        {
            GiftTreeControl.Visible = false;
            TreeEmptyLabel.Visible = true;
            SelectedGiftTitleLabel.Text = Loc.GetString("w40k-ch-upgrade-none-title");
            SelectedGiftDescriptionLabel.Text = Loc.GetString("w40k-ch-upgrade-none-description");
            GiftTreeControl.ClearFocus();
            return;
        }

        var slot = _activeUpgradeSlot;
        var giftTitle = Loc.GetString(WH40KChaosUiShared.GetGiftTitleKey(state.Patron, slot));
        var giftDescription = Loc.GetString(WH40KChaosUiShared.GetGiftDescriptionKey(state.Patron, slot));
        var giftTexture = ResolveGiftTexture(state.Patron, slot);
        var accent = WH40KChaosUiShared.ResolvePatronAccent(state.Patron);
        var (powerTier, cooldownTier, utilityTier, exUnlocked) = GetUpgradeSnapshot(state, slot);
        var pathKeys = WH40KChaosUiShared.ResolvePathKeys(state.Patron, slot);

        TreeEmptyLabel.Visible = false;
        GiftTreeControl.Visible = true;
        GiftTreeControl.SetFocus(giftTexture, giftTitle, accent);
        GiftTreeControl.SetPathLabels(
            "w40k-ch-upgrade-path-power-short",
            "w40k-ch-upgrade-path-cooldown-short",
            "w40k-ch-upgrade-path-cast-time-short",
            pathKeys.PowerLong,
            pathKeys.CooldownLong,
            pathKeys.UtilityLong);
        GiftTreeControl.SetUpgradeProgress(powerTier, cooldownTier, utilityTier, exUnlocked);
        GiftTreeControl.SetInteractionEnabled(state.CanEdit);

        SelectedGiftTitleLabel.Text = Loc.GetString("w40k-ch-upgrade-selected-title", ("gift", giftTitle));
        SelectedGiftDescriptionLabel.Text = BuildUpgradeDescription(giftDescription);
    }

