    public void ApplyState(WH40KChaosSkrizhalPatronBranchBuiState state)
    {
        var firstApply = _state == null;
        _state = state;

        if (firstApply)
            _activeUpgradeSlot = state.PrimaryGiftSlot != 0 ? state.PrimaryGiftSlot : 4;

        if (_activeUpgradeSlot is > 0 and <= 3 && !IsGiftSlotUnlocked(state, _activeUpgradeSlot))
            _activeUpgradeSlot = state.PrimaryGiftSlot != 0 && IsGiftSlotUnlocked(state, state.PrimaryGiftSlot)
                ? state.PrimaryGiftSlot
                : 4;

        var patronLoc = Loc.GetString(WH40KChaosUiShared.GetPatronLocKey(state.Patron));
        var xpProgress = state.NextLevelXp <= 0f
            ? 1f
            : Math.Clamp(state.LevelXp / state.NextLevelXp, 0f, 1f);

        PatronLabel.Text = Loc.GetString("w40k-ch-patron", ("patron", patronLoc));
        LevelLabel.Text = Loc.GetString("w40k-ch-level", ("level", state.Level), ("max", state.MaxLevel));
        XpBarTitleLabel.Text = Loc.GetString("w40k-ch-telemetry-xp-short");
        XpBarValueLabel.Text = FormatRatio(state.LevelXp, state.NextLevelXp);
        PassiveIncomeLabel.Text = Loc.GetString(
            "w40k-ch-passive-income",
            ("xp", WH40KChaosUiShared.FormatNumber(state.PassiveXpPerTick)),
            ("seconds", state.PassiveXpIntervalSeconds));
        LevelProgressBar.Value = xpProgress;

        CommandLeaderLabel.Text = Loc.GetString("wh40k-chaos-leader-seat-name", ("leader", ResolveLeaderName(state)));
        CommandEconomyLabel.Text = Loc.GetString(
            "wh40k-chaos-leader-seat-economy",
            ("points", state.DevelopmentPoints),
            ("souls", state.PatronSoulOfferCount));

        UpdateProgressAccent(state.Patron);

        ApplyGiftCardState(1, state, _giftPanelStyles[0], GiftOneTitleLabel, GiftOneDescriptionLabel, GiftOneStatusLabel, GiftOneCardButton, GiftOneIcon);
        ApplyGiftCardState(2, state, _giftPanelStyles[1], GiftTwoTitleLabel, GiftTwoDescriptionLabel, GiftTwoStatusLabel, GiftTwoCardButton, GiftTwoIcon);
        ApplyGiftCardState(3, state, _giftPanelStyles[2], GiftThreeTitleLabel, GiftThreeDescriptionLabel, GiftThreeStatusLabel, GiftThreeCardButton, GiftThreeIcon);
        ApplyPassiveCardState(state);

        RefreshUpgradeWorkspace(state);
        RefreshLiveTelemetry(state);
    }

    private void OnGiftCardPressed(int slot)
    {
        if (_state is not { } state || !IsGiftSlotValid(slot))
            return;

        if (!state.CanEdit)
            return;

        if (state.PrimaryGiftSlot == 0)
        {
            SelectPrimaryRequested?.Invoke(slot);
            return;
        }

        if (IsGiftSlotUnlocked(state, slot))
        {
            _activeUpgradeSlot = slot;
            RefreshUpgradeWorkspace(state);
            RefreshLiveTelemetry(state);
            return;
        }

        if (state.DevelopmentPoints < state.GiftUnlockCost)
            return;

        UnlockRequested?.Invoke(slot);
    }

    private void OnPassiveCardPressed()
    {
        if (_state is not { } state)
            return;

        _activeUpgradeSlot = 4;
        RefreshUpgradeWorkspace(state);
        RefreshLiveTelemetry(state);
    }

    private void OnUpgradeNodePressed(int pathIndex, int tier)
    {
        if (_state is not { } state)
            return;

        if (!state.CanEdit)
            return;

        if (_activeUpgradeSlot == 0 || !CanUpgradeSlot(state, _activeUpgradeSlot))
            return;

        var path = pathIndex switch
        {
            0 => WH40KChaosGiftUpgradePath.Power,
            1 => WH40KChaosGiftUpgradePath.Cooldown,
            2 => WH40KChaosGiftUpgradePath.Utility,
            _ => WH40KChaosGiftUpgradePath.Power,
        };

        UpgradeTierRequested?.Invoke(_activeUpgradeSlot, path, tier);
    }

    private void OnUpgradeExPressed()
    {
        if (_state is not { } state)
            return;

        if (!state.CanEdit)
            return;

        if (_activeUpgradeSlot == 0 || !CanUpgradeSlot(state, _activeUpgradeSlot))
            return;

        UnlockExRequested?.Invoke(_activeUpgradeSlot);
    }

