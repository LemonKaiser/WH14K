    private void UpdateActionButtonStyle(
        StyleBoxFlat style,
        WH40KChaosPatron patron,
        bool active,
        bool disabled,
        bool unlocked,
        bool primary)
    {
        var accent = WH40KChaosUiShared.ResolvePatronAccent(patron);
        var brass = Color.FromHex("#9D7746");
        var baseColor = disabled ? Color.FromHex("#28201D") : Color.FromHex("#342924");
        var mixed = WH40KChaosUiShared.MixColor(baseColor, accent, active ? 0.28f : unlocked ? 0.05f : 0.02f);
        style.BackgroundColor = disabled
            ? WH40KChaosUiShared.MixColor(mixed, Color.FromHex("#1B1716"), 0.36f)
            : mixed;
        style.BorderColor = active
            ? WH40KChaosUiShared.LightenColor(accent, 0.12f).WithAlpha(0.96f)
            : disabled
                ? brass.WithAlpha(0.30f)
                : brass.WithAlpha(0.68f);
        style.BorderThickness = new Thickness(active ? 2f : 1f);
    }

    private StyleBoxFlat GetActionButtonStyle(int slot)
    {
        return slot switch
        {
            1 => _giftButtonStyles[0],
            2 => _giftButtonStyles[1],
            3 => _giftButtonStyles[2],
            _ => _giftButtonStyles[3],
        };
    }

