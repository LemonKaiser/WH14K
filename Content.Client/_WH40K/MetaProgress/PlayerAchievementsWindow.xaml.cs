using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Client._WH40K.MetaProgress;

[GenerateTypedNameReferences]
public sealed partial class PlayerAchievementsWindow : FancyWindow, ILocalizedControl
{
    [Dependency] private readonly IPrototypeManager _prototype = default!;
    private static readonly Color SummaryBackground = Color.FromHex("#1B1A14");
    private static readonly Color SummaryBorder = Color.FromHex("#7B6430");
    private static readonly Color LockedBackground = Color.FromHex("#1A1D24");
    private static readonly Color LockedBorder = Color.FromHex("#4C4127");
    private static readonly Color LockedChip = Color.FromHex("#5B5446");
    private static readonly Color InProgressBackground = Color.FromHex("#201D15");
    private static readonly Color InProgressBorder = Color.FromHex("#8B743A");
    private static readonly Color InProgressChip = Color.FromHex("#9E8140");
    private static readonly Color UnlockedBackground = Color.FromHex("#182017");
    private static readonly Color UnlockedBorder = Color.FromHex("#6E845A");
    private static readonly Color UnlockedChip = Color.FromHex("#5F7A50");

    private readonly List<WH40KMetaAchievementSnapshotEntry> _entries = new();
    private readonly WH40KMetaProgressSystem _metaProgress;
    private AchievementFilterCategory _activeCategory = AchievementFilterCategory.All;
    private int _completedAchievements;
    private int _totalAchievements;
    private bool _snapshotLoaded;

    public PlayerAchievementsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _metaProgress = IoCManager.Resolve<IEntityManager>().System<WH40KMetaProgressSystem>();

        ApplyStyles();
        BindFilterButtons();
        Relocalize();

        _metaProgress.SnapshotUpdated += OnMetaSnapshotUpdated;
        _metaProgress.EnsureSnapshot();

        if (_metaProgress.TryGetCachedSnapshot(out var snapshot))
            ApplySnapshot(snapshot);
        else
            RefreshView();
    }

    [Obsolete]
    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _metaProgress.SnapshotUpdated -= OnMetaSnapshotUpdated;

#pragma warning disable CS0618
        base.Dispose(disposing);
#pragma warning restore CS0618
    }

    private void OnMetaSnapshotUpdated(WH40KMetaProgressSnapshot snapshot)
    {
        ApplySnapshot(snapshot);
    }

    private void ApplySnapshot(WH40KMetaProgressSnapshot snapshot)
    {
        _entries.Clear();
        _entries.AddRange(snapshot.Achievements
            .OrderBy(entry => GetCategoryOrder(entry.Category))
            .ThenBy(entry => Loc.GetString(entry.TitleKey)));
        _completedAchievements = snapshot.CompletedAchievements;
        _totalAchievements = snapshot.TotalAchievements;

        _snapshotLoaded = true;
        RefreshView();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("wh40k-meta-progress-achievements-window-title");
        SummaryHeaderLabel.Text = Loc.GetString("wh40k-meta-progress-achievements-summary-header");
        FilterHeaderLabel.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-header");
        RefreshFilterButtonText();
        RefreshView();
    }

    private void BindFilterButtons()
    {
        FilterAllButton.OnPressed += _ => SetFilter(AchievementFilterCategory.All);
        FilterCombatButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Combat);
        FilterSupportButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Support);
        FilterLogisticsButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Logistics);
        FilterObjectiveButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Objective);
        FilterParticipationButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Participation);
        FilterHiddenButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Hidden);
        FilterSpecialButton.OnPressed += _ => SetFilter(AchievementFilterCategory.Special);
    }

    private void RefreshFilterButtonText()
    {
        FilterAllButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-all");
        FilterCombatButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-combat");
        FilterSupportButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-support");
        FilterLogisticsButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-logistics");
        FilterObjectiveButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-objective");
        FilterParticipationButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-participation");
        FilterHiddenButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-hidden");
        FilterSpecialButton.Text = Loc.GetString("wh40k-meta-progress-achievements-filter-special");
    }

    private void SetFilter(AchievementFilterCategory category)
    {
        _activeCategory = category;
        RefreshView();
        AchievementsScroll.SetScrollValue(Vector2.Zero);
    }

    private void RefreshView()
    {
        FilterAllButton.Pressed = _activeCategory == AchievementFilterCategory.All;
        FilterCombatButton.Pressed = _activeCategory == AchievementFilterCategory.Combat;
        FilterSupportButton.Pressed = _activeCategory == AchievementFilterCategory.Support;
        FilterLogisticsButton.Pressed = _activeCategory == AchievementFilterCategory.Logistics;
        FilterObjectiveButton.Pressed = _activeCategory == AchievementFilterCategory.Objective;
        FilterParticipationButton.Pressed = _activeCategory == AchievementFilterCategory.Participation;
        FilterHiddenButton.Pressed = _activeCategory == AchievementFilterCategory.Hidden;
        FilterSpecialButton.Pressed = _activeCategory == AchievementFilterCategory.Special;

        RefreshSummary();
        RefreshCards();
    }

    private void RefreshSummary()
    {
        var completed = _completedAchievements;
        var total = _totalAchievements;
        var percent = total == 0
            ? 0
            : (int) Math.Floor(completed * 100f / total);

        SummaryProgressLabel.Text = Loc.GetString(
            "wh40k-meta-progress-achievements-summary-progress",
            ("unlocked", completed),
            ("total", total),
            ("percent", percent));

        SummaryCompletionBar.MinValue = 0;
        SummaryCompletionBar.MaxValue = 100;
        SummaryCompletionBar.Value = Math.Clamp(percent, 0, 100);
    }

    private void RefreshCards()
    {
        AchievementsList.RemoveAllChildren();

        if (!_snapshotLoaded)
        {
            AchievementsList.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-meta-progress-achievements-loading"),
                Margin = new Thickness(4),
            });

            return;
        }

        var filtered = _entries
            .Where(MatchesFilter)
            .ToList();

        if (filtered.Count == 0)
        {
            AchievementsList.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-meta-progress-achievements-empty"),
                Margin = new Thickness(4),
            });

            return;
        }

        foreach (var entry in filtered)
        {
            AchievementsList.AddChild(CreateCard(entry));
        }
    }

    private bool MatchesFilter(WH40KMetaAchievementSnapshotEntry entry)
    {
        return _activeCategory switch
        {
            AchievementFilterCategory.All => true,
            AchievementFilterCategory.Combat => entry.Category == WH40KMetaAchievementCategory.Combat,
            AchievementFilterCategory.Support => entry.Category == WH40KMetaAchievementCategory.Support,
            AchievementFilterCategory.Logistics => entry.Category == WH40KMetaAchievementCategory.Logistics,
            AchievementFilterCategory.Objective => entry.Category == WH40KMetaAchievementCategory.Objective,
            AchievementFilterCategory.Participation => entry.Category == WH40KMetaAchievementCategory.Participation,
            AchievementFilterCategory.Hidden => entry.Category == WH40KMetaAchievementCategory.Hidden,
            AchievementFilterCategory.Special => entry.Category == WH40KMetaAchievementCategory.Special,
            _ => true,
        };
    }

    private Control CreateCard(WH40KMetaAchievementSnapshotEntry entry)
    {
        var unlocked = entry.Completed;
        var inProgress = !unlocked && entry.Progress > 0;
        var displayProgress = unlocked
            ? Math.Max(entry.Progress, entry.Target)
            : entry.Progress;
        var maskSecretDetails = WH40KMetaAchievementDisplayHelper.ShouldMaskSecretDetails(entry);

        var stateKey = unlocked
            ? "wh40k-meta-progress-achievements-status-unlocked"
            : inProgress
                ? "wh40k-meta-progress-achievements-status-in-progress"
                : "wh40k-meta-progress-achievements-status-locked";

        var card = new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = unlocked
                    ? UnlockedBackground
                    : inProgress
                        ? InProgressBackground
                        : LockedBackground,
                BorderColor = unlocked
                    ? UnlockedBorder
                    : inProgress
                        ? InProgressBorder
                        : LockedBorder,
                BorderThickness = new Thickness(1),
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
            },
        };

        var root = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SeparationOverride = 4,
        };

        var header = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        header.AddChild(new Label
        {
            Text = Loc.GetString(entry.TitleKey),
            HorizontalExpand = true,
            StyleClasses = { "LabelHeading" },
        });

        header.AddChild(new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = unlocked
                    ? UnlockedChip
                    : inProgress
                        ? InProgressChip
                        : LockedChip,
                ContentMarginTopOverride = 2,
                ContentMarginBottomOverride = 2,
                ContentMarginLeftOverride = 6,
                ContentMarginRightOverride = 6,
            },
            Children =
            {
                new Label
                {
                    Text = Loc.GetString(stateKey),
                },
            },
        });

        root.AddChild(header);

        root.AddChild(new Label
        {
            Text = maskSecretDetails
                ? WH40KMetaAchievementDisplayHelper.HiddenPlaceholder
                : Loc.GetString(entry.DescriptionKey),
            HorizontalExpand = true,
        });

        root.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-meta-progress-achievements-task-line",
                ("task", maskSecretDetails
                    ? WH40KMetaAchievementDisplayHelper.HiddenPlaceholder
                    : Loc.GetString(entry.TaskKey))),
            HorizontalExpand = true,
        });

        root.AddChild(new ProgressBar
        {
            MinValue = 0,
            MaxValue = Math.Max(1, entry.Target),
            Value = Math.Clamp(displayProgress, 0, Math.Max(1, entry.Target)),
        });

        var footer = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
        };

        footer.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-meta-progress-achievements-progress-line",
                ("current", displayProgress),
                ("target", Math.Max(1, entry.Target))),
            HorizontalExpand = true,
        });

        footer.AddChild(new Label
        {
            Text = Loc.GetString(GetCategoryLocKey(entry.Category)),
        });

        root.AddChild(footer);

        root.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-meta-progress-achievements-reward-line",
                ("reward", BuildRewardText(entry))),
            HorizontalExpand = true,
        });

        card.AddChild(root);

        return card;
    }

    private string BuildRewardText(WH40KMetaAchievementSnapshotEntry entry)
    {
        var parts = new List<string>();

        if (entry.RewardXp > 0)
        {
            parts.Add(Loc.GetString(
                "wh40k-meta-progress-achievements-reward-xp",
                ("xp", entry.RewardXp)));
        }

        var decorationNames = entry.RewardDecorationIds
            .Select(ResolveDecorationTitle)
            .Where(title => !string.IsNullOrWhiteSpace(title))
            .Distinct(StringComparer.Ordinal)
            .ToList();

        if (decorationNames.Count > 0)
        {
            parts.Add(Loc.GetString(
                "wh40k-meta-progress-achievements-reward-decorations",
                ("decorations", string.Join(", ", decorationNames))));
        }

        if (parts.Count == 0)
            return Loc.GetString(entry.RewardKey);

        return string.Join(Environment.NewLine, parts);
    }

    private string ResolveDecorationTitle(string decorationId)
    {
        if (!_prototype.TryIndex<WH40KMetaDecorationPrototype>(decorationId, out var prototype) ||
            string.IsNullOrWhiteSpace(prototype?.TitleKey))
            return decorationId;

        return Loc.GetString(prototype.TitleKey);
    }

    private void ApplyStyles()
    {
        SummaryProgressHighlight.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = SummaryBackground,
            BorderColor = SummaryBorder,
            BorderThickness = new Thickness(1),
        };
    }

    private static int GetCategoryOrder(WH40KMetaAchievementCategory category)
    {
        return category switch
        {
            WH40KMetaAchievementCategory.Combat => 10,
            WH40KMetaAchievementCategory.Support => 20,
            WH40KMetaAchievementCategory.Logistics => 30,
            WH40KMetaAchievementCategory.Objective => 40,
            WH40KMetaAchievementCategory.Participation => 50,
            WH40KMetaAchievementCategory.Hidden => 60,
            WH40KMetaAchievementCategory.Special => 70,
            _ => 100,
        };
    }

    private static string GetCategoryLocKey(WH40KMetaAchievementCategory category)
    {
        return category switch
        {
            WH40KMetaAchievementCategory.Combat => "wh40k-meta-progress-achievements-filter-combat",
            WH40KMetaAchievementCategory.Support => "wh40k-meta-progress-achievements-filter-support",
            WH40KMetaAchievementCategory.Logistics => "wh40k-meta-progress-achievements-filter-logistics",
            WH40KMetaAchievementCategory.Objective => "wh40k-meta-progress-achievements-filter-objective",
            WH40KMetaAchievementCategory.Participation => "wh40k-meta-progress-achievements-filter-participation",
            WH40KMetaAchievementCategory.Hidden => "wh40k-meta-progress-achievements-filter-hidden",
            WH40KMetaAchievementCategory.Special => "wh40k-meta-progress-achievements-filter-special",
            _ => "wh40k-meta-progress-achievements-filter-all",
        };
    }

    private enum AchievementFilterCategory
    {
        All,
        Combat,
        Support,
        Logistics,
        Objective,
        Participation,
        Hidden,
        Special,
    }
}
