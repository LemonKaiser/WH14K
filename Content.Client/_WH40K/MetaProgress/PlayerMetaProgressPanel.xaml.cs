using Content.Client.Lobby.UI;
using Content.Shared.CCVar;
using Content.Shared._WH40K.MetaProgress;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Maths;

namespace Content.Client._WH40K.MetaProgress;

[GenerateTypedNameReferences]
public sealed partial class PlayerMetaProgressPanel : PanelContainer
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;

    public PlayerMetaProgressPanel()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        ApplyStyles();
        _cfg.OnValueChanged(CCVars.LobbyCustomizationPanelOpacity, OnCustomizationPanelOpacityChanged, true);
    }

    public void SetPreviewFromPlaytime(TimeSpan overallPlaytime)
    {
        var preview = CalculatePreviewProgress(overallPlaytime);

        LevelBadgeLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-level-badge",
            ("level", preview.Level));

        LevelProgressBar.MinValue = 0;
        LevelProgressBar.MaxValue = Math.Max(1, preview.RequiredXp);
        LevelProgressBar.Value = Math.Clamp(preview.CurrentXp, 0, preview.RequiredXp);

        ProgressLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-progress",
            ("current", preview.CurrentXp),
            ("required", preview.RequiredXp),
            ("total", preview.TotalXp));

        NextRewardLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-next-reward",
            ("level", GetNextRewardLevel(preview.Level)),
            ("decor", GetPreviewDecorationReward(preview.Level)),
            ("skills", GetPreviewSkillPointReward(preview.Level)));
    }

    public void SetFromSnapshot(WH40KMetaProgressSnapshot snapshot)
    {
        LevelBadgeLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-level-badge",
            ("level", snapshot.Level));

        LevelProgressBar.MinValue = 0;
        LevelProgressBar.MaxValue = Math.Max(1, snapshot.RequiredXp);
        LevelProgressBar.Value = Math.Clamp(snapshot.CurrentXp, 0, snapshot.RequiredXp);

        ProgressLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-progress",
            ("current", snapshot.CurrentXp),
            ("required", snapshot.RequiredXp),
            ("total", snapshot.LifetimeXp));

        if (snapshot.NextReward != null)
        {
            NextRewardLabel.Text = Loc.GetString(
                "wh40k-meta-progress-panel-next-reward",
                ("level", snapshot.NextReward.Level),
                ("decor", snapshot.NextReward.Decorations),
                ("skills", snapshot.NextReward.SkillPoints));

            return;
        }

        NextRewardLabel.Text = Loc.GetString(
            "wh40k-meta-progress-panel-next-reward",
            ("level", snapshot.Level),
            ("decor", 0),
            ("skills", 0));
    }

    public static (int Level, int CurrentXp, int RequiredXp, int TotalXp) CalculatePreviewProgress(TimeSpan playtime)
    {
        var totalXp = WH40KMetaProgressMath.LifetimeXpFromOverallPlaytime(playtime);
        var result = WH40KMetaProgressMath.CalculateFromLifetimeXp(totalXp);
        return (result.Level, result.CurrentXp, result.RequiredXp, result.LifetimeXp);
    }

    private static int GetNextRewardLevel(int currentLevel)
    {
        var normalizedLevel = Math.Max(1, currentLevel);
        var nextMilestone = ((normalizedLevel + 4) / 5) * 5;
        return nextMilestone > normalizedLevel ? nextMilestone : normalizedLevel + 5;
    }

    private static int GetPreviewDecorationReward(int currentLevel)
    {
        return 4;
    }

    private static int GetPreviewSkillPointReward(int currentLevel)
    {
        return 3;
    }

    private void ApplyStyles()
    {
        LevelBadgeContainer.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#3A3D54"),
            BorderColor = Color.FromHex("#70789A"),
            BorderThickness = new Thickness(1),
        };
    }

    private void OnCustomizationPanelOpacityChanged(float opacity)
    {
        LobbyPanelOpacityHelper.ApplyPanelOpacity(this, opacity);
        LobbyPanelOpacityHelper.ApplyPanelOpacity(LevelBadgeContainer, opacity);
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _cfg.UnsubValueChanged(CCVars.LobbyCustomizationPanelOpacity, OnCustomizationPanelOpacityChanged);

        base.Dispose(disposing);
    }
}
