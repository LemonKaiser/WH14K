            {
                BackgroundColor = style.Background,
                BorderColor = style.Border,
                BorderThickness = new Thickness(1),
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
            },
        };

        var root = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            SeparationOverride = 6,
            VerticalExpand = true,
        };

        root.AddChild(new Label
        {
            Text = FitTextWithEllipsis(Loc.GetString(entry.TitleKey), CardTitleMaxPixelWidth),
            ToolTip = Loc.GetString(entry.TitleKey),
            ClipText = true,
            HorizontalExpand = true,
            StyleClasses = { "LabelHeading" },
        });

        var previewPanel = new PanelContainer
        {
            MinSize = new Vector2(0, PreviewPanelMinHeight),
            VerticalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#232632"),
                BorderColor = Color.FromHex("#5D6588"),
                BorderThickness = new Thickness(1),
                ContentMarginTopOverride = 6,
                ContentMarginBottomOverride = 6,
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
            },
        };

        previewPanel.AddChild(BuildPreviewContent(entry));
        root.AddChild(previewPanel);
        root.AddChild(new Control { VerticalExpand = true });
        var actionButton = BuildActionButton(entry, unlocked, selected);
        root.AddChild(actionButton);

        card.AddChild(root);

        if (!unlocked && !selected && !string.IsNullOrWhiteSpace(actionButton.ToolTip))
            card.ToolTip = actionButton.ToolTip;

        return card;
    }

    private Button BuildActionButton(WH40KMetaDecorationSnapshotEntry entry, bool unlocked, bool selected)
    {
        var button = new Button
        {
            HorizontalExpand = true,
        };

        if (selected)
        {
            button.Text = Loc.GetString("w40k-decs-action-selected");
            button.Disabled = true;
            return button;
        }

        if (unlocked)
        {
            button.Text = Loc.GetString("w40k-decs-action-choose");
            button.OnPressed += _ =>
            {
                _selectedByCategory[entry.Category] = entry.Id;
                _metaProgress.SetDecorationSelection(entry.Category, entry.Id);
                RefreshView();
            };

            return button;
        }

        button.Text = BuildLockedActionText(entry.Requirement);
        button.Disabled = true;
        button.ToolTip = BuildLockedActionTooltip(entry.Requirement);
        return button;
    }

    private static string BuildLockedActionText(WH40KMetaDecorationRequirementSnapshot requirement)
    {
        if (requirement.AdminOnly)
        {
            return Loc.GetString("w40k-decs-action-admin-only");
        }

        var hasAchievements = requirement.RequiredAchievements.Count > 0;
        var hasLevel = requirement.RequiredLevel > 1;
        var hasDiscordRole = requirement.RequiredDiscordRoleIds.Count > 0;
        var hasDiscordGuild = requirement.RequiredDiscordGuildMember;
        var hasDiscordRequirement = hasDiscordRole || hasDiscordGuild;

        if (hasDiscordRequirement && (hasLevel || hasAchievements))
        {
            return Loc.GetString("w40k-decs-action-requires-discord-and-meta");
        }

        if (hasDiscordRole)
        {
            return Loc.GetString("w40k-decs-action-requires-discord-role");
        }

        if (hasDiscordGuild)
        {
            return Loc.GetString("w40k-decs-action-requires-discord-guild");
        }

        if (hasLevel && hasAchievements)
        {
            return Loc.GetString(
                "w40k-decs-action-requires-level-and-achievements",
                ("level", requirement.RequiredLevel),
                ("count", requirement.RequiredAchievements.Count));
        }

        if (hasAchievements)
        {
            return Loc.GetString(
                "w40k-decs-action-requires-achievements",
                ("count", requirement.RequiredAchievements.Count));
        }

        return Loc.GetString(
            "w40k-decs-action-requires-level",
            ("level", requirement.RequiredLevel));
    }

    private string? BuildLockedActionTooltip(WH40KMetaDecorationRequirementSnapshot requirement)
    {
        if (requirement.AdminOnly)
            return Loc.GetString("w40k-decs-tooltip-admin-only");

        var lines = new List<string>();

        if (requirement.RequiredLevel > 1)
        {
            lines.Add(Loc.GetString(
                "w40k-decs-tooltip-level",
                ("level", requirement.RequiredLevel)));
        }

        if (requirement.RequiredAchievements.Count > 0)
        {
            var titles = requirement.RequiredAchievements
                .Select(ResolveAchievementTitle)
                .Where(title => !string.IsNullOrWhiteSpace(title))
                .Distinct(StringComparer.Ordinal)
                .ToList();

            if (titles.Count == 0)
            {
                lines.Add(Loc.GetString(
                    "w40k-decs-tooltip-achievements",
                    ("count", requirement.RequiredAchievements.Count)));
            }
            else
            {
                lines.Add(Loc.GetString("w40k-decs-tooltip-achievements-header"));
                lines.AddRange(titles.Select(title => $"- {title}"));
            }
        }

        if (requirement.RequiredDiscordGuildMember || requirement.RequiredDiscordRoleIds.Count > 0)
        {
            lines.Add(Loc.GetString("w40k-decs-tooltip-discord-link"));
        }

        if (requirement.RequiredDiscordGuildMember || requirement.RequiredDiscordRoleIds.Count > 0)
        {
            lines.Add(Loc.GetString("w40k-decs-tooltip-discord-guild"));
        }

        if (requirement.RequiredDiscordRoleIds.Count > 0)
        {
            lines.Add(Loc.GetString(
                "w40k-decs-tooltip-discord-roles",
                ("roles", string.Join(", ", requirement.RequiredDiscordRoleIds))));
        }

        if (lines.Count == 0)
            return null;

        return string.Join(Environment.NewLine, lines);
    }

    private string ResolveAchievementTitle(string achievementId)
    {
        if (!_prototype.TryIndex<WH40KMetaAchievementPrototype>(achievementId, out var prototype) ||
            string.IsNullOrWhiteSpace(prototype?.TitleKey))
            return achievementId;

        return Loc.GetString(prototype.TitleKey);
    }

    private Control BuildPreviewContent(WH40KMetaDecorationSnapshotEntry entry)
    {
        if (entry.Category == WH40KMetaDecorationCategory.GhostSkins)
            return BuildGhostPreview(entry);

        if (entry.Category == WH40KMetaDecorationCategory.OocNameColors &&
            TryBuildOocColorPreviewMarkup(entry, out var colorMarkup))
        {
            var colorPreviewText = BuildPreviewText(entry, truncate: false);
            var gradientPreview = new RichTextLabel
            {
                HorizontalExpand = true,
                VerticalExpand = true,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                RectClipContent = true,
                ToolTip = colorPreviewText,
            };

            if (TrySetMarkupPreviewMessage(gradientPreview, colorMarkup))
                return gradientPreview;
        }

        if (entry.Category == WH40KMetaDecorationCategory.OocTitles &&
            TryBuildOocTitleEffectPreviewMarkup(entry, ResolveSelectedOocColorEntry(), out var titleMarkup))
        {
            var titlePreviewText = BuildPreviewText(entry, truncate: false);
            var titlePreview = new RichTextLabel
            {
                HorizontalExpand = true,
                VerticalExpand = true,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                RectClipContent = true,
                ToolTip = titlePreviewText,
            };

            if (TrySetMarkupPreviewMessage(titlePreview, titleMarkup))
                return titlePreview;
        }

        var fullPreviewText = BuildPreviewText(entry, truncate: false);
        var previewText = FitTextWithEllipsis(fullPreviewText, PreviewTextMaxPixelWidth);
        var previewLabel = new RichTextLabel
        {
            ToolTip = fullPreviewText,
            RectClipContent = true,
            HorizontalExpand = true,
            VerticalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        };

        if (entry.Category == WH40KMetaDecorationCategory.OocNameColors &&
            Color.TryFromHex(entry.OocColorHex) is { } color)
        {
            previewLabel.SetMessage(FormattedMessage.FromUnformatted(previewText), tagsAllowed: null, defaultColor: color);
            return previewLabel;
        }

        previewLabel.SetMessage(FormattedMessage.FromUnformatted(previewText), tagsAllowed: null);
        return previewLabel;
    }

    private WH40KMetaDecorationSnapshotEntry? ResolveSelectedOocColorEntry()
    {
        if (!_selectedByCategory.TryGetValue(WH40KMetaDecorationCategory.OocNameColors, out var selectedColorId))
            return null;

        foreach (var entry in _entries)
        {
            if (!entry.Unlocked ||
                entry.Category != WH40KMetaDecorationCategory.OocNameColors ||
                !string.Equals(entry.Id, selectedColorId, StringComparison.Ordinal))
            {
                continue;
            }

            return entry;
        }

        return null;
    }

    private bool TryBuildOocColorPreviewMarkup(
        WH40KMetaDecorationSnapshotEntry entry,
        out string markup)
    {
        markup = string.Empty;

        if (entry.Category != WH40KMetaDecorationCategory.OocNameColors)
            return false;

        var palette = new List<string>(entry.OocGradientColors.Count + 1);
        foreach (var paletteEntry in entry.OocGradientColors)
        {
            if (!TryResolveColor(paletteEntry, out var parsed))
                continue;

            palette.Add(parsed.ToHex());
        }

        var hasGradient = palette.Count >= 2;
        if (!hasGradient && TryResolveColor(entry.OocColorHex, out var solidColor))
            palette.Add(solidColor.ToHex());

        if (palette.Count == 0)
            return false;

        var safeText = SanitizeGradientTagParameter(FitTextWithEllipsis(_previewPlayerName, PreviewTextMaxPixelWidth));
        var safePalette = SanitizeGradientTagParameter(string.Join("|", palette));
        var animated = hasGradient && entry.OocGradientAnimated ? 1 : 0;
        var durationMs = Math.Clamp(entry.OocGradientDurationMs, 400, 60000);
        var auraColor = Color.White;
        var hasAura = entry.OocAuraRadius > 0 &&
                      entry.OocAuraAlphaPercent > 0 &&
                      TryResolveColor(entry.OocAuraHex, out auraColor);

        if (!hasGradient && !hasAura)
            return false;

        var builder = new StringBuilder();
        builder.Append("[wh40kgradient=\"")
            .Append(safeText)
            .Append("\" palette=\"")
            .Append(safePalette)
            .Append("\" animated=")
            .Append(animated)
            .Append(" duration=")
            .Append(durationMs);

        if (hasAura)
        {
            builder.Append(" aura=1")
                .Append(" auracolor=\"")
                .Append(SanitizeGradientTagParameter(auraColor.ToHex()))
                .Append("\" auraradius=")
                .Append(Math.Clamp(entry.OocAuraRadius, 1, 4))
                .Append(" auraalpha=")
                .Append(Math.Clamp(entry.OocAuraAlphaPercent, 1, 100));
        }

        builder.Append("/]");
        markup = builder.ToString();
        return true;
    }

    private bool TryBuildOocTitleEffectPreviewMarkup(
        WH40KMetaDecorationSnapshotEntry entry,
        WH40KMetaDecorationSnapshotEntry? colorEntry,
        out string markup)
    {
        markup = string.Empty;

        if (entry.Category != WH40KMetaDecorationCategory.OocTitles ||
            entry.SuppressTitlePrefix)
        {
            return false;
        }

        var titlePreviewName = ResolvePreviewName(entry);
        if (string.IsNullOrWhiteSpace(titlePreviewName))
            return false;

        BuildTitlePreviewParts(titlePreviewName, out var titleText, out var nameText);
        if (string.IsNullOrWhiteSpace(titleText))
            return false;

        if (!TryBuildTitlePalette(entry, colorEntry, out var palette, out var animated, out var durationMs))
            return false;

        var safeTitle = SanitizeGradientTagParameter(titleText);
        var safeName = FormattedMessage.EscapeText(nameText);
        var safePalette = SanitizeGradientTagParameter(string.Join("|", palette));
        var hasEffect = TryNormalizeTitleEffect(entry.OocTitleEffect, out var effect);
        var revealMs = Math.Clamp(entry.OocTitleEffectRevealMs, 100, 120000);
        var holdMs = Math.Clamp(entry.OocTitleEffectHoldMs, 100, 120000);
        var dissolveMs = Math.Clamp(entry.OocTitleEffectDissolveMs, 100, 120000);

        var hasOutline = TryResolveTitleOutline(entry, out var outlineColorHex, out var outlineWidth, out var outlineAlphaPercent);
        var builder = new StringBuilder();
        builder.Append("[wh40ktitlefx=\"")
            .Append(safeTitle)
            .Append("\" palette=\"")
            .Append(safePalette)
            .Append("\" animated=")
            .Append(animated)
            .Append(" duration=")
            .Append(durationMs)
            .Append(" reveal=")
            .Append(revealMs)
            .Append(" hold=")
            .Append(holdMs)
            .Append(" dissolve=")
            .Append(dissolveMs)
            .Append(" cursor=1");

        if (hasEffect)
        {
            builder.Append(" effect=\"")
                .Append(SanitizeGradientTagParameter(effect))
                .Append("\"");
        }

        if (hasOutline)
        {
            builder.Append(" outline=1")
                .Append(" outlinecolor=\"")
                .Append(SanitizeGradientTagParameter(outlineColorHex))
                .Append("\" outlinewidth=")
                .Append(outlineWidth)
                .Append(" outlinealpha=")
                .Append(outlineAlphaPercent);
        }

        builder.Append("/]");
        if (!string.IsNullOrWhiteSpace(nameText))
        {
            builder.Append(' ')
                .Append(safeName);
        }

        markup = builder.ToString();
        return true;
    }

    private static bool TryNormalizeTitleEffect(string source, out string effect)
    {
        effect = string.Empty;

        if (string.IsNullOrWhiteSpace(source))
            return false;

        effect = source.Trim().ToLowerInvariant() switch
        {
            "binary" => "binary",
            "scan" => "scan",
            "fish" or "fish-swim" => "fish",
            "scramble-decode" or "scramble" => "scramble-decode",
            "typewriter-cursor" or "typewriter" => "typewriter-cursor",
            "wave" => "wave",
            "glitch-slice" or "glitch" => "glitch-slice",
            "noise-dissolve" or "dissolve-noise" or "noise" => "noise-dissolve",
            "scanline" => "scanline",
            "flip" or "discord-flip" => "flip",
            _ => string.Empty,
        };

        return effect.Length > 0;
    }

    private void BuildTitlePreviewParts(string titlePreviewName, out string titleText, out string nameText)
    {
        var baseTitle = $"({titlePreviewName})";
        if (string.IsNullOrWhiteSpace(baseTitle))
        {
            titleText = string.Empty;
            nameText = FitTextWithEllipsis(_previewPlayerName, PreviewTextMaxPixelWidth);
            return;
        }

        var font = UserInterfaceManager.ThemeDefaults.LabelFont;
        var spaceWidth = MeasureTextWidth(" ", font);

        nameText = FitTextWithEllipsis(_previewPlayerName, PreviewTextMaxPixelWidth);
        var maxTitleWidth = (int) MathF.Max(
            40f,
            PreviewTextMaxPixelWidth - MeasureTextWidth(nameText, font) - spaceWidth);
        titleText = FitTextWithEllipsis(baseTitle, maxTitleWidth);

        var combinedWidth = MeasureTextWidth($"{titleText} {nameText}", font);
        if (combinedWidth <= PreviewTextMaxPixelWidth)
            return;

        var maxNameWidth = (int) MathF.Max(
            30f,
            PreviewTextMaxPixelWidth - MeasureTextWidth(titleText, font) - spaceWidth);
        nameText = FitTextWithEllipsis(_previewPlayerName, maxNameWidth);
    }

    private static bool TryBuildTitlePalette(
        WH40KMetaDecorationSnapshotEntry titleEntry,
        WH40KMetaDecorationSnapshotEntry? fallbackColorEntry,
        out List<string> palette,
        out int animated,
        out int durationMs)
    {
        palette = new List<string>();
        animated = 0;
        durationMs = 3500;

        WH40KMetaDecorationSnapshotEntry? sourceEntry = null;
        if (TryAppendPaletteFromEntry(titleEntry, palette))
            sourceEntry = titleEntry;
        else if (TryAppendPaletteFromEntry(fallbackColorEntry, palette))
            sourceEntry = fallbackColorEntry;

        if (palette.Count == 0 && TryResolveColor("#87CEFA", out var defaultColor))
            palette.Add(defaultColor.ToHex());

        if (palette.Count == 0)
            return false;

        var hasGradient = palette.Count >= 2;
        animated = hasGradient && sourceEntry?.OocGradientAnimated == true ? 1 : 0;
        durationMs = Math.Clamp(sourceEntry?.OocGradientDurationMs ?? 3500, 400, 60000);
        return true;
    }

    private static bool TryAppendPaletteFromEntry(
        WH40KMetaDecorationSnapshotEntry? entry,
        List<string> palette)
    {
        if (entry == null)
            return false;

        var startCount = palette.Count;
        foreach (var paletteEntry in entry.OocGradientColors)
        {
            if (!TryResolveColor(paletteEntry, out var paletteColor))
                continue;

            palette.Add(paletteColor.ToHex());
        }

        if (palette.Count == startCount && TryResolveColor(entry.OocColorHex, out var solidColor))
            palette.Add(solidColor.ToHex());

        return palette.Count > startCount;
    }

    private static bool TryResolveTitleOutline(
        WH40KMetaDecorationSnapshotEntry entry,
        out string outlineColorHex,
        out int outlineWidth,
        out int outlineAlphaPercent)
    {
        outlineColorHex = string.Empty;
        outlineWidth = 0;
        outlineAlphaPercent = 0;

        if (entry.OocTitleOutlineWidth <= 0 ||
            entry.OocTitleOutlineAlphaPercent <= 0 ||
            !TryResolveColor(entry.OocTitleOutlineHex, out var outlineColor))
        {
            return false;
        }

        outlineColorHex = outlineColor.ToHex();
        outlineWidth = Math.Clamp(entry.OocTitleOutlineWidth, 1, 3);
        outlineAlphaPercent = Math.Clamp(entry.OocTitleOutlineAlphaPercent, 1, 100);
        return true;
    }

    private static bool TryResolveColor(string source, out Color color)
    {
        color = default;

        if (string.IsNullOrWhiteSpace(source))
            return false;

        var trimmed = source.Trim();
        if (Color.TryFromHex(trimmed) is { } hexColor)
        {
            color = hexColor;
            return true;
        }

        if (Color.TryFromName(trimmed, out var namedColor))
        {
            color = namedColor;
            return true;
        }

        return false;
    }

