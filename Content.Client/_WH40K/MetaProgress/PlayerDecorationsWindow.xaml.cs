    private Control BuildGhostPreview(WH40KMetaDecorationSnapshotEntry entry)
    {
        var grid = new GridContainer
        {
            Columns = 2,
            HSeparationOverride = 8,
            VSeparationOverride = 8,
            HorizontalExpand = false,
            VerticalExpand = false,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
        };

        var tint = Color.TryFromHex(entry.GhostTintHex) ?? Color.White;
        var added = 0;

        foreach (var direction in GhostPreviewDirections)
        {
            var texture = ResolveGhostTexture(entry, direction);
            if (texture == null)
                continue;

            added++;
            grid.AddChild(new TextureRect
            {
                Texture = texture,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                CanShrink = true,
                MinSize = new Vector2(GhostPreviewCellSize, GhostPreviewCellSize),
                SetSize = new Vector2(GhostPreviewCellSize, GhostPreviewCellSize),
                HorizontalExpand = false,
                VerticalExpand = false,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                Modulate = tint,
            });
        }

        if (added > 0)
            return grid;

        return new Label
        {
            Text = BuildPreviewText(entry),
            ToolTip = BuildPreviewText(entry, truncate: false),
            ClipText = true,
            HorizontalExpand = true,
            VerticalExpand = true,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            Align = Label.AlignMode.Center,
        };
    }

    private Texture? ResolveGhostTexture(WH40KMetaDecorationSnapshotEntry entry, Direction direction)
    {
        if (string.IsNullOrWhiteSpace(entry.GhostRsiPath) || string.IsNullOrWhiteSpace(entry.GhostState))
            return null;

        if (!_resources.TryGetResource<RSIResource>(new ResPath(entry.GhostRsiPath), out var resource))
            return null;

        if (!resource.RSI.TryGetState(entry.GhostState, out var state))
            return null;

        if (state.DelayCount <= 0)
            return null;

        var rsiDirection = direction.Convert(state.RsiDirections);
        return state.GetFrame(rsiDirection, 0);
    }

    private string BuildPreviewText(WH40KMetaDecorationSnapshotEntry entry, bool truncate = true)
    {
        var text = entry.Category switch
        {
            WH40KMetaDecorationCategory.GhostSkins => Loc.GetString(
                "w40k-decs-ghost-preview-format",
                ("preview", ResolvePreviewName(entry))),

            WH40KMetaDecorationCategory.OocTitles => Loc.GetString(
                entry.SuppressTitlePrefix
                    ? "w40k-decs-ooc-title-preview-none-format"
                    : "w40k-decs-ooc-title-preview-format",
                ("title", ResolvePreviewName(entry)),
                ("name", _previewPlayerName)),

            WH40KMetaDecorationCategory.OocNameColors => Loc.GetString(
                "w40k-decs-ooc-color-preview-format",
                ("name", _previewPlayerName)),

            _ => Loc.GetString(entry.TitleKey),
        };

        return truncate
            ? FitTextWithEllipsis(text, PreviewTextMaxPixelWidth)
            : text;
    }

    private string FitTextWithEllipsis(string? source, int maxPixelWidth)
    {
        if (string.IsNullOrWhiteSpace(source))
            return string.Empty;

        if (maxPixelWidth <= 0)
            return "...";

        var font = UserInterfaceManager.ThemeDefaults.LabelFont;
        var text = source.Trim();

        if (MeasureTextWidth(text, font) <= maxPixelWidth)
            return text;

        const string ellipsis = "...";
        var ellipsisWidth = MeasureTextWidth(ellipsis, font);
        var allowedWidth = Math.Max(0f, maxPixelWidth - ellipsisWidth);

        var width = 0f;
        var cutIndex = 0;
        foreach (var rune in text.EnumerateRunes())
        {
            var advance = GetRuneAdvance(font, rune);
            if (width + advance > allowedWidth)
                break;

            width += advance;
            cutIndex += rune.Utf16SequenceLength;
        }

        if (cutIndex <= 0)
            return ellipsis;

        return $"{text[..cutIndex]}{ellipsis}";
    }

    private float MeasureTextWidth(string text, Font font)
    {
        var width = 0f;
        foreach (var rune in text.EnumerateRunes())
        {
            width += GetRuneAdvance(font, rune);
        }

        return width;
    }

    private float GetRuneAdvance(Font font, Rune rune)
    {
        var metrics = font.GetCharMetrics(rune, UIScale, fallback: true);
        if (metrics is { } measured)
            return measured.Advance;

        return font.GetCharMetrics(new Rune('?'), UIScale, fallback: false)?.Advance ?? 0f;
    }

    private static int GetCategoryOrder(WH40KMetaDecorationCategory category)
    {
        return category switch
        {
            WH40KMetaDecorationCategory.GhostSkins => 10,
            WH40KMetaDecorationCategory.OocTitles => 20,
            WH40KMetaDecorationCategory.OocNameColors => 30,
            _ => 100,
        };
    }

    private string ResolvePreviewName(WH40KMetaDecorationSnapshotEntry entry)
    {
        var key = string.IsNullOrWhiteSpace(entry.PreviewKey)
            ? entry.TitleKey
            : entry.PreviewKey;
        return Loc.GetString(key);
    }

    private bool IsSelected(WH40KMetaDecorationSnapshotEntry entry)
    {
        return entry.Unlocked &&
               _selectedByCategory.TryGetValue(entry.Category, out var selectedId) &&
               string.Equals(selectedId, entry.Id, StringComparison.Ordinal);
    }

