    public PlayerDecorationsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _metaProgress = _entManager.System<WH40KMetaProgressSystem>();

        ResolvePreviewContext();
        ApplyStyles();
        BindCategoryButtons();
        Relocalize();

        _metaProgress.SnapshotUpdated += OnMetaSnapshotUpdated;
        _metaProgress.EnsureSnapshot();

        if (_metaProgress.TryGetCachedSnapshot(out var snapshot))
            ApplySnapshot(snapshot);
        else
            RefreshView();
    }

    [Obsolete]
    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _metaProgress.SnapshotUpdated -= OnMetaSnapshotUpdated;

#pragma warning disable CS0618
        base.Dispose(disposing);
#pragma warning restore CS0618
    }

    private void ResolvePreviewContext()
    {
        if (!string.IsNullOrWhiteSpace(_playerManager.LocalSession?.Name))
        {
            _previewPlayerName = _playerManager.LocalSession!.Name;
        }
        else
        {
            _previewPlayerName = Loc.GetString("w40k-decs-player-fallback");
        }
    }

    private void OnMetaSnapshotUpdated(WH40KMetaProgressSnapshot snapshot)
    {
        ApplySnapshot(snapshot);
    }

    private void ApplySnapshot(WH40KMetaProgressSnapshot snapshot)
    {
        _accountLevel = Math.Max(1, snapshot.Level);

        _entries.Clear();
        _entries.AddRange(snapshot.Decorations
            .OrderBy(entry => GetCategoryOrder(entry.Category))
            .ThenBy(entry => entry.SortOrder)
            .ThenBy(entry => entry.Id));

        _selectedByCategory.Clear();

        TrySeedSelected(
            WH40KMetaDecorationCategory.GhostSkins,
            snapshot.DecorationSelection.SelectedGhostSkinId);
        TrySeedSelected(
            WH40KMetaDecorationCategory.OocTitles,
            snapshot.DecorationSelection.SelectedOocTitleId);
        TrySeedSelected(
            WH40KMetaDecorationCategory.OocNameColors,
            snapshot.DecorationSelection.SelectedOocNameColorId);

        SeedMissingSelectedEntries();

        _snapshotLoaded = true;
        RefreshView();
    }

    private void TrySeedSelected(WH40KMetaDecorationCategory category, string decorationId)
    {
        if (string.IsNullOrWhiteSpace(decorationId))
            return;

        _selectedByCategory[category] = decorationId;
    }

    private void SeedMissingSelectedEntries()
    {
        foreach (var category in Enum.GetValues<WH40KMetaDecorationCategory>())
        {
            var categoryEntries = _entries
                .Where(entry => entry.Category == category)
                .OrderBy(entry => entry.SortOrder)
                .ThenBy(entry => entry.Id)
                .ToList();

            if (categoryEntries.Count == 0)
                continue;

            if (_selectedByCategory.TryGetValue(category, out var currentSelected))
            {
                var selectedEntry = categoryEntries.FirstOrDefault(entry =>
                    string.Equals(entry.Id, currentSelected, StringComparison.Ordinal));
                if (selectedEntry != null && selectedEntry.Unlocked)
                    continue;
            }

            var firstUnlocked = categoryEntries.FirstOrDefault(entry => entry.Unlocked);
            _selectedByCategory[category] = firstUnlocked?.Id ?? categoryEntries[0].Id;
        }
    }

    public void Relocalize()
    {
        ResolvePreviewContext();
        Title = Loc.GetString("w40k-decs-window-title");
        MenuHeaderLabel.Text = Loc.GetString("w40k-decs-menu-header");
        GhostSkinsTabButton.Text = Loc.GetString("w40k-decs-tab-ghost-skins");
        OocTitlesTabButton.Text = Loc.GetString("w40k-decs-tab-ooc-titles");
        OocNameColorsTabButton.Text = Loc.GetString("w40k-decs-tab-ooc-name-colors");
        RefreshView();
    }

    private void BindCategoryButtons()
    {
        GhostSkinsTabButton.OnPressed += _ => SetFilter(WH40KMetaDecorationCategory.GhostSkins);
        OocTitlesTabButton.OnPressed += _ => SetFilter(WH40KMetaDecorationCategory.OocTitles);
        OocNameColorsTabButton.OnPressed += _ => SetFilter(WH40KMetaDecorationCategory.OocNameColors);
    }

    private void SetFilter(WH40KMetaDecorationCategory category)
    {
        _activeCategory = category;
        RefreshView();
    }

    private void RefreshView()
    {
        GhostSkinsTabButton.Pressed = _activeCategory == WH40KMetaDecorationCategory.GhostSkins;
        OocTitlesTabButton.Pressed = _activeCategory == WH40KMetaDecorationCategory.OocTitles;
        OocNameColorsTabButton.Pressed = _activeCategory == WH40KMetaDecorationCategory.OocNameColors;

        RefreshSummary();
        RefreshCards();
    }

    private void RefreshSummary()
    {
        var ghostUnlocked = _entries.Count(entry =>
            entry.Category == WH40KMetaDecorationCategory.GhostSkins && entry.Unlocked);
        var ghostTotal = _entries.Count(entry => entry.Category == WH40KMetaDecorationCategory.GhostSkins);

        var titleUnlocked = _entries.Count(entry =>
            entry.Category == WH40KMetaDecorationCategory.OocTitles && entry.Unlocked);
        var titleTotal = _entries.Count(entry => entry.Category == WH40KMetaDecorationCategory.OocTitles);

        var colorUnlocked = _entries.Count(entry =>
            entry.Category == WH40KMetaDecorationCategory.OocNameColors && entry.Unlocked);
        var colorTotal = _entries.Count(entry => entry.Category == WH40KMetaDecorationCategory.OocNameColors);

        SummaryProgressLabel.Text = Loc.GetString(
            "w40k-decs-summary-by-category",
            ("ghostUnlocked", ghostUnlocked),
            ("ghostTotal", ghostTotal),
            ("titleUnlocked", titleUnlocked),
            ("titleTotal", titleTotal),
            ("colorUnlocked", colorUnlocked),
            ("colorTotal", colorTotal));

        AccountLevelLabel.Text = Loc.GetString(
            "w40k-decs-account-level",
            ("level", _accountLevel));
    }

    private void RefreshCards()
    {
        CardsList.RemoveAllChildren();

        if (!_snapshotLoaded)
        {
            CardsList.AddChild(new Label
            {
                Text = Loc.GetString("w40k-decs-loading"),
                Margin = new Thickness(4),
            });

            return;
        }

        var filtered = _entries
            .Where(entry => entry.Category == _activeCategory)
            .OrderBy(entry => entry.SortOrder)
            .ThenBy(entry => entry.Id)
            .ToList();

        if (filtered.Count == 0)
        {
            CardsList.AddChild(new Label
            {
                Text = Loc.GetString("w40k-decs-empty"),
                Margin = new Thickness(4),
            });

            return;
        }

        const int cardsPerRow = 3;
        BoxContainer? row = null;

        for (var i = 0; i < filtered.Count; i++)
        {
            if (i % cardsPerRow == 0)
            {
                row = new BoxContainer
                {
                    Orientation = LayoutOrientation.Horizontal,
                    SeparationOverride = 8,
                    HorizontalExpand = true,
                };

                CardsList.AddChild(row);
            }

            row!.AddChild(CreateCard(filtered[i]));
        }
    }

