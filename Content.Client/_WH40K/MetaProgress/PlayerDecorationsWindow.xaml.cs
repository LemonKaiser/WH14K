        var unlocked = entry.Unlocked;
        var selected = IsSelected(entry);
        var style = GetCardStyle(unlocked, selected);

        var card = new PanelContainer
        {
            MinSize = new Vector2(CardWidth, CardHeight),
            SetSize = new Vector2(CardWidth, CardHeight),
            HorizontalExpand = false,
