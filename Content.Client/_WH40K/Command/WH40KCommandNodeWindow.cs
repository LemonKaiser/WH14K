    private void ApplyFooter(WH40KCommandNodeBoundUserInterfaceState state)
    {
        FooterLabel.Text = CanUpgradeNode(state)
            ? Loc.GetString("w40k-cmd-footer-upgrade-ready", ("cost", FormatFundsResearchCost(state.UpgradeFundsCost, state.UpgradeResearchCost)))
            : CanCallReinforcement(state)
                ? Loc.GetString("w40k-cmd-footer-reinforcement-ready", ("cost", FormatReinforcementCost(state)))
                : BuildCompactText(BuildFocusText(state), 176);
    }

    private static bool CanUpgradeNode(WH40KCommandNodeBoundUserInterfaceState state)
    {
        return (state.UpgradeFundsCost > 0 || state.UpgradeResearchCost > 0) &&
               state.Funds >= state.UpgradeFundsCost &&
               state.ResearchPoints >= state.UpgradeResearchCost;
    }

    private static bool CanCallReinforcement(WH40KCommandNodeBoundUserInterfaceState state)
    {
        return state.Phase == WH40KBattlePhase.Assault &&
               (state.ReinforcementFundsCost > 0 || state.ReinforcementInfluenceCost > 0 || state.ReinforcementArtifactCost > 0) &&
               state.Funds >= state.ReinforcementFundsCost &&
               state.InfluencePoints >= state.ReinforcementInfluenceCost &&
               state.ArtifactPoints >= state.ReinforcementArtifactCost &&
               state.ReinforcementCooldownSeconds <= 0;
    }

    private static string BuildStatusBadgeText(WH40KCommandNodeBoundUserInterfaceState state)
    {
        return CanUpgradeNode(state) || CanCallReinforcement(state)
            ? Loc.GetString("w40k-cmd-status-badge-ready")
            : Loc.GetString("w40k-cmd-status-badge-limited");
    }

    private static StyleBoxFlat ResolvePhaseBadgeStyle(WH40KBattlePhase phase, Color accent, bool chaosTheme)
    {
        return phase switch
        {
            WH40KBattlePhase.Preparation => WH40KCommandUiStyles.CreateBadgeStyle(
                WH40KCommandUiStyles.ResolveBadgeBackground(chaosTheme),
                WH40KCommandUiStyles.InfoBadge),
            WH40KBattlePhase.Assault => WH40KCommandUiStyles.CreateBadgeStyle(
                WH40KCommandUiStyles.ResolveBadgeBackground(chaosTheme),
                accent),
            WH40KBattlePhase.Apocalypse => WH40KCommandUiStyles.CreateBadgeStyle(
                Color.FromHex("#231012".AsSpan()),
                WH40KCommandUiStyles.DangerBadge),
            _ => WH40KCommandUiStyles.CreateBadgeStyle(
                WH40KCommandUiStyles.ResolveBadgeBackground(chaosTheme),
                WH40KCommandUiStyles.InfoBadge)
        };
    }

    private static StyleBoxFlat ResolveStatusBadgeStyle(
        WH40KCommandNodeBoundUserInterfaceState state,
        Color accent,
        bool chaosTheme)
    {
        if (CanUpgradeNode(state) || CanCallReinforcement(state))
        {
            return WH40KCommandUiStyles.CreateBadgeStyle(
                Color.FromHex("#162015".AsSpan()),
                WH40KCommandUiStyles.ReadyBadge);
        }

        if (state.Phase >= WH40KBattlePhase.Apocalypse)
        {
            return WH40KCommandUiStyles.CreateBadgeStyle(
                Color.FromHex("#231012".AsSpan()),
                WH40KCommandUiStyles.DangerBadge);
        }

        return WH40KCommandUiStyles.CreateBadgeStyle(
            WH40KCommandUiStyles.ResolveBadgeBackground(chaosTheme),
            accent);
    }

