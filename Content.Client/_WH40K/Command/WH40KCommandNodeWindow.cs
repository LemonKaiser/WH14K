    private static (float Value, int SegmentCurrent, int SegmentTotal) CalculateBaseProgress(
        WH40KCommandNodeBoundUserInterfaceState state)
    {
        if (state.PointsToNextLevel == null)
            return (1f, 1, 1);

        if (state.LevelThresholds.Length == 0)
        {
            var total = Math.Max(1, state.PointsToNextLevel.Value);
            return (0f, 0, total);
        }

        var level = Math.Max(1, state.BaseLevel);
        var thresholds = state.LevelThresholds;

        var segmentStart = 0;
        if (level > 1)
        {
            var previousThresholdIndex = Math.Clamp(level - 2, 0, thresholds.Length - 1);
            segmentStart = thresholds[previousThresholdIndex];
        }

        var currentThresholdIndex = Math.Clamp(level - 1, 0, thresholds.Length - 1);
        var segmentEnd = thresholds[currentThresholdIndex];

        if (segmentEnd <= segmentStart)
        {
            var fallbackTotal = Math.Max(1, state.PointsToNextLevel.Value + Math.Max(0, state.FrontPoints - segmentStart));
            var fallbackCurrent = Math.Clamp(fallbackTotal - state.PointsToNextLevel.Value, 0, fallbackTotal);
            return ((float) fallbackCurrent / fallbackTotal, fallbackCurrent, fallbackTotal);
        }

        var segmentTotal = segmentEnd - segmentStart;
        var segmentCurrent = Math.Clamp(state.FrontPoints - segmentStart, 0, segmentTotal);
        var value = Math.Clamp((float) segmentCurrent / segmentTotal, 0f, 1f);
        return (value, segmentCurrent, segmentTotal);
    }

    private static string BuildFocusText(WH40KCommandNodeBoundUserInterfaceState state)
    {
        var upgradeHint = state.CommandPoints >= state.UpgradeCost
            ? Loc.GetString("w40k-cmd-focus-upgrade-ready", ("cost", state.UpgradeCost))
            : Loc.GetString("w40k-cmd-focus-upgrade-wait", ("cost", state.UpgradeCost));

        return state.PointsToNextLevel is { } pointsLeft
            ? Loc.GetString("w40k-cmd-focus-next-level", ("points", pointsLeft), ("upgrade", upgradeHint))
            : Loc.GetString("w40k-cmd-focus-max-level", ("upgrade", upgradeHint));
    }

    private static string BuildEventReadinessText(WH40KCommandTeamEventRuntimeState runtime)
    {
        if (!runtime.HasProfile)
            return Loc.GetString("w40k-cmd-event-status-disabled");

        if (runtime.HasActiveEvent)
        {
            return Loc.GetString(
                "w40k-cmd-event-status-active",
                ("title", ResolveLocalizedOrRaw(runtime.ActiveEventTitle)),
                ("time", FormatDuration(runtime.ActiveRemainingSeconds)));
        }

        if (runtime.NextRollSeconds > 0)
        {
            return Loc.GetString(
                "w40k-cmd-event-status-next",
                ("time", FormatDuration(runtime.NextRollSeconds)));
        }

        return Loc.GetString("w40k-cmd-event-status-waiting");
    }

    private static string BuildIntelDetailText(WH40KCommandNodeBonusIntelState intel)
    {
        return BuildCompactText(
            Loc.GetString(
                "w40k-cmd-intel-detail",
                ("interval", FormatDuration((int) MathF.Ceiling(intel.NodePassiveIntervalSeconds))),
                ("eng_speed", intel.EngineeringSpeedBonusPercent),
                ("log_eta", intel.LogisticsTierDeliveryReductionMinutes),
                ("log_discount", intel.LogisticsExternalPriceDiscountPercent),
                ("ore_tier", intel.OreExtractorTier)),
            124);
    }

    private static string BuildPreviewBlock(string[] lines, int maxLines, string emptyLoc)
    {
        if (lines.Length == 0)
            return Loc.GetString(emptyLoc);

        return string.Join(" | ", lines
            .Take(maxLines)
            .Select(line => BuildCompactText(line, 52))
            .Where(line => !string.IsNullOrWhiteSpace(line)));
    }

    private static WH40KCommandMissionRuntimeState? ResolveActiveMission(WH40KCommandNodeBoundUserInterfaceState state)
    {
        if (state.TeamMissionRuntime.IsActive)
            return state.TeamMissionRuntime;

        if (state.GlobalMissionRuntime.IsActive)
            return state.GlobalMissionRuntime;

        return null;
    }

    private static string ResolveMissionScopeLabel(WH40KCommandDynamicMissionScope scope)
    {
        return scope switch
        {
            WH40KCommandDynamicMissionScope.Global => Loc.GetString("w40k-cmd-mission-board-scope-global"),
            WH40KCommandDynamicMissionScope.Faction => Loc.GetString("w40k-cmd-mission-board-scope-faction"),
            _ => Loc.GetString("w40k-cmd-mission-board-scope-global")
        };
    }

    private static string ResolveLocalizedOrRaw(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return string.Empty;

        if (IoCManager.Resolve<ILocalizationManager>().TryGetString(value, out var localized) && !string.IsNullOrWhiteSpace(localized))
            return localized!;

        return value;
    }

    private static string BuildCompactText(string text, int maxCharacters)
    {
        var resolved = ResolveLocalizedOrRaw(text);
        if (string.IsNullOrWhiteSpace(resolved))
            return string.Empty;

        var normalized = resolved
            .Replace("\\n", "\n", StringComparison.Ordinal)
            .Replace("\r", "\n", StringComparison.Ordinal);

        var lines = normalized
            .Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .Select(CollapseWhitespace)
            .Where(line => !string.IsNullOrWhiteSpace(line))
            .ToArray();

        var compact = lines.Length == 0
            ? CollapseWhitespace(normalized)
            : string.Join(" | ", lines);

        if (compact.Length <= maxCharacters)
            return compact;

        var shortened = compact[..Math.Max(1, maxCharacters - 3)].TrimEnd(' ', ',', ';', '|', '.', ':');
        return $"{shortened}...";
    }

    private static string CollapseWhitespace(string text)
    {
        return string.Join(" ", text.Split(new[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries));
    }

    private static string FormatDuration(int seconds)
    {
        var clamped = Math.Max(0, seconds);
        var minutes = clamped / 60;
        var secs = clamped % 60;
        return $"{minutes:00}:{secs:00}";
    }

    private static string GetPhaseKey(WH40KBattlePhase phase)
    {
        return phase switch
        {
            WH40KBattlePhase.Preparation => "wh40k-phase-preparation-name",
            WH40KBattlePhase.Assault => "wh40k-phase-assault-name",
            WH40KBattlePhase.Apocalypse => "wh40k-phase-apocalypse-name",
            _ => "wh40k-phase-preparation-name"
        };
    }

