    private void ApplyHeader(WH40KCommandNodeBoundUserInterfaceState state)
    {
        var resolvedTeam = ResolveLocalizedOrRaw(state.TeamName);
        var teamName = string.IsNullOrWhiteSpace(resolvedTeam) ? "?" : resolvedTeam.ToUpperInvariant();
        var phaseName = Loc.GetString(GetPhaseKey(state.Phase));

        HeaderSubtitleLabel.Text = Loc.GetString("w40k-cmd-header-subtitle-team", ("team", resolvedTeam));
        TeamBadgeLabel.Text = teamName;
        PhaseBadgeLabel.Text = phaseName;
        LevelBadgeLabel.Text = Loc.GetString("w40k-cmd-level-badge", ("level", state.BaseLevel));
        StatusBadgeLabel.Text = BuildStatusBadgeText(state);
        RoundBadgeLabel.Text = Loc.GetString(
            "w40k-cmd-round-badge",
            ("time", FormatDuration(state.RoundElapsedSeconds)));
    }

