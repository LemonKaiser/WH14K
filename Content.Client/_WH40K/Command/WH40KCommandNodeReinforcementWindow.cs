        minus.OnPressed += _ => AdjustDraftCount(autoMode ? _autoDraft : _manualDraft, role.RoleId, -1, autoMode);
        row.AddChild(minus);

        var plus = CreateStepperButton("+", !CanIncrementDraft(autoMode ? _autoDraft : _manualDraft, role.RoleId, autoMode), true);
        plus.OnPressed += _ => AdjustDraftCount(autoMode ? _autoDraft : _manualDraft, role.RoleId, 1, autoMode);
        row.AddChild(plus);

        return row;
    }

