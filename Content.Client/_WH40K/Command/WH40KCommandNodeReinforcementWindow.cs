    public WH40KCommandNodeReinforcementWindow()
    {
        RobustXamlLoader.Load(this);

        SearchBar.OnTextChanged += args =>
        {
            _searchText = args.Text ?? string.Empty;
            RebuildCatalog(animateRows: true);
        };

        CatalogModeButton.OnPressed += _ =>
        {
            _catalogAutoMode = !_catalogAutoMode;
            ApplyCatalogModeButtonTheme();
            RebuildCatalog(animateRows: false);
            RefreshSummary();
        };

        SubmitManualButton.OnPressed += _ => OnManualSubmitRequested?.Invoke(BuildDraftEntries(_manualDraft));
        ClearManualButton.OnPressed += _ =>
        {
            _manualDraft.Clear();
            RefreshDraftDisplay(autoMode: false);
        };

        AutoEnabledCheckBox.OnToggled += args =>
        {
            if (_suppressAutoInput)
                return;

            _autoEnabled = args.Pressed;
            _autoDirty = true;
            RefreshSummary();
        };

        ThresholdSlider.OnValueChanged += _ =>
        {
            if (_suppressAutoInput)
                return;

            var threshold = Math.Clamp(
                (int) MathF.Round(ThresholdSlider.Value, MidpointRounding.AwayFromZero),
                20,
                50);

            if (threshold == _autoThresholdPercent)
                return;

            _autoThresholdPercent = threshold;
            _autoDirty = true;
            RefreshSummary(syncAutoInputs: false);
        };
        ThresholdSlider.MinValue = 20;
        ThresholdSlider.MaxValue = 50;
        ThresholdSlider.Rounded = true;
        ThresholdSlider.RoundingDecimals = 0;
        ThresholdSlider.OnReleased += _ => RefreshSummary();

        SaveAutoButton.OnPressed += _ =>
        {
            _autoDirty = false;
            OnAutoSaveRequested?.Invoke(_autoEnabled, _autoThresholdPercent, BuildDraftEntries(_autoDraft));
        };
        ResetAutoButton.OnPressed += _ =>
        {
            LoadAutoDraftFromState(force: true);
            RefreshDraftDisplay(autoMode: true);
        };
        ClearAutoButton.OnPressed += _ =>
        {
            _autoEnabled = false;
            _autoDraft.Clear();
            _autoDirty = true;
            RefreshDraftDisplay(autoMode: true);
        };

        WH40KUiChrome.StartLoopingPulse(CatalogAccent, "reinforcement-catalog-pulse", new Color(0.6f, 0.6f, 0.6f, 1f), Color.White, 4.2f);
        WH40KUiChrome.StartLoopingPulse(BottomAccent, "reinforcement-footer-pulse", new Color(0.6f, 0.6f, 0.6f, 1f), Color.White, 4f);

        Relocalize();
    }

