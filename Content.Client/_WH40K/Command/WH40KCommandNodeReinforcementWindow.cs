        WH40KCommandReinforcementCatalogEntryState role,
        int count,
        bool autoMode)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            HorizontalExpand = true,
            MinHeight = 34
        };

        var summary = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = CreatePanelStyle(ThemeInset, ThemeBorder, 1, 8, 6)
        };
        var summaryBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            HorizontalExpand = true
        };
        summary.AddChild(summaryBox);

        var label = new Label
        {
            HorizontalExpand = true,
            ClipText = true,
            Text = $"{WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.Name)} x{count}",
            FontColorOverride = ThemeText
        };
        summaryBox.AddChild(label);
        summaryBox.AddChild(new Label
        {
            Text = $"{role.UnitCost * count} OP",
            FontColorOverride = autoMode ? ThemeAction : _accent
        });
        row.AddChild(summary);

