    private static int ComputeCatalogHash(IEnumerable<WH40KCommandReinforcementCatalogEntryState> catalog)
    {
        var hash = new HashCode();
        foreach (var entry in catalog)
        {
            hash.Add(entry.RoleId, StringComparer.OrdinalIgnoreCase);
            hash.Add(entry.Name, StringComparer.Ordinal);
            hash.Add(entry.Description, StringComparer.Ordinal);
            hash.Add(entry.GroupKey, StringComparer.Ordinal);
            hash.Add(entry.GearSummary, StringComparer.Ordinal);
            hash.Add(entry.PreviewPrototypeId, StringComparer.Ordinal);
            hash.Add(entry.UnitCost);
            hash.Add(entry.PerRoleCap);
            hash.Add(entry.AllowAuto);
        }

        return hash.ToHashCode();
    }

    private static int ComputeDraftHash(Dictionary<string, int> draft)
    {
        var hash = new HashCode();
        foreach (var (roleId, count) in draft.OrderBy(entry => entry.Key, StringComparer.OrdinalIgnoreCase))
        {
            hash.Add(roleId, StringComparer.OrdinalIgnoreCase);
            hash.Add(count);
        }

        return hash.ToHashCode();
    }

    private static int ComputePendingRolesHash(WH40KCommandReinforcementPendingRequestState pending)
    {
        var hash = new HashCode();
        hash.Add(pending.Kind);
        hash.Add(pending.TotalCount);
        hash.Add(pending.TotalCost);
        foreach (var role in pending.Roles)
        {
            hash.Add(role.RoleId, StringComparer.OrdinalIgnoreCase);
            hash.Add(role.Name, StringComparer.Ordinal);
            hash.Add(role.Count);
            hash.Add(role.UnitCost);
            hash.Add(role.TotalCost);
        }

        return hash.ToHashCode();
    }
