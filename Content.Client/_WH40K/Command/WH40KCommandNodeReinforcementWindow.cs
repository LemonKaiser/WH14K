    private void RefreshAll(bool animateCatalog = false)
    {
        if (_latestState == null)
            return;

        ApplyHeader(_latestState);
        ApplyCatalogModeButtonTheme();
        RebuildCatalog(animateCatalog);
        RebuildPending(forceRows: true);
        RebuildDraftList(ManualRoles, _manualDraft, false);
        RebuildDraftList(AutoRoles, _autoDraft, true);
        RefreshSummary();
    }

    private void RefreshFromState(
        bool rebuildCatalog,
        bool rebuildManualDraft,
        bool rebuildAutoDraft,
        bool animateCatalog,
        bool forcePendingRows)
    {
        if (_latestState == null)
            return;

        ApplyHeader(_latestState);
        ApplyCatalogModeButtonTheme();

        if (rebuildCatalog)
            RebuildCatalog(animateCatalog);

        RebuildPending(forcePendingRows);

        if (rebuildManualDraft)
            RebuildDraftList(ManualRoles, _manualDraft, false);

        if (rebuildAutoDraft)
            RebuildDraftList(AutoRoles, _autoDraft, true);

        RefreshSummary();
    }

    private void RefreshDraftDisplay(bool autoMode)
    {
        if (_latestState == null)
            return;

        if (_catalogAutoMode == autoMode)
            RebuildCatalog(animateRows: false);

        RebuildDraftList(autoMode ? AutoRoles : ManualRoles, autoMode ? _autoDraft : _manualDraft, autoMode);
        RefreshSummary();
    }

