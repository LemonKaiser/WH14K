    private void UpdateState(WH40KCommandReinforcementBoundUserInterfaceState state, bool forceRebuild)
    {
        var previousManualDraftHash = ComputeDraftHash(_manualDraft);
        var previousAutoDraftHash = ComputeDraftHash(_autoDraft);
        var nextCatalogHash = ComputeCatalogHash(state.Catalog);
        var catalogChanged = forceRebuild || !_catalogBuilt || nextCatalogHash != _catalogHash;

        _latestState = state;
        _catalogHash = nextCatalogHash;
        _catalogIndex.Clear();
        foreach (var entry in state.Catalog)
        {
            _catalogIndex[entry.RoleId] = entry;
        }

        var nextAccent = WH40KTeamIdentityClientResolver.ResolveAccentColor(state.TeamId, WH40KCommandUiStyles.DefaultAccent);
        var nextChaosTheme = WH40KTeamIdentityClientResolver.UsesHereticsDoctrinePresentation(state.TeamId);
        var themeChanged = forceRebuild || !_catalogBuilt || !_accent.Equals(nextAccent) || _chaosTheme != nextChaosTheme;
        _accent = nextAccent;
        _chaosTheme = nextChaosTheme;

        if (!_autoDirty)
            LoadAutoDraftFromState(force: true);
        else
            ClampDraft(_autoDraft, true);

        ClampDraft(_manualDraft, false);

        var manualDraftChanged = forceRebuild || previousManualDraftHash != ComputeDraftHash(_manualDraft);
        var autoDraftChanged = forceRebuild || previousAutoDraftHash != ComputeDraftHash(_autoDraft);

        Title = Loc.GetString(
            "w40k-cmd-reinforcement-rework-window-title-team",
            ("team", WH40KCommandUiStyles.ResolveLocalizedOrRaw(state.TeamName)));

        if (themeChanged)
            ApplyTheme();
        else
            ApplyCatalogModeButtonTheme();

        RefreshFromState(
            rebuildCatalog: catalogChanged || themeChanged || manualDraftChanged || autoDraftChanged,
            rebuildManualDraft: catalogChanged || themeChanged || manualDraftChanged,
            rebuildAutoDraft: catalogChanged || themeChanged || autoDraftChanged,
            animateCatalog: !_catalogBuilt && !forceRebuild,
            forcePendingRows: forceRebuild || themeChanged || catalogChanged);
    }

