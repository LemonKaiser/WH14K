    private void RefreshSummary(bool syncAutoInputs = true)
    {
        if (_latestState == null)
            return;

        var (manualCount, manualCost) = GetDraftTotals(_manualDraft);
        var (autoCount, autoCost) = GetDraftTotals(_autoDraft);

        ManualSummaryLabel.Text = Loc.GetString(
            "w40k-cmd-reinforcement-rework-manual-summary",
            ("count", manualCount),
            ("max", _latestState.MaxTotalCount),
            ("cost", manualCost),
            ("delay", _latestState.ManualDelaySeconds / 60));
        AutoMetaLabel.Text = Loc.GetString(
            "w40k-cmd-reinforcement-rework-auto-meta",
            ("check", _latestState.AutoCheckIntervalSeconds),
            ("delay", _latestState.AutoDelaySeconds / 60));
        AutoSummaryLabel.Text = Loc.GetString(
            "w40k-cmd-reinforcement-rework-auto-summary",
            ("count", autoCount),
            ("max", _latestState.MaxTotalCount),
            ("cost", autoCost));
        ThresholdValueLabel.Text = Loc.GetString(
            "w40k-cmd-reinforcement-rework-threshold",
            ("value", _autoThresholdPercent));

        _suppressAutoInput = true;
        AutoEnabledCheckBox.Pressed = _autoEnabled;
        if (syncAutoInputs && !ThresholdSlider.Grabbed)
            ThresholdSlider.SetValueWithoutEvent(_autoThresholdPercent);
        _suppressAutoInput = false;

        SubmitManualButton.Disabled = !CanSubmitManual(_latestState, manualCount, manualCost);
        ClearManualButton.Disabled = manualCount <= 0;
        SaveAutoButton.Disabled = !CanSaveAuto(_latestState, autoCount);
        ResetAutoButton.Disabled = !_autoDirty;
        ClearAutoButton.Disabled = autoCount <= 0 && !_autoEnabled;

        ApplyActionButtonTheme(SubmitManualButton, _accent, SubmitManualButton.Disabled);
        ApplyActionButtonTheme(ClearManualButton, ThemeAction, ClearManualButton.Disabled);
        ApplyActionButtonTheme(SaveAutoButton, _accent, SaveAutoButton.Disabled);
        ApplyActionButtonTheme(ResetAutoButton, ThemeAction, ResetAutoButton.Disabled);
        ApplyActionButtonTheme(ClearAutoButton, TerminalDanger, ClearAutoButton.Disabled);

        AutoEnabledCheckBox.StyleBoxOverride = CreatePanelStyle(ThemePanelAlt, _autoEnabled ? _accent : ThemeBorder, 1, 4, 4);
        AutoEnabledCheckBox.Label.FontColorOverride = _autoEnabled ? ThemeText : ThemeMuted;
    }

    private void LoadAutoDraftFromState(bool force)
    {
        if (_latestState == null || (!force && _autoDirty))
            return;

        _autoDraft.Clear();
        foreach (var role in _latestState.AutoConfig.Roles)
        {
            if (string.IsNullOrWhiteSpace(role.RoleId) || role.Count <= 0)
                continue;

            _autoDraft[role.RoleId] = role.Count;
        }

        _autoEnabled = _latestState.AutoConfig.Enabled;
        _autoThresholdPercent = _latestState.AutoConfig.ThresholdPercent;
        _autoDirty = false;
    }

    private void AdjustDraftCount(Dictionary<string, int> draft, string roleId, int delta, bool autoMode)
    {
        if (_latestState == null || string.IsNullOrWhiteSpace(roleId) || !_catalogIndex.TryGetValue(roleId, out var role))
            return;

        if (autoMode && !role.AllowAuto)
            return;

        var current = draft.GetValueOrDefault(roleId);
        var next = Math.Clamp(current + delta, 0, role.PerRoleCap);
        if (next == current)
            return;

        if (delta > 0)
        {
            var (totalCount, _) = GetDraftTotals(draft);
            if (totalCount >= _latestState.MaxTotalCount)
                return;
        }

        if (next <= 0)
            draft.Remove(roleId);
        else
            draft[roleId] = next;

        if (autoMode)
            _autoDirty = true;

        RefreshDraftDisplay(autoMode);
    }

    private bool CanIncrementDraft(Dictionary<string, int> draft, string roleId, bool autoMode)
    {
        if (_latestState == null || string.IsNullOrWhiteSpace(roleId) || !_catalogIndex.TryGetValue(roleId, out var role))
            return false;

        if (autoMode && !role.AllowAuto)
            return false;

        var current = draft.GetValueOrDefault(roleId);
        if (current >= role.PerRoleCap)
            return false;

        var (totalCount, _) = GetDraftTotals(draft);
        return totalCount < _latestState.MaxTotalCount;
    }

    private void ClampDraft(Dictionary<string, int> draft, bool autoMode)
    {
        if (_latestState == null)
            return;

        foreach (var roleId in draft.Keys.ToArray())
        {
            if (!_catalogIndex.TryGetValue(roleId, out var role))
            {
                draft.Remove(roleId);
                continue;
            }

            if (autoMode && !role.AllowAuto)
            {
                draft.Remove(roleId);
                continue;
            }

            draft[roleId] = Math.Clamp(draft[roleId], 1, role.PerRoleCap);
        }

        while (GetDraftTotals(draft).TotalCount > _latestState.MaxTotalCount)
        {
            var key = draft.Keys.LastOrDefault();
            if (key == null)
                break;

            if (draft[key] <= 1)
                draft.Remove(key);
            else
                draft[key]--;
        }
    }

    private bool MatchesSearch(WH40KCommandReinforcementCatalogEntryState role)
    {
        if (string.IsNullOrWhiteSpace(_searchText))
            return true;

        var needle = _searchText.Trim();
        if (string.IsNullOrWhiteSpace(needle))
            return true;

        return WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.Name).Contains(needle, StringComparison.OrdinalIgnoreCase)
               || WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.Description).Contains(needle, StringComparison.OrdinalIgnoreCase)
               || WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.GearSummary).Contains(needle, StringComparison.OrdinalIgnoreCase);
    }

    private List<(WH40KCommandReinforcementCatalogEntryState Role, int Count)> BuildResolvedDraftEntries(Dictionary<string, int> draft)
    {
        var resolved = new List<(WH40KCommandReinforcementCatalogEntryState Role, int Count)>();
        foreach (var (roleId, count) in draft)
        {
            if (!_catalogIndex.TryGetValue(roleId, out var role) || count <= 0)
                continue;

            resolved.Add((role, count));
        }

        return resolved
            .OrderBy(entry => WH40KCommandUiStyles.ResolveLocalizedOrRaw(entry.Role.Name), StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    private WH40KCommandReinforcementDraftEntry[] BuildDraftEntries(Dictionary<string, int> draft)
    {
        return BuildResolvedDraftEntries(draft)
            .Select(entry => new WH40KCommandReinforcementDraftEntry(entry.Role.RoleId, entry.Count))
            .ToArray();
    }

    private (int TotalCount, int TotalCost) GetDraftTotals(Dictionary<string, int> draft)
    {
        var totalCount = 0;
        var totalCost = 0;
        foreach (var (role, count) in BuildResolvedDraftEntries(draft))
        {
            totalCount += count;
            totalCost += role.UnitCost * count;
        }

        return (totalCount, totalCost);
    }

    private bool CanSubmitManual(WH40KCommandReinforcementBoundUserInterfaceState state, int totalCount, int totalCost)
    {
        if (totalCount <= 0 || totalCost <= 0)
            return false;

        if (state.PendingRequest != null)
            return false;

        if (state.Phase != WH40KBattlePhase.Assault)
            return false;

        if (state.CooldownSeconds > 0)
            return false;

        return state.CommandPoints >= totalCost;
    }

    private bool CanSaveAuto(WH40KCommandReinforcementBoundUserInterfaceState state, int totalCount)
    {
        if (!_autoDirty)
            return false;

        if (!_autoEnabled)
            return true;

        return totalCount > 0 && totalCount <= state.MaxTotalCount;
    }

    private string BuildHeaderStatus(WH40KCommandReinforcementBoundUserInterfaceState state)
    {
        if (state.PendingRequest != null)
            return Loc.GetString("w40k-cmd-reinforcement-rework-status-pending");

        if (state.CooldownSeconds > 0)
            return Loc.GetString("w40k-cmd-reinforcement-rework-status-cooldown");

        return state.Phase == WH40KBattlePhase.Assault
            ? Loc.GetString("w40k-cmd-reinforcement-rework-status-ready")
            : Loc.GetString("w40k-cmd-reinforcement-rework-status-locked");
    }

    private static string FormatDuration(int totalSeconds)
    {
        var clamped = Math.Max(0, totalSeconds);
        var minutes = clamped / 60;
        var seconds = clamped % 60;
        return $"{minutes:00}:{seconds:00}";
    }

