    {
        TeamBadgeLabel.Text = WH40KCommandUiStyles.ResolveLocalizedOrRaw(state.TeamName).ToUpperInvariant();
        PhaseBadgeLabel.Text = Loc.GetString(GetPhaseKey(state.Phase));
