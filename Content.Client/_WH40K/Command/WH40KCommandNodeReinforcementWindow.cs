    }

    private void RebuildCatalog(bool animateRows = false)
    {
        RoleSections.RemoveAllChildren();
        if (_latestState == null)
            return;

        _catalogBuilt = true;
        if (_latestState.Catalog.Length == 0)
        {
            RoleSections.AddChild(CreateEmptyLabel("w40k-cmd-reinforcement-rework-empty-catalog"));
            return;
        }

        var filtered = _latestState.Catalog
            .Where(MatchesSearch)
            .ToArray();
        if (filtered.Length == 0)
        {
            RoleSections.AddChild(CreateEmptyLabel("w40k-cmd-reinforcement-rework-no-search-results"));
            return;
        }

        var grouped = filtered
            .GroupBy(entry => entry.GroupKey)
            .ToArray();

        var index = 0;
        foreach (var group in grouped)
        {
            var section = new CMAutomatedVendorSection();
            WH40KCommandUiStyles.SetWrappedText(
                section.Label,
                WH40KCommandUiStyles.ResolveLocalizedOrRaw(group.Key),
                _accent);

            foreach (var role in group)
            {
                var row = CreateCatalogRow(role);
                section.Entries.AddChild(row);
                if (animateRows)
                    WH40KUiChrome.PlayFadeIn(row, $"catalog-row-{index}", 0.16f, index * 0.02f);

                index++;
            }

            RoleSections.AddChild(section);
        }
    }

    private Control CreateCatalogRow(WH40KCommandReinforcementCatalogEntryState role)
    {
        var activeDraft = _catalogAutoMode ? _autoDraft : _manualDraft;
        var activeCount = activeDraft.GetValueOrDefault(role.RoleId);
        var hasActiveDraft = activeCount > 0;
        var blockedByMode = _catalogAutoMode && !role.AllowAuto;

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            HorizontalExpand = true,
            MinHeight = 42
        };

        var iconFrame = new PanelContainer
        {
            MinWidth = 44,
            MinHeight = 40,
            PanelOverride = CreatePanelStyle(ThemeInset, ThemeBorder, 1, 4, 4)
        };
        var preview = new EntityPrototypeView
        {
            MinSize = new Vector2(32f, 32f),
            Scale = new Vector2(1.35f, 1.35f),
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center
        };
        preview.SetPrototype(role.PreviewPrototypeId);
        iconFrame.AddChild(preview);
        row.AddChild(iconFrame);

        var namePanel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = CreatePanelStyle(
                hasActiveDraft ? (_chaosTheme ? Color.FromHex("#19090C".AsSpan()) : Color.FromHex("#171713".AsSpan())) : ThemeInset,
                hasActiveDraft ? _accent : blockedByMode ? TerminalDanger : ThemeBorder,
                1,
                8,
                6)
        };
        namePanel.AddChild(new Label
        {
            Text = WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.Name),
            FontColorOverride = blockedByMode ? ThemeMuted : hasActiveDraft ? Color.White : ThemeText,
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center
        });
        row.AddChild(namePanel);

        row.AddChild(CreateMiniBadge($"{role.UnitCost} OP", ThemeInset, ThemeAction, ThemeText));
        row.AddChild(CreateCatalogStepper(role, activeDraft, activeCount, _catalogAutoMode));

        return row;
    }

    private Control CreateCatalogStepper(
        WH40KCommandReinforcementCatalogEntryState role,
        Dictionary<string, int> draft,
        int count,
        bool autoMode)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
            VerticalAlignment = VAlignment.Center
        };

        var minus = CreateStepperButton("-", count <= 0, false);
        minus.OnPressed += _ => AdjustDraftCount(draft, role.RoleId, -1, autoMode);
        box.AddChild(minus);

        var plus = CreateStepperButton("+", !CanIncrementDraft(draft, role.RoleId, autoMode), true);
        plus.OnPressed += _ => AdjustDraftCount(draft, role.RoleId, 1, autoMode);
        box.AddChild(plus);

        return box;
    }

    private Button CreateStepperButton(string text, bool disabled, bool primary)
    {
        var border = disabled
            ? ThemeBorder
            : primary
                ? _accent
                : ThemeBorderStrong;
        var button = new Button
        {
            Text = text,
            MinWidth = 28,
            Disabled = disabled,
            StyleBoxOverride = CreatePanelStyle(ThemeInset, border, 1, 8, 4),
            TextAlign = Label.AlignMode.Center
        };
        button.Label.FontColorOverride = disabled
            ? ThemeMuted
            : primary
                ? Color.White
                : ThemeText;
        return button;
    }

    private void RebuildPending(bool forceRows = false)
    {
        if (_latestState?.PendingRequest == null)
        {
            PendingStatusLabel.Text = Loc.GetString("w40k-cmd-reinforcement-rework-no-pending");
            PendingStatusLabel.ModulateSelfOverride = ThemeMuted;
            if (forceRows || !_pendingRowsBuilt || _pendingRolesHash != NoPendingRolesHash)
            {
                PendingRoles.RemoveAllChildren();
                PendingRoles.AddChild(CreateEmptyLabel("w40k-cmd-reinforcement-rework-pending-empty"));
                _pendingRowsBuilt = true;
                _pendingRolesHash = NoPendingRolesHash;
            }

            return;
        }

        var pending = _latestState.PendingRequest;
        var nextPendingHash = ComputePendingRolesHash(pending);
        PendingStatusLabel.Text = Loc.GetString(
            pending.Kind == WH40KCommandReinforcementRequestKind.Auto
                ? "w40k-cmd-reinforcement-rework-pending-auto"
                : "w40k-cmd-reinforcement-rework-pending-manual",
            ("count", pending.TotalCount),
            ("cost", pending.TotalCost),
            ("time", FormatDuration(pending.ArrivalSeconds)));
        PendingStatusLabel.ModulateSelfOverride = ThemeAction;

        if (!forceRows && _pendingRowsBuilt && _pendingRolesHash == nextPendingHash)
            return;

        PendingRoles.RemoveAllChildren();
        foreach (var role in pending.Roles)
        {
            PendingRoles.AddChild(CreateReadOnlyRow(
                $"{WH40KCommandUiStyles.ResolveLocalizedOrRaw(role.Name)} x{role.Count}",
                $"{role.TotalCost} OP"));
        }

        _pendingRowsBuilt = true;
        _pendingRolesHash = nextPendingHash;
    }

    private void RebuildDraftList(BoxContainer container, Dictionary<string, int> draft, bool autoMode)
    {
        container.RemoveAllChildren();
        var entries = BuildResolvedDraftEntries(draft);
        if (entries.Count == 0)
        {
            container.AddChild(CreateEmptyLabel(
                autoMode
                    ? "w40k-cmd-reinforcement-rework-auto-empty"
                    : "w40k-cmd-reinforcement-rework-manual-empty"));
            return;
        }

        foreach (var (role, count) in entries)
        {
            container.AddChild(CreateDraftRow(role, count, autoMode));
        }
    }

