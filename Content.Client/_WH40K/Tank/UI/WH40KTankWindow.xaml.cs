    public WH40KTankWindow()
    {
        RobustXamlLoader.Load(this);
        ApplyChrome();
        Relocalize();
    }

    public void ApplyState(WH40KTankBuiState state)
    {
        _latestState = state;
        RefreshState();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("wh40k-tank-ui-window-title");
        CrewTitleLabel.Text = Loc.GetString("wh40k-tank-ui-crew-title");
        CrewSubtitleLabel.Text = Loc.GetString("wh40k-tank-ui-crew-subtitle");
        SystemsTitleLabel.Text = Loc.GetString("wh40k-tank-ui-systems-title");
        SystemsSubtitleLabel.Text = Loc.GetString("wh40k-tank-ui-systems-subtitle");
        AlertsTitleLabel.Text = Loc.GetString("wh40k-tank-ui-alerts-title");
        AlertsSubtitleLabel.Text = Loc.GetString("wh40k-tank-ui-alerts-subtitle");

        if (_latestState != null)
        {
            RefreshState();
            return;
        }

        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.DiamondNested, Loc.GetString("wh40k-tank-ui-header-title"));
        HeaderSubtitleLabel.Text = Loc.GetString("wh40k-tank-ui-header-subtitle");
        HullStatusLabel.Text = Loc.GetString("wh40k-tank-ui-placeholder");
        FuelStatusLabel.Text = Loc.GetString("wh40k-tank-ui-placeholder");
        GunneryStatusLabel.Text = Loc.GetString("wh40k-tank-ui-placeholder");
        EngineBadgeLabel.Text = Loc.GetString("wh40k-tank-ui-engine-offline");
        FuelBadgeLabel.Text = Loc.GetString("wh40k-tank-ui-fuel-badge", ("percent", 0));
        WeaponsBadgeLabel.Text = Loc.GetString("wh40k-tank-ui-weapons-degraded");
        FooterLabel.Text = Loc.GetString("wh40k-tank-ui-footer-idle");

        CrewList.RemoveAllChildren();
        ModuleList.RemoveAllChildren();
        AlertList.RemoveAllChildren();
        AlertList.AddChild(BuildAlertCard(new AlertEntry(
            Loc.GetString("wh40k-tank-ui-alerts-awaiting"),
            WarningAccent,
            PanelAltBackground)));
    }

