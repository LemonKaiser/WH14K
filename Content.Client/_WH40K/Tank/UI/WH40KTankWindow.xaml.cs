    private void RefreshState()
    {
        if (_latestState == null)
            return;

        var state = _latestState;
        Title = Loc.GetString("wh40k-tank-ui-window-title");
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.DiamondNested, state.TankName.ToUpperInvariant());
        HeaderSubtitleLabel.Text = Loc.GetString("wh40k-tank-ui-header-subtitle");

        var engineModule = GetModule(state, WH40KTankModuleType.Engine);
        var mainModule = GetModule(state, WH40KTankModuleType.MainGun);
        var coaxModule = GetModule(state, WH40KTankModuleType.Coaxial);

        EngineBadgeLabel.Text = BuildEngineBadgeText(state, engineModule);
        FuelBadgeLabel.Text = Loc.GetString("wh40k-tank-ui-fuel-badge", ("percent", Percent(state.FuelFraction)));
        WeaponsBadgeLabel.Text = BuildWeaponsBadgeText(state, mainModule, coaxModule);

        EngineBadge.PanelOverride = CreateBadgeStyle(
            PanelAltBackground,
            engineModule?.Status == WH40KTankModuleStatus.Destroyed
                ? DangerAccent
                : state.EngineRunning
                    ? GoodAccent
                    : WarningAccent);
        FuelBadge.PanelOverride = CreateBadgeStyle(
            PanelAltBackground,
            state.FuelFraction <= 0.15f
                ? DangerAccent
                : state.FuelFraction <= 0.35f
                    ? WarningAccent
                    : Accent);
        WeaponsBadge.PanelOverride = CreateBadgeStyle(
            PanelAltBackground,
            ResolveWeaponsAccent(state, mainModule, coaxModule));

        HullStatusLabel.Text = Loc.GetString("wh40k-tank-ui-hull-value", ("percent", Percent(state.HullIntegrityFraction)));
        FuelStatusLabel.Text = Loc.GetString(
            "wh40k-tank-ui-fuel-value",
            ("current", FormatValue(state.FuelCurrent)),
            ("capacity", FormatValue(state.FuelCapacity)),
            ("percent", Percent(state.FuelFraction)));

        var mainGunneryText = Loc.GetString(
            "wh40k-tank-ui-gunnery-main",
            ("state", ResolveWeaponState(
                mainModule,
                state.PendingMainGunFire,
                state.HasAimPoint,
                state.MainGunAmmoCount,
                state.MainGunAmmoCapacity,
                state.MainGunReloadTimeLeft)),
            ("count", state.MainGunAmmoCount),
            ("capacity", state.MainGunAmmoCapacity));

        var coaxGunneryText = state.HasCoaxialWeapon
            ? Loc.GetString(
                "wh40k-tank-ui-gunnery-coax",
                ("state", ResolveWeaponState(
                    coaxModule,
                    state.PendingCoaxialFire,
                    state.HasAimPoint,
                    state.CoaxialAmmoCount,
                    state.CoaxialAmmoCapacity,
                    state.CoaxialReloadTimeLeft)),
                ("count", state.CoaxialAmmoCount),
                ("capacity", state.CoaxialAmmoCapacity))
            : Loc.GetString(
                "wh40k-tank-ui-gunnery-coax",
                ("state", Loc.GetString("wh40k-tank-ui-weapon-missing")),
                ("count", 0),
                ("capacity", 0));

        GunneryStatusLabel.Text = $"{mainGunneryText}   |   {coaxGunneryText}";

        RebuildCrew(state);
        RebuildModules(state);
        RebuildAlerts(state);
        FooterLabel.Text = BuildFooterText(state);
    }

    private void RebuildCrew(WH40KTankBuiState state)
    {
        CrewList.RemoveAllChildren();

        foreach (var entry in state.Crew)
        {
            var occupied = entry.Occupied;
            var border = occupied ? Accent : BorderMuted;
            var badgeBorder = occupied ? GoodAccent : WarningAccent;

            var panel = new PanelContainer
            {
                PanelOverride = CreatePanelStyle(PanelAltBackground, border, 1, 10),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 6,
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            header.AddChild(new Label
            {
                Text = ResolveRoleLabel(entry.Role),
                StyleClasses = { "LabelHeading" },
                FontColorOverride = PrimaryText,
                HorizontalExpand = true,
            });

            var badge = new PanelContainer
            {
                PanelOverride = CreateBadgeStyle(PanelBackground, badgeBorder),
            };
            badge.AddChild(new Label
            {
                Text = Loc.GetString(occupied ? "wh40k-tank-ui-crew-occupied" : "wh40k-tank-ui-crew-empty-badge"),
                FontColorOverride = occupied ? GoodAccent : WarningAccent,
            });

            header.AddChild(badge);
            content.AddChild(header);
            content.AddChild(new Label
            {
                Text = occupied ? entry.OccupantName : Loc.GetString("wh40k-tank-ui-crew-unmanned"),
                StyleClasses = { occupied ? "LabelBig" : "LabelSubText" },
                FontColorOverride = occupied ? PrimaryText : SecondaryText,
                ClipText = true,
            });

            panel.AddChild(content);
            CrewList.AddChild(panel);
        }
    }

    private void RebuildModules(WH40KTankBuiState state)
    {
        ModuleList.RemoveAllChildren();

        foreach (var module in state.Modules)
        {
            var accent = ResolveStatusColor(module.Status);
            var panel = new PanelContainer
            {
                PanelOverride = CreatePanelStyle(PanelAltBackground, accent, 1, 10),
            };

            var content = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                SeparationOverride = 6,
            };

            var header = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 8,
            };

            header.AddChild(new Label
            {
                Text = ResolveModuleLabel(state, module.Module),
                StyleClasses = { "LabelHeading" },
                FontColorOverride = PrimaryText,
                HorizontalExpand = true,
            });

            var badge = new PanelContainer
            {
                PanelOverride = CreateBadgeStyle(PanelBackground, accent),
            };
            badge.AddChild(new Label
            {
                Text = ResolveModuleStatusText(module.Status),
                FontColorOverride = accent,
            });

            header.AddChild(badge);
            content.AddChild(header);

            content.AddChild(new ProgressBar
            {
                MinValue = 0,
                MaxValue = 100,
                Value = module.IntegrityFraction * 100f,
                HorizontalExpand = true,
                MinSize = new Vector2(0f, 14f),
            });

            content.AddChild(new Label
            {
                Text = Loc.GetString("wh40k-tank-ui-module-detail", ("integrity", Percent(module.IntegrityFraction))),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = SecondaryText,
            });

            AddWeaponModuleDetails(content, state, module);

            panel.AddChild(content);
            ModuleList.AddChild(panel);
        }
    }

    private void AddWeaponModuleDetails(
        BoxContainer content,
        WH40KTankBuiState state,
        WH40KTankModuleEntry module)
    {
        if (!TryGetWeaponDisplayData(
                state,
                module.Module,
                out var ammoLocKey,
                out var ammoCount,
                out var ammoCapacity,
                out var reloadTimeLeft,
                out var queued))
        {
            return;
        }

        var weaponState = ResolveWeaponState(
            module,
            queued,
            state.HasAimPoint,
            ammoCount,
            ammoCapacity,
            reloadTimeLeft);

        content.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-tank-ui-weapon-ammo-type-detail",
                ("ammo", Loc.GetString(ammoLocKey))),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = SecondaryText,
        });

        content.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-tank-ui-weapon-feed-detail",
                ("count", ammoCount),
                ("capacity", ammoCapacity)),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = IsWeaponEmpty(ammoCount, ammoCapacity) ? DangerAccent : SecondaryText,
        });

        content.AddChild(new Label
        {
            Text = Loc.GetString(
                "wh40k-tank-ui-weapon-state-detail",
                ("state", weaponState)),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = ResolveWeaponStateColor(module, queued, state.HasAimPoint, ammoCount, ammoCapacity, reloadTimeLeft),
        });

        content.AddChild(new Label
        {
            Text = reloadTimeLeft > 0f
                ? Loc.GetString(
                    "wh40k-tank-ui-weapon-reload-active-detail",
                    ("seconds", RemainingSeconds(reloadTimeLeft)))
                : Loc.GetString("wh40k-tank-ui-weapon-reload-ready-detail"),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = reloadTimeLeft > 0f ? WarningAccent : SecondaryText,
        });

        content.AddChild(new Label
        {
            Text = Loc.GetString("wh40k-tank-ui-weapon-control-detail"),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = SecondaryText,
        });
    }

    private void RebuildAlerts(WH40KTankBuiState state)
    {
        AlertList.RemoveAllChildren();

        var alerts = new List<AlertEntry>();

        if (state.HullIntegrityFraction <= 0.35f)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString("wh40k-tank-ui-alert-hull-critical"),
                DangerAccent,
                PanelAltBackground));
        }

        if (state.FuelFraction <= 0.15f)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString("wh40k-tank-ui-alert-fuel-critical"),
                DangerAccent,
                PanelAltBackground));
        }
        else if (state.FuelFraction <= 0.35f)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString("wh40k-tank-ui-alert-fuel-low"),
                WarningAccent,
                PanelAltBackground));
        }

        foreach (var module in state.Modules)
        {
            if (module.Status == WH40KTankModuleStatus.Destroyed)
            {
                alerts.Add(new AlertEntry(
                    Loc.GetString("wh40k-tank-ui-alert-module-offline", ("module", ResolveModuleLabel(state, module.Module))),
                    DangerAccent,
                    PanelAltBackground));
            }
            else if (module.Status == WH40KTankModuleStatus.Critical)
            {
                alerts.Add(new AlertEntry(
                    Loc.GetString("wh40k-tank-ui-alert-module-critical", ("module", ResolveModuleLabel(state, module.Module))),
                    WarningAccent,
                    PanelAltBackground));
            }
        }

        if (state.MainGunReloadTimeLeft > 0f)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString(
                    "wh40k-tank-ui-alert-weapon-reloading",
                    ("weapon", ResolveModuleLabel(state, WH40KTankModuleType.MainGun)),
                    ("seconds", RemainingSeconds(state.MainGunReloadTimeLeft))),
                WarningAccent,
                PanelAltBackground));
        }
        else if (IsWeaponEmpty(state.MainGunAmmoCount, state.MainGunAmmoCapacity))
        {
            alerts.Add(new AlertEntry(
                Loc.GetString(
                    "wh40k-tank-ui-alert-weapon-empty",
                    ("weapon", ResolveModuleLabel(state, WH40KTankModuleType.MainGun))),
                DangerAccent,
                PanelAltBackground));
        }

        if (state.HasCoaxialWeapon)
        {
            if (state.CoaxialReloadTimeLeft > 0f)
            {
                alerts.Add(new AlertEntry(
                    Loc.GetString(
                        "wh40k-tank-ui-alert-weapon-reloading",
                        ("weapon", ResolveModuleLabel(state, WH40KTankModuleType.Coaxial)),
                        ("seconds", RemainingSeconds(state.CoaxialReloadTimeLeft))),
                    WarningAccent,
                    PanelAltBackground));
            }
            else if (IsWeaponEmpty(state.CoaxialAmmoCount, state.CoaxialAmmoCapacity))
            {
                alerts.Add(new AlertEntry(
                    Loc.GetString(
                        "wh40k-tank-ui-alert-weapon-empty",
                        ("weapon", ResolveModuleLabel(state, WH40KTankModuleType.Coaxial))),
                    DangerAccent,
                    PanelAltBackground));
            }
        }

        if ((state.PendingMainGunFire || state.PendingCoaxialFire) && !state.HasAimPoint)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString("wh40k-tank-ui-alert-no-aim"),
                WarningAccent,
                PanelAltBackground));
        }

        if (alerts.Count == 0)
        {
            alerts.Add(new AlertEntry(
                Loc.GetString("wh40k-tank-ui-alerts-clear"),
                GoodAccent,
                PanelAltBackground));
        }

        foreach (var alert in alerts)
        {
            AlertList.AddChild(BuildAlertCard(alert));
        }
    }

    private Robust.Client.UserInterface.Control BuildAlertCard(AlertEntry alert)
    {
        var panel = new PanelContainer
        {
            PanelOverride = CreatePanelStyle(alert.Background, alert.Border, 1, 10),
        };

        panel.AddChild(new Label
        {
            Text = alert.Text,
            FontColorOverride = PrimaryText,
            ClipText = true,
        });

        return panel;
    }

    private string BuildEngineBadgeText(WH40KTankBuiState state, WH40KTankModuleEntry? engineModule)
    {
        if (engineModule?.Status == WH40KTankModuleStatus.Destroyed)
            return Loc.GetString("wh40k-tank-ui-engine-disabled");

        return Loc.GetString(state.EngineRunning ? "wh40k-tank-ui-engine-running" : "wh40k-tank-ui-engine-offline");
    }

    private string BuildWeaponsBadgeText(
        WH40KTankBuiState state,
        WH40KTankModuleEntry? mainModule,
        WH40KTankModuleEntry? coaxModule)
    {
        if (state.MainGunReloadTimeLeft > 0f || state.CoaxialReloadTimeLeft > 0f)
            return Loc.GetString("wh40k-tank-ui-weapons-reloading");

        if (IsWeaponEmpty(state.MainGunAmmoCount, state.MainGunAmmoCapacity) ||
            (state.HasCoaxialWeapon && IsWeaponEmpty(state.CoaxialAmmoCount, state.CoaxialAmmoCapacity)))
        {
            return Loc.GetString("wh40k-tank-ui-weapons-empty");
        }

        if (state.PendingMainGunFire || state.PendingCoaxialFire)
            return Loc.GetString("wh40k-tank-ui-weapons-queued");

        if (mainModule?.Status == WH40KTankModuleStatus.Destroyed ||
            coaxModule?.Status == WH40KTankModuleStatus.Destroyed)
        {
            return Loc.GetString("wh40k-tank-ui-weapons-degraded");
        }

        return Loc.GetString("wh40k-tank-ui-weapons-ready");
    }

    private string BuildFooterText(WH40KTankBuiState state)
    {
        if (state.MainGunReloadTimeLeft > 0f || state.CoaxialReloadTimeLeft > 0f)
            return Loc.GetString("wh40k-tank-ui-footer-reloading");

        var anyBadModule = state.Modules.Any(module => module.Status != WH40KTankModuleStatus.Operational);
        return anyBadModule || state.FuelFraction <= 0.35f || state.HullIntegrityFraction <= 0.7f
            ? Loc.GetString("wh40k-tank-ui-footer-damaged")
            : Loc.GetString("wh40k-tank-ui-footer-nominal");
    }

    private Color ResolveWeaponsAccent(
        WH40KTankBuiState state,
        WH40KTankModuleEntry? mainModule,
        WH40KTankModuleEntry? coaxModule)
    {
        if (state.MainGunReloadTimeLeft > 0f || state.CoaxialReloadTimeLeft > 0f)
            return WarningAccent;

        if (IsWeaponEmpty(state.MainGunAmmoCount, state.MainGunAmmoCapacity) ||
            (state.HasCoaxialWeapon && IsWeaponEmpty(state.CoaxialAmmoCount, state.CoaxialAmmoCapacity)))
        {
            return DangerAccent;
        }

        if (state.PendingMainGunFire || state.PendingCoaxialFire)
            return WarningAccent;

        if (mainModule?.Status == WH40KTankModuleStatus.Destroyed ||
            coaxModule?.Status == WH40KTankModuleStatus.Destroyed)
        {
            return DangerAccent;
        }

        return GoodAccent;
    }

    private string ResolveWeaponState(
        WH40KTankModuleEntry? module,
        bool queued,
        bool hasAimPoint,
        int ammoCount,
        int ammoCapacity,
        float reloadTimeLeft)
    {
        if (module == null || ammoCapacity <= 0)
            return Loc.GetString("wh40k-tank-ui-weapon-missing");

        if (module.Status == WH40KTankModuleStatus.Destroyed)
            return Loc.GetString("wh40k-tank-ui-weapon-offline");

        if (reloadTimeLeft > 0f)
        {
            return Loc.GetString(
                "wh40k-tank-ui-weapon-reloading",
                ("seconds", RemainingSeconds(reloadTimeLeft)));
        }

        if (IsWeaponEmpty(ammoCount, ammoCapacity))
            return Loc.GetString("wh40k-tank-ui-weapon-empty");

        if (queued)
            return Loc.GetString("wh40k-tank-ui-weapon-queued");

        if (!hasAimPoint)
            return Loc.GetString("wh40k-tank-ui-weapon-awaiting-aim");

        return Loc.GetString("wh40k-tank-ui-weapon-ready");
    }

    private Color ResolveWeaponStateColor(
        WH40KTankModuleEntry? module,
        bool queued,
        bool hasAimPoint,
        int ammoCount,
        int ammoCapacity,
        float reloadTimeLeft)
    {
        if (module == null || ammoCapacity <= 0)
            return SecondaryText;

        if (module.Status == WH40KTankModuleStatus.Destroyed || IsWeaponEmpty(ammoCount, ammoCapacity))
            return DangerAccent;

        if (reloadTimeLeft > 0f || queued)
            return WarningAccent;

        if (!hasAimPoint)
            return Accent;

        return GoodAccent;
    }

    private static bool TryGetWeaponDisplayData(
        WH40KTankBuiState state,
        WH40KTankModuleType module,
        out string ammoLocKey,
        out int ammoCount,
        out int ammoCapacity,
        out float reloadTimeLeft,
        out bool queued)
    {
        switch (module)
        {
            case WH40KTankModuleType.MainGun:
                ammoLocKey = state.MainAmmoLocKey;
                ammoCount = state.MainGunAmmoCount;
                ammoCapacity = state.MainGunAmmoCapacity;
                reloadTimeLeft = state.MainGunReloadTimeLeft;
                queued = state.PendingMainGunFire;
                return true;
            case WH40KTankModuleType.Coaxial when state.HasCoaxialWeapon:
                ammoLocKey = state.CoaxialAmmoLocKey;
                ammoCount = state.CoaxialAmmoCount;
                ammoCapacity = state.CoaxialAmmoCapacity;
                reloadTimeLeft = state.CoaxialReloadTimeLeft;
                queued = state.PendingCoaxialFire;
                return true;
            default:
                ammoLocKey = string.Empty;
                ammoCount = 0;
                ammoCapacity = 0;
                reloadTimeLeft = 0f;
                queued = false;
                return false;
        }
    }

    private static WH40KTankModuleEntry? GetModule(WH40KTankBuiState state, WH40KTankModuleType type)
    {
        return state.Modules.FirstOrDefault(entry => entry.Module == type);
    }

    private string ResolveRoleLabel(WH40KTankCrewRole role)
    {
        return Loc.GetString(role switch
        {
            WH40KTankCrewRole.Driver => "wh40k-tank-role-driver",
            WH40KTankCrewRole.Gunner => "wh40k-tank-role-gunner",
            WH40KTankCrewRole.Commander => "wh40k-tank-role-commander",
            WH40KTankCrewRole.Loader => "wh40k-tank-role-loader",
            _ => "wh40k-tank-role-driver",
        });
    }

    private string ResolveModuleLabel(WH40KTankBuiState state, WH40KTankModuleType module)
    {
        return Loc.GetString(module switch
        {
            WH40KTankModuleType.Engine => "wh40k-tank-ui-module-engine",
            WH40KTankModuleType.Tracks => "wh40k-tank-ui-module-tracks",
            WH40KTankModuleType.Turret => "wh40k-tank-ui-module-turret",
            WH40KTankModuleType.MainGun => state.MainWeaponLocKey,
            WH40KTankModuleType.Coaxial => state.CoaxialWeaponLocKey,
            _ => "wh40k-tank-ui-module-engine",
        });
    }

    private string ResolveModuleStatusText(WH40KTankModuleStatus status)
    {
        return Loc.GetString(status switch
        {
            WH40KTankModuleStatus.Operational => "wh40k-tank-ui-module-status-operational",
            WH40KTankModuleStatus.Damaged => "wh40k-tank-ui-module-status-damaged",
            WH40KTankModuleStatus.Critical => "wh40k-tank-ui-module-status-critical",
            WH40KTankModuleStatus.Destroyed => "wh40k-tank-ui-module-status-destroyed",
            _ => "wh40k-tank-ui-module-status-operational",
        });
    }

    private Color ResolveStatusColor(WH40KTankModuleStatus status)
    {
        return status switch
        {
            WH40KTankModuleStatus.Operational => GoodAccent,
            WH40KTankModuleStatus.Damaged => Accent,
            WH40KTankModuleStatus.Critical => WarningAccent,
            WH40KTankModuleStatus.Destroyed => DangerAccent,
            _ => Accent,
        };
    }

