    private static int Percent(float fraction)
    {
        return (int) MathF.Round(Math.Clamp(fraction, 0f, 1f) * 100f);
    }

    private static bool IsWeaponEmpty(int ammoCount, int ammoCapacity)
    {
        return ammoCapacity > 0 && ammoCount <= 0;
    }

    private static int RemainingSeconds(float seconds)
    {
        return Math.Max(1, (int) MathF.Ceiling(seconds));
    }

    private static string FormatValue(float value)
    {
        return value.ToString("0.#");
    }
