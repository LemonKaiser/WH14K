using Content.Client.Localization;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Info;

[GenerateTypedNameReferences]
public sealed partial class RulesPopup : Control, ILocalizedControl
{
    private const string RussianCultureName = "ru-RU";
    private const string EnglishCultureName = "en-US";

    private float _timer;

    public float Timer
    {
        get => _timer;
        set
        {
            _timer = value;
            UpdateWaitLabel();
        }
    }

    public event Action? OnQuitPressed;
    public event Action<string>? OnContinuePressed;

    public RulesPopup()
    {
        RobustXamlLoader.Load(this);

        ContinueRuButton.OnPressed += _ => OnContinuePressed?.Invoke(RussianCultureName);
        ContinueEnButton.OnPressed += _ => OnContinuePressed?.Invoke(EnglishCultureName);
        QuitButton.OnPressed += OnQuitButtonPressed;

        Relocalize();
    }

    public void Relocalize()
    {
        ContinueRuButton.Text = Loc.GetString("ui-rules-continue-ru");
        ContinueEnButton.Text = Loc.GetString("ui-rules-continue-en");
        QuitButton.Text = Loc.GetString("ui-escape-quit");
        UpdateWaitLabel();
    }

    private void OnQuitButtonPressed(BaseButton.ButtonEventArgs obj)
    {
        OnQuitPressed?.Invoke();
    }

    private void UpdateWaitLabel()
    {
        WaitLabel.Text = Loc.GetString("ui-rules-wait", ("time", MathF.Floor(_timer)));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!ContinueRuButton.Disabled && !ContinueEnButton.Disabled)
            return;

        if (Timer > 0.0)
        {
            if (Timer - args.DeltaSeconds < 0)
                Timer = 0;
            else
                Timer -= args.DeltaSeconds;
        }
        else
        {
            ContinueRuButton.Disabled = false;
            ContinueEnButton.Disabled = false;
        }
    }
}
