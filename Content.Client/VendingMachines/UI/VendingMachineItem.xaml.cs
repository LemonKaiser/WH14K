using Content.Shared.VendingMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Content.Client._WH40K.Interface;

namespace Content.Client.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class VendingMachineItem : BoxContainer
{
    public VendingMachineItem(EntProtoId entProto)
    {
        RobustXamlLoader.Load(this);
        ItemPrototype.SetPrototype(entProto);
    }

    public void ApplyState(
        string itemName,
        string metaText,
        uint amount,
        InventoryType inventoryType,
        bool enabled,
        bool lowStock,
        VendingMachineMenuTheme theme)
    {
        var itemGlyph = inventoryType switch
        {
            InventoryType.Emagged => WH40KUiChrome.Blade,
            InventoryType.Contraband => WH40KUiChrome.Skull,
            _ => WH40KUiChrome.DiamondOutline,
        };

        NameLabel.SetMessage($"{itemGlyph} {itemName}", defaultColor: enabled ? theme.PrimaryText : theme.SecondaryText);
        MetaLabel.SetMessage($"{WH40KUiChrome.Arrow} {metaText}", defaultColor: ResolveMetaColor(inventoryType, enabled, lowStock, theme));
        AmountLabel.Text = Loc.GetString("vending-machine-ui-row-amount", ("amount", amount));
        AmountLabel.FontColorOverride = ResolveAmountColor(amount, lowStock, theme);

        IconFrame.PanelOverride = VendingMachineMenuStyles.CreateBadgeStyle(
            theme.PanelAltBackground,
            ResolveInventoryTypeColor(inventoryType, theme),
            6,
            6);

        AmountBadge.PanelOverride = VendingMachineMenuStyles.CreateBadgeStyle(
            amount == 0 ? theme.PanelAltBackground : theme.PanelBackground,
            ResolveAmountColor(amount, lowStock, theme).WithAlpha(0.82f),
            10,
            6);
    }

    private static Color ResolveInventoryTypeColor(InventoryType inventoryType, VendingMachineMenuTheme theme)
    {
        return inventoryType switch
        {
            InventoryType.Emagged => theme.WarningAccent,
            InventoryType.Contraband => theme.DangerAccent,
            _ => theme.BorderStrongColor,
        };
    }

    private static Color ResolveMetaColor(InventoryType inventoryType, bool enabled, bool lowStock, VendingMachineMenuTheme theme)
    {
        if (!enabled)
            return theme.SecondaryText;

        return inventoryType switch
        {
            InventoryType.Emagged => theme.WarningAccent,
            InventoryType.Contraband => theme.DangerAccent,
            _ => lowStock ? theme.WarningAccent : theme.SecondaryText,
        };
    }

    private static Color ResolveAmountColor(uint amount, bool lowStock, VendingMachineMenuTheme theme)
    {
        if (amount == 0)
            return theme.DangerAccent;

        return lowStock ? theme.WarningAccent : theme.Accent;
    }
}
