using System;
using System.Collections.Generic;
using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Client._WH40K.Interface;
using Content.Shared.IdentityManagement;
using Content.Shared.VendingMachines;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client.VendingMachines.UI;

[GenerateTypedNameReferences]
public sealed partial class VendingMachineMenu : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;
    [Dependency] private readonly IEntityManager _entityManager = default!;

    private readonly Dictionary<EntProtoId, EntityUid> _dummies = [];
    private readonly List<VendorItemsListData> _allEntries = new();

    private VendingMachineMenuTheme _theme = VendingMachineMenuTheme.Default;
    private VendorFilterMode _currentFilter = VendorFilterMode.All;
    private EntityUid _owner;
    private bool _enabled;
    private string _titleText = string.Empty;
    private string _subtitleText = string.Empty;
    private VendingMachineUiStatus? _lastStatus;

    public event Action<GUIBoundKeyEventArgs, ListData>? OnItemSelected;

    public VendingMachineMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VendingContents.SearchBar = SearchBar;
        VendingContents.DataFilterCondition += DataFilterCondition;
        VendingContents.GenerateItem += GenerateButton;
        VendingContents.ItemKeyBindDown += (args, data) => OnItemSelected?.Invoke(args, data);

        FilterOption.OnItemSelected += OnFilterSelected;

        ApplyTheme();
        PopulateFilterOptions();
        ApplyFilters();
    }

    public void SetEntity(EntityUid uid)
    {
        _owner = uid;

        var metaData = _entityManager.GetComponent<MetaDataComponent>(uid);
        _titleText = metaData.EntityName;
        _subtitleText = string.IsNullOrWhiteSpace(metaData.EntityDescription)
            ? Loc.GetString("vending-machine-ui-header-subtitle-fallback")
            : metaData.EntityDescription;
        _theme = VendingMachineMenuStyles.ResolveTheme(metaData.EntityPrototype?.ID);
        _lastStatus = null;

        ApplyTheme();
        RefreshStatusPanel();
        RefreshSummaryCards();
        RefreshFooter();
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        foreach (var entity in _dummies.Values)
        {
            _entityManager.QueueDeleteEntity(entity);
        }

        _dummies.Clear();
    }

    public void Populate(List<VendingMachineInventoryEntry> inventory, bool enabled)
    {
        _enabled = enabled;
        _allEntries.Clear();

        for (var i = 0; i < inventory.Count; i++)
        {
            var entry = inventory[i];

            if (!_prototypeManager.TryIndex<EntityPrototype>(entry.ID, out var prototype))
                continue;

            if (!_dummies.TryGetValue(prototype.ID, out var dummy))
            {
                dummy = _entityManager.Spawn(entry.ID);
                _dummies[prototype.ID] = dummy;
            }

            var itemName = Identity.Name(dummy, _entityManager);
            var description = _entityManager.TryGetComponent(dummy, out MetaDataComponent? metaData)
                ? metaData.EntityDescription
                : string.Empty;
            var lowStock = entry.Amount > 0 && entry.Amount <= 2;
            var typeText = Loc.GetString(GetInventoryTypeLocKey(entry.Type));
            var stockText = Loc.GetString(GetStockLocKey(entry.Amount, lowStock));

            _allEntries.Add(new VendorItemsListData(prototype.ID, i)
            {
                ItemName = itemName,
                Description = description,
                Amount = entry.Amount,
                InventoryType = entry.Type,
                LowStock = lowStock,
                SearchText = $"{itemName} {description} {typeText} {stockText}",
            });
        }

        RefreshStatusPanel();
        RefreshSummaryCards();
        ApplyFilters();
        RefreshFooter();
    }

    public void UpdateAmounts(List<VendingMachineInventoryEntry> cachedInventory, bool enabled)
    {
        Populate(cachedInventory, enabled);
    }

    private void OnFilterSelected(OptionButton.ItemSelectedEventArgs args)
    {
        _currentFilter = Enum.IsDefined(typeof(VendorFilterMode), args.Id)
            ? (VendorFilterMode) args.Id
            : VendorFilterMode.All;
        FilterOption.SelectId(args.Id);
        RefreshSummaryCards();
        ApplyFilters();
    }

    private bool DataFilterCondition(string filter, ListData data)
    {
        if (data is not VendorItemsListData entry)
            return false;

        if (string.IsNullOrWhiteSpace(filter))
            return true;

        return entry.SearchText.Contains(filter, StringComparison.CurrentCultureIgnoreCase);
    }

    private void GenerateButton(ListData data, ListContainerButton button)
    {
        if (data is not VendorItemsListData entry)
            return;

        var item = new VendingMachineItem(entry.ItemProtoID);
        item.ApplyState(
            entry.ItemName,
            BuildMetaText(entry),
            entry.Amount,
            entry.InventoryType,
            _enabled && entry.Amount > 0,
            entry.LowStock,
            _theme);

        button.AddChild(item);
        button.MinSize = new Vector2(0f, 72f);
        button.Disabled = !_enabled || entry.Amount == 0;
        var normalStyle = CreateRowStyle(entry, false);
        var hoverStyle = CreateRowStyle(entry, true);
        button.StyleBoxOverride = normalStyle;
        button.ToolTip = BuildTooltip(entry);

        button.OnMouseEntered += _ =>
        {
            button.StyleBoxOverride = hoverStyle;
            WH40KUiChrome.PlayHoverFlash(item, "hover-flash");
        };
        button.OnMouseExited += _ => button.StyleBoxOverride = normalStyle;

    }

    private void PopulateFilterOptions()
    {
        var selectedId = FilterOption.ItemCount > 0 ? FilterOption.SelectedId : (int) _currentFilter;

        FilterOption.Clear();

        foreach (VendorFilterMode mode in Enum.GetValues<VendorFilterMode>())
        {
            FilterOption.AddItem(Loc.GetString(GetFilterLocKey(mode)), (int) mode);
        }

        if (!FilterOption.TrySelectId(selectedId))
            FilterOption.SelectId((int) _currentFilter);
    }

    private void ApplyFilters()
    {
        var filtered = _allEntries
            .Where(MatchesCurrentFilter)
            .Cast<ListData>()
            .ToList();

        VendingContents.PopulateList(filtered);

        var hasConfiguredStock = _allEntries.Count > 0;
        var hasVisibleEntries = filtered.Count > 0;

        CatalogEmptyLabel.Visible = !hasVisibleEntries;
        VendingContents.Visible = hasVisibleEntries;
        CatalogEmptyLabel.Text = Loc.GetString(hasConfiguredStock
            ? "vending-machine-ui-catalog-empty-filter"
            : "vending-machine-ui-catalog-empty-machine");

        SetWrappedText(
            CatalogSubtitleLabel,
            Loc.GetString(
                "vending-machine-ui-catalog-subtitle-count",
                ("visible", filtered.Count),
                ("total", _allEntries.Count)),
            _theme.SecondaryText);
    }

    private void ApplyTheme()
    {
        Title = string.IsNullOrWhiteSpace(_titleText) ? "Vending Machine" : _titleText;
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Cog, Title);
        StatusPanelTitleLabel.Text = WH40KUiChrome.DecorateIfMissing(StatusPanelTitleLabel.Text, WH40KUiChrome.DiamondNested);
        StockCardLabel.Text = WH40KUiChrome.DecorateIfMissing(StockCardLabel.Text, WH40KUiChrome.Diamond);
        CatalogCardLabel.Text = WH40KUiChrome.DecorateIfMissing(CatalogCardLabel.Text, WH40KUiChrome.Diamond);
        FilterCardLabel.Text = WH40KUiChrome.DecorateIfMissing(FilterCardLabel.Text, WH40KUiChrome.DiamondOutline);
        SpecialCardLabel.Text = WH40KUiChrome.DecorateIfMissing(SpecialCardLabel.Text, WH40KUiChrome.Blade);
        CatalogTitleLabel.Text = WH40KUiChrome.DecorateIfMissing(CatalogTitleLabel.Text, WH40KUiChrome.Diamond);

        SetWrappedText(
            HeaderSubtitleLabel,
            string.IsNullOrWhiteSpace(_subtitleText)
                ? Loc.GetString("vending-machine-ui-header-subtitle-fallback")
                : _subtitleText,
            _theme.SecondaryText);

        SetWrappedText(
            CatalogSubtitleLabel,
            Loc.GetString("vending-machine-ui-catalog-subtitle"),
            _theme.SecondaryText);

        RootFrame.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.WindowBackground, _theme.BorderStrongColor, 0);
        HeaderPanel.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        StatusPanel.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        StockCard.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        CatalogCard.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        FilterCard.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        SpecialCard.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        SearchPanel.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        CatalogPanel.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        CatalogHeaderPanel.PanelOverride = VendingMachineMenuStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
        CatalogBodyPanel.PanelOverride = VendingMachineMenuStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        FooterDivider.MinSize = new Vector2(0f, 1f);
        FooterDivider.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = _theme.BorderStrongColor,
        };

        SearchBar.StyleBoxOverride = VendingMachineMenuStyles.CreateInputStyle(_theme);
        FilterOption.StyleBoxOverride = VendingMachineMenuStyles.CreateSecondaryButtonStyle(_theme);
        FilterOption.PopupButtonStyleOverride = VendingMachineMenuStyles.CreateSecondaryButtonStyle(_theme);
        FilterOption.PopupSelectedButtonStyleOverride = VendingMachineMenuStyles.CreatePrimaryButtonStyle(_theme);
        FilterOption.PopupButtonFontColorOverride = _theme.PrimaryText;
        FilterOption.PopupSelectedButtonFontColorOverride = _theme.PrimaryText;
        FilterOption.RefreshPopupItemTheme();

        HeaderTitleLabel.FontColorOverride = _theme.Accent;
        CatalogTitleLabel.FontColorOverride = _theme.Accent;
        StatusPanelTitleLabel.FontColorOverride = _theme.LabelText;
        StatusValueLabel.FontColorOverride = _theme.PrimaryText;
        CatalogEmptyLabel.FontColorOverride = _theme.SecondaryText;

        foreach (var label in new[]
                 {
                     StockCardLabel,
                     CatalogCardLabel,
                     FilterCardLabel,
                     SpecialCardLabel
                 })
        {
            label.FontColorOverride = _theme.LabelText;
        }

        foreach (var label in new[]
                 {
                     StockValueLabel,
                     CatalogValueLabel,
                     FilterValueLabel,
                     SpecialValueLabel
                 })
        {
            label.FontColorOverride = _theme.PrimaryText;
        }

        WH40KUiChrome.StartLoopingPulse(HeaderTitleLabel, "title-pulse", new Color(0.8f, 0.8f, 0.8f, 1f), Color.White, 3.2f);
        WH40KUiChrome.StartLoopingPulse(FooterDivider, "footer-pulse", new Color(0.55f, 0.55f, 0.55f, 1f), Color.White, 4.2f);
    }

    private void RefreshStatusPanel()
    {
        var status = GetCurrentStatus();
        var accent = GetStatusColor(status);
        var changed = _lastStatus != status;
        _lastStatus = status;

        StatusPanel.PanelOverride = VendingMachineMenuStyles.CreatePanelStyle(_theme.PanelAltBackground, accent.WithAlpha(0.82f), 0);
        StatusValueLabel.Text = Loc.GetString(GetStatusLocKey(status));
        StatusValueLabel.FontColorOverride = accent;
        SetWrappedText(StatusHintLabel, Loc.GetString(GetStatusHintLocKey(status)), _theme.SecondaryText);
        if (changed)
            WH40KUiChrome.PlayHoverFlash(StatusPanel, "status-flash", new Color(0.86f, 0.86f, 0.9f, 1f), 0.18f);
    }

    private void RefreshSummaryCards()
    {
        var totalUnits = _allEntries.Sum(entry => (int) entry.Amount);
        var availableUnits = _allEntries.Where(entry => entry.Amount > 0).Sum(entry => (int) entry.Amount);
        var totalLines = _allEntries.Count;
        var availableLines = _allEntries.Count(entry => entry.Amount > 0);
        var lowStockLines = _allEntries.Count(entry => entry.LowStock);
        var specialLines = _allEntries.Count(entry => entry.InventoryType != InventoryType.Regular);

        StockValueLabel.Text = Loc.GetString(
            "vending-machine-ui-stock-value",
            ("availableUnits", availableUnits),
            ("totalUnits", totalUnits));
        CatalogValueLabel.Text = Loc.GetString(
            "vending-machine-ui-catalog-value",
            ("availableLines", availableLines),
            ("totalLines", totalLines));
        FilterValueLabel.Text = Loc.GetString(GetFilterLocKey(_currentFilter));
        SpecialValueLabel.Text = Loc.GetString(
            "vending-machine-ui-special-value",
            ("specialLines", specialLines),
            ("lowStockLines", lowStockLines));
    }

    private void RefreshFooter()
    {
        var footerLocKey = GetCurrentStatus() switch
        {
            VendingMachineUiStatus.Dispensing => "vending-machine-ui-footer-dispensing",
            VendingMachineUiStatus.Empty => "vending-machine-ui-footer-empty",
            _ when _allEntries.Any(entry => entry.LowStock) => "vending-machine-ui-footer-low-stock",
            _ => "vending-machine-ui-footer-default",
        };

        SetWrappedText(FooterLabel, Loc.GetString(footerLocKey), _theme.SecondaryText);
    }

    private bool MatchesCurrentFilter(VendorItemsListData entry)
    {
        return _currentFilter switch
        {
            VendorFilterMode.Available => entry.Amount > 0,
            VendorFilterMode.LowStock => entry.LowStock,
            VendorFilterMode.Special => entry.InventoryType != InventoryType.Regular,
            _ => true,
        };
    }

    private StyleBoxFlat CreateRowStyle(VendorItemsListData entry, bool hovered)
    {
        var background = entry.Amount == 0
            ? _theme.PanelAltBackground
            : hovered ? _theme.PanelBackground : _theme.SurfaceBackground;

        var border = hovered
            ? _theme.Accent.WithAlpha(0.84f)
            : entry.Amount == 0
            ? _theme.BorderColor
            : entry.InventoryType switch
            {
                InventoryType.Emagged => _theme.WarningAccent.WithAlpha(0.75f),
                InventoryType.Contraband => _theme.DangerAccent.WithAlpha(0.75f),
                _ => entry.LowStock ? _theme.WarningAccent.WithAlpha(0.75f) : _theme.BorderColor,
            };

        return VendingMachineMenuStyles.CreateRowStyle(background, border);
    }

    private string BuildMetaText(VendorItemsListData entry)
    {
        return Loc.GetString(
            "vending-machine-ui-row-meta",
            ("type", Loc.GetString(GetInventoryTypeLocKey(entry.InventoryType))),
            ("stock", Loc.GetString(GetStockLocKey(entry.Amount, entry.LowStock))));
    }

    private string BuildTooltip(VendorItemsListData entry)
    {
        var description = string.IsNullOrWhiteSpace(entry.Description)
            ? Loc.GetString("vending-machine-ui-tooltip-no-description")
            : entry.Description;

        var lines = new[]
        {
            entry.ItemName,
            description,
            string.Empty,
            $"{Loc.GetString("vending-machine-ui-tooltip-type")}: {Loc.GetString(GetInventoryTypeLocKey(entry.InventoryType))}",
            $"{Loc.GetString("vending-machine-ui-tooltip-stock")}: {Loc.GetString(GetStockLocKey(entry.Amount, entry.LowStock))}",
        };

        return string.Join("\n", lines);
    }

    private VendingMachineUiStatus GetCurrentStatus()
    {
        if (_owner != EntityUid.Invalid &&
            _entityManager.TryGetComponent(_owner, out VendingMachineComponent? vending))
        {
            if (vending.Broken)
                return VendingMachineUiStatus.Broken;

            if (vending.Denying)
                return VendingMachineUiStatus.Denied;

            if (vending.Ejecting)
                return VendingMachineUiStatus.Dispensing;
        }

        if (_allEntries.Count == 0 || _allEntries.All(entry => entry.Amount == 0))
            return VendingMachineUiStatus.Empty;

        if (!_enabled)
            return VendingMachineUiStatus.Unavailable;

        return VendingMachineUiStatus.Ready;
    }

    private Color GetStatusColor(VendingMachineUiStatus status)
    {
        return status switch
        {
            VendingMachineUiStatus.Ready => _theme.SuccessAccent,
            VendingMachineUiStatus.Dispensing => _theme.Accent,
            VendingMachineUiStatus.Denied => _theme.WarningAccent,
            VendingMachineUiStatus.Unavailable => _theme.WarningAccent,
            VendingMachineUiStatus.Broken => _theme.DangerAccent,
            VendingMachineUiStatus.Empty => _theme.WarningAccent,
            _ => _theme.PrimaryText,
        };
    }

    private static string GetStatusLocKey(VendingMachineUiStatus status)
    {
        return status switch
        {
            VendingMachineUiStatus.Ready => "vending-machine-ui-status-ready",
            VendingMachineUiStatus.Dispensing => "vending-machine-ui-status-dispensing",
            VendingMachineUiStatus.Denied => "vending-machine-ui-status-denied",
            VendingMachineUiStatus.Unavailable => "vending-machine-ui-status-unavailable",
            VendingMachineUiStatus.Broken => "vending-machine-ui-status-broken",
            VendingMachineUiStatus.Empty => "vending-machine-ui-status-empty",
            _ => "vending-machine-ui-status-ready",
        };
    }

    private static string GetStatusHintLocKey(VendingMachineUiStatus status)
    {
        return status switch
        {
            VendingMachineUiStatus.Ready => "vending-machine-ui-status-hint-ready",
            VendingMachineUiStatus.Dispensing => "vending-machine-ui-status-hint-dispensing",
            VendingMachineUiStatus.Denied => "vending-machine-ui-status-hint-denied",
            VendingMachineUiStatus.Unavailable => "vending-machine-ui-status-hint-unavailable",
            VendingMachineUiStatus.Broken => "vending-machine-ui-status-hint-broken",
            VendingMachineUiStatus.Empty => "vending-machine-ui-status-hint-empty",
            _ => "vending-machine-ui-status-hint-ready",
        };
    }

    private static string GetFilterLocKey(VendorFilterMode mode)
    {
        return mode switch
        {
            VendorFilterMode.Available => "vending-machine-ui-filter-available",
            VendorFilterMode.LowStock => "vending-machine-ui-filter-low-stock",
            VendorFilterMode.Special => "vending-machine-ui-filter-special",
            _ => "vending-machine-ui-filter-all",
        };
    }

    private static string GetInventoryTypeLocKey(InventoryType inventoryType)
    {
        return inventoryType switch
        {
            InventoryType.Emagged => "vending-machine-ui-row-type-emagged",
            InventoryType.Contraband => "vending-machine-ui-row-type-contraband",
            _ => "vending-machine-ui-row-type-regular",
        };
    }

    private static string GetStockLocKey(uint amount, bool lowStock)
    {
        if (amount == 0)
            return "vending-machine-ui-row-stock-empty";

        return lowStock
            ? "vending-machine-ui-row-stock-low"
            : "vending-machine-ui-row-stock-ready";
    }

    private static void SetWrappedText(RichTextLabel label, string text, Color color)
    {
        label.SetMessage(text.Replace("\\n", "\n", StringComparison.Ordinal), defaultColor: color);
    }

    private enum VendorFilterMode
    {
        All = 0,
        Available = 1,
        LowStock = 2,
        Special = 3,
    }

    private enum VendingMachineUiStatus
    {
        Ready,
        Dispensing,
        Denied,
        Unavailable,
        Broken,
        Empty,
    }
}

public record VendorItemsListData(EntProtoId ItemProtoID, int ItemIndex) : ListData
{
    public string ItemName = string.Empty;
    public string Description = string.Empty;
    public string SearchText = string.Empty;
    public InventoryType InventoryType;
    public uint Amount;
    public bool LowStock;
}
