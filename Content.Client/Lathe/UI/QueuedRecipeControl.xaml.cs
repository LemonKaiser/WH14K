using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client._WH40K.Interface;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class QueuedRecipeControl : Control
{
    public Action<int>? OnDeletePressed;
    public Action<int>? OnMoveUpPressed;
    public Action<int>? OnMoveDownPressed;

    private int _index;

    public QueuedRecipeControl(string displayText, int index, Control displayControl, WH40KLatheMenuTheme theme)
    {
        RobustXamlLoader.Load(this);

        CardPanel.PanelOverride = WH40KLatheMenuStyles.CreatePanelStyle(theme.SurfaceBackground, theme.BorderColor, 0);
        SlotBadge.PanelOverride = WH40KLatheMenuStyles.CreateBadgeStyle(theme.PanelAltBackground, theme.Accent.WithAlpha(0.72f), 8, 5);
        IconPanel.PanelOverride = WH40KLatheMenuStyles.CreateBadgeStyle(theme.PreviewBackground, theme.BorderColor, 4, 4);
        RecipeName.FontColorOverride = theme.PrimaryText;
        SlotLabel.FontColorOverride = theme.PrimaryText;

        WH40KLatheMenuStyles.ApplyButtonTheme(MoveUp, WH40KLatheMenuStyles.CreateSecondaryButtonStyle(theme), theme.PrimaryText);
        WH40KLatheMenuStyles.ApplyButtonTheme(MoveDown, WH40KLatheMenuStyles.CreateSecondaryButtonStyle(theme), theme.PrimaryText);
        WH40KLatheMenuStyles.ApplyButtonTheme(Delete, WH40KLatheMenuStyles.CreateDangerButtonStyle(theme), theme.PrimaryText);

        SetDisplayText(displayText);
        SetDisplayControl(displayControl);
        SetIndex(index);

        MoveUp.OnPressed += _ =>
        {
            OnMoveUpPressed?.Invoke(_index);
        };

        MoveDown.OnPressed += _ =>
        {
            OnMoveDownPressed?.Invoke(_index);
        };

        Delete.OnPressed += _ =>
        {
            OnDeletePressed?.Invoke(_index);
        };

        MoveUp.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(CardPanel, "hover-flash");
        MoveDown.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(CardPanel, "hover-flash");
        Delete.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(CardPanel, "hover-flash");
        WH40KUiChrome.StartLoopingPulse(SlotBadge, "slot-pulse", new Color(0.72f, 0.72f, 0.72f, 1f), Color.White, 4.4f);
    }

    public void SetDisplayText(string displayText)
    {
        RecipeName.Text = WH40KUiChrome.DecorateIfMissing(displayText, WH40KUiChrome.Arrow);
    }

    public void SetDisplayControl(Control displayControl)
    {
        RecipeDisplayContainer.Children.Clear();
        RecipeDisplayContainer.AddChild(displayControl);
    }

    public void SetIndex(int index)
    {
        _index = index;
        SlotLabel.Text = $"#{index + 1:00}";
        MoveUp.Disabled = index <= 0;
    }
}
