using Content.Shared.Research.Prototypes;
using Content.Client._WH40K.Interface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class RecipeControl : Control
{
    public Action<string>? OnButtonPressed;
    public Action<string>? OnInfiniteButtonPressed;
    public Func<string> TooltipTextSupplier;

    private readonly WH40KLatheMenuTheme _theme;
    private ProtoId<LatheRecipePrototype> _recipeId;
    private ProtoId<LatheRecipePrototype>? _displayRecipeId;
    private readonly LatheSystem _latheSystem;
    private bool? _canProduce;
    private string _metaText = string.Empty;

    public RecipeControl(
        LatheSystem latheSystem,
        LatheRecipePrototype recipe,
        Func<string> tooltipTextSupplier,
        bool canProduce,
        Control displayControl,
        string metaText,
        WH40KLatheMenuTheme theme)
    {
        RobustXamlLoader.Load(this);

        _theme = theme;
        _latheSystem = latheSystem;
        _recipeId = recipe.ID;
        _metaText = metaText;
        TooltipTextSupplier = tooltipTextSupplier;

        CardPanel.PanelOverride = WH40KLatheMenuStyles.CreatePanelStyle(theme.SurfaceBackground, theme.BorderColor, 0);
        IconPanel.PanelOverride = WH40KLatheMenuStyles.CreateBadgeStyle(theme.PreviewBackground, theme.BorderColor, 4, 4);
        AccentBar.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = theme.Accent.WithAlpha(0.8f),
        };

        RecipeName.FontColorOverride = theme.PrimaryText;
        WH40KLatheMenuStyles.ApplyButtonTheme(Button, WH40KLatheMenuStyles.CreatePrimaryButtonStyle(theme), theme.PrimaryText);
        WH40KLatheMenuStyles.ApplyButtonTheme(InfiniteButton, WH40KLatheMenuStyles.CreateSecondaryButtonStyle(theme), theme.PrimaryText);

        SetRecipe(recipe, metaText);
        SetCanProduce(canProduce);
        SetDisplayControl(displayControl, recipe.ID);

        Button.OnPressed += _ =>
        {
            OnButtonPressed?.Invoke(_recipeId);
        };
        InfiniteButton.OnPressed += _ =>
        {
            OnInfiniteButtonPressed?.Invoke(_recipeId);
        };
        Button.TooltipSupplier = SupplyTooltip;
        InfiniteButton.TooltipSupplier = SupplyTooltip;
        Button.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(CardPanel, "hover-flash");
        InfiniteButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(CardPanel, "hover-flash");
        WH40KUiChrome.StartLoopingPulse(AccentBar, "accent-pulse", new Color(0.72f, 0.72f, 0.72f, 1f), Color.White, 4.1f);
    }

    public void SetRecipe(LatheRecipePrototype recipe, string metaText)
    {
        RecipeName.Text = WH40KUiChrome.DecorateIfMissing(_latheSystem.GetRecipeName(recipe), WH40KUiChrome.DiamondOutline);
        _recipeId = recipe.ID;
        _metaText = metaText;
        UpdateMetaText(Button.Disabled);
    }

    public void SetTooltipSupplier(Func<string> tooltipTextSupplier)
    {
        TooltipTextSupplier = tooltipTextSupplier;
    }

    public void SetCanProduce(bool canProduce)
    {
        if (_canProduce == canProduce)
        {
            UpdateMetaText(!canProduce);
            return;
        }

        _canProduce = canProduce;
        Button.Disabled = !canProduce;
        AccentBar.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = canProduce
                ? _theme.Accent.WithAlpha(0.84f)
                : _theme.DangerAccent.WithAlpha(0.72f),
        };
        CardPanel.PanelOverride = WH40KLatheMenuStyles.CreatePanelStyle(
            canProduce ? _theme.SurfaceBackground : _theme.PanelAltBackground,
            canProduce ? _theme.BorderColor : _theme.DangerAccent.WithAlpha(0.68f),
            0);
        WH40KLatheMenuStyles.ApplyButtonTheme(
            Button,
            canProduce
                ? WH40KLatheMenuStyles.CreatePrimaryButtonStyle(_theme)
                : WH40KLatheMenuStyles.CreateSecondaryButtonStyle(_theme),
            canProduce ? _theme.PrimaryText : _theme.SecondaryText);
        UpdateMetaText(!canProduce);
    }

    public void SetDisplayControl(Control displayControl, ProtoId<LatheRecipePrototype> recipeId)
    {
        if (_displayRecipeId == recipeId && RecipeDisplayContainer.ChildCount == 1)
            return;

        _displayRecipeId = recipeId;
        RecipeDisplayContainer.Children.Clear();
        RecipeDisplayContainer.AddChild(displayControl);
    }

    private void UpdateMetaText(bool blocked)
    {
        var statusKey = blocked
            ? "lathe-menu-recipe-status-blocked"
            : "lathe-menu-recipe-status-ready";
        RecipeMetaLabel.Text = $"{WH40KUiChrome.Arrow} {_metaText} | {Loc.GetString(statusKey)}";
        RecipeMetaLabel.FontColorOverride = blocked ? _theme.DangerAccent : _theme.SecondaryText;
    }

    private Control? SupplyTooltip(Control sender)
    {
        return new RecipeTooltip(RecipeName.Text ?? string.Empty, TooltipTextSupplier(), _theme);
    }
}
