    private void RefreshMachineReadouts()
    {
        if (Entity == default || !_entityManager.EntityExists(Entity))
            return;

        UpdateMaterialMetrics();

        if (!_entityManager.TryGetComponent(Entity, out LatheComponent? lathe))
            return;

        _researchCapable = lathe.DynamicPacks.Any();
        ServerListButton.Visible = _researchCapable;
        ServerListButton.Disabled = !_researchCapable;

        ProfileValueLabel.Text = Loc.GetString(_theme.ProfileLocKey);
        DesignValueLabel.Text = Loc.GetString("lathe-menu-summary-designs-value", ("visible", _visibleRecipeCount), ("total", _totalRecipeCount));
        QueueValueLabel.Text = Loc.GetString(
            _progressRecipe == null
                ? "lathe-menu-summary-queue-value-idle"
                : "lathe-menu-summary-queue-value-active",
            ("batches", _queueBatchCount));
        MaterialsValueLabel.Text = _materialStorageLimit is { } limit && limit > 0
            ? Loc.GetString("lathe-menu-summary-materials-value-limited", ("current", _storedMaterialVolume), ("max", limit))
            : Loc.GetString("lathe-menu-summary-materials-value", ("current", _storedMaterialVolume));

        ServerPanelStatusLabel.SetMessage(
            _researchCapable
                ? Loc.GetString("lathe-menu-server-status-linked", ("packs", lathe.DynamicPacks.Count))
                : Loc.GetString("lathe-menu-server-status-static"),
            defaultColor: _researchCapable ? _theme.Accent : _theme.SecondaryText);

        QueueStateValueLabel.Text = _progressRecipe == null
            ? Loc.GetString("lathe-menu-queue-state-idle")
            : Loc.GetString("lathe-menu-queue-state-printing", ("name", GetRecipeDisplayName(_progressRecipe.Value)));
        QueueStateValueLabel.FontColorOverride = _progressRecipe == null ? _theme.SecondaryText : _theme.Accent;

        QueueDepthValueLabel.Text = _queueInfiniteCount > 0
            ? Loc.GetString("lathe-menu-queue-depth-value-infinite", ("batches", _queueBatchCount), ("items", _queueRequestedTotal), ("infinite", _queueInfiniteCount))
            : Loc.GetString("lathe-menu-queue-depth-value", ("batches", _queueBatchCount), ("items", _queueRequestedTotal));

        RequestValueLabel.Text = Loc.GetString("lathe-menu-queue-request-value", ("amount", GetCurrentRequestedAmount()));
        StorageValueLabel.Text = _materialStorageLimit is { } max && max > 0
            ? Loc.GetString("lathe-menu-materials-storage-value-limited", ("current", _storedMaterialVolume), ("max", max), ("types", _loadedMaterialTypes))
            : Loc.GetString("lathe-menu-materials-storage-value", ("current", _storedMaterialVolume), ("types", _loadedMaterialTypes));

        SourceValueLabel.Text = Loc.GetString(_siloLinked
            ? "lathe-menu-materials-source-silo"
            : "lathe-menu-materials-source-internal");
        SourceValueLabel.FontColorOverride = _siloLinked ? _theme.Accent : _theme.PrimaryText;

        EfficiencyValueLabel.Text = Loc.GetString("lathe-menu-materials-efficiency-value", ("multiplier", lathe.MaterialUseMultiplier.ToString("0.##")));
        EfficiencyValueLabel.FontColorOverride = lathe.MaterialUseMultiplier < 1f
            ? _theme.SuccessAccent
            : _theme.PrimaryText;

        DesignsHeaderSubtitleLabel.Text = BuildDesignSubtitleText();
        QueueEmptyLabel.Visible = _queueBatchCount == 0;
        RecipeEmptyLabel.Visible = _visibleRecipeCount == 0;
    }

    private void UpdateMaterialMetrics()
    {
        _storedMaterialVolume = 0;
        _loadedMaterialTypes = 0;
        _siloLinked = false;

        if (!_entityManager.TryGetComponent(Entity, out MaterialStorageComponent? materialStorage))
            return;

        var stored = _materialStorage.GetStoredMaterials((Entity, materialStorage));
        _storedMaterialVolume = stored.Values.Sum();
        _loadedMaterialTypes = stored.Count(pair => pair.Value > 0);
        _siloLinked = _entityManager.TryGetComponent<OreSiloClientComponent>(Entity, out var client) && client.Silo != null;
    }

    private string BuildRecipeMetaText(LatheRecipePrototype prototype)
    {
        var materialKinds = prototype.Materials.Count;
        var seconds = Math.Max(1, (int) MathF.Ceiling((float) prototype.CompleteTime.TotalSeconds));

        if (prototype.Categories.Count > 0 &&
            _prototypeManager.TryIndex(prototype.Categories[0], out LatheCategoryPrototype? category))
        {
            return Loc.GetString("lathe-menu-recipe-meta-category", ("category", Loc.GetString(category.Name)), ("materials", materialKinds), ("seconds", seconds));
        }

        return Loc.GetString("lathe-menu-recipe-meta", ("materials", materialKinds), ("seconds", seconds));
    }

    private string BuildDesignSubtitleText()
    {
        if (CurrentCategory != null &&
            _prototypeManager.TryIndex(CurrentCategory.Value, out LatheCategoryPrototype? category))
        {
            return Loc.GetString("lathe-menu-designs-subtitle-filtered", ("category", Loc.GetString(category.Name)));
        }

        return Loc.GetString("lathe-menu-designs-subtitle", ("categories", Categories?.Count ?? 0));
    }

    private int GetCurrentRequestedAmount()
    {
        if (!int.TryParse(AmountLineEdit.Text, out var amount) || amount <= 0)
            return 1;

        return amount;
    }

    private string GetRecipeDisplayName(ProtoId<LatheRecipePrototype> recipe)
    {
        return _prototypeManager.TryIndex(recipe, out LatheRecipePrototype? prototype)
            ? _lathe.GetRecipeName(prototype)
            : recipe;
    }

    private static StyleBoxFlat CreateDividerStyle(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
        };
    }
