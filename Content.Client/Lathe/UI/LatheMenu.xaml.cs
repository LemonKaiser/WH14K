    /// <summary>
    /// Populates the list of all the recipes
    /// </summary>
    public void PopulateRecipes()
    {
        var recipesToShow = new List<LatheRecipePrototype>();
        var totalRecipes = 0;
        foreach (var recipe in Recipes)
        {
            if (!_prototypeManager.Resolve(recipe, out var proto))
                continue;

            totalRecipes++;

            if (CurrentCategory != null)
            {
                if (proto.Categories.Count <= 0)
                    continue;

                if (!proto.Categories.Any(category => category == CurrentCategory))
                    continue;
            }

            if (SearchBar.Text.Trim().Length != 0)
            {
                if (_lathe.GetRecipeName(recipe).ToLowerInvariant().Contains(SearchBar.Text.Trim().ToLowerInvariant()))
                    recipesToShow.Add(proto);
            }
            else
            {
                recipesToShow.Add(proto);
            }
        }

        _totalRecipeCount = totalRecipes;
        _visibleRecipeCount = recipesToShow.Count;

        if (!int.TryParse(AmountLineEdit.Text, out var quantity) || quantity <= 0)
            quantity = 1;

        RecipeCountValueLabel.Text = Loc.GetString("lathe-menu-recipe-count", ("count", recipesToShow.Count));

        var sortedRecipesToShow = recipesToShow.OrderBy(_lathe.GetRecipeName);

        var oldChildCount = RecipeList.ChildCount;
        _entityManager.TryGetComponent(Entity, out LatheComponent? lathe);

        var idx = 0;
        foreach (var prototype in sortedRecipesToShow)
        {
            var canProduce = _lathe.CanProduce(Entity, prototype, quantity, component: lathe);
            var tooltipFunction = () => GenerateTooltipText(prototype);
            var metaText = BuildRecipeMetaText(prototype);

            if (idx >= oldChildCount)
            {
                var control = new RecipeControl(_lathe, prototype, tooltipFunction, canProduce, GetRecipeDisplayControl(prototype), metaText, _theme);
                control.OnButtonPressed += s =>
                {
                    if (!int.TryParse(AmountLineEdit.Text, out var amount) || amount <= 0)
                        amount = 1;
                    RecipeQueueAction?.Invoke(s, amount);
                };
                control.OnInfiniteButtonPressed += s =>
                {
                    RecipeQueueInfiniteAction?.Invoke(s);
                };
                RecipeList.AddChild(control);
                WH40KUiChrome.PlayFadeIn(control, "appear", 0.18f, MathF.Min(idx * 0.018f, 0.22f));
            }
            else
            {
                var child = RecipeList.GetChild(idx) as RecipeControl;

                if (child == null)
                {
                    DebugTools.Assert($"Lathe menu recipe control at {idx} is not of type RecipeControl"); // Something's gone terribly wrong.
                    continue;
                }

                child.SetRecipe(prototype, metaText);
                child.SetTooltipSupplier(tooltipFunction);
                child.SetCanProduce(canProduce);
                child.SetDisplayControl(GetRecipeDisplayControl(prototype), prototype.ID);
            }
            idx++;
        }

        for (var childIdx = oldChildCount - 1; idx <= childIdx; childIdx--)
        {
            RecipeList.RemoveChild(childIdx);
        }

        RecipeEmptyLabel.Visible = _visibleRecipeCount == 0;
        DesignsHeaderSubtitleLabel.Text = BuildDesignSubtitleText();
        RefreshMachineReadouts();
    }

    private string GenerateTooltipText(LatheRecipePrototype prototype)
    {
        StringBuilder sb = new();
        var multiplier = _entityManager.GetComponent<LatheComponent>(Entity).MaterialUseMultiplier;

        foreach (var (id, amount) in prototype.Materials)
        {
            if (!_prototypeManager.Resolve(id, out var proto))
                continue;

            var adjustedAmount = SharedLatheSystem.AdjustMaterial(amount, prototype.ApplyMaterialDiscount, multiplier);
            var sheetVolume = _materialStorage.GetSheetVolume(proto);

            var unit = Loc.GetString(proto.Unit);
            var sheets = adjustedAmount / (float) sheetVolume;

            var availableAmount = _materialStorage.GetMaterialAmount(Entity, id);
            var missingAmount = Math.Max(0, adjustedAmount - availableAmount);
            var missingSheets = missingAmount / (float) sheetVolume;

            var name = Loc.GetString(proto.Name);

            string tooltipText;
            if (missingSheets > 0)
            {
                tooltipText = Loc.GetString("lathe-menu-material-amount-missing", ("amount", sheets), ("missingAmount", missingSheets), ("unit", unit), ("material", name));
            }
            else
            {
                var amountText = Loc.GetString("lathe-menu-material-amount", ("amount", sheets), ("unit", unit));
                tooltipText = Loc.GetString("lathe-menu-tooltip-display", ("material", name), ("amount", amountText));
            }

            sb.AppendLine(tooltipText);
        }

        var desc = _lathe.GetRecipeDescription(prototype);
        if (!string.IsNullOrWhiteSpace(desc))
            sb.AppendLine(Loc.GetString("lathe-menu-description-display", ("description", desc)));

        // Remove last newline
        if (sb.Length > 0)
            sb.Remove(sb.Length - 1, 1);

        return sb.ToString();
    }

    public void UpdateCategories()
    {
        var currentCategories = new List<ProtoId<LatheCategoryPrototype>>();
        foreach (var recipeId in Recipes)
        {
            if (!_prototypeManager.TryIndex(recipeId, out LatheRecipePrototype? recipe))
                continue;

            if (recipe.Categories.Count <= 0)
                continue;

            foreach (var category in recipe.Categories)
            {
                if (currentCategories.Contains(category))
                    continue;

                currentCategories.Add(category);
            }
        }

        var changed = Categories == null ||
                      Categories.Count != currentCategories.Count ||
                      !Categories.All(currentCategories.Contains);

        if (!changed)
        {
            DesignsHeaderSubtitleLabel.Text = BuildDesignSubtitleText();
            return;
        }

        Categories = currentCategories;
        var sortedCategories = currentCategories
            .Select(p => _prototypeManager.Index(p))
            .OrderBy(p => Loc.GetString(p.Name))
            .ToList();

        FilterOption.Clear();
        FilterOption.AddItem(Loc.GetString("lathe-menu-category-all"), -1);
        foreach (var category in sortedCategories)
        {
            FilterOption.AddItem(Loc.GetString(category.Name), Categories.IndexOf(category.ID));
        }

        if (CurrentCategory != null && Categories.Contains(CurrentCategory.Value))
            FilterOption.SelectId(Categories.IndexOf(CurrentCategory.Value));
        else
            FilterOption.SelectId(-1);

        DesignsHeaderSubtitleLabel.Text = BuildDesignSubtitleText();
    }

    /// <summary>
    /// Populates the build queue list with all queued items
    /// </summary>
    /// <param name="queue"></param>
    public void PopulateQueueList(IReadOnlyCollection<LatheRecipeBatch> queue)
    {
        var oldChildCount = QueueList.ChildCount;
        _queueBatchCount = queue.Count;
        _queueRequestedTotal = queue.Where(batch => !batch.Infinite).Sum(batch => Math.Max(1, batch.ItemsRequested));
        _queueInfiniteCount = queue.Count(batch => batch.Infinite);

        var idx = 0;
        foreach (var batch in queue)
        {
            var recipe = _prototypeManager.Index(batch.Recipe);

            var itemName = _lathe.GetRecipeName(batch.Recipe);
            string displayText;
            if (batch.Infinite)
                displayText = Loc.GetString("lathe-menu-queue-row-infinite",
                    ("name", itemName),
                    ("printed", batch.ItemsPrinted),
                    ("infinity", InfinitySymbol));
            else if (batch.ItemsRequested > 1)
                displayText = Loc.GetString("lathe-menu-queue-row-batch", ("name", itemName), ("printed", batch.ItemsPrinted), ("total", batch.ItemsRequested));
            else
                displayText = Loc.GetString("lathe-menu-queue-row-single", ("name", itemName));

            if (idx >= oldChildCount)
            {
                var queuedRecipeBox = new QueuedRecipeControl(displayText, idx, GetRecipeDisplayControl(recipe), recipe.ID, _theme);
                queuedRecipeBox.OnDeletePressed += s => QueueDeleteAction?.Invoke(s);
                queuedRecipeBox.OnMoveUpPressed += s => QueueMoveUpAction?.Invoke(s);
                queuedRecipeBox.OnMoveDownPressed += s => QueueMoveDownAction?.Invoke(s);
                QueueList.AddChild(queuedRecipeBox);
                WH40KUiChrome.PlayFadeIn(queuedRecipeBox, "appear", 0.18f, MathF.Min(idx * 0.018f, 0.22f));
            }
            else
            {
                var child = QueueList.GetChild(idx) as QueuedRecipeControl;

                if (child == null)
                {
                    DebugTools.Assert($"Lathe menu queued recipe control at {idx} is not of type QueuedRecipeControl"); // Something's gone terribly wrong.
                    continue;
                }

                child.SetDisplayText(displayText);
                child.SetIndex(idx);
                child.SetDisplayControl(GetRecipeDisplayControl(recipe), recipe.ID);
            }
            idx++;
        }

        for (var childIdx = oldChildCount - 1; idx <= childIdx; childIdx--)
        {
            QueueList.RemoveChild(childIdx);
        }

        QueueEmptyLabel.Visible = _queueBatchCount == 0;
        RefreshMachineReadouts();
    }

    public void SetQueueInfo(
        ProtoId<LatheRecipePrototype>? recipeProto,
        LatheRecipeBatch? activeBatch,
        IReadOnlyList<LatheRecipeBatch> queue,
        bool isProducing,
        TimeSpan productionStartTime,
        TimeSpan productionLength)
    {
        FabricatingContainer.Visible = recipeProto != null;
        if (recipeProto == null)
        {
            FabricatingProgressBar.Value = 0;
            FabricatingNameLabel.Text = string.Empty;
            _progressRecipe = null;
            _fabricatingDisplayRecipe = null;
            RefreshMachineReadouts();
            return;
        }

        var recipe = _prototypeManager.Index(recipeProto.Value);
        var isInfiniteBatch = activeBatch?.Infinite == true;
        var printed = activeBatch != null ? Math.Max(0, activeBatch.ItemsPrinted) : 0;
        var requested = activeBatch != null ? Math.Max(0, activeBatch.ItemsRequested) : 0;

        if (_progressRecipe != recipe.ID ||
            _progressPrinted != printed ||
            _progressStepStart != productionStartTime ||
            _progressStepDuration != productionLength)
        {
            var cycleChanged = _progressRecipe != recipe.ID || _progressPrinted != printed;
            var stepStart = isProducing ? productionStartTime : TimeSpan.Zero;
            if (isProducing && cycleChanged && _progressRecipe != null)
            {
                var oldestVisibleStart = _timing.CurTime - ProgressSyncClamp;
                if (stepStart < oldestVisibleStart)
                    stepStart = oldestVisibleStart;
            }

            _progressRecipe = recipe.ID;
            _progressPrinted = printed;
            _progressStepStart = stepStart;
            _progressStepDuration = isProducing ? productionLength : TimeSpan.Zero;
        }

        if (_fabricatingDisplayRecipe != recipe.ID || FabricatingDisplayContainer.ChildCount == 0)
        {
            _fabricatingDisplayRecipe = recipe.ID;
            FabricatingDisplayContainer.Children.Clear();
            FabricatingDisplayContainer.AddChild(GetRecipeDisplayControl(recipe));
        }

        var nameText = _lathe.GetRecipeName(recipe);
        if (isInfiniteBatch)
        {
            nameText = Loc.GetString("lathe-menu-item-progress-infinite",
                ("name", nameText),
                ("printed", printed),
                ("infinity", InfinitySymbol));
        }
        else if (activeBatch != null && requested > 1)
        {
            nameText = $"{nameText} ({printed}/{requested})";
        }

        FabricatingNameLabel.Text = nameText;
        UpdateFabricatingProgress();
        RefreshMachineReadouts();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

