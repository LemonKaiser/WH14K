using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.Lathe.UI;

[GenerateTypedNameReferences]
public sealed partial class RecipeTooltip : Control
{
    public RecipeTooltip(string title, string tooltip, WH40KLatheMenuTheme theme)
    {
        RobustXamlLoader.Load(this);

        CardPanel.PanelOverride = WH40KLatheMenuStyles.CreatePanelStyle(theme.PanelBackground, theme.BorderStrongColor, 0);
        HeaderPanel.PanelOverride = WH40KLatheMenuStyles.CreateEdgePanelStyle(
            theme.HeaderBackground,
            theme.Accent.WithAlpha(0.74f),
            new Thickness(0f, 0f, 0f, 1f),
            0);
        TitleLabel.Text = title;
        TitleLabel.FontColorOverride = theme.Accent;
        RecipeTooltipLabel.SetMarkup(tooltip);
        RecipeTooltipLabel.ModulateSelfOverride = theme.PrimaryText;
    }
}
