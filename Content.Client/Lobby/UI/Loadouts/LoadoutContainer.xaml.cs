using Content.Shared._WH40K.Weapons.Mods;
using Content.Shared.Clothing;
using Content.Shared.Preferences.Loadouts;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.Lobby.UI.Loadouts;

[GenerateTypedNameReferences]
public sealed partial class LoadoutContainer : BoxContainer
{
    [Dependency] private IEntityManager _entManager = default!;
    [Dependency] private IPrototypeManager _protoManager = default!;

    private readonly EntityUid? _entity;
    private readonly ProtoId<LoadoutPrototype> _protoId;

    public Button Select => SelectButton;

    public string? Text
    {
        get => SelectButton.Text;
        set => SelectButton.Text = value;
    }

    public LoadoutContainer(ProtoId<LoadoutPrototype> proto, bool disabled, FormattedMessage? reason)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _protoId = proto;

        SelectButton.Disabled = disabled;

        if (disabled && reason != null)
        {
            var tooltip = new Tooltip();
            tooltip.SetMessage(reason);
            SelectButton.TooltipSupplier = _ => tooltip;
        }

        if (_protoManager.Resolve(proto, out var loadProto))
        {
            var ent = loadProto.DummyEntity ?? _entManager.System<LoadoutSystem>().GetFirstOrNull(loadProto);

            if (ent == null)
                return;

            _entity = _entManager.SpawnEntity(ent, MapCoordinates.Nullspace);
            Sprite.SetEntity(_entity);

            var spriteTooltip = new Tooltip();
            spriteTooltip.SetMessage(FormattedMessage.FromUnformatted(_entManager.GetComponent<MetaDataComponent>(_entity.Value).EntityDescription));

            TooltipSupplier = _ => spriteTooltip;
        }
    }

    /// <summary>
    /// WH40K: applies the given mods (slot id -> mod proto id) to the dummy preview entity
    /// and rebuilds the overlay appearance so the sprite shows installed mods.
    /// No-op if the dummy has no weapon-mod host.
    /// </summary>
    public void ApplyModsToDummy(Dictionary<string, string> selectedMods)
    {
        if (_entity == null || selectedMods.Count == 0)
            return;

        var modSystem = _entManager.System<WH40KLoadoutModSystem>();
        modSystem.ApplyModsToEntity(_entity.Value, selectedMods);
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);
        if (!disposing)
            return;

        _entManager.DeleteEntity(_entity);
    }
}
