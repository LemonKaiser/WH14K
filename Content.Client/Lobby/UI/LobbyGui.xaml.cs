using Content.Client.Message;
using Content.Client.Localization;
using Content.Client.UserInterface.Systems.EscapeMenu;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Shared.Configuration;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen, ILocalizedControl
    {
        [Dependency] private readonly IClientConsoleHost _consoleHost = default!;
        [Dependency] private readonly IConfigurationManager _cfg = default!;
        [Dependency] private readonly IUriOpener _uriOpener = default!;

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();
            DiscordButton.OnPressed += OnDiscordButtonPressed;

            CollapseButton.OnPressed += _ => TogglePanel(false);
            ExpandButton.OnPressed += _ => TogglePanel(true);

            _cfg.OnValueChanged(CCVars.InfoLinksDiscord, OnDiscordLinkChanged, true);
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    RightSide.Visible = true;
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;

                    var actualWidth = (float) UserInterfaceManager.RootControl.PixelWidth;
                    var setupWidth = (float) LeftSide.PixelWidth;

                    if (1 - (setupWidth / actualWidth) > 0.30)
                    {
                        RightSide.Visible = false;
                    }

                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();

                    break;
            }
        }

        private void TogglePanel(bool value)
        {
            RightSide.Visible = value;
            ExpandPanel.Visible = !value;
        }

        public void ApplyPanelBackgroundOpacity(float opacity)
        {
            LobbyPanelOpacityHelper.ApplyPanelOpacity(LeftSideTop, opacity);
            LobbyPanelOpacityHelper.ApplyPanelOpacity(BottomInfoPanel, opacity);
            LobbyPanelOpacityHelper.ApplyPanelOpacity(RightSide, opacity);
            LobbyPanelOpacityHelper.ApplyPanelOpacity(ExpandPanel, opacity);
        }

        public void Relocalize()
        {
            AHelpButton.Text = Loc.GetString("ui-lobby-ahelp-button");
            DiscordButton.Text = Loc.GetString("server-info-discord-button");
            ServerInfoHeading.Text = Loc.GetString("ui-lobby-server-info-block");
        }

        [Obsolete]
        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                _cfg.UnsubValueChanged(CCVars.InfoLinksDiscord, OnDiscordLinkChanged);
            }

#pragma warning disable CS0618
            base.Dispose(disposing);
#pragma warning restore CS0618
        }

        private void OnDiscordButtonPressed(BaseButton.ButtonEventArgs args)
        {
            var url = _cfg.GetCVar(CCVars.InfoLinksDiscord);
            if (string.IsNullOrWhiteSpace(url))
                return;

            _uriOpener.OpenUri(url);
        }

        private void OnDiscordLinkChanged(string url)
        {
            DiscordButton.Visible = !string.IsNullOrWhiteSpace(url);
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
