using Content.Client.Localization;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control, ILocalizedControl
{
    [Dependency] private readonly IClientPreferencesManager _preferencesManager = default!;

    public Button CharacterSetupButton => CharacterSetup;

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
    }

    public void SetSummaryText(string value)
    {
        Summary.Text = value;
    }

    public void Relocalize()
    {
        Header.Text = Loc.GetString("lobby-character-preview-panel-header");
        CharacterSetup.Text = Loc.GetString("lobby-character-preview-panel-character-setup-button");
        Unloaded.Text = Loc.GetString("lobby-character-preview-panel-unloaded-preferences-label");

        Summary.Text = _preferencesManager.Preferences?.SelectedCharacter is HumanoidCharacterProfile humanoid
            ? humanoid.Summary
            : string.Empty;
    }
}
