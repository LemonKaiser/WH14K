using System;
using Content.Client.Localization;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control, ILocalizedControl
{
    [Dependency] private  IClientPreferencesManager _preferencesManager = default!;

    public Button CharacterSetupButton => CharacterSetup;
    public bool HasCharacters => CharacterCarousel.HasCharacters;
    public event Action<int>? CharacterSelected
    {
        add => CharacterCarousel.CharacterSelected += value;
        remove => CharacterCarousel.CharacterSelected -= value;
    }

    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;

        if (!value)
            CharacterCarousel.Clear();
    }

    public void SetSummaryText(string value)
    {
        Summary.Text = value;
    }

    public void SetCharacters(PlayerPreferences? preferences)
    {
        CharacterCarousel.SetCharacters(preferences);
    }

    public void SetSelectedSlot(int? slot)
    {
        CharacterCarousel.SetSelectedSlot(slot);
    }

    public void Relocalize()
    {
        Header.Text = Loc.GetString("lobby-character-preview-panel-header");
        CharacterSetup.Text = Loc.GetString("lobby-character-preview-panel-character-setup-button");
        Unloaded.Text = Loc.GetString("lobby-character-preview-panel-unloaded-preferences-label");

        Summary.Text = _preferencesManager.Preferences?.SelectedCharacter is HumanoidCharacterProfile humanoid
            ? humanoid.Summary
            : string.Empty;
    }
}
