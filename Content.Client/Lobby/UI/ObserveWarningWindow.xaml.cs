using Content.Shared.Administration.Managers;
using Content.Client.Localization;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
[UsedImplicitly]
public sealed partial class ObserveWarningWindow : DefaultWindow, ILocalizedControl
{
    [Dependency] private readonly ISharedAdminManager _adminManager = default!;
    [Dependency] private readonly IPlayerManager _playerManager = default!;

    public ObserveWarningWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        var player = _playerManager.LocalSession;

        if (player != null && _adminManager.IsAdmin(player))
        {
            ObserveButton.Text = Loc.GetString("observe-as-player");
            ObserveAsAdminButton.Visible = true;
            ObserveAsAdminButton.OnPressed += _ => { this.Close(); };
        }

        ObserveButton.OnPressed += _ => { this.Close(); };
        NevermindButton.OnPressed += _ => { this.Close(); };
        Relocalize();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("observe-warning-window-title");
        WarningLabel1.Text = Loc.GetString("observe-warning-1");
        WarningLabel2.Text = Loc.GetString("observe-warning-2");
        NevermindButton.Text = Loc.GetString("observe-nevermind");
        ObserveButton.Text = Loc.GetString("observe-as-player");

        var player = _playerManager.LocalSession;
        if (player != null && _adminManager.IsAdmin(player))
        {
            ObserveButton.Text = Loc.GetString("observe-as-player");
            ObserveAsAdminButton.Text = Loc.GetString("observe-as-admin");
        }
        else
        {
            ObserveButton.Text = Loc.GetString("observe-confirm");
        }
    }
}
