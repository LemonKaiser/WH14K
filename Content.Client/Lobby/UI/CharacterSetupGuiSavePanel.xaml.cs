using Content.Client.Localization;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterSetupGuiSavePanel : DefaultWindow, ILocalizedControl
{
    public CharacterSetupGuiSavePanel()
    {
        RobustXamlLoader.Load(this);

        CancelButton.OnPressed += _ =>
        {
            Close();
        };

        CloseButton.Visible = false;
        Relocalize();
    }

    public void Relocalize()
    {
        Title = Loc.GetString("character-setup-gui-save-panel-title");
        SaveButton.Text = Loc.GetString("character-setup-gui-save-panel-save");
        NoSaveButton.Text = Loc.GetString("character-setup-gui-save-panel-nosave");
        CancelButton.Text = Loc.GetString("character-setup-gui-save-panel-cancel");
    }
}
