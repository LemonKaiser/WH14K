using Content.Shared.Mech;
using Content.Shared.Mech.Module.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Mech.Ui.Equipment;

[GenerateTypedNameReferences]
public sealed partial class MechGeneratorUiFragment : BoxContainer
{
    public event Action? OnEject;

    public MechGeneratorUiFragment()
    {
        RobustXamlLoader.Load(this);
        EjectButton.OnPressed += _ => OnEject?.Invoke();
    }

    public void UpdateContents(MechGeneratorUiState state)
    {
        OutputLabel.Text = Loc.GetString("mech-generator-output-label",
            ("rate", $"{state.ChargeCurrent:F0}/{state.ChargeMax:F0}"));

        if (state.GenerationType == MechGenerationType.TeslaRelay)
        {
            FuelLabel.Visible = true;
            FuelLabel.Text = Loc.GetString("mech-generator-tesla-hint-label",
                ("status", Loc.GetString(state.TeslaPoweredNearby
                    ? "mech-generator-tesla-status-online"
                    : "mech-generator-tesla-status-offline")));
            EjectButton.Visible = false;
            return;
        }

        if (state.HasFuel)
        {
            FuelLabel.Visible = true;
            FuelLabel.Text = Loc.GetString("mech-generator-fuel-label",
                ("name", state.FuelName ?? ""),
                ("amount", $"{state.FuelAmount:F0}/{state.FuelCapacity:F0}"));
            EjectButton.Visible = true;
        }
        else
        {
            FuelLabel.Visible = false;
            EjectButton.Visible = false;
        }
    }
}
