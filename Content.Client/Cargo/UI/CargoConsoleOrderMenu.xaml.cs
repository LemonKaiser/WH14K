using System.Collections.Generic;
using System;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Client._WH40K.Interface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Localization;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client.Cargo.UI
{
    [GenerateTypedNameReferences]
    sealed partial class CargoConsoleOrderMenu : FancyWindow
    {
        private WH40KCargoConsoleTheme _theme = WH40KCargoConsoleTheme.Disabled;
        private bool _isClosingAnimated;

        public CargoConsoleOrderMenu()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            Amount.SetButtons(new List<int> { -3, -2, -1 }, new List<int> { 1, 2, 3 });
            Amount.IsValid = n => n > 0;
        }

        public void ApplyWh40KTheme(WH40KCargoConsoleTheme theme)
        {
            _theme = theme;
            Title = Loc.GetString(theme.OrderMenuTitleLocKey);
            MinSize = new Vector2(620f, 390f);
            SetSize = new Vector2(760f, 520f);

            if (GetChild(0) is PanelContainer windowBackdrop)
                windowBackdrop.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(theme.WindowBackground, theme.BorderStrongColor, 0);

            WindowHeader.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
                theme.HeaderBackground,
                theme.BorderStrongColor,
                new Thickness(0f, 0f, 0f, 1f),
                0);
            WindowTitle.FontColorOverride = theme.Accent;
            CloseButton.ModulateSelfOverride = theme.LabelText;

            HeaderPanel.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(theme.PanelAltBackground, theme.BorderStrongColor, 0);
            OrderInfoPanel.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(theme.SurfaceBackground, theme.BorderColor, 0);
            SubmitPanel.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(
                theme.PanelAltBackground,
                theme.BorderStrongColor,
                10);
            FooterDivider.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(theme.Accent.WithAlpha(0.28f), theme.BorderColor, new Thickness(0), 0);

            HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(
                WH40KUiChrome.DiamondNested,
                Loc.GetString(theme.IsHeretics
                    ? "wh40k-cargo-console-order-header-title-heretics"
                    : "wh40k-cargo-console-order-header-title-imperium"));
            HeaderTitleLabel.FontColorOverride = theme.PrimaryText;
            HeaderSubtitleLabel.SetMessage(
                Loc.GetString(theme.IsHeretics
                    ? "wh40k-cargo-console-order-header-subtitle-heretics"
                    : "wh40k-cargo-console-order-header-subtitle-imperium"),
                defaultColor: theme.SecondaryText);

            ProductLabel.FontColorOverride = theme.LabelText;
            DescriptionLabel.FontColorOverride = theme.LabelText;
            CostLabel.FontColorOverride = theme.LabelText;
            RequesterLabel.FontColorOverride = theme.LabelText;
            AmountLabel.FontColorOverride = theme.LabelText;
            ProductName.FontColorOverride = theme.PrimaryText;
            PointCost.FontColorOverride = theme.Accent;
            Requester.StyleBoxOverride = WH40KCargoConsoleStyles.CreateInputStyle(theme);
            Amount.LineEditControl.StyleBoxOverride = WH40KCargoConsoleStyles.CreateInputStyle(theme);

            foreach (var child in Amount.Children)
            {
                if (child is Button spinButton)
                    WH40KCargoConsoleStyles.ApplyButtonTheme(spinButton, WH40KCargoConsoleStyles.CreateSecondaryButtonStyle(theme), theme.PrimaryText);
            }

            WH40KCargoConsoleStyles.ApplyButtonTheme(SubmitButton, WH40KCargoConsoleStyles.CreatePrimaryButtonStyle(theme), theme.PrimaryText);

            ProductLabel.Text = WH40KUiChrome.DecorateIfMissing(ProductLabel.Text, WH40KUiChrome.Diamond);
            DescriptionLabel.Text = WH40KUiChrome.DecorateIfMissing(DescriptionLabel.Text, WH40KUiChrome.Arrow);
            CostLabel.Text = WH40KUiChrome.DecorateIfMissing(CostLabel.Text, WH40KUiChrome.Cog);
            RequesterLabel.Text = WH40KUiChrome.DecorateIfMissing(RequesterLabel.Text, WH40KUiChrome.DiamondOutline);
            AmountLabel.Text = WH40KUiChrome.DecorateIfMissing(AmountLabel.Text, WH40KUiChrome.Blade);

            SubmitButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(SubmitPanel, "submit-flash", theme.Accent.WithAlpha(0.82f), 0.18f);
            CloseButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(WindowHeader, "close-flash", theme.BorderStrongColor.WithAlpha(0.86f), 0.18f);
            WH40KUiChrome.StartLoopingPulse(HeaderTitleLabel, "title-pulse", theme.Accent.WithAlpha(0.82f), Color.White, 3.4f);
            WH40KUiChrome.StartLoopingPulse(FooterDivider, "footer-pulse", theme.Accent.WithAlpha(0.35f), Color.White, 4.1f);
        }

        protected override void Opened()
        {
            base.Opened();
            _isClosingAnimated = false;

            if (!_theme.Enabled)
                return;

            WindowHeader.Modulate = new Color(1f, 1f, 1f, 0f);
            WindowTitle.Modulate = new Color(1f, 1f, 1f, 0f);
            HeaderPanel.Modulate = new Color(1f, 1f, 1f, 0f);
            FooterDivider.Modulate = new Color(1f, 1f, 1f, 0f);

            WH40KUiChrome.PlayFadeIn(WindowHeader, "window-header-appear", 0.14f);
            WH40KUiChrome.PlayFadeIn(WindowTitle, "window-title-appear", 0.14f, 0.02f);
            WH40KUiChrome.PlayFadeIn(HeaderPanel, "header-appear", 0.16f, 0.03f);
            WH40KUiChrome.PlayFadeIn(FooterDivider, "footer-appear", 0.18f, 0.11f);
        }

        public override void Close()
        {
            if (!_theme.Enabled || !IsOpen)
            {
                base.Close();
                return;
            }

            if (_isClosingAnimated)
                return;

            _isClosingAnimated = true;
            var closeAccent = _theme.BorderStrongColor.WithAlpha(0.9f);
            var closeHighlight = _theme.Accent.WithAlpha(0.56f);
            WH40KUiChrome.PlayFadeOut(FooterDivider, "footer-close", closeHighlight.WithAlpha(0.72f), 0.14f, 0.02f);
            WH40KUiChrome.PlayFadeOut(HeaderPanel, "header-close", closeAccent, 0.12f, 0.04f);
            WH40KUiChrome.PlayFadeOut(WindowTitle, "window-title-close", closeHighlight, 0.1f, 0.04f);
            WH40KUiChrome.PlayFadeOut(WindowHeader, "window-header-close", closeAccent, 0.12f, 0.02f);

            Timer.Spawn(TimeSpan.FromSeconds(0.24f), () =>
            {
                _isClosingAnimated = false;
                if (IsOpen)
                    base.Close();
            });
        }
    }
}
