using System;
using Content.Shared.Cargo;
using Content.Client._WH40K.Interface;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client.Cargo.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class CargoOrderRow : PanelContainer
    {
        public CargoOrderData? Order { get; set; }

        public CargoOrderRow()
        {
            RobustXamlLoader.Load(this);
        }

        public void SetApproveVisible(bool visible)
        {
            Approve.Visible = visible;
        }

        public void SetActionButtonsVisible(bool approveVisible, bool cancelVisible)
        {
            SetApproveVisible(approveVisible);
            Cancel.Visible = cancelVisible;
            Actions.Visible = approveVisible || cancelVisible;
        }

        public void SetRemoveRequestVisible(bool visible)
        {
            RemoveRequestButton.Visible = visible;
        }

        public void ApplyWh40KTheme(WH40KCargoConsoleTheme theme)
        {
            CardPanel.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(theme.SurfaceBackground, theme.BorderColor, 0);
            HeaderPanel.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
                theme.HeaderBackground,
                theme.BorderStrongColor,
                new Thickness(0f, 0f, 0f, 1f),
                0);
            IconPanel.PanelOverride = WH40KCargoConsoleStyles.CreateBadgeStyle(theme.PreviewBackground, theme.BorderColor, 4, 4);
            Actions.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
                theme.PanelAltBackground,
                theme.BorderColor,
                new Thickness(0f, 1f, 0f, 0f),
                0);
            Stride.PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = theme.BorderStrongColor,
                ContentMarginBottomOverride = 2f,
            };

            Title.FontColorOverride = theme.Accent;
            Title.Text = WH40KUiChrome.DecorateIfMissing(Title.Text, WH40KUiChrome.Diamond);
            MainTextColor(theme);
            WH40KCargoConsoleStyles.ApplyButtonTheme(Approve, WH40KCargoConsoleStyles.CreatePrimaryButtonStyle(theme), theme.PrimaryText);
            WH40KCargoConsoleStyles.ApplyButtonTheme(Cancel, WH40KCargoConsoleStyles.CreateDangerButtonStyle(theme), theme.PrimaryText);
            WH40KCargoConsoleStyles.ApplyButtonTheme(RemoveRequestButton, WH40KCargoConsoleStyles.CreateDangerButtonStyle(theme), theme.PrimaryText);
        }

        public void AnimateAppear(float delay)
        {
            WH40KUiChrome.PlayFadeIn(this, "appear", 0.22f, delay);
        }

        public void AnimateRemoval(Color accent, float delay = 0f, Action? onComplete = null)
        {
            WH40KUiChrome.PlayFadeOut(this, "remove", accent, 0.2f, delay);
            Timer.Spawn(TimeSpan.FromSeconds(delay + 0.22f), () => onComplete?.Invoke());
        }

        public void PlayAttentionFlash(Color accent)
        {
            WH40KUiChrome.PlayHoverFlash(HeaderPanel, "header-flash", accent.WithAlpha(0.84f), 0.16f);
            WH40KUiChrome.PlayHoverFlash(CardPanel, "card-flash", accent.WithAlpha(0.48f), 0.2f);
        }

        private void MainTextColor(WH40KCargoConsoleTheme theme)
        {
            if (!string.IsNullOrWhiteSpace(ProductName.Text))
                ProductName.SetMessage(ProductName.Text!, defaultColor: theme.PrimaryText);

            if (!string.IsNullOrWhiteSpace(Description.Text))
                Description.SetMessage(Description.Text!, defaultColor: theme.SecondaryText);
        }
    }
}
