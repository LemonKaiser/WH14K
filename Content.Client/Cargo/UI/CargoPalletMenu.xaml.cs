using Content.Client.UserInterface.Controls;
using Content.Client._WH40K.Interface;
using Content.Shared.Cargo;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.Cargo.UI;

[GenerateTypedNameReferences]
public sealed partial class CargoPalletMenu : FancyWindow
{
    public Action? SellRequested;
    public Action? AppraiseRequested;

    private WH40KCargoConsoleTheme _theme = WH40KCargoConsoleTheme.Disabled;
    private int _appraisal;
    private int _saleValue;
    private int _count;
    private bool _enabled;
    private string _titleLocKey = "cargo-pallet-console-menu-title";
    private string _subtitleLocKey = "cargo-pallet-menu-subtitle";
    private string _detailsLocKey = "cargo-pallet-menu-details-header";
    private string _routingLocKey = "cargo-pallet-menu-routing-default";
    private string _acceptedGoodsLocKey = "cargo-pallet-menu-accepted-default";
    private string _footerLocKey = "cargo-pallet-menu-footer-status";
    private string _footerRightLocKey = "cargo-pallet-menu-footer-right";
    private string? _prototypeId;
    private int _salePayoutPercent = 50;

    public CargoPalletMenu()
    {
        RobustXamlLoader.Load(this);
        SellButton.OnPressed += OnSellPressed;
        AppraiseButton.OnPressed += OnAppraisePressed;
        ApplyVisualTheme();
        UpdateMetrics();
    }

    public void ApplyThemeFromPrototype(string? prototypeId)
    {
        _prototypeId = prototypeId;

        switch (prototypeId)
        {
            case "StructureLogisticsConsoleImperiumSell":
                _theme = WH40KCargoConsoleStyles.ResolveTheme("WH40KImperium");
                _titleLocKey = "wh40k-cargo-pallet-title-imperium";
                _subtitleLocKey = "wh40k-cargo-pallet-subtitle-imperium";
                _detailsLocKey = "cargo-pallet-menu-details-header";
                _routingLocKey = "wh40k-cargo-pallet-route-imperium";
                _acceptedGoodsLocKey = "wh40k-cargo-pallet-accepted-imperium";
                _footerLocKey = "wh40k-cargo-pallet-footer-left-imperium";
                _footerRightLocKey = "wh40k-cargo-console-footer-right";
                break;

            case "StructureLogisticsConsoleHereticsSell":
                _theme = WH40KCargoConsoleStyles.ResolveTheme("WH40KHeretics");
                _titleLocKey = "wh40k-cargo-pallet-title-heretics";
                _subtitleLocKey = "wh40k-cargo-pallet-subtitle-heretics";
                _detailsLocKey = "cargo-pallet-menu-details-header";
                _routingLocKey = "wh40k-cargo-pallet-route-heretics";
                _acceptedGoodsLocKey = "wh40k-cargo-pallet-accepted-heretics";
                _footerLocKey = "wh40k-cargo-pallet-footer-left-heretics";
                _footerRightLocKey = "wh40k-cargo-console-footer-right";
                break;

            default:
                _theme = WH40KCargoConsoleTheme.Disabled;
                _titleLocKey = "cargo-pallet-console-menu-title";
                _subtitleLocKey = "cargo-pallet-menu-subtitle";
                _detailsLocKey = "cargo-pallet-menu-details-header";
                _routingLocKey = "cargo-pallet-menu-routing-default";
                _acceptedGoodsLocKey = "cargo-pallet-menu-accepted-default";
                _footerLocKey = "cargo-pallet-menu-footer-status";
                _footerRightLocKey = "cargo-pallet-menu-footer-right";
                break;
        }

        ApplyVisualTheme();
        UpdateMetrics();
    }

    public void ApplyRuntimeSaleRules(int salePayoutPercent)
    {
        salePayoutPercent = Math.Clamp(salePayoutPercent, 0, 100);
        if (_salePayoutPercent == salePayoutPercent)
        {
            return;
        }

        _salePayoutPercent = salePayoutPercent;
        ApplyThemeFromPrototype(_prototypeId);
    }

    public void SetValuation(int appraisal, int saleValue)
    {
        _appraisal = appraisal;
        _saleValue = saleValue;
        UpdateMetrics();
    }

    public void SetCount(int count)
    {
        _count = count;
        UpdateMetrics();
    }

    public void SetEnabled(bool enabled)
    {
        _enabled = enabled;
        AppraiseButton.Disabled = !enabled;
        SellButton.Disabled = !enabled || _count <= 0;
        UpdateMetrics();
    }

    private void ApplyVisualTheme()
    {
        var saleTaxPercent = Math.Clamp(100 - _salePayoutPercent, 0, 100);

        Title = Loc.GetString(_titleLocKey);
        HeaderTitle.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.DiamondNested, Title);
        HeaderSubtitle.SetMessage(Loc.GetString(_subtitleLocKey, ("tax", saleTaxPercent), ("payout", _salePayoutPercent)), defaultColor: _theme.SecondaryText);
        DetailsHeaderTitle.Text = WH40KUiChrome.DecorateIfMissing(Loc.GetString(_detailsLocKey), WH40KUiChrome.Diamond);
        RoutingValueLabel.SetMessage(Loc.GetString(_routingLocKey), defaultColor: _theme.PrimaryText);
        AcceptedGoodsValueLabel.SetMessage(Loc.GetString(_acceptedGoodsLocKey, ("tax", saleTaxPercent), ("payout", _salePayoutPercent)), defaultColor: _theme.PrimaryText);
        FooterLeftLabel.Text = Loc.GetString(_footerLocKey);
        FooterRightLabel.Text = Loc.GetString(_footerRightLocKey);
        AppraisalKeyLabel.Text = WH40KUiChrome.DecorateIfMissing(Loc.GetString("cargo-pallet-menu-appraisal-label"), WH40KUiChrome.Diamond);
        CountKeyLabel.Text = WH40KUiChrome.DecorateIfMissing(Loc.GetString("cargo-pallet-menu-count-label"), WH40KUiChrome.Diamond);
        AverageKeyLabel.Text = WH40KUiChrome.DecorateIfMissing(
            Loc.GetString("cargo-pallet-menu-total-label", ("tax", saleTaxPercent)),
            WH40KUiChrome.DiamondOutline);
        StatusLabel.Text = WH40KUiChrome.DecorateIfMissing(StatusLabel.Text, WH40KUiChrome.DiamondNested);
        RoutingLabel.Text = WH40KUiChrome.DecorateIfMissing(RoutingLabel.Text, WH40KUiChrome.Arrow);
        AcceptedGoodsLabel.Text = WH40KUiChrome.DecorateIfMissing(AcceptedGoodsLabel.Text, WH40KUiChrome.Cog);

        MainFrame.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.WindowBackground, _theme.BorderStrongColor, 0);
        HeaderPanel.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        AppraisalCard.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        CountCard.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        AverageCard.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        DetailsFrame.PanelOverride = WH40KCargoConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        DetailsHeaderPanel.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
        DetailsBodyPanel.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);
        ButtonsFrame.PanelOverride = WH40KCargoConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelAltBackground,
            _theme.BorderColor,
            new Thickness(0f, 1f, 0f, 0f),
            0);

        FooterDivider.MinSize = new(0f, 1f);
        FooterDivider.PanelOverride = CreateDividerStyle(_theme.BorderStrongColor);
        StatusDivider.MinSize = new(1f, 0f);
        RoutingDivider.MinSize = new(1f, 0f);
        AcceptedDivider.MinSize = new(1f, 0f);
        StatusDivider.PanelOverride = CreateDividerStyle(_theme.BorderColor);
        RoutingDivider.PanelOverride = CreateDividerStyle(_theme.BorderColor);
        AcceptedDivider.PanelOverride = CreateDividerStyle(_theme.BorderColor);

        HeaderTitle.FontColorOverride = _theme.Accent;
        AppraisalKeyLabel.FontColorOverride = _theme.LabelText;
        CountKeyLabel.FontColorOverride = _theme.LabelText;
        AverageKeyLabel.FontColorOverride = _theme.LabelText;
        StatusLabel.FontColorOverride = _theme.LabelText;
        RoutingLabel.FontColorOverride = _theme.LabelText;
        AcceptedGoodsLabel.FontColorOverride = _theme.LabelText;
        DetailsHeaderTitle.FontColorOverride = _theme.Accent;
        AppraisalLabel.FontColorOverride = _theme.Accent;
        CountLabel.FontColorOverride = _theme.PrimaryText;
        AverageValueLabel.FontColorOverride = _theme.PrimaryText;
        FooterLeftLabel.FontColorOverride = _theme.SecondaryText;
        FooterRightLabel.FontColorOverride = _theme.LabelText;
        FooterLogo.Visible = false;

        var sharedButtonStyle = WH40KCargoConsoleStyles.CreatePrimaryButtonStyle(_theme);
        WH40KCargoConsoleStyles.ApplyButtonTheme(AppraiseButton, sharedButtonStyle, _theme.PrimaryText);
        WH40KCargoConsoleStyles.ApplyButtonTheme(SellButton, WH40KCargoConsoleStyles.CreatePrimaryButtonStyle(_theme), _theme.PrimaryText);
        WH40KUiChrome.StartLoopingPulse(HeaderTitle, "title-pulse", new Color(0.8f, 0.8f, 0.8f, 1f), Color.White, 3.2f);
        WH40KUiChrome.StartLoopingPulse(FooterDivider, "footer-pulse", new Color(0.55f, 0.55f, 0.55f, 1f), Color.White, 4.2f);
        WH40KUiChrome.StartLoopingPulse(DetailsHeaderTitle, "details-pulse", _theme.Accent.WithAlpha(0.78f), Color.White, 4f);
    }

    private void UpdateMetrics()
    {
        AppraisalLabel.Text = FormatDisplayCurrency(_appraisal);
        CountLabel.Text = _count.ToString();
        AverageValueLabel.Text = FormatDisplayCurrency(_saleValue);

        string statusLocKey;
        Color statusColor;

        if (!_enabled)
        {
            statusLocKey = "cargo-pallet-menu-status-offline";
            statusColor = _theme.DangerAccent;
        }
        else if (_count <= 0)
        {
            statusLocKey = "cargo-pallet-menu-status-empty";
            statusColor = _theme.SecondaryText;
        }
        else
        {
            statusLocKey = "cargo-pallet-menu-status-ready";
            statusColor = _theme.Accent;
        }

        StatusValueLabel.Text = Loc.GetString(statusLocKey);
        StatusValueLabel.FontColorOverride = statusColor;
        SellButton.Disabled = !_enabled || _count <= 0;
    }

    private void OnSellPressed(BaseButton.ButtonEventArgs obj)
    {
        SellRequested?.Invoke();
    }

    private void OnAppraisePressed(BaseButton.ButtonEventArgs obj)
    {
        AppraiseRequested?.Invoke();
    }

    private static StyleBoxFlat CreateDividerStyle(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
        };
    }

    private static string FormatDisplayCurrency(int amount)
    {
        return $"\u20AE{amount}";
    }
}
