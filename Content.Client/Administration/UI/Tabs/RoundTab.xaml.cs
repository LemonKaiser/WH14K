using Content.Client.Localization;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.Tabs
{
    [GenerateTypedNameReferences]
    public sealed partial class RoundTab : Control, ILocalizedControl
    {
        [Dependency] private IClientConsoleHost _console = default!;

        public RoundTab()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            StartRound.OnPressed += _ => _console.ExecuteCommand("startround");
            EndRound.OnPressed += _ => _console.ExecuteCommand("endround");
            RestartRound.OnPressed += _ => _console.ExecuteCommand("restartround");
            RestartRoundNow.OnPressed += _ => _console.ExecuteCommand("restartroundnow");

            Relocalize();
        }

        public void Relocalize()
        {
            StartRound.Text = Loc.GetString("administration-ui-round-tab-start-round");
            EndRound.Text = Loc.GetString("administration-ui-round-tab-end-round");
            RestartRound.Text = Loc.GetString("administration-ui-round-tab-restart-round");
            RestartRoundNow.Text = Loc.GetString("administration-ui-round-tab-restart-round-now");
        }
    }
}
