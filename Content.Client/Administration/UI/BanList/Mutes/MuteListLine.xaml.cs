using Content.Shared._WH40K.Administration.Mute;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.BanList.Mutes;

[GenerateTypedNameReferences]
public sealed partial class MuteListLine : BoxContainer
{
    public MuteListLine(WH40KSharedMute mute)
    {
        RobustXamlLoader.Load(this);

        Id.Text = mute.Id.ToString();
        Type.Text = Loc.GetString(mute.Type == WH40KMuteType.Chat
            ? "wh40k-mute-scope-chat"
            : "wh40k-mute-scope-ahelp");
        Reason.Text = mute.Reason;
        MuteTime.Text = BanListEui.FormatDate(mute.MuteTime);
        Expires.Text = mute.ExpirationTime == null
            ? Loc.GetString("ban-list-permanent")
            : BanListEui.FormatDate(mute.ExpirationTime.Value);

        if (mute.Unmute is { } unmute)
        {
            var unmuted = Loc.GetString("wh40k-mute-list-unmuted", ("date", BanListEui.FormatDate(unmute.UnbanTime)));
            var unmutedBy = unmute.UnbanningAdmin == null
                ? string.Empty
                : $"\n{Loc.GetString("wh40k-mute-list-unmuted-by", ("unmuter", unmute.UnbanningAdmin))}";

            Expires.Text += $"\n{unmuted}{unmutedBy}";
        }

        MutingAdmin.Text = mute.MutingAdminName;
    }
}
