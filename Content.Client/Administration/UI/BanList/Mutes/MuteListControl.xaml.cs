using Content.Client.Administration.UI.CustomControls;
using Content.Shared._WH40K.Administration.Mute;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Administration.UI.BanList.Mutes;

[GenerateTypedNameReferences]
public sealed partial class MuteListControl : Control
{
    public MuteListControl()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetMutes(List<WH40KSharedMute> mutes)
    {
        for (var i = Mutes.ChildCount - 1; i >= 1; i--)
        {
            Mutes.GetChild(i).Dispose();
        }

        foreach (var mute in mutes)
        {
            Mutes.AddChild(new HSeparator());
            Mutes.AddChild(new MuteListLine(mute));
        }
    }
}
