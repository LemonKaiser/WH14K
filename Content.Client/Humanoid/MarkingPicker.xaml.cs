using System;
using System.Linq;
using Content.Client.Lobby.UI;
using Robust.Client.Graphics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;

namespace Content.Client.Humanoid;

[GenerateTypedNameReferences]
public sealed partial class MarkingPicker : Control
{
    [Dependency] private readonly ILocalizationManager _loc = default!;
    private MarkingsViewModel? _markingsModel;
    private float _panelOpacity = 1f;

    public MarkingPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        UpdateMarkings();
    }

    public void SetModel(MarkingsViewModel model)
    {
        _markingsModel = model;

        _markingsModel.OrganDataChanged += UpdateMarkings;
        _markingsModel.EnforcementsChanged += UpdateMarkings;
    }

    public void SetPanelOpacity(float opacity)
    {
        _panelOpacity = Math.Clamp(opacity, 0f, 1f);
        ApplyPanelOpacity(this);
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _markingsModel?.OrganDataChanged += UpdateMarkings;
        _markingsModel?.EnforcementsChanged += UpdateMarkings;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _markingsModel?.OrganDataChanged -= UpdateMarkings;
        _markingsModel?.EnforcementsChanged -= UpdateMarkings;
    }

    private void UpdateMarkings()
    {
        if (_markingsModel is null)
            return;

        OrganTabs.RemoveAllChildren();

        var i = 0;
        foreach (var (organ, organData) in _markingsModel.OrganData)
        {
            var control = new OrganMarkingPicker(_markingsModel, organ, organData.Layers, organData.Group);
            if (control.Empty)
                continue;

            OrganTabs.AddChild(control);
            if (_loc.TryGetString($"markings-organ-{organ.Id}", out var organTitle))
                OrganTabs.SetTabTitle(i, organTitle);
            else
                OrganTabs.SetTabTitle(i, organ.Id);
            i++;
        }

        if (i > 0)
            OrganTabs.CurrentTab = 0;
        OrganTabs.TabsVisible = i > 1;

        ApplyPanelOpacity(this);
    }

    private void ApplyPanelOpacity(Control control)
    {
        if (control is TabContainer tabContainer)
        {
            StyleBox? source = tabContainer.PanelStyleBoxOverride;
            if (source == null
                && tabContainer.TryGetStyleProperty<StyleBox>(TabContainer.StylePropertyPanelStyleBox, out var styleProperty))
            {
                source = styleProperty;
            }

            tabContainer.PanelStyleBoxOverride = LobbyPanelOpacityHelper.CreateOpacityStyle(source, _panelOpacity);
        }

        foreach (var child in control.Children)
        {
            ApplyPanelOpacity(child);
        }
    }
}
