using System;
using System.Collections.Generic;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Client._WH40K.Interface;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class ResearchClientServerSelectionMenu : FancyWindow
{
    [Dependency] private readonly IEntityManager _entity = default!;

    private readonly Dictionary<int, ResearchServerEntryControl> _serverEntries = new();

    private WH40KResearchConsoleTheme _theme = WH40KResearchConsoleTheme.Disabled;
    private int _serverCount;
    private string[] _serverNames = Array.Empty<string>();
    private int[] _serverIds = Array.Empty<int>();
    private int _selectedServerId = -1;
    private string? _lastStateKey;

    public event Action<int>? OnServerSelected;
    public event Action? OnServerDeselected;

    public ResearchClientServerSelectionMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ApplyTheme();
    }

    public void SetEntity(EntityUid entity)
    {
        var prototypeId = _entity.GetComponent<MetaDataComponent>(entity).EntityPrototype?.ID;
        _theme = WH40KResearchConsoleStyles.ResolveTheme(prototypeId);
        _lastStateKey = null;

        ApplyTheme();
        RebuildServerCards();
        UpdateSummary();
    }

    public void Populate(int serverCount, string[] serverNames, int[] serverIds, int selectedServerId)
    {
        _serverCount = serverCount;
        _serverNames = serverNames;
        _serverIds = serverIds;
        _selectedServerId = selectedServerId;

        var stateKey = BuildStateKey();
        if (_lastStateKey != stateKey)
        {
            RebuildServerCards();
            _lastStateKey = stateKey;
        }
        else
        {
            ApplySelectionState();
        }

        UpdateSummary();
    }

    private void ApplyTheme()
    {
        Title = Loc.GetString("research-client-server-selection-menu-title");
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Cog, Title);
        HeaderSubtitleLabel.SetMessage(Loc.GetString(GetSubtitleLocKey()), defaultColor: _theme.SecondaryText);

        SelectedServerCardLabel.Text = WH40KUiChrome.DecorateTitle(
            WH40KUiChrome.Eye,
            Loc.GetString("research-client-server-selection-menu-selected-label"));
        ServerCountCardLabel.Text = WH40KUiChrome.DecorateTitle(
            WH40KUiChrome.Diamond,
            Loc.GetString("research-client-server-selection-menu-count-label"));
        ServerListHeaderLabel.Text = WH40KUiChrome.DecorateTitle(
            WH40KUiChrome.DiamondNested,
            Loc.GetString("research-client-server-selection-menu-list-label"));

        MinSize = new Vector2(420f, 360f);
        SetSize = new Vector2(470f, 440f);

        MainFrame.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.WindowBackground, _theme.BorderStrongColor, 0);
        HeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        SelectedServerCard.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        ServerCountCard.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        ServerListPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        ServerListHeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
        ServerListBodyPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        FooterDivider.MinSize = new Vector2(0f, 1f);
        FooterDivider.PanelOverride = CreateDividerStyle(_theme.BorderStrongColor);

        HeaderTitleLabel.FontColorOverride = _theme.Accent;
        SelectedServerCardLabel.FontColorOverride = _theme.LabelText;
        ServerCountCardLabel.FontColorOverride = _theme.LabelText;
        ServerListHeaderLabel.FontColorOverride = _theme.Accent;
        ServerListCountLabel.FontColorOverride = _theme.SecondaryText;
        ServerCountValueLabel.FontColorOverride = _theme.Accent;
        NoServersLabel.FontColorOverride = _theme.SecondaryText;
        FooterLeftLabel.FontColorOverride = _theme.SecondaryText;
        FooterRightLabel.FontColorOverride = _theme.LabelText;

        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());
        FooterRightLabel.ToolTip = Loc.GetString(GetFooterRightLocKey());
        FooterLeftLabel.ToolTip = Loc.GetString(GetSubtitleLocKey());

        WH40KUiChrome.StartLoopingPulse(HeaderTitleLabel, "title-pulse", new Color(0.8f, 0.8f, 0.8f, 1f), Color.White, 3.1f);
        WH40KUiChrome.StartLoopingPulse(FooterDivider, "footer-pulse", new Color(0.55f, 0.55f, 0.55f, 1f), Color.White, 4.1f);
    }

    private void RebuildServerCards()
    {
        ServerCardsContainer.Children.Clear();
        _serverEntries.Clear();

        NoServersLabel.Visible = _serverCount == 0;
        ServerListScroll.Visible = _serverCount > 0;

        for (var i = 0; i < _serverCount; i++)
        {
            var id = _serverIds[i];
            var serverName = _serverNames[i];
            var entry = new ResearchServerEntryControl(id, serverName, id == _selectedServerId, _theme);
            entry.OnPressed += OnEntryPressed;
            _serverEntries[id] = entry;
            ServerCardsContainer.AddChild(entry);
        }
    }

    private void OnEntryPressed(int serverId)
    {
        if (serverId == _selectedServerId)
        {
            ApplyLocalSelection(-1);
            OnServerDeselected?.Invoke();
            return;
        }

        ApplyLocalSelection(serverId);
        OnServerSelected?.Invoke(serverId);
    }

    private void ApplyLocalSelection(int serverId)
    {
        _selectedServerId = serverId;
        _lastStateKey = BuildStateKey();
        ApplySelectionState();
        UpdateSummary();
    }

    private void ApplySelectionState()
    {
        foreach (var (serverId, entry) in _serverEntries)
        {
            entry.ApplySelection(serverId == _selectedServerId);
        }
    }

    private void UpdateSummary()
    {
        var selectedName = GetSelectedServerName();
        SelectedServerValueLabel.Text = selectedName ?? Loc.GetString("research-client-server-selection-menu-none");
        SelectedServerValueLabel.ToolTip = selectedName;
        SelectedServerValueLabel.FontColorOverride = selectedName == null
            ? _theme.SecondaryText
            : _theme.Accent;

        ServerCountValueLabel.Text = _serverCount.ToString();
        ServerListCountLabel.Text = Loc.GetString("research-client-server-selection-menu-list-count", ("count", _serverCount));
        FooterLeftLabel.Text = Loc.GetString(GetFooterStatusLocKey());
        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());
    }

    private string? GetSelectedServerName()
    {
        var index = Array.IndexOf(_serverIds, _selectedServerId);
        return index >= 0 && index < _serverNames.Length
            ? _serverNames[index]
            : null;
    }

    private string BuildStateKey()
    {
        var ids = string.Join(",", _serverIds);
        var names = string.Join(",", _serverNames);

        return $"count={_serverCount}|selected={_selectedServerId}|ids={ids}|names={names}";
    }

    private string GetSubtitleLocKey()
    {
        return _theme.TeamId switch
        {
            "Imperium" => "research-client-server-selection-menu-subtitle-imperium",
            "Heretics" => "research-client-server-selection-menu-subtitle-heretics",
            _ => "research-client-server-selection-menu-subtitle",
        };
    }

    private string GetFooterRightLocKey()
    {
        return _theme.TeamId switch
        {
            "Imperium" => "wh40k-research-console-footer-right-imperium",
            "Heretics" => "wh40k-research-console-footer-right-heretics",
            _ => "research-console-footer-right-panel",
        };
    }

    private string GetFooterStatusLocKey()
    {
        if (_serverCount == 0)
            return "research-client-server-selection-menu-footer-empty";

        return _selectedServerId == -1
            ? "research-client-server-selection-menu-footer-ready"
            : "research-client-server-selection-menu-footer-linked";
    }

    private static StyleBoxFlat CreateDividerStyle(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
        };
    }
}
