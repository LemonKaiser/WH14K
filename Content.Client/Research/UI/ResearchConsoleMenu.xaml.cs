        MinSize = new Vector2(880f, 620f);
        SetSize = new Vector2(1040f, 760f);

        MainFrame.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.WindowBackground, _theme.BorderStrongColor, 0);
        HeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
