        AvailableCountLabel.Text = Loc.GetString("research-console-available-subtitle", ("count", _availableVisibleCount));
        UnlockedCountLabel.Text = Loc.GetString("research-console-unlocked-subtitle", ("count", _unlockedVisibleCount));
        TechnologyDeckSubtitleLabel.Text = Loc.GetString("research-console-technology-deck-count", ("count", _currentCardCount));
        FooterLeftLabel.Text = Loc.GetString("research-console-footer-status-ready");
        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());

        PointsCardLabel.Text = WH40KUiChrome.DecorateIfMissing(PointsCardLabel.Text, WH40KUiChrome.Diamond);
        DisciplineCardLabel.Text = WH40KUiChrome.DecorateIfMissing(DisciplineCardLabel.Text, WH40KUiChrome.DiamondOutline);
        ActiveCardLabel.Text = WH40KUiChrome.DecorateIfMissing(ActiveCardLabel.Text, WH40KUiChrome.Blade);
        AvailableHeaderLabel.Text = WH40KUiChrome.DecorateIfMissing(AvailableHeaderLabel.Text, WH40KUiChrome.Diamond);
        UnlockedHeaderLabel.Text = WH40KUiChrome.DecorateIfMissing(UnlockedHeaderLabel.Text, WH40KUiChrome.DiamondOutline);
