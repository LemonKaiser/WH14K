        DisciplineCard.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);
        ActiveResearchCard.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelAltBackground, _theme.BorderColor, 0);

        AvailablePanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        AvailableHeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
