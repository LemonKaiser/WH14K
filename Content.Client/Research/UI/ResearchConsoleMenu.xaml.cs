        WH40KUiChrome.StartLoopingPulse(FooterDivider, "footer-pulse", new Color(0.55f, 0.55f, 0.55f, 1f), Color.White, 4.1f);
    }

    private void RebuildPanels(
        ResearchConsoleBoundInterfaceState state,
        TechnologyDatabaseComponent database,
        IReadOnlyList<TechnologyPrototype> availableTech,
        IReadOnlyList<TechnologyPrototype> unlockedTech)
    {
        AvailableCardsContainer.Children.Clear();
        UnlockedCardsContainer.Children.Clear();
        TechnologyCardsContainer.Children.Clear();

        PopulateMiniTechnologyList(AvailableCardsContainer, availableTech);

        var deckIndex = 0;
        foreach (var techId in database.CurrentTechnologyCards)
        {
            var tech = _prototype.Index<TechnologyPrototype>(techId);
            var cardControl = new TechnologyCardControl(
                tech,
                _prototype,
                _sprite,
                _research.GetTechnologyDescription(tech, includeTier: false),
                state.Points,
                _hasAccess,
                state.TimedResearchEnabled && state.ActiveTechnologyId != null,
                state.ActiveTechnologyId == techId,
                _theme);
            cardControl.OnPressed += () => OnTechnologyCardPressed?.Invoke(techId);
            TechnologyCardsContainer.AddChild(cardControl);
            WH40KUiChrome.PlayFadeIn(cardControl, "appear", 0.22f, MathF.Min(deckIndex * 0.025f, 0.24f));
            deckIndex++;
        }

        PopulateMiniTechnologyList(UnlockedCardsContainer, unlockedTech);
    }

    private void PopulateMiniTechnologyList(BoxContainer container, IEnumerable<TechnologyPrototype> technologies)
    {
        container.Children.Clear();
        var visualIndex = 0;
        foreach (var tech in technologies)
        {
            var mini = new MiniTechnologyCardControl(tech, _prototype, _sprite, _research.GetTechnologyDescription(tech), _theme);
            container.AddChild(mini);
            WH40KUiChrome.PlayFadeIn(mini, "appear", 0.18f, MathF.Min(visualIndex * 0.02f, 0.2f));
            visualIndex++;
        }
    }

    private void UpdateDeckCounters()
    {
        AvailableCountLabel.Text = Loc.GetString("research-console-available-subtitle", ("count", _availableVisibleCount));
        UnlockedCountLabel.Text = Loc.GetString("research-console-unlocked-subtitle", ("count", _unlockedVisibleCount));
        TechnologyDeckSubtitleLabel.Text = Loc.GetString("research-console-technology-deck-count", ("count", _currentCardCount));
    }

    private void RefreshFooter(ResearchConsoleBoundInterfaceState state)
    {
        FooterLeftLabel.Text = Loc.GetString(GetFooterStatusLocKey(state));
        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());
    }

    private bool HasResearchAccess()
    {
        return _player.LocalEntity is not { } local ||
               !_entity.TryGetComponent<AccessReaderComponent>(Entity, out var access) ||
               _accessReader.IsAllowed(local, Entity, access);
    }

    private string BuildActiveResearchText(ResearchConsoleBoundInterfaceState state)
    {
        if (state.ActiveTechnologyId == null)
            return Loc.GetString("research-console-summary-active-idle");

        return Loc.GetString(
            "research-console-summary-active-running",
            ("technology", GetTechnologyDisplayName(state.ActiveTechnologyId)),
            ("time", FormatRemainingTime(state.ActiveTechnologyRemainingSeconds)));
    }

    private string GetTechnologyDisplayName(string techId)
    {
        return _prototype.TryIndex<TechnologyPrototype>(techId, out var technology)
            ? Loc.GetString(technology.Name)
            : techId;
    }

    private string GetFooterStatusLocKey(ResearchConsoleBoundInterfaceState state)
    {
        if (state.ActiveTechnologyId != null)
            return "research-console-footer-status-active";

        if (!_hasAccess)
            return "research-console-footer-status-restricted";

        return "research-console-footer-status-ready";
    }

    private string GetFooterRightLocKey()
    {
        return _theme.TeamId switch
        {
            "Imperium" => "wh40k-research-console-footer-right-imperium",
            "Heretics" => "wh40k-research-console-footer-right-heretics",
            _ => "research-console-footer-right-panel",
        };
    }

    private static string BuildPanelStateKey(
        ResearchConsoleBoundInterfaceState state,
        TechnologyDatabaseComponent database,
        IReadOnlyList<TechnologyPrototype> availableTech,
        IReadOnlyList<TechnologyPrototype> unlockedTech,
        bool hasAccess)
    {
        var available = string.Join(",", availableTech.Select(t => t.ID));
        var cards = string.Join(",", database.CurrentTechnologyCards);
        var unlocked = string.Join(",", unlockedTech.Select(t => t.ID));

        return $"points={state.Points}" +
               $"|access={hasAccess}" +
               $"|busy={state.TimedResearchEnabled && state.ActiveTechnologyId != null}" +
               $"|active={state.ActiveTechnologyId ?? string.Empty}" +
               $"|available={available}" +
               $"|cards={cards}" +
               $"|unlocked={unlocked}";
    }

    private static void SortTechnologies(List<TechnologyPrototype> technologies)
    {
        technologies.Sort((a, b) =>
        {
            var tierCompare = a.Tier.CompareTo(b.Tier);
            if (tierCompare != 0)
                return tierCompare;

            return string.Compare(Loc.GetString(a.Name), Loc.GetString(b.Name), StringComparison.CurrentCultureIgnoreCase);
        });
    }

    private static StyleBoxFlat CreateDividerStyle(Color color)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = color,
        };
    }

    private static string FormatRemainingTime(int totalSeconds)
    {
        var clamped = Math.Max(0, totalSeconds);
        var timeSpan = TimeSpan.FromSeconds(clamped);
        return $"{(int) timeSpan.TotalMinutes:00}:{timeSpan.Seconds:00}";
    }
}
