            new Thickness(0f, 0f, 0f, 1f),
            0);
        AvailableBodyPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        UnlockedPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        UnlockedHeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
        UnlockedBodyPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        TechnologyDeckPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        TechnologyDeckHeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
        TechnologyDeckBodyPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        FooterDivider.MinSize = new Vector2(0f, 1f);
        FooterDivider.PanelOverride = CreateDividerStyle(_theme.BorderStrongColor);

        HeaderTitleLabel.FontColorOverride = _theme.Accent;
        PointsCardLabel.FontColorOverride = _theme.LabelText;
        DisciplineCardLabel.FontColorOverride = _theme.LabelText;
        ActiveCardLabel.FontColorOverride = _theme.LabelText;
        ResearchPointsValueLabel.FontColorOverride = _theme.Accent;
        AvailableHeaderLabel.FontColorOverride = _theme.Accent;
