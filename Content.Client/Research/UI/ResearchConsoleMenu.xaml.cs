            0);
        AvailableBodyPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.PanelBackground,
            Color.Transparent,
            new Thickness(0f),
            0);

        UnlockedPanel.PanelOverride = WH40KResearchConsoleStyles.CreatePanelStyle(_theme.PanelBackground, _theme.BorderStrongColor, 0);
        UnlockedHeaderPanel.PanelOverride = WH40KResearchConsoleStyles.CreateEdgePanelStyle(
            _theme.HeaderBackground,
            _theme.BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);
