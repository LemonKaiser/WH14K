[GenerateTypedNameReferences]
public sealed partial class ResearchConsoleMenu : FancyWindow
{
    public Action<string>? OnTechnologyCardPressed;
    public Action? OnServerButtonPressed;

    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IPlayerManager _player = default!;
    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprite;
    private readonly AccessReaderSystem _accessReader;

    private WH40KResearchConsoleTheme _theme = WH40KResearchConsoleTheme.Disabled;
    private int _availableVisibleCount;
    private int _unlockedVisibleCount;
    private int _currentCardCount;
    private bool _hasAccess = true;

    public EntityUid Entity;

    public ResearchConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _research = _entity.System<ResearchSystem>();
        _sprite = _entity.System<SpriteSystem>();
        _accessReader = _entity.System<AccessReaderSystem>();

        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        ApplyTheme();
    }

    public void SetEntity(EntityUid entity)
    {
        Entity = entity;
        var prototypeId = _entity.GetComponent<MetaDataComponent>(entity).EntityPrototype?.ID;
        _theme = WH40KResearchConsoleStyles.ResolveTheme(prototypeId);
        ApplyTheme();
    }

    public void UpdatePanels(ResearchConsoleBoundInterfaceState state)
    {
        _hasAccess = HasResearchAccess();
        _availableVisibleCount = 0;
        _unlockedVisibleCount = 0;
        _currentCardCount = 0;

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
        {
            SyncMiniTechnologyList(AvailableCardsContainer, Array.Empty<TechnologyPrototype>());
            SyncMiniTechnologyList(UnlockedCardsContainer, Array.Empty<TechnologyPrototype>());
            SyncTechnologyDeckCards(state, Array.Empty<string>());
            UpdateDeckCounters();
            RefreshFooter(state);
            return;
        }

        var availableTech = _research
            .GetAvailableTechnologies(Entity)
            .Where(tech => !tech.Hidden)
            .ToList();
        SortTechnologies(availableTech);

        var unlockedTech = database.UnlockedTechnologies
            .Select(id => _prototype.Index<TechnologyPrototype>(id))
            .Where(tech => !tech.Hidden)
            .ToList();
        SortTechnologies(unlockedTech);

        _availableVisibleCount = availableTech.Count;
        _unlockedVisibleCount = unlockedTech.Count;
        _currentCardCount = database.CurrentTechnologyCards.Count;

        SyncMiniTechnologyList(AvailableCardsContainer, availableTech);
        SyncTechnologyDeckCards(state, database.CurrentTechnologyCards);
        SyncMiniTechnologyList(UnlockedCardsContainer, unlockedTech);
        UpdateDeckCounters();
        RefreshFooter(state);
    }

    public void UpdateInformationPanel(ResearchConsoleBoundInterfaceState state)
    {
        ResearchPointsValueLabel.Text = WH40KCommandUiStyles.FormatResearch(state.Points);

        if (!_entity.TryGetComponent(Entity, out TechnologyDatabaseComponent? database))
        {
            MainDisciplineValueLabel.SetMessage(Loc.GetString("research-console-summary-none"), defaultColor: _theme.SecondaryText);
            ActiveResearchValueLabel.SetMessage(Loc.GetString("research-console-summary-active-idle"), defaultColor: _theme.SecondaryText);
            RefreshFooter(state);
            return;
        }

        var disciplineText = Loc.GetString("research-console-summary-none");
        var disciplineColor = _theme.SecondaryText;

        if (database.MainDiscipline != null)
        {
            var discipline = _prototype.Index<TechDisciplinePrototype>(database.MainDiscipline);
            disciplineText = Loc.GetString(discipline.Name);
            disciplineColor = discipline.Color;
        }

        MainDisciplineValueLabel.SetMessage(disciplineText, defaultColor: disciplineColor);
        ActiveResearchValueLabel.SetMessage(
            BuildActiveResearchText(state),
            defaultColor: state.ActiveTechnologyId == null
                ? _theme.SecondaryText
                : _theme.Accent);

        RefreshFooter(state);
    }

