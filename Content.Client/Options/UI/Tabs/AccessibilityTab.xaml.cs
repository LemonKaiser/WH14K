using System.Collections.Generic;
using System.Linq;
using Content.Client.Localization;
using Content.Shared.CCVar;
using Content.Shared.GameTicking.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class AccessibilityTab : Control, ILocalizedControl
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private const string LobbyBackgroundModeServer = "server";
    private const string LobbyBackgroundModeStatic = "static";
    private const string LobbyBackgroundModeAnimated = "animated";
    private const string LobbyBackgroundUnknownTitleLoc = "lobby-state-background-unknown-title";

    private readonly OptionDropDownCVar<string> _lobbyBackgroundModeOption;
    private readonly OptionDropDownCVar<string> _lobbyStaticBackgroundOption;
    private readonly OptionDropDownCVar<string> _lobbyAnimatedBackgroundOption;

    public AccessibilityTab()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        Control.AddOptionCheckBox(CCVars.ChatEnableColorName, EnableColorNameCheckBox);
        Control.AddOptionCheckBox(CCVars.AccessibilityColorblindFriendly, ColorblindFriendlyCheckBox);
        Control.AddOptionCheckBox(CCVars.ReducedMotion, ReducedMotionCheckBox);
        Control.AddOptionPercentSlider(CCVars.ScreenShakeIntensity, ScreenShakeIntensitySlider);
        _lobbyBackgroundModeOption = Control.AddOptionDropDown(CCVars.LobbyBackgroundType, DropDownLobbyBackgroundType, BuildLobbyBackgroundModeOptions());
        _lobbyStaticBackgroundOption = Control.AddOptionDropDown(CCVars.LobbyStaticBackground, DropDownLobbyStaticBackground, BuildLobbyBackgroundOptions(animated: false));
        _lobbyAnimatedBackgroundOption = Control.AddOptionDropDown(CCVars.LobbyAnimatedBackground, DropDownLobbyAnimatedBackground, BuildLobbyBackgroundOptions(animated: true));
        Control.AddOptionPercentSlider(CCVars.LobbyPanelOpacity, LobbyPanelOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.LobbyCustomizationPanelOpacity, CustomizationPanelOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.ChatWindowOpacity, ChatWindowOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.SpeechBubbleTextOpacity, SpeechBubbleTextOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.SpeechBubbleSpeakerOpacity, SpeechBubbleSpeakerOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.SpeechBubbleBackgroundOpacity, SpeechBubbleBackgroundOpacitySlider);
        Control.AddOptionCheckBox(CCVars.ChatAutoFillHighlights, AutoFillHighlightsCheckBox);
        Control.AddOptionColorSlider(CCVars.ChatHighlightsColor, HighlightsColorSlider);

        Control.AddOptionCheckBox(CCVars.AccessibilityClientCensorNudity, CensorNudityCheckBox);

        _lobbyBackgroundModeOption.ImmediateValueChanged += UpdateLobbyBackgroundSelectorVisibility;
        Control.Initialize();
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLobbyBackgroundModeOptions()
    {
        return
        [
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeServer, Loc.GetString("ui-options-lobby-background-type-server")),
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeStatic, Loc.GetString("ui-options-lobby-background-type-static")),
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeAnimated, Loc.GetString("ui-options-lobby-background-type-animated")),
        ];
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLobbyBackgroundOptions(bool animated)
    {
        var options = new List<OptionDropDownCVar<string>.ValueOption>
        {
            new(string.Empty, Loc.GetString("ui-options-lobby-background-auto")),
        };

        foreach (var proto in _prototypeManager.EnumeratePrototypes<LobbyBackgroundPrototype>()
                     .OrderBy(GetBackgroundDisplayName))
        {
            if (animated && proto.BackgroundGif == null)
                continue;

            if (!animated && proto.Background == null)
                continue;

            options.Add(new OptionDropDownCVar<string>.ValueOption(proto.ID, GetBackgroundDisplayName(proto)));
        }

        return options;
    }

    private string GetBackgroundDisplayName(LobbyBackgroundPrototype proto)
    {
        if (proto.Title == LobbyBackgroundUnknownTitleLoc)
            return proto.ID;

        var localizedTitle = Loc.GetString(proto.Title);
        var plainTitle = FormattedMessage.RemoveMarkupPermissive(localizedTitle).Trim();
        return string.IsNullOrWhiteSpace(plainTitle) ? proto.ID : plainTitle;
    }

    private void UpdateLobbyBackgroundSelectorVisibility(string mode)
    {
        var normalized = string.IsNullOrWhiteSpace(mode) ? LobbyBackgroundModeServer : mode.ToLowerInvariant();
        DropDownLobbyStaticBackground.Visible = normalized == LobbyBackgroundModeStatic;
        DropDownLobbyAnimatedBackground.Visible = normalized == LobbyBackgroundModeAnimated;
    }

    private void UpdateLobbyBackgroundSelectorVisibilityFromDropDown()
    {
        var selectedMode = DropDownLobbyBackgroundType.Button.SelectedMetadata as string
                           ?? _cfg.GetCVar(CCVars.LobbyBackgroundType);
        UpdateLobbyBackgroundSelectorVisibility(selectedMode);
    }

    public void Relocalize()
    {
        VisualsHeaderLabel.Text = Loc.GetString("ui-options-accessability-header-visuals");
        LobbyHeaderLabel.Text = Loc.GetString("ui-options-accessability-header-lobby");
        ContentHeaderLabel.Text = Loc.GetString("ui-options-accessability-header-content");

        ReducedMotionCheckBox.Text = Loc.GetString("ui-options-reduced-motion");
        EnableColorNameCheckBox.Text = Loc.GetString("ui-options-enable-color-name");
        ColorblindFriendlyCheckBox.Text = Loc.GetString("ui-options-colorblind-friendly");
        ScreenShakeIntensitySlider.Title = Loc.GetString("ui-options-screen-shake-intensity");
        DropDownLobbyBackgroundType.Title = Loc.GetString("ui-options-lobby-background-type");
        DropDownLobbyStaticBackground.Title = Loc.GetString("ui-options-lobby-static-background");
        DropDownLobbyAnimatedBackground.Title = Loc.GetString("ui-options-lobby-animated-background");
        LobbyPanelOpacitySlider.Title = Loc.GetString("ui-options-lobby-panel-opacity");
        CustomizationPanelOpacitySlider.Title = Loc.GetString("ui-options-customization-panel-opacity");
        ChatWindowOpacitySlider.Title = Loc.GetString("ui-options-chat-window-opacity");
        SpeechBubbleTextOpacitySlider.Title = Loc.GetString("ui-options-speech-bubble-text-opacity");
        SpeechBubbleSpeakerOpacitySlider.Title = Loc.GetString("ui-options-speech-bubble-speaker-opacity");
        SpeechBubbleBackgroundOpacitySlider.Title = Loc.GetString("ui-options-speech-bubble-background-opacity");
        AutoFillHighlightsCheckBox.Text = Loc.GetString("ui-options-auto-fill-highlights");
        HighlightsColorSlider.Title = Loc.GetString("ui-options-highlights-color");
        HighlightsColorSlider.Example = Loc.GetString("ui-options-highlights-color-example");
        CensorNudityCheckBox.Text = Loc.GetString("ui-options-censor-nudity");

        _lobbyBackgroundModeOption.ReloadOptions(BuildLobbyBackgroundModeOptions());
        _lobbyStaticBackgroundOption.ReloadOptions(BuildLobbyBackgroundOptions(animated: false));
        _lobbyAnimatedBackgroundOption.ReloadOptions(BuildLobbyBackgroundOptions(animated: true));
        Control.RefreshLocalization();
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }
}

