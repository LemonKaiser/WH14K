using Content.Client.Administration;
using Content.Client.Administration.UI.Tabs.PlayerTab;
using Content.Shared.CCVar;
using Content.Client.Localization;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class AdminOptionsTab : Control, ILocalizedControl
{
    private const float OverlayMergeMin = 0.05f;
    private const float OverlayMergeMax = 0.95f;
    private const int OverlayGhostFadeMin = 0;
    private const int OverlayGhostFadeMax = 10;
    private const int OverlayGhostHideMin = 0;
    private const int OverlayGhostHideMax = 5;

    private readonly OptionDropDownCVar<string> _playerTabSymbolOption;
    private readonly OptionDropDownCVar<string> _playerTabRoleOption;
    private readonly OptionDropDownCVar<string> _playerTabColorOption;
    private readonly OptionDropDownCVar<string> _overlayAntagFormatOption;
    private readonly OptionDropDownCVar<string> _overlayAntagSymbolOption;

    public AdminOptionsTab()
    {
        RobustXamlLoader.Load(this);

        _playerTabSymbolOption = Control.AddOptionDropDown(CCVars.AdminPlayerTabSymbolSetting, DropDownPlayerTabSymbolSetting, BuildPlayerTabSymbolSettings());
        _playerTabRoleOption = Control.AddOptionDropDown(CCVars.AdminPlayerTabRoleSetting, DropDownPlayerTabRoleSetting, BuildPlayerTabRoleSettings());
        _playerTabColorOption = Control.AddOptionDropDown(CCVars.AdminPlayerTabColorSetting, DropDownPlayerTabColorSetting, BuildPlayerTabColorSettings());

        _overlayAntagFormatOption = Control.AddOptionDropDown(CCVars.AdminOverlayAntagFormat, DropDownOverlayAntagFormat, BuildAntagFormats());
        _overlayAntagSymbolOption = Control.AddOptionDropDown(CCVars.AdminOverlaySymbolStyle, DropDownOverlayAntagSymbol, BuildAntagSymbolStyles());

        Control.AddOptionCheckBox(CCVars.AdminOverlayPlaytime, EnableOverlayPlaytimeCheckBox);
        Control.AddOptionCheckBox(CCVars.AdminOverlayStartingJob, EnableOverlayStartingJobCheckBox);

        Control.Initialize();

        Control.AddOptionPercentSlider(
            CCVars.AdminOverlayMergeDistance,
            OverlayMergeDistanceSlider,
            OverlayMergeMin,
            OverlayMergeMax);

        Control.AddOptionSlider(
            CCVars.AdminOverlayGhostFadeDistance,
            OverlayGhostFadeSlider,
            OverlayGhostFadeMin,
            OverlayGhostFadeMax);

        Control.AddOptionSlider(
            CCVars.AdminOverlayGhostHideDistance,
            OverlayGhostHideSlider,
            OverlayGhostHideMin,
            OverlayGhostHideMax);
    }

    public void Relocalize()
    {
        PlayerPanelHeaderLabel.Text = Loc.GetString("ui-options-admin-player-panel");
        OverlayHeaderLabel.Text = Loc.GetString("ui-options-admin-overlay-title");
        DropDownPlayerTabSymbolSetting.Title = Loc.GetString("ui-options-admin-player-tab-symbol-setting");
        DropDownPlayerTabRoleSetting.Title = Loc.GetString("ui-options-admin-player-tab-role-setting");
        DropDownPlayerTabColorSetting.Title = Loc.GetString("ui-options-admin-player-tab-color-setting");
        DropDownOverlayAntagFormat.Title = Loc.GetString("ui-options-admin-overlay-antag-format");
        DropDownOverlayAntagSymbol.Title = Loc.GetString("ui-options-admin-overlay-antag-symbol");
        EnableOverlayPlaytimeCheckBox.Text = Loc.GetString("ui-options-admin-enable-overlay-playtime");
        EnableOverlayStartingJobCheckBox.Text = Loc.GetString("ui-options-admin-enable-overlay-starting-job");
        OverlayMergeDistanceSlider.Title = Loc.GetString("ui-options-admin-overlay-merge-distance");
        OverlayGhostFadeSlider.Title = Loc.GetString("ui-options-admin-overlay-ghost-fade-distance");
        OverlayGhostHideSlider.Title = Loc.GetString("ui-options-admin-overlay-ghost-hide-distance");

        _playerTabSymbolOption.ReloadOptions(BuildPlayerTabSymbolSettings());
        _playerTabRoleOption.ReloadOptions(BuildPlayerTabRoleSettings());
        _playerTabColorOption.ReloadOptions(BuildPlayerTabColorSettings());
        _overlayAntagFormatOption.ReloadOptions(BuildAntagFormats());
        _overlayAntagSymbolOption.ReloadOptions(BuildAntagSymbolStyles());
        Control.RefreshLocalization();
    }

    private static IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildAntagFormats()
    {
        var antagFormats = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var format in Enum.GetValues(typeof(AdminOverlayAntagFormat)))
        {
            antagFormats.Add(new OptionDropDownCVar<string>.ValueOption(format.ToString()!, Loc.GetString($"ui-options-admin-overlay-antag-format-{format.ToString()!.ToLower()}")));
        }

        return antagFormats;
    }

    private static IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildAntagSymbolStyles()
    {
        var antagSymbolStyles = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var symbol in Enum.GetValues(typeof(AdminOverlayAntagSymbolStyle)))
        {
            antagSymbolStyles.Add(new OptionDropDownCVar<string>.ValueOption(symbol.ToString()!, Loc.GetString($"ui-options-admin-overlay-antag-symbol-{symbol.ToString()!.ToLower()}")));
        }

        return antagSymbolStyles;
    }

    private static IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildPlayerTabColorSettings()
    {
        var playerTabColorSettings = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var setting in Enum.GetValues(typeof(AdminPlayerTabColorOption)))
        {
            playerTabColorSettings.Add(new OptionDropDownCVar<string>.ValueOption(setting.ToString()!, Loc.GetString($"ui-options-admin-player-tab-color-setting-{setting.ToString()!.ToLower()}")));
        }

        return playerTabColorSettings;
    }

    private static IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildPlayerTabRoleSettings()
    {
        var playerTabRoleSettings = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var setting in Enum.GetValues(typeof(AdminPlayerTabRoleTypeOption)))
        {
            playerTabRoleSettings.Add(new OptionDropDownCVar<string>.ValueOption(setting.ToString()!, Loc.GetString($"ui-options-admin-player-tab-role-setting-{setting.ToString()!.ToLower()}")));
        }

        return playerTabRoleSettings;
    }

    private static IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildPlayerTabSymbolSettings()
    {
        var playerTabSymbolSettings = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var setting in Enum.GetValues(typeof(AdminPlayerTabSymbolOption)))
        {
            playerTabSymbolSettings.Add(new OptionDropDownCVar<string>.ValueOption(setting.ToString()!, Loc.GetString($"ui-options-admin-player-tab-symbol-setting-{setting.ToString()!.ToLower()}")));
        }

        return playerTabSymbolSettings;
    }
}

