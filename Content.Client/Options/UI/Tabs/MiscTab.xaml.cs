    private void NormalizeNotificationDisplayModeCVar()
    {
        var mode = _cfg.GetCVar(CCVars.WH40KNotificationDisplayMode);
        if (string.Equals(mode, WH40KNotificationMetadata.DisplayModeFull, StringComparison.OrdinalIgnoreCase) ||
            string.Equals(mode, WH40KNotificationMetadata.DisplayModeCompact, StringComparison.OrdinalIgnoreCase) ||
            string.Equals(mode, WH40KNotificationMetadata.DisplayModeOff, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        _cfg.SetCVar(CCVars.WH40KNotificationDisplayMode, WH40KNotificationMetadata.DisplayModeFull);
    }

