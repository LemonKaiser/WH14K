namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class MiscTab : Control, ILocalizedControl
{
    [Dependency] private readonly IPlayerManager _playerManager = default!;
    [Dependency] private readonly ILocalizationManager _localization = default!;
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private const string LobbyBackgroundModeServer = "server";
    private const string LobbyBackgroundModeStatic = "static";
    private const string LobbyBackgroundModeAnimated = "animated";
    private const string LobbyBackgroundUnknownTitleLoc = "lobby-state-background-unknown-title";

    private readonly OptionDropDownCVar<string> _themeOption;
    private readonly OptionDropDownCVar<string> _layoutOption;
    private readonly OptionDropDownCVar<string> _languageOption;
    private readonly OptionDropDownCVar<string> _lobbyBackgroundModeOption;
    private readonly OptionDropDownCVar<string> _lobbyStaticBackgroundOption;
    private readonly OptionDropDownCVar<string> _lobbyAnimatedBackgroundOption;

    public MiscTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Channel can be null in replays so.
        // ReSharper disable once ConditionalAccessQualifierIsNonNullableAccordingToAPIContract
        ShowOocPatronColor.Visible = _playerManager.LocalSession?.Channel?.UserData.PatronTier is { };

        _themeOption = Control.AddOptionDropDown(CCVars.WH40KInterfaceThemePreference, DropDownHudTheme, BuildThemeEntries());
        _layoutOption = Control.AddOptionDropDown(CCVars.UILayout, DropDownHudLayout, BuildLayoutEntries());
        _languageOption = Control.AddOptionDropDown(CVars.LocCultureName, DropDownLanguage, BuildLanguageEntries());
        _lobbyBackgroundModeOption = Control.AddOptionDropDown(CCVars.LobbyBackgroundType, DropDownLobbyBackgroundType, BuildLobbyBackgroundModeOptions());
        _lobbyStaticBackgroundOption = Control.AddOptionDropDown(CCVars.LobbyStaticBackground, DropDownLobbyStaticBackground, BuildLobbyBackgroundOptions(animated: false));
        _lobbyAnimatedBackgroundOption = Control.AddOptionDropDown(CCVars.LobbyAnimatedBackground, DropDownLobbyAnimatedBackground, BuildLobbyBackgroundOptions(animated: true));

        Control.AddOptionCheckBox(CVars.DiscordEnabled, DiscordRich);
        Control.AddOptionCheckBox(CCVars.ShowOocPatronColor, ShowOocPatronColor);
        Control.AddOptionCheckBox(CCVars.LoocAboveHeadShow, ShowLoocAboveHeadCheckBox);
        Control.AddOptionCheckBox(CCVars.HudHeldItemShow, ShowHeldItemCheckBox);
        Control.AddOptionCheckBox(CCVars.CombatModeIndicatorsPointShow, ShowCombatModeIndicatorsCheckBox);
        Control.AddOptionCheckBox(CCVars.OpaqueStorageWindow, OpaqueStorageWindowCheckBox);
        Control.AddOptionCheckBox(CCVars.ChatEnableFancyBubbles, FancySpeechBubblesCheckBox);
        Control.AddOptionCheckBox(CCVars.ChatFancyNameBackground, FancyNameBackgroundsCheckBox);
        Control.AddOptionCheckBox(CCVars.StaticStorageUI, StaticStorageUI);
        Control.AddOptionPercentSlider(CCVars.LobbyPanelOpacity, LobbyPanelOpacitySlider);
        Control.AddOptionPercentSlider(CCVars.LobbyCustomizationPanelOpacity, CustomizationPanelOpacitySlider);

        _lobbyBackgroundModeOption.ImmediateValueChanged += UpdateLobbyBackgroundSelectorVisibility;
        Control.Initialize();
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }

    public void Relocalize()
    {
        UiStyleHeaderLabel.Text = Loc.GetString("ui-options-general-ui-style");
        LobbyHeaderLabel.Text = Loc.GetString("ui-options-general-lobby");
        DiscordHeaderLabel.Text = Loc.GetString("ui-options-general-discord");
        SpeechHeaderLabel.Text = Loc.GetString("ui-options-general-speech");
        CursorHeaderLabel.Text = Loc.GetString("ui-options-general-cursor");
        StorageHeaderLabel.Text = Loc.GetString("ui-options-general-storage");

        DropDownHudTheme.Title = Loc.GetString("ui-options-hud-theme");
        DropDownHudLayout.Title = Loc.GetString("ui-options-hud-layout");
        DropDownLanguage.Title = Loc.GetString("ui-options-language");
        DropDownLobbyBackgroundType.Title = Loc.GetString("ui-options-lobby-background-type");
        DropDownLobbyStaticBackground.Title = Loc.GetString("ui-options-lobby-static-background");
        DropDownLobbyAnimatedBackground.Title = Loc.GetString("ui-options-lobby-animated-background");
        LobbyPanelOpacitySlider.Title = Loc.GetString("ui-options-lobby-panel-opacity");
        CustomizationPanelOpacitySlider.Title = Loc.GetString("ui-options-customization-panel-opacity");
        DiscordRich.Text = Loc.GetString("ui-options-discordrich");
        ShowOocPatronColor.Text = Loc.GetString("ui-options-show-ooc-patron-color");
        ShowLoocAboveHeadCheckBox.Text = Loc.GetString("ui-options-show-looc-on-head");
        FancySpeechBubblesCheckBox.Text = Loc.GetString("ui-options-fancy-speech");
        FancyNameBackgroundsCheckBox.Text = Loc.GetString("ui-options-fancy-name-background");
        ShowHeldItemCheckBox.Text = Loc.GetString("ui-options-show-held-item");
        ShowCombatModeIndicatorsCheckBox.Text = Loc.GetString("ui-options-show-combat-mode-indicators");
        OpaqueStorageWindowCheckBox.Text = Loc.GetString("ui-options-opaque-storage-window");
        StaticStorageUI.Text = Loc.GetString("ui-options-static-storage-ui");

        _themeOption.ReloadOptions(BuildThemeEntries());
        _layoutOption.ReloadOptions(BuildLayoutEntries());
        _languageOption.ReloadOptions(BuildLanguageEntries());
        _lobbyBackgroundModeOption.ReloadOptions(BuildLobbyBackgroundModeOptions());
        _lobbyStaticBackgroundOption.ReloadOptions(BuildLobbyBackgroundOptions(animated: false));
        _lobbyAnimatedBackgroundOption.ReloadOptions(BuildLobbyBackgroundOptions(animated: true));
        Control.RefreshLocalization();
        UpdateLobbyBackgroundSelectorVisibilityFromDropDown();
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildThemeEntries()
    {
        var themes = _prototypeManager.EnumeratePrototypes<HudThemePrototype>().ToList();
        themes.Sort();

        var themeEntries = new List<OptionDropDownCVar<string>.ValueOption>(themes.Count + 1)
        {
            new(WH40KInterfaceThemes.Auto, Loc.GetString("ui-options-hud-theme-auto"))
        };

        foreach (var gear in themes)
        {
            themeEntries.Add(new OptionDropDownCVar<string>.ValueOption(gear.ID, Loc.GetString(gear.Name)));
        }

        return themeEntries;
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLobbyBackgroundModeOptions()
    {
        return
        [
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeServer, Loc.GetString("ui-options-lobby-background-type-server")),
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeStatic, Loc.GetString("ui-options-lobby-background-type-static")),
            new OptionDropDownCVar<string>.ValueOption(LobbyBackgroundModeAnimated, Loc.GetString("ui-options-lobby-background-type-animated")),
        ];
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLobbyBackgroundOptions(bool animated)
    {
        var options = new List<OptionDropDownCVar<string>.ValueOption>
        {
            new(string.Empty, Loc.GetString("ui-options-lobby-background-auto")),
        };

        foreach (var proto in _prototypeManager.EnumeratePrototypes<LobbyBackgroundPrototype>()
                     .OrderBy(GetBackgroundDisplayName))
        {
            if (animated && proto.BackgroundGif == null)
                continue;

            if (!animated && proto.Background == null)
                continue;

            options.Add(new OptionDropDownCVar<string>.ValueOption(proto.ID, GetBackgroundDisplayName(proto)));
        }

        return options;
    }

    private string GetBackgroundDisplayName(LobbyBackgroundPrototype proto)
    {
        if (proto.Title == LobbyBackgroundUnknownTitleLoc)
            return proto.ID;

        var localizedTitle = Loc.GetString(proto.Title);
        var plainTitle = FormattedMessage.RemoveMarkupPermissive(localizedTitle).Trim();
        return string.IsNullOrWhiteSpace(plainTitle) ? proto.ID : plainTitle;
    }

    private void UpdateLobbyBackgroundSelectorVisibility(string mode)
    {
        var normalized = string.IsNullOrWhiteSpace(mode) ? LobbyBackgroundModeServer : mode.ToLowerInvariant();
        DropDownLobbyStaticBackground.Visible = normalized == LobbyBackgroundModeStatic;
        DropDownLobbyAnimatedBackground.Visible = normalized == LobbyBackgroundModeAnimated;
    }

    private void UpdateLobbyBackgroundSelectorVisibilityFromDropDown()
    {
        var selectedMode = DropDownLobbyBackgroundType.Button.SelectedMetadata as string
                           ?? _cfg.GetCVar(CCVars.LobbyBackgroundType);
        UpdateLobbyBackgroundSelectorVisibility(selectedMode);
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLayoutEntries()
    {
        var layoutEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var layout in Enum.GetValues(typeof(ScreenType)))
        {
            layoutEntries.Add(new OptionDropDownCVar<string>.ValueOption(layout.ToString()!, Loc.GetString($"ui-options-hud-layout-{layout.ToString()!.ToLower()}")));
        }

        return layoutEntries;
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> BuildLanguageEntries()
    {
        var cultures = _localization.GetFoundCultures();
        cultures.Sort((a, b) => string.Compare(a.NativeName, b.NativeName, StringComparison.CurrentCultureIgnoreCase));

        var entries = new List<OptionDropDownCVar<string>.ValueOption>(cultures.Count);

        foreach (var culture in cultures)
        {
            entries.Add(new OptionDropDownCVar<string>.ValueOption(culture.Name, FormatCultureLabel(culture)));
        }

        return entries;
    }

    private static string FormatCultureLabel(CultureInfo culture)
    {
        var label = !string.IsNullOrWhiteSpace(culture.NativeName)
            ? culture.NativeName
            : !string.IsNullOrWhiteSpace(culture.DisplayName)
                ? culture.DisplayName
                : culture.Name;

        if (!string.IsNullOrWhiteSpace(label))
        {
            var chars = label.ToCharArray();
            chars[0] = char.ToUpper(chars[0], culture);
            label = new string(chars);
        }

        return string.Concat(label, " [", culture.Name, "]");
    }
}
