    private static string FormatCultureLabel(CultureInfo culture)
    {
        var label = !string.IsNullOrWhiteSpace(culture.NativeName)
            ? culture.NativeName
            : !string.IsNullOrWhiteSpace(culture.DisplayName)
                ? culture.DisplayName
                : culture.Name;

        if (!string.IsNullOrWhiteSpace(label))
        {
            var chars = label.ToCharArray();
            chars[0] = char.ToUpper(chars[0], culture);
            label = new string(chars);
        }

        return string.Concat(label, " [", culture.Name, "]");
    }

    private readonly record struct NotificationCategoryEntry(WH40KNotificationCategory Category, string Label)
    {
        public string Id => WH40KNotificationMetadata.CategoryId(Category);
    }

    private sealed class NotificationCategoryOptionCVar : BaseOptionCVar<string>
    {
        private readonly NotificationCategoryButton _button;
        private readonly Func<IReadOnlyList<NotificationCategoryEntry>> _buildEntries;
        private IReadOnlyList<NotificationCategoryEntry> _entries;

        protected override string Value
        {
            get => string.Join(',', _button.SelectedKeys);
            set
            {
                _button.DeselectAll();
                var selected = value
                    .Split([',', ';', '\n', '\r'], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                    .ToHashSet(StringComparer.OrdinalIgnoreCase);

                foreach (var entry in _entries)
                {
                    if (selected.Contains(entry.Id))
                        _button.SelectKey(entry.Id);
                }

                UpdateLabel();
            }
        }

        public NotificationCategoryOptionCVar(
            OptionsTabControlRow controller,
            IConfigurationManager cfg,
            CVarDef<string> cVar,
            NotificationCategoryButton button,
            Func<IReadOnlyList<NotificationCategoryEntry>> buildEntries)
            : base(controller, cfg, cVar)
        {
            _button = button;
            _buildEntries = buildEntries;
            _entries = buildEntries();
            Populate();

            _button.SelectionChanged += () =>
            {
                UpdateLabel();
                ValueChanged();
            };
        }

        public void ReloadOptions(IReadOnlyList<NotificationCategoryEntry> entries)
        {
            var current = Value;
            _entries = entries;
            Populate();
            Value = current;
        }

        public override void RefreshLocalization()
        {
            ReloadOptions(_buildEntries());
        }

        private void Populate()
        {
            _button.Clear();
            foreach (var entry in _entries)
            {
                _button.AddItem(entry.Label, entry.Id);
            }

            UpdateLabel();
        }

        private void UpdateLabel()
        {
            var selected = _button.SelectedKeys;
            if (selected.Count == 0)
            {
                _button.Label = Loc.GetString("ui-options-wh40k-notifications-categories-none");
                return;
            }

            if (selected.Count == _entries.Count)
            {
                _button.Label = Loc.GetString("ui-options-wh40k-notifications-categories-all");
                return;
            }

            if (selected.Count == 1)
            {
                var labels = selected
                    .Select(id => _entries.FirstOrDefault(entry => string.Equals(entry.Id, id, StringComparison.OrdinalIgnoreCase)).Label)
                    .Where(label => !string.IsNullOrWhiteSpace(label));

                _button.Label = string.Join(", ", labels);
                return;
            }

            _button.Label = Loc.GetString("ui-options-wh40k-notifications-categories-count", ("count", selected.Count));
        }
    }

    private sealed class NotificationCategoryButton : ContainerButton
    {
        private readonly Popup _popup;
        private readonly ScrollContainer _scroll;
        private readonly BoxContainer _popupBox;
        private readonly Label _label;
        private readonly Dictionary<string, CheckBox> _checkBoxes = new(StringComparer.OrdinalIgnoreCase);
        private readonly List<string> _selectedKeys = new();

        public event Action? SelectionChanged;

        public IReadOnlyList<string> SelectedKeys => _selectedKeys;

        public string? Label
        {
            get => _label.Text;
            set => _label.Text = value;
        }

        public NotificationCategoryButton()
        {
            AddStyleClass(StyleClassButton);
            HorizontalExpand = false;
            MinSize = new Vector2(220f, 0f);

            OnPressed += _ => TogglePopup(true);

            var hBox = new BoxContainer
            {
                Orientation = LayoutOrientation.Horizontal,
            };
            AddChild(hBox);

            _label = new Label
            {
                StyleClasses = { OptionButton.StyleClassOptionButton },
                HorizontalExpand = true,
                ClipText = true,
            };
            hBox.AddChild(_label);

            hBox.AddChild(new TextureRect
            {
                StyleClasses = { OptionButton.StyleClassOptionTriangle },
                VerticalAlignment = VAlignment.Center,
            });

            _popupBox = new BoxContainer
            {
                Orientation = LayoutOrientation.Vertical,
                MinSize = new Vector2(220f, 0f),
            };

            _scroll = new ScrollContainer
            {
                Children = { _popupBox },
                ReturnMeasure = true,
                MaxHeight = 245,
            };

            _popup = new Popup
            {
                Children =
                {
                    new PanelContainer
                    {
                        StyleClasses = { OptionButton.StyleClassOptionsBackground },
                    },
                    _scroll,
                },
                StyleClasses = { OptionButton.StyleClassPopup },
            };
            _popup.OnPopupHide += () => _popup.Orphan();
        }

        public void AddItem(string label, string key)
        {
            if (_checkBoxes.ContainsKey(key))
                throw new ArgumentException("An item with the same key already exists.");

            var checkBox = new CheckBox
            {
                Text = label,
                HorizontalExpand = true,
            };
            checkBox.OnPressed += _ => ToggleKey(key, checkBox.Pressed);

            _checkBoxes.Add(key, checkBox);
            _popupBox.AddChild(checkBox);
        }

        public void Clear()
        {
            TogglePopup(false);
            _checkBoxes.Clear();
            _selectedKeys.Clear();
            _popupBox.DisposeAllChildren();
        }

        public void DeselectAll()
        {
            foreach (var checkBox in _checkBoxes.Values)
            {
                checkBox.Pressed = false;
            }

            _selectedKeys.Clear();
        }

        public void SelectKey(string key)
        {
            if (!_checkBoxes.TryGetValue(key, out var checkBox))
                return;

            checkBox.Pressed = true;
            if (!_selectedKeys.Contains(key, StringComparer.OrdinalIgnoreCase))
                _selectedKeys.Add(key);
        }

        private void ToggleKey(string key, bool selected)
        {
            if (selected)
            {
                if (!_selectedKeys.Contains(key, StringComparer.OrdinalIgnoreCase))
                    _selectedKeys.Add(key);
            }
            else
            {
                _selectedKeys.RemoveAll(existing => string.Equals(existing, key, StringComparison.OrdinalIgnoreCase));
            }

            SelectionChanged?.Invoke();
        }

        private void TogglePopup(bool show)
        {
            if (show)
            {
                if (_popup.Parent != null)
                {
                    TogglePopup(false);
                    return;
                }

                if (Root == null)
                    throw new InvalidOperationException("No UI root! We can't pop up!");

                var globalPos = GlobalPosition;
                globalPos.Y += Size.Y + 1;
                _scroll.Measure(Window?.Size ?? Vector2Helpers.Infinity);
                var desired = _scroll.DesiredSize;
                var box = UIBox2.FromDimensions(globalPos, new Vector2(Math.Max(desired.X, Width), desired.Y));
                Root.ModalRoot.AddChild(_popup);
                _popup.Open(box);
                return;
            }

            _popup.Close();
        }

        protected override void ExitedTree()
        {
            base.ExitedTree();
            TogglePopup(false);
        }
    }
