using System.Numerics;
using Content.Client.Guidebook;
using Content.Client.Guidebook.Components;
using Content.Client.Stylesheets;
using Content.Shared.CCVar;
using Content.Shared.Guidebook;
using Robust.Client.Graphics;
using Robust.Client.AutoGenerated;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Controls
{
    [GenerateTypedNameReferences]
    [Virtual]
    public partial class FancyWindow : BaseWindow
    {
        [Dependency] private IEntitySystemManager _sysMan = default!;
        [Dependency] private IStylesheetManager _styleMan = default!;
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private IResourceCache _resourceCache = default!;
        private GuidebookSystem? _guidebookSystem;
        private const int DRAG_MARGIN_SIZE = 7;

        public const string StyleClassWindowHelpButton = "windowHelpButton";
        public const string StyleClassWindowCloseButton = "windowCloseButton";
        private float _uiWindowOpacity = WindowOpacityHelper.MaxUiWindowOpacity;
        private bool _windowOpacityDirty = true;
        private StyleBox? _lastBackgroundPanelOverride;
        private StyleBox? _lastHeaderPanelOverride;
        private StyleBox? _lastDividerPanelOverride;

        public FancyWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            CloseButton.OnPressed += _ => Close();
            HelpButton.OnPressed += _ => Help();
            XamlChildren = ContentsContainer.Children;
            _cfg.OnValueChanged(CCVars.UiWindowOpacity, OnUiWindowOpacityChanged, true);
        }

        public string? Title
        {
            get => WindowTitle.Text;
            set => WindowTitle.Text = value;
        }

        private bool _showBackgroundLogo;

        public bool ShowBackgroundLogo
        {
            get => _showBackgroundLogo;
            set
            {
                _showBackgroundLogo = value;
                ApplyBackgroundLogoConfiguration();
            }
        }

        private string? _backgroundLogoTexturePath;

        public string? BackgroundLogoTexturePath
        {
            get => _backgroundLogoTexturePath;
            set
            {
                _backgroundLogoTexturePath = string.IsNullOrWhiteSpace(value) ? null : value;
                ApplyBackgroundLogoConfiguration();
            }
        }

        private string? _stylesheet;

        public new string? Stylesheet
        {
            get => _stylesheet;
            set
            {
                _stylesheet = value;
                if (value is not null && _styleMan.TryGetStylesheet(value, out var stylesheet))
                    base.Stylesheet = stylesheet;
            }
        }

        private List<ProtoId<GuideEntryPrototype>>? _helpGuidebookIds;

        public List<ProtoId<GuideEntryPrototype>>? HelpGuidebookIds
        {
            get => _helpGuidebookIds;
            set
            {
                _helpGuidebookIds = value;
                HelpButton.Disabled = _helpGuidebookIds == null;
                HelpButton.Visible = !HelpButton.Disabled;
            }
        }

        public void Help()
        {
            if (HelpGuidebookIds is null)
                return;
            _guidebookSystem ??= _sysMan.GetEntitySystem<GuidebookSystem>();
            _guidebookSystem.OpenHelp(HelpGuidebookIds);
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            if (!_windowOpacityDirty &&
                ReferenceEquals(WindowBackgroundPanel.PanelOverride, _lastBackgroundPanelOverride) &&
                ReferenceEquals(WindowHeader.PanelOverride, _lastHeaderPanelOverride) &&
                ReferenceEquals(WindowDivider.PanelOverride, _lastDividerPanelOverride))
            {
                return;
            }

            ApplyWindowOpacity();
        }

        protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
        {
            var mode = DragMode.Move;

            if (Resizable)
            {
                if (relativeMousePos.Y < DRAG_MARGIN_SIZE)
                {
                    mode = DragMode.Top;
                }
                else if (relativeMousePos.Y > Size.Y - DRAG_MARGIN_SIZE)
                {
                    mode = DragMode.Bottom;
                }

                if (relativeMousePos.X < DRAG_MARGIN_SIZE)
                {
                    mode |= DragMode.Left;
                }
                else if (relativeMousePos.X > Size.X - DRAG_MARGIN_SIZE)
                {
                    mode |= DragMode.Right;
                }
            }

            return mode;
        }

        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                _cfg.UnsubValueChanged(CCVars.UiWindowOpacity, OnUiWindowOpacityChanged);
            }

            base.Dispose(disposing);
        }

        private void OnUiWindowOpacityChanged(float opacity)
        {
            _uiWindowOpacity = opacity;
            _windowOpacityDirty = true;
        }

        private void ApplyBackgroundLogoConfiguration()
        {
            WindowCenterLogoRect.Visible = _showBackgroundLogo;

            if (!_showBackgroundLogo)
                return;

            WindowCenterLogoRect.Texture = _backgroundLogoTexturePath == null
                ? null
                : _resourceCache.GetResource<TextureResource>(_backgroundLogoTexturePath).Texture;
        }

        private void ApplyWindowOpacity()
        {
            WindowOpacityHelper.ApplyPanelOpacity(WindowBackgroundPanel, _uiWindowOpacity);
            WindowOpacityHelper.ApplyPanelOpacity(WindowHeader, _uiWindowOpacity);
            WindowOpacityHelper.ApplyPanelOpacity(WindowDivider, _uiWindowOpacity);
            WindowOpacityHelper.ApplySelfModulateOpacity(WindowCenterLogoRect, _uiWindowOpacity);

            var backdropOpacity = WindowOpacityHelper.ResolveReadableBackdropOpacity(_uiWindowOpacity);
            WindowContentsBackdrop.Visible = backdropOpacity > 0f;
            WindowContentsBackdrop.PanelOverride = backdropOpacity > 0f
                ? new StyleBoxFlat
                {
                    BackgroundColor = Color.Black.WithAlpha(backdropOpacity),
                }
                : null;

            _lastBackgroundPanelOverride = WindowBackgroundPanel.PanelOverride;
            _lastHeaderPanelOverride = WindowHeader.PanelOverride;
            _lastDividerPanelOverride = WindowDivider.PanelOverride;
            _windowOpacityDirty = false;
        }

        public string HeaderClass { set => WindowHeader.SetOnlyStyleClass(value); }
        public string TitleClass { set => WindowTitle.SetOnlyStyleClass(value); }
    }

    /// <summary>
    /// Helper functions for working with <see cref="FancyWindow"/>.
    /// </summary>
    public static class FancyWindowExt
    {
        /// <summary>
        /// Sets information for a window (title and guidebooks) based on an entity.
        /// </summary>
        /// <param name="window">The window to modify.</param>
        /// <param name="entityManager">Entity manager used to retrieve the information.</param>
        /// <param name="entity">The entity that this window represents.</param>
        /// <seealso cref="SetTitleFromEntity"/>
        /// <seealso cref="SetGuidebookFromEntity"/>
        public static void SetInfoFromEntity(this FancyWindow window, IEntityManager entityManager, EntityUid entity)
        {
            window.SetTitleFromEntity(entityManager, entity);
            window.SetGuidebookFromEntity(entityManager, entity);
        }

        /// <summary>
        /// Set a window's title to the name of an entity.
        /// </summary>
        /// <param name="window">The window to modify.</param>
        /// <param name="entityManager">Entity manager used to retrieve the information.</param>
        /// <param name="entity">The entity that this window represents.</param>
        /// <seealso cref="SetInfoFromEntity"/>
        public static void SetTitleFromEntity(
            this FancyWindow window,
            IEntityManager entityManager,
            EntityUid entity)
        {
            window.Title = entityManager.GetComponent<MetaDataComponent>(entity).EntityName;
        }

        /// <summary>
        /// Set a window's guidebook IDs to those of an entity.
        /// </summary>
        /// <param name="window">The window to modify.</param>
        /// <param name="entityManager">Entity manager used to retrieve the information.</param>
        /// <param name="entity">The entity that this window represents.</param>
        /// <seealso cref="SetInfoFromEntity"/>
        public static void SetGuidebookFromEntity(
            this FancyWindow window,
            IEntityManager entityManager,
            EntityUid entity)
        {
            window.HelpGuidebookIds = entityManager.GetComponentOrNull<GuideHelpComponent>(entity)?.Guides;
        }
    }
}
