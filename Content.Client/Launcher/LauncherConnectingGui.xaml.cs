namespace Content.Client.Launcher
{
    [GenerateTypedNameReferences]
    public sealed partial class LauncherConnectingGui : Control
    {
        private const float RedialWaitTimeSeconds = 15f;
        private readonly LauncherConnecting _state;
        private float _waitTime;

        // Pressing reconnect will redial instead of simply reconnecting.
        private bool _redial;

        private readonly IRobustRandom _random;
        private readonly IPrototypeManager _prototype;
        private readonly IConfigurationManager _cfg;
        private readonly IClipboardManager _clipboard;
        private readonly IClyde _clyde;
        private readonly IGameTiming _timing;
        private readonly IUriOpener _uri;
        private readonly ExtendedDisconnectInformationManager _extendedDisconnectInformationManager;
        private string? _discordAuthUrl;
        private string _discordAuthAction = WH40KDiscordAuthConstants.ConnectDenyAuthActionLink;
        private string _discordAuthLinkMode = WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeLink;
        private TimeSpan _discordAuthRefreshAvailableAt;
        private bool _awaitingDiscordBrowserReturn;
        private bool _discordBrowserFocusLost;
        private TimeSpan _nextDiscordAutoRetryAt;
        private TimeSpan _discordAutoRetryUntil;

        private static readonly TimeSpan DiscordAutoRetryInterval = TimeSpan.FromSeconds(2);
        private static readonly TimeSpan DiscordAutoRetryWindow = TimeSpan.FromMinutes(1);

        public LauncherConnectingGui(LauncherConnecting state, IRobustRandom random,
            IPrototypeManager prototype, IConfigurationManager config, IClipboardManager clipboard)
        {
            _state = state;
            _random = random;
            _prototype = prototype;
            _cfg = config;
            _clipboard = clipboard;
            _clyde = IoCManager.Resolve<IClyde>();
            _timing = IoCManager.Resolve<IGameTiming>();
            _uri = IoCManager.Resolve<IUriOpener>();
            _extendedDisconnectInformationManager = IoCManager.Resolve<ExtendedDisconnectInformationManager>();

            RobustXamlLoader.Load(this);

            LayoutContainer.SetAnchorPreset(this, LayoutContainer.LayoutPreset.Wide);

            Stylesheet = IoCManager.Resolve<IStylesheetManager>().SheetSystem;

            ChangeLoginTip();
            ExitButton.Text = Loc.GetString(state.UsesManualConnectTarget ? "connecting-back" : "connecting-exit");
            RetryButton.OnPressed += ReconnectButtonPressed;
            ReconnectButton.OnPressed += ReconnectButtonPressed;
            AlternativeConnectButton.OnPressed += AlternativeConnectButtonPressed;
            AlternativeReconnectButton.OnPressed += AlternativeConnectButtonPressed;

            CopyButton.OnPressed += CopyButtonPressed;
            CopyButtonDisconnected.OnPressed += CopyButtonDisconnectedPressed;
            DiscordAuthChangeButton.OnPressed += DiscordAuthChangeButtonPressed;
            ExitButton.OnPressed += ExitButtonPressed;

            var addr = state.Address;
            if (addr != null)
                ConnectingAddress.Text = addr;

            state.PageChanged += OnPageChanged;
            state.ConnectFailReasonChanged += ConnectFailReasonChanged;
            state.ConnectionStateChanged += ConnectionStateChanged;
            state.ConnectFailed += HandleDisconnectReason;
            state.AddressChanged += AddressChanged;
            state.AlternativeConnectAvailabilityChanged += AlternativeConnectAvailabilityChanged;
            _cfg.OnValueChanged(CCVars.UiWindowOpacity, ApplyConfiguredWindowOpacity, true);

            ConnectionStateChanged(state.ConnectionState);
            UpdateAlternativeConnectControls();

            // Redial flag setup
            _extendedDisconnectInformationManager.LastNetDisconnectedArgsChanged += LastNetDisconnectedArgsChanged;
            LastNetDisconnectedArgsChanged(_extendedDisconnectInformationManager.LastNetDisconnectedArgs);
        }

        protected override void EnteredTree()
        {
            base.EnteredTree();
            _clyde.OnWindowFocused += OnWindowFocused;
        }

        protected override void ExitedTree()
        {
            base.ExitedTree();
            _clyde.OnWindowFocused -= OnWindowFocused;
        }

        [Obsolete]
        protected override void Dispose(bool disposing)
        {
            if (disposing)
            {
                _state.PageChanged -= OnPageChanged;
                _state.ConnectFailReasonChanged -= ConnectFailReasonChanged;
                _state.ConnectionStateChanged -= ConnectionStateChanged;
                _state.ConnectFailed -= HandleDisconnectReason;
                _state.AddressChanged -= AddressChanged;
                _state.AlternativeConnectAvailabilityChanged -= AlternativeConnectAvailabilityChanged;
                _extendedDisconnectInformationManager.LastNetDisconnectedArgsChanged -= LastNetDisconnectedArgsChanged;
                _cfg.UnsubValueChanged(CCVars.UiWindowOpacity, ApplyConfiguredWindowOpacity);

                RetryButton.OnPressed -= ReconnectButtonPressed;
                ReconnectButton.OnPressed -= ReconnectButtonPressed;
                AlternativeConnectButton.OnPressed -= AlternativeConnectButtonPressed;
                AlternativeReconnectButton.OnPressed -= AlternativeConnectButtonPressed;
                CopyButton.OnPressed -= CopyButtonPressed;
                CopyButtonDisconnected.OnPressed -= CopyButtonDisconnectedPressed;
                DiscordAuthChangeButton.OnPressed -= DiscordAuthChangeButtonPressed;
                ExitButton.OnPressed -= ExitButtonPressed;
            }

#pragma warning disable CS0618
            base.Dispose(disposing);
#pragma warning restore CS0618
        }

        // Just button, there's only one at once anyways :)
        private void ReconnectButtonPressed(BaseButton.ButtonEventArgs args)
        {
            if (_state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                && _discordAuthAction == WH40KDiscordAuthConstants.ConnectDenyAuthActionRefresh)
            {
                if (GetDiscordRefreshCooldownRemaining() > TimeSpan.Zero)
                    return;

                _state.RetryConnect();
                return;
            }

            if (_redial)
            {
                // Redial shouldn't fail, but if it does, try a reconnect (maybe we're being run from debug)
                if (_state.Redial())
                    return;
            }

            _state.RetryConnect();
        }

        private void AlternativeConnectButtonPressed(BaseButton.ButtonEventArgs args)
        {
            _state.TryConnectAlternative(automatic: false);
        }

        private void CopyButtonPressed(BaseButton.ButtonEventArgs args)
        {
            CopyText(ConnectFailReason.Text);
        }

        private void CopyButtonDisconnectedPressed(BaseButton.ButtonEventArgs args)
        {
            CopyText(DisconnectReason.Text);
        }

        private void CopyText(string? text)
        {
            if (!string.IsNullOrEmpty(text))
            {
                _clipboard.SetText(text);
            }
        }

        private void DiscordAuthChangeButtonPressed(BaseButton.ButtonEventArgs args)
        {
            if (!string.IsNullOrWhiteSpace(_discordAuthUrl))
            {
                BeginAwaitingDiscordBrowserReturn();
                _uri.OpenUri(_discordAuthUrl);
            }
        }

        private void ExitButtonPressed(BaseButton.ButtonEventArgs args)
        {
            _state.Leave();
        }

        private void ConnectFailReasonChanged(string? reason)
        {
            ConnectFailReason.SetMessage(reason == null
                ? ""
                : Loc.GetString("connecting-fail-reason", ("reason", reason)));
        }

        private void AddressChanged(string? address)
        {
            ConnectingAddress.Text = address ?? string.Empty;
        }

        private void AlternativeConnectAvailabilityChanged()
        {
            UpdateAlternativeConnectControls();
        }

        private void LastNetDisconnectedArgsChanged(NetDisconnectedArgs? args)
        {
            HandleDisconnectReason(args);
        }

        private void HandleDisconnectReason(INetStructuredReason? reason)
        {
            _discordAuthUrl = null;
            _discordAuthAction = WH40KDiscordAuthConstants.ConnectDenyAuthActionLink;
            _discordAuthLinkMode = WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeLink;
            _discordAuthRefreshAvailableAt = TimeSpan.Zero;

            if (reason == null)
            {
                _waitTime = 0;
                _redial = false;
                _awaitingDiscordBrowserReturn = false;
                _discordBrowserFocusLost = false;
                _nextDiscordAutoRetryAt = TimeSpan.Zero;
                _discordAutoRetryUntil = TimeSpan.Zero;
            }
            else
            {
                _redial = reason.RedialFlag;

                if (reason.Message.Int32Of("delay") is { } delay)
                {
                    _waitTime = delay;
                }
                else if (_redial)
                {
                    _waitTime = RedialWaitTimeSeconds;
                }

                _discordAuthUrl = reason.Message.StringOf(WH40KDiscordAuthConstants.ConnectDenyAuthUrlKey);
                _discordAuthAction = reason.Message.StringOf(WH40KDiscordAuthConstants.ConnectDenyAuthActionKey)
                    ?? WH40KDiscordAuthConstants.ConnectDenyAuthActionLink;
                _discordAuthLinkMode = reason.Message.StringOf(WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeKey)
                    ?? WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeLink;
                if (reason.Message.Int32Of(WH40KDiscordAuthConstants.ConnectDenyRefreshCooldownKey) is { } refreshCooldown
                    && refreshCooldown > 0)
                {
                    _discordAuthRefreshAvailableAt = _timing.RealTime + TimeSpan.FromSeconds(refreshCooldown);
                }

                if (string.IsNullOrWhiteSpace(_discordAuthUrl))
                {
                    _awaitingDiscordBrowserReturn = false;
                    _discordBrowserFocusLost = false;
                    _nextDiscordAutoRetryAt = TimeSpan.Zero;
                    _discordAutoRetryUntil = TimeSpan.Zero;
                }

            }

            UpdateDiscordAuthControls();
            UpdateDiscordAutoRetry();
        }

        private void ChangeLoginTip()
        {
            var tipsDataset = _cfg.GetCVar(CCVars.LoginTipsDataset);
            var loginTipsEnabled = _prototype.TryIndex<LocalizedDatasetPrototype>(tipsDataset, out var tips);

            LoginTips.Visible = loginTipsEnabled;
            if (!loginTipsEnabled)
            {
                return;
            }

            var tipList = tips!.Values;

            if (tipList.Count == 0)
                return;

            var randomIndex = _random.Next(tipList.Count);
            var tip = tipList[randomIndex];
            LoginTip.SetMessage(Loc.GetString(tip));

            LoginTipTitle.Text = Loc.GetString("connecting-window-tip", ("numberTip", randomIndex));
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            _state.TryRunPendingAutomaticFallback();

            var button = _state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                ? RetryButton
                : ReconnectButton;

            _waitTime -= args.DeltaSeconds;
            if (_waitTime <= 0)
            {
                button.Disabled = false;
                var key = _redial
                    ? "connecting-redial"
                    : _state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                        ? "connecting-reconnect"
                        : "connecting-retry";

                button.Text = Loc.GetString(key);
            }
            else
            {
                var seconds = Math.Max(1, (int) Math.Ceiling(_waitTime));
                button.Disabled = true;
                button.Text = Loc.GetString("connecting-redial-wait", ("time", seconds));
            }

            UpdateDiscordAuthControls();
            UpdateAlternativeConnectControls();
            UpdateDiscordAutoRetry();
        }

        private void OnPageChanged(LauncherConnecting.Page page)
        {
            ConnectingStatus.Visible = page == LauncherConnecting.Page.Connecting;
            ConnectFail.Visible = page == LauncherConnecting.Page.ConnectFailed;
            Disconnected.Visible = page == LauncherConnecting.Page.Disconnected;

            if (page != LauncherConnecting.Page.ConnectFailed)
            {
                _awaitingDiscordBrowserReturn = false;
                _discordBrowserFocusLost = false;
                _nextDiscordAutoRetryAt = TimeSpan.Zero;
                _discordAutoRetryUntil = TimeSpan.Zero;
            }

            UpdateDiscordAuthControls();
            UpdateAlternativeConnectControls();

            if (page == LauncherConnecting.Page.Disconnected)
                DisconnectReason.Text = _state.LastDisconnectReason;
        }

        private void ConnectionStateChanged(ClientConnectionState state)
        {
            ConnectStatus.Text = Loc.GetString($"connecting-state-{state}");
        }

        private TimeSpan GetDiscordRefreshCooldownRemaining()
        {
            if (_discordAuthAction != WH40KDiscordAuthConstants.ConnectDenyAuthActionRefresh)
                return TimeSpan.Zero;

            var remaining = _discordAuthRefreshAvailableAt - _timing.RealTime;
            return remaining > TimeSpan.Zero ? remaining : TimeSpan.Zero;
        }

        private void UpdateDiscordAuthControls()
        {
            UpdateRetryButtonState();

            var showChangeButton = _state.CurrentPage == LauncherConnecting.Page.ConnectFailed
                && !string.IsNullOrWhiteSpace(_discordAuthUrl);

            DiscordAuthChangeButton.Visible = showChangeButton;
            if (!showChangeButton)
                return;

            DiscordAuthChangeButton.Disabled = false;
            DiscordAuthChangeButton.Text = GetDiscordChangeButtonText();
        }

        private void UpdateAlternativeConnectControls()
        {
            var show = _state.CanUseAlternativeConnection;

            AlternativeConnectButton.Visible = show &&
                                               _state.CurrentPage == LauncherConnecting.Page.ConnectFailed;
            AlternativeReconnectButton.Visible = show &&
                                                 _state.CurrentPage == LauncherConnecting.Page.Disconnected;

            if (!show)
                return;

            var cooldown = _state.AlternativeConnectCooldownRemaining;
            var disabled = cooldown > TimeSpan.Zero;
            var text = disabled
                ? Loc.GetString("connecting-alt-address-wait", ("time", Math.Max(1, (int) Math.Ceiling(cooldown.TotalSeconds))))
                : Loc.GetString("connecting-alt-address");

            AlternativeConnectButton.Disabled = disabled;
            AlternativeReconnectButton.Disabled = disabled;
            AlternativeConnectButton.Text = text;
            AlternativeReconnectButton.Text = text;
        }

        private void UpdateRetryButtonState()
        {
            if (_state.CurrentPage != LauncherConnecting.Page.ConnectFailed || _waitTime > 0)
                return;

            if (_discordAuthAction == WH40KDiscordAuthConstants.ConnectDenyAuthActionRefresh)
            {
                var remaining = GetDiscordRefreshCooldownRemaining();
                if (remaining > TimeSpan.Zero)
                {
                    var seconds = Math.Max(1, (int) Math.Ceiling(remaining.TotalSeconds));
                    RetryButton.Disabled = true;
                    RetryButton.Text = Loc.GetString("connecting-discord-auth-retry-cooldown", ("seconds", seconds));
                }
                else
                {
                    RetryButton.Disabled = false;
                    RetryButton.Text = Loc.GetString("connecting-discord-auth-retry");
                }

                return;
            }

            RetryButton.Disabled = false;
            RetryButton.Text = Loc.GetString("connecting-reconnect");
        }

        private string GetDiscordChangeButtonText()
        {
            return _discordAuthLinkMode switch
            {
                WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeChange => Loc.GetString("connecting-discord-auth-change"),
                WH40KDiscordAuthConstants.ConnectDenyAuthLinkModeReauth => Loc.GetString("connecting-discord-auth-reauth"),
                _ => Loc.GetString("connecting-discord-auth-link"),
            };
        }

        private void BeginAwaitingDiscordBrowserReturn()
        {
            _awaitingDiscordBrowserReturn = true;
            _discordBrowserFocusLost = false;
            _nextDiscordAutoRetryAt = TimeSpan.MaxValue;
            _discordAutoRetryUntil = _timing.RealTime + DiscordAutoRetryWindow;
        }

        private void OnWindowFocused(WindowFocusedEventArgs args)
        {
            if (!_awaitingDiscordBrowserReturn)
                return;

            if (!args.Focused)
            {
                _discordBrowserFocusLost = true;
                return;
            }

            if (!_discordBrowserFocusLost)
                return;

            _nextDiscordAutoRetryAt = _timing.RealTime;
            _discordBrowserFocusLost = false;
        }

        private void UpdateDiscordAutoRetry()
        {
            if (!_awaitingDiscordBrowserReturn)
                return;

            if (_state.CurrentPage != LauncherConnecting.Page.ConnectFailed ||
                string.IsNullOrWhiteSpace(_discordAuthUrl))
            {
                _awaitingDiscordBrowserReturn = false;
                return;
            }

            var now = _timing.RealTime;
            if (now >= _discordAutoRetryUntil)
            {
                _awaitingDiscordBrowserReturn = false;
                return;
            }

            if (now < _nextDiscordAutoRetryAt)
                return;

            _nextDiscordAutoRetryAt = now + DiscordAutoRetryInterval;
            _state.RetryConnect();
        }

        private void ApplyConfiguredWindowOpacity(float opacity)
        {
            WindowOpacityHelper.ApplyPanelOpacity(ConnectingPanel, opacity);
            WindowOpacityHelper.ApplyPanelOpacity(ConnectingFooterDivider, opacity, Color.FromHex("#444444"));
            WindowOpacityHelper.ApplyPanelOpacity(LoginTips, opacity);
            WindowOpacityHelper.ApplySelfModulateOpacity(LoginTipsHeaderStripe, opacity);
        }
    }
