    private void UpdateTitle()
    {
        var resolvedName = _entityManager.TryGetComponent<MetaDataComponent>(_owner, out var metaData)
            ? metaData.EntityName
            : Loc.GetString("grinder-menu-title");

        Title = resolvedName;
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Cog, resolvedName.ToUpperInvariant());
    }

    private void ApplyDynamicState(
        GrinderAutoMode autoMode,
        GrinderProgram? program,
        int storageMaxEntities,
        bool active,
        bool powered,
        bool hasBeaker,
        bool hasInput,
        bool canGrind,
        bool canJuice,
        int inputCount,
        int reagentCount)
    {
        var statusKey = ResolveStatusLocKey(active, program, powered, hasBeaker, hasInput);
        var statusNoteKey = ResolveStatusNoteLocKey(active, program, powered, hasBeaker, hasInput);
        var footerKey = ResolveFooterLocKey(active, program, powered, hasBeaker, hasInput);

        StatusValueLabel.Text = Loc.GetString(statusKey);
        StatusValueLabel.FontColorOverride = ResolveStatusColor(active, program, powered, hasBeaker, hasInput);
        StatusHintLabel.SetMessage(Loc.GetString(statusNoteKey), defaultColor: SecondaryText);

        DoctrineValueLabel.Text = Loc.GetString(ResolveDoctrineValueLocKey(autoMode));
        DoctrineValueLabel.FontColorOverride = ResolveDoctrineColor(autoMode);
        DoctrineHintLabel.SetMessage(Loc.GetString(ResolveDoctrineNoteLocKey(autoMode)), defaultColor: SecondaryText);

        VesselValueLabel.Text = Loc.GetString(hasBeaker
            ? "grinder-menu-vessel-attached"
            : "grinder-menu-vessel-missing");
        VesselValueLabel.FontColorOverride = hasBeaker ? VesselAccent : DangerAccent;
        VesselHintLabel.SetMessage(
            Loc.GetString(hasBeaker
                ? "grinder-menu-vessel-note-attached"
                : "grinder-menu-vessel-note-missing",
                ("count", reagentCount)),
            defaultColor: SecondaryText);

        ChamberCounterLabel.Text = Loc.GetString("grinder-menu-chamber-count",
            ("count", inputCount),
            ("max", storageMaxEntities));
        BeakerCounterLabel.Text = Loc.GetString("grinder-menu-beaker-count", ("count", reagentCount));

        ChamberNoteLabel.SetMessage(Loc.GetString(active
            ? "grinder-menu-panel-chamber-note-active"
            : "grinder-menu-panel-chamber-note"), defaultColor: SecondaryText);
        BeakerNoteLabel.SetMessage(Loc.GetString(hasBeaker
            ? "grinder-menu-panel-beaker-note"
            : "grinder-menu-panel-beaker-note-missing"), defaultColor: SecondaryText);
        OperationStatusLabel.SetMessage(Loc.GetString(statusNoteKey), defaultColor: ResolveStatusColor(active, program, powered, hasBeaker, hasInput));

        FooterLeftLabel.Text = Loc.GetString(footerKey);
        FooterLeftLabel.FontColorOverride = ResolveStatusColor(active, program, powered, hasBeaker, hasInput);
        FooterRightLabel.Text = Loc.GetString("grinder-menu-footer-right");

        AutoModeButton.Text = Loc.GetString(ResolveAutoButtonLocKey(autoMode));
        GrindButton.Text = Loc.GetString("grinder-menu-grind-button-wh40k");
        JuiceButton.Text = Loc.GetString("grinder-menu-juice-button-wh40k");
        ChamberEjectButton.Text = Loc.GetString("grinder-menu-chamber-content-box-button-wh40k");
        BeakerEjectButton.Text = Loc.GetString("grinder-menu-beaker-content-box-button-wh40k");

        ChamberEjectButton.Disabled = active || !hasInput;
        BeakerEjectButton.Disabled = active || !hasBeaker;
        GrindButton.Disabled = active || !canGrind || !powered || !hasBeaker;
        JuiceButton.Disabled = active || !canJuice || !powered || !hasBeaker;

        ApplyActionButtonTheme(AutoModeButton, CreateAutoButtonStyle(autoMode), PrimaryText, false);
        ApplyActionButtonTheme(GrindButton, CreateActionButtonStyle(
            Accent,
            active && program == GrinderProgram.Grind ? 0.32f : 0.22f),
            PrimaryText,
            GrindButton.Disabled);
        ApplyActionButtonTheme(JuiceButton, CreateActionButtonStyle(
            WarningAccent,
            active && program == GrinderProgram.Juice ? 0.32f : 0.22f),
            PrimaryText,
            JuiceButton.Disabled);
        ApplyActionButtonTheme(ChamberEjectButton, CreateSecondaryButtonStyle(), PrimaryText, ChamberEjectButton.Disabled);
        ApplyActionButtonTheme(BeakerEjectButton, CreateSecondaryButtonStyle(), PrimaryText, BeakerEjectButton.Disabled);
    }

    private void PopulateChamberContents(ReagentGrinderComponent grinderComp, bool active)
    {
        ChamberContentsList.RemoveAllChildren();

        if (!grinderComp.InputContainer.ContainedEntities.Any())
        {
            ChamberContentsList.AddChild(CreatePlaceholderEntry(
                Loc.GetString("grinder-menu-chamber-empty"),
                SecondaryText));
            return;
        }

        foreach (var entity in grinderComp.InputContainer.ContainedEntities)
        {
            ChamberContentsList.AddChild(CreateChamberEntry(entity, active));
        }
    }

    private void PopulateBeakerContents(EntityUid? beaker, IReadOnlyList<string> reagentEntries)
    {
        BeakerContentsList.RemoveAllChildren();

        if (!beaker.HasValue)
        {
            BeakerContentsList.AddChild(CreatePlaceholderEntry(
                Loc.GetString("grinder-menu-beaker-missing"),
                DangerAccent));
            return;
        }

        if (reagentEntries.Count == 0)
        {
            BeakerContentsList.AddChild(CreatePlaceholderEntry(
                Loc.GetString("grinder-menu-beaker-content-box-is-empty"),
                SecondaryText));
            return;
        }

        foreach (var reagentText in reagentEntries)
        {
            BeakerContentsList.AddChild(CreateTextEntry(reagentText, WarningAccent));
        }
    }

    private Control CreateChamberEntry(EntityUid entity, bool disabled)
    {
        var rowButton = new ContainerButton
        {
            HorizontalExpand = true,
            MinHeight = 40,
            Disabled = disabled,
            StyleBoxOverride = CreateListButtonStyle(disabled ? BorderColor : Accent.WithAlpha(0.78f), disabled ? 0.12f : 0.2f),
            ModulateSelfOverride = Color.White,
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            HorizontalExpand = true,
        };

        var iconPanel = new PanelContainer
        {
            MinSize = new Vector2(34f, 34f),
            PanelOverride = CreatePanelStyle(PanelAltBackground, BorderColor, 0),
        };

        var texture = _entityManager.GetComponent<SpriteComponent>(entity).Icon?.Default;
        if (texture != null)
        {
            iconPanel.AddChild(new TextureRect
            {
                Texture = texture,
                TextureScale = new Vector2(1.05f, 1.05f),
                Stretch = TextureRect.StretchMode.KeepCentered,
                HorizontalExpand = true,
                VerticalExpand = true,
            });
        }
        else
        {
            iconPanel.AddChild(new Label
            {
                Text = WH40KUiChrome.DiamondOutline,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = LabelText,
            });
        }

        row.AddChild(iconPanel);

        row.AddChild(new Label
        {
            Text = _entityManager.GetComponent<MetaDataComponent>(entity).EntityName,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = PrimaryText,
        });

        row.AddChild(new Label
        {
            Text = WH40KUiChrome.Arrow,
            HorizontalAlignment = HAlignment.Right,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = LabelText,
        });

        rowButton.AddChild(row);
        rowButton.OnPressed += _ => OnEjectChamber?.Invoke(entity);
        rowButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(rowButton, "grinder-row-hover", Accent.WithAlpha(0.72f), 0.15f);

        return rowButton;
    }

    private Control CreateTextEntry(string text, Color accent)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = CreatePanelStyle(PanelAltBackground, BorderColor, 8),
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };

        row.AddChild(new Label
        {
            Text = WH40KUiChrome.DiamondOutline,
            VerticalAlignment = VAlignment.Center,
