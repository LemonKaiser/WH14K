    private static string ResolveAutoButtonLocKey(GrinderAutoMode mode)
    {
        return mode switch
        {
            GrinderAutoMode.Grind => "grinder-menu-auto-button-mode-grind",
            GrinderAutoMode.Juice => "grinder-menu-auto-button-mode-juice",
            _ => "grinder-menu-auto-button-mode-off",
        };
    }

    private static string ResolveDoctrineValueLocKey(GrinderAutoMode mode)
    {
        return mode switch
        {
            GrinderAutoMode.Grind => "grinder-menu-doctrine-grind",
            GrinderAutoMode.Juice => "grinder-menu-doctrine-juice",
            _ => "grinder-menu-doctrine-off",
        };
    }

    private static string ResolveDoctrineNoteLocKey(GrinderAutoMode mode)
    {
        return mode switch
        {
            GrinderAutoMode.Grind => "grinder-menu-doctrine-note-grind",
            GrinderAutoMode.Juice => "grinder-menu-doctrine-note-juice",
            _ => "grinder-menu-doctrine-note-off",
        };
    }

    private static string ResolveStatusLocKey(bool active, GrinderProgram? program, bool powered, bool hasBeaker, bool hasInput)
    {
        if (!powered)
            return "grinder-menu-status-no-power";

        if (active && program == GrinderProgram.Juice)
            return "grinder-menu-status-processing-juice";

        if (active)
            return "grinder-menu-status-processing-grind";

        if (!hasBeaker)
            return "grinder-menu-status-no-beaker";

        if (!hasInput)
            return "grinder-menu-status-no-input";

        return "grinder-menu-status-ready";
    }

    private static string ResolveStatusNoteLocKey(bool active, GrinderProgram? program, bool powered, bool hasBeaker, bool hasInput)
    {
        if (!powered)
            return "grinder-menu-status-note-no-power";

        if (active && program == GrinderProgram.Juice)
            return "grinder-menu-status-note-processing-juice";

        if (active)
            return "grinder-menu-status-note-processing-grind";

        if (!hasBeaker)
            return "grinder-menu-status-note-no-beaker";

        if (!hasInput)
            return "grinder-menu-status-note-no-input";

        return "grinder-menu-status-note-ready";
    }

    private static string ResolveFooterLocKey(bool active, GrinderProgram? program, bool powered, bool hasBeaker, bool hasInput)
    {
        if (!powered)
            return "grinder-menu-footer-no-power";

        if (active && program == GrinderProgram.Juice)
            return "grinder-menu-footer-processing-juice";

        if (active)
            return "grinder-menu-footer-processing-grind";

        if (!hasBeaker)
            return "grinder-menu-footer-no-beaker";

        if (!hasInput)
            return "grinder-menu-footer-no-input";

        return "grinder-menu-footer-ready";
    }

    private static Color ResolveStatusColor(bool active, GrinderProgram? program, bool powered, bool hasBeaker, bool hasInput)
    {
        if (!powered)
            return DangerAccent;

        if (active && program == GrinderProgram.Juice)
            return WarningAccent;

        if (active)
            return Accent;

        if (!hasBeaker)
            return WarningAccent;

        if (!hasInput)
            return SecondaryText;

        return Accent;
    }

    private static Color ResolveDoctrineColor(GrinderAutoMode mode)
    {
        return mode switch
        {
            GrinderAutoMode.Grind => Accent,
            GrinderAutoMode.Juice => WarningAccent,
            _ => SecondaryText,
        };
    }

