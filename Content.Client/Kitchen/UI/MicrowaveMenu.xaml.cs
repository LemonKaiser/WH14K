    public bool IsBusy { get; private set; }
    public TimeSpan CurrentCooktimeEnd { get; private set; }

    private bool HasIngredients => _ingredientEntries.Count > 0;
    private bool HasSelectedIngredient => _selectedIngredientIndex >= 0 && _selectedIngredientIndex < _ingredientEntries.Count;

    public MicrowaveMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CookTimeButtonGroup = new ButtonGroup();
        _plateTexture = IoCManager.Resolve<IEntityManager>().System<SpriteSystem>().Frame0(new SpriteSpecifier.Rsi(PlateRsi, "plate"));

        ApplyTheme();
        ConfigurePreviewStage();
        WireInteractions();
        BuildCookTimeButtons();

        InstantCookButton.Group = CookTimeButtonGroup;
        InstantCookButton.ToggleMode = true;
        InstantCookButton.OnPressed += _ => SelectCookTime(0, 0, true);

        SetEntityName(Loc.GetString("microwave-menu-title"));
        SetCookTimeSelection(0, 0);
        SetIngredientEntries(Array.Empty<MicrowaveIngredientEntry>());
        SetBusyState(false, TimeSpan.Zero);
    }

    protected override void Opened()
    {
        base.Opened();

        WindowHeader.Modulate = new Color(1f, 1f, 1f, 0f);
        WindowTitle.Modulate = new Color(1f, 1f, 1f, 0f);
        HeaderPanel.Modulate = new Color(1f, 1f, 1f, 0f);
        FooterDivider.Modulate = new Color(1f, 1f, 1f, 0f);
        FooterBar.Modulate = new Color(1f, 1f, 1f, 0f);

        WH40KUiChrome.PlayFadeIn(WindowHeader, "microwave-window-header-appear", 0.12f);
        WH40KUiChrome.PlayFadeIn(WindowTitle, "microwave-window-title-appear", 0.12f, 0.02f);
        WH40KUiChrome.PlayFadeIn(HeaderPanel, "microwave-header-appear", 0.16f, 0.04f);
        WH40KUiChrome.PlayFadeIn(FooterDivider, "microwave-footer-appear", 0.18f, 0.16f);
        WH40KUiChrome.PlayFadeIn(FooterBar, "microwave-footer-panel-appear", 0.18f, 0.18f);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (IsBusy)
            UpdateCookTimeInfo();
    }

    public void SetEntityName(string entityName)
    {
        if (string.IsNullOrWhiteSpace(entityName))
            entityName = Loc.GetString("microwave-menu-title");

        Title = entityName;
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Cog, entityName.ToUpperInvariant());
    }

    public void SetCookTimeSelection(int buttonIndex, uint cookTime)
    {
        _activeButtonIndex = buttonIndex;
        _selectedCookTime = cookTime;

        InstantCookButton.Pressed = buttonIndex == 0;

        foreach (var button in _cookTimeButtons)
        {
            button.Pressed = button.ButtonIndex == buttonIndex;
        }

        UpdateCookTimeInfo();
        UpdateCookTimeButtonStyles();
        UpdateOperationalText();
    }

    public void SetBusyState(bool busy, TimeSpan currentCooktimeEnd)
    {
        IsBusy = busy;
        CurrentCooktimeEnd = currentCooktimeEnd;

        RefreshState();
    }

    public void SetIngredientEntries(IReadOnlyList<MicrowaveIngredientEntry> entries)
    {
        _ingredientEntries.Clear();
        _ingredientEntries.AddRange(entries);
        _selectedIngredientIndex = _ingredientEntries.Count switch
        {
            0 => -1,
            _ when _selectedIngredientIndex < 0 => 0,
            _ => Math.Clamp(_selectedIngredientIndex, 0, _ingredientEntries.Count - 1),
        };

        RebuildIngredientEntries();
        RefreshState();
    }

    public void ToggleBusyDisableOverlayPanel(bool shouldShow)
    {
        DisableCookingPanelOverlay.Visible = shouldShow;
    }

