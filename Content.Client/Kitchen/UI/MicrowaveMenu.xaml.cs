        DisableCookingPanelOverlay.PanelOverride = CreatePanelStyle(
            WindowBackground.WithAlpha(0.62f),
            WarningAccent.WithAlpha(0.7f),
            0);

        WH40KUiChrome.StartLoopingPulse(HeaderTitleLabel, "microwave-title-pulse", Accent.WithAlpha(0.82f), Color.White, 3.2f);
        WH40KUiChrome.StartLoopingPulse(FooterDivider, "microwave-divider-pulse", Accent.WithAlpha(0.34f), Color.White, 4.1f);
    }

    private void ConfigurePreviewStage()
    {
        PlateTextureRect.Texture = _plateTexture;
        PlateTextureRect.ModulateSelfOverride = new Color(1f, 1f, 1f, 0.82f);

        LayoutContainer.SetAnchorPreset(StageBackdropPanel, LayoutContainer.LayoutPreset.Wide);

        SetCenteredStageRect(PlateTextureRect, 236f, 128f, PlateStageAnchorY);
        SetCenteredStageRect(IngredientPreviewTextureRect, IngredientPreviewWidth, IngredientPreviewHeight, IngredientStageAnchorY);

        LayoutContainer.SetAnchorPreset(IngredientPreviewPlaceholderLabel, LayoutContainer.LayoutPreset.Wide);
    }

    private void WireInteractions()
    {
        BindHoverState(InstantCookButton, hovered =>
        {
            _instantHovered = hovered;
            UpdateCookTimeButtonStyles();
        });

        BindHoverState(StartButton, hovered =>
        {
            _startHovered = hovered;
            UpdateActionButtonStyles();
        });

        BindHoverState(EjectButton, hovered =>
        {
            _ejectHovered = hovered;
            UpdateActionButtonStyles();
        });

        BindHoverState(PreviewActionButton, hovered =>
        {
            _previewHovered = hovered;
            UpdatePanelStyles();
        });

        BindHoverState(CloseButton, hovered =>
        {
            _closeHovered = hovered;
            UpdateHeaderStyles();
        });

        PreviewActionButton.OnPressed += _ =>
        {
            if (!IsBusy && HasSelectedIngredient)
                OnIngredientSelected?.Invoke(_selectedIngredientIndex);
        };
    }

    private void BuildCookTimeButtons()
    {
        for (var i = 1; i <= 6; i++)
        {
            var buttonIndex = i;
            var cookTime = (uint) (i * 5);

            var button = new MicrowaveCookTimeButton
            {
                ButtonIndex = buttonIndex,
                CookTime = cookTime,
                Text = cookTime.ToString(),
                TextAlign = Label.AlignMode.Center,
                ToggleMode = true,
                Group = CookTimeButtonGroup,
                HorizontalExpand = true,
                MinHeight = 24,
            };

            button.OnPressed += _ => SelectCookTime(buttonIndex, cookTime, true);
            BindHoverState(button, hovered =>
            {
                button.HoveredState = hovered;
                UpdateCookTimeButtonStyles();
            });

            _cookTimeButtons.Add(button);
            CookTimeButtonVbox.AddChild(button);
        }
    }

    private void SelectCookTime(int buttonIndex, uint cookTime, bool raiseEvent)
    {
        SetCookTimeSelection(buttonIndex, cookTime);

        if (raiseEvent)
            OnCookTimeSelected?.Invoke(buttonIndex, cookTime);
    }

    private void RefreshState()
    {
        var controlsDisabled = IsBusy || !HasIngredients;

        StartButton.Disabled = controlsDisabled;
        EjectButton.Disabled = controlsDisabled;
        InstantCookButton.Disabled = controlsDisabled;

        foreach (var button in _cookTimeButtons)
        {
            button.Disabled = controlsDisabled;
        }

        ToggleBusyDisableOverlayPanel(IsBusy);
        RebuildIngredientEntries();
        UpdatePanelStyles();
        UpdateCookTimeInfo();
        UpdateCookTimeButtonStyles();
        UpdateActionButtonStyles();
        UpdateOperationalText();
        UpdatePreviewStage();
    }

    private void RebuildIngredientEntries()
    {
        IngredientSelectorGrid.RemoveAllChildren();
        SelectorPanel.Visible = _ingredientEntries.Count > 1;

        if (!SelectorPanel.Visible)
            return;

        foreach (var entry in _ingredientEntries)
        {
            IngredientSelectorGrid.AddChild(CreateIngredientSelectorButton(entry));
        }
    }

    private void UpdateCookTimeInfo()
    {
        var displayTime = BuildSelectedCookTimeText();

        if (IsBusy && CurrentCooktimeEnd > _timing.CurTime)
        {
            var secondsLeft = (int) Math.Ceiling((CurrentCooktimeEnd - _timing.CurTime).TotalSeconds);
            displayTime = Math.Max(secondsLeft, 0).ToString();
        }

        CookTimeValueLabel.Text = displayTime;
    }

    private void UpdatePanelStyles()
    {
        var chamberBorder = IsBusy
            ? WarningAccent
            : HasIngredients
                ? BorderStrongColor
                : BorderColor;

        var chamberBackground = IsBusy
            ? Blend(PanelBackground, WarningAccent, 0.12f)
            : PanelBackground;
        var stageHovered = _previewHovered && !PreviewActionButton.Disabled;
        var stageBorder = stageHovered
            ? Accent.WithAlpha(0.92f)
            : chamberBorder;

        IngredientsPanel.PanelOverride = CreatePanelStyle(chamberBackground, chamberBorder, 0);
        PreviewActionButton.StyleBoxOverride = CreateStageButtonStyle(
            stageBorder,
            IsBusy ? 0.1f : stageHovered ? 0.24f : 0.18f);
        StageBackdropPanel.PanelOverride = CreateStageBackdropStyle(stageHovered);
        SelectorPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, BorderColor, 0);

        var statusBorder = IsBusy
            ? WarningAccent
            : HasIngredients
                ? Accent.WithAlpha(0.7f)
                : BorderColor;

        StatusPanel.PanelOverride = CreatePanelStyle(
            IsBusy ? Blend(PanelAltBackground, WarningAccent, 0.12f) : PanelAltBackground,
            statusBorder,
            0);

        TimePanel.PanelOverride = CreatePanelStyle(
            PanelAltBackground,
            HasIngredients ? BorderStrongColor : BorderColor,
            0);
    }

    private void UpdateOperationalText()
    {
        IngredientCountLabel.Text = Loc.GetString("microwave-menu-chamber-count", ("count", _ingredientEntries.Count));
        ChamberNoteLabel.SetMessage(Loc.GetString(ResolveChamberNoteLocKey()), defaultColor: SecondaryText);

        MachineStatusLabel.Text = Loc.GetString(ResolveStatusLocKey());
        MachineStatusLabel.FontColorOverride = ResolveStatusColor();

        ModeStatusLabel.SetMessage(Loc.GetString(ResolveModeLocKey(), ("mode", BuildSelectedCookTimeText())), defaultColor: SecondaryText);

        FooterLeftLabel.Text = Loc.GetString(ResolveFooterLocKey());
        FooterLeftLabel.FontColorOverride = ResolveStatusColor();
        FooterRightLabel.Text = Loc.GetString("microwave-menu-footer-right");
    }

    private void UpdatePreviewStage()
    {
        PreviewActionButton.Disabled = IsBusy || !HasSelectedIngredient;
        PlateTextureRect.Visible = true;
        PlateTextureRect.ModulateSelfOverride = HasSelectedIngredient
            ? new Color(1f, 1f, 1f, 0.82f)
            : new Color(1f, 1f, 1f, 0.42f);

        if (!HasSelectedIngredient)
        {
            IngredientPreviewTextureRect.Texture = null;
            IngredientPreviewTextureRect.Visible = false;
            IngredientPreviewPlaceholderLabel.Visible = true;
            IngredientPreviewPlaceholderLabel.Text = Loc.GetString("microwave-menu-stage-empty");
            SelectedIngredientLabel.Text = Loc.GetString("microwave-menu-stage-empty");
            SelectedIngredientLabel.FontColorOverride = SecondaryText;
            SelectedIngredientHintLabel.SetMessage(Loc.GetString("microwave-menu-stage-hint-empty"), defaultColor: SecondaryText);
            return;
        }

        var selected = _ingredientEntries[_selectedIngredientIndex];
        IngredientPreviewTextureRect.Texture = selected.Icon;
        IngredientPreviewTextureRect.Visible = selected.Icon != null;
        IngredientPreviewPlaceholderLabel.Visible = selected.Icon == null;
        IngredientPreviewPlaceholderLabel.Text = WH40KUiChrome.DiamondOutline;
        IngredientPreviewPlaceholderLabel.FontColorOverride = LabelText;
        SelectedIngredientLabel.Text = selected.Name;
        SelectedIngredientLabel.FontColorOverride = PrimaryText;
        SelectedIngredientHintLabel.SetMessage(
            Loc.GetString(IsBusy
                ? "microwave-menu-stage-hint-busy"
                : "microwave-menu-stage-hint-ready"),
            defaultColor: IsBusy ? WarningAccent : SecondaryText);
    }

    private void UpdateCookTimeButtonStyles()
    {
        ApplyButtonTheme(
            InstantCookButton,
            CreateTimeButtonStyle(InstantCookButton.Pressed, InstantCookButton.Disabled, _instantHovered),
            PrimaryText,
            InstantCookButton.Disabled);

        foreach (var button in _cookTimeButtons)
        {
            ApplyButtonTheme(
                button,
                CreateTimeButtonStyle(button.Pressed, button.Disabled, button.HoveredState),
                PrimaryText,
                button.Disabled);
        }
    }

    private void UpdateActionButtonStyles()
    {
        ApplyButtonTheme(
            StartButton,
            CreatePrimaryButtonStyle(StartButton.Disabled ? 0.1f : _startHovered ? 0.3f : 0.22f),
            PrimaryText,
            StartButton.Disabled);

        ApplyButtonTheme(
            EjectButton,
            CreateDangerButtonStyle(EjectButton.Disabled ? 0.08f : _ejectHovered ? 0.24f : 0.16f),
            PrimaryText,
            EjectButton.Disabled);

        UpdateHeaderStyles();
    }

    private Control CreateIngredientSelectorButton(MicrowaveIngredientEntry entry)
    {
        var selected = entry.Index == _selectedIngredientIndex;
        var normalButtonStyle = CreateSelectorButtonStyle(selected, IsBusy, false);
        var hoverButtonStyle = CreateSelectorButtonStyle(selected, IsBusy, true);
        var normalPanelStyle = CreateSelectorPanelStyle(selected, false);
        var hoverPanelStyle = CreateSelectorPanelStyle(selected, true);

        var button = new ContainerButton
        {
            HorizontalExpand = true,
            MinHeight = 42,
            Disabled = IsBusy,
            ToolTip = entry.Name,
            StyleBoxOverride = normalButtonStyle,
            ModulateSelfOverride = Color.White,
        };

        var panel = new PanelContainer
        {
            MinSize = new Vector2(32f, 32f),
            HorizontalExpand = true,
            VerticalExpand = true,
            PanelOverride = normalPanelStyle,
        };

        if (entry.Icon != null)
        {
            panel.AddChild(new TextureRect
            {
                Texture = entry.Icon,
                TextureScale = new Vector2(1.05f, 1.05f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalExpand = true,
                VerticalExpand = true,
            });
        }
        else
        {
            panel.AddChild(new Label
            {
                Text = WH40KUiChrome.DiamondOutline,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                FontColorOverride = LabelText,
            });
        }

        button.AddChild(panel);
        button.OnPressed += _ =>
        {
            if (IsBusy)
                return;

            _selectedIngredientIndex = entry.Index;
            UpdatePreviewStage();
            RebuildIngredientEntries();
        };
        button.OnMouseEntered += _ =>
        {
            if (IsBusy)
                return;

            button.StyleBoxOverride = hoverButtonStyle;
            panel.PanelOverride = hoverPanelStyle;
        };
        button.OnMouseExited += _ =>
        {
            button.StyleBoxOverride = normalButtonStyle;
            panel.PanelOverride = normalPanelStyle;
        };

        return button;
    }

    private void UpdateHeaderStyles()
    {
        CloseButton.ModulateSelfOverride = _closeHovered ? Accent : LabelText;
    }

    private string ResolveStatusLocKey()
    {
        if (IsBusy)
            return "microwave-menu-status-busy";

        return HasIngredients
            ? "microwave-menu-status-ready"
            : "microwave-menu-status-empty";
    }

    private string ResolveChamberNoteLocKey()
    {
        if (IsBusy)
            return "microwave-menu-chamber-note-busy";

        return HasIngredients
            ? "microwave-menu-chamber-note-ready"
            : "microwave-menu-chamber-note-empty";
    }

    private string ResolveModeLocKey()
    {
        if (IsBusy)
            return "microwave-menu-mode-busy";

        return HasIngredients
            ? "microwave-menu-mode-selected"
            : "microwave-menu-mode-awaiting";
    }

    private string ResolveFooterLocKey()
    {
        if (IsBusy)
            return "microwave-menu-footer-busy";

        return HasIngredients
            ? "microwave-menu-footer-ready"
            : "microwave-menu-footer-empty";
    }

    private Color ResolveStatusColor()
    {
        if (IsBusy)
            return WarningAccent;

        return HasIngredients ? Accent : SecondaryText;
    }

    private string BuildSelectedCookTimeText()
    {
        return _activeButtonIndex == 0
            ? Loc.GetString("microwave-menu-instant-button")
            : _selectedCookTime.ToString();
    }

