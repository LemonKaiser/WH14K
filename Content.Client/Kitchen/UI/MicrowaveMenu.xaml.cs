        ChamberTitleLabel.FontColorOverride = Accent;
        IngredientCountLabel.FontColorOverride = SecondaryText;
        ChamberNoteLabel.SetMessage(Loc.GetString("microwave-menu-chamber-note-empty"), defaultColor: SecondaryText);
        SelectorTitleLabel.FontColorOverride = LabelText;

        CookTimeInfoLabel.FontColorOverride = LabelText;
        CookTimeValueLabel.FontColorOverride = Accent;
        MachineStatusLabel.FontColorOverride = SecondaryText;
        ModeStatusLabel.SetMessage(Loc.GetString("microwave-menu-mode-awaiting"), defaultColor: SecondaryText);
        SelectedIngredientLabel.FontColorOverride = PrimaryText;
        SelectedIngredientHintLabel.SetMessage(Loc.GetString("microwave-menu-stage-hint-empty"), defaultColor: SecondaryText);
        IngredientPreviewPlaceholderLabel.FontColorOverride = LabelText;

        FooterLeftLabel.FontColorOverride = SecondaryText;
        FooterRightLabel.FontColorOverride = LabelText;
        FooterRightLabel.Text = Loc.GetString("microwave-menu-footer-right");
