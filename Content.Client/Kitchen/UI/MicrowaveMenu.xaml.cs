    {
        return CreateButtonStyle(DangerAccent.WithAlpha(0.84f), DangerAccent, tintAmount);
    }

    private static StyleBoxFlat CreateTimeButtonStyle(bool active, bool disabled, bool hovered)
    {
        if (disabled)
            return CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.08f);

        if (hovered && !active)
            return CreateButtonStyle(Accent.WithAlpha(0.74f), Accent, 0.2f);

        return active
            ? CreateButtonStyle(Accent.WithAlpha(0.9f), Accent, hovered ? 0.32f : 0.24f)
            : CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.16f);
    }

    private static StyleBoxFlat CreateListButtonStyle(Color border, float tintAmount)
    {
        return CreateButtonStyle(border, border, tintAmount);
    }

    private static StyleBoxFlat CreateStageButtonStyle(Color border, float tintAmount)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = Blend(SurfaceBackground, Accent, tintAmount),
            BorderColor = border.WithAlpha(0.88f),
            BorderThickness = new Thickness(1),
            ContentMarginLeftOverride = 0,
            ContentMarginTopOverride = 0,
            ContentMarginRightOverride = 0,
            ContentMarginBottomOverride = 0,
        };
    }

    private static StyleBoxFlat CreateStageBackdropStyle(bool hovered)
    {
        return CreatePanelStyle(
            Blend(SurfaceBackground, Accent, hovered ? 0.1f : 0.06f),
            hovered ? Accent.WithAlpha(0.7f) : BorderColor,
            0);
    }

    private static StyleBoxFlat CreateSelectorButtonStyle(bool selected, bool disabled, bool hovered)
    {
        if (disabled)
            return CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.08f);

        if (hovered && !selected)
            return CreateButtonStyle(Accent.WithAlpha(0.76f), Accent, 0.18f);

        return selected
            ? CreateButtonStyle(Accent.WithAlpha(0.88f), Accent, hovered ? 0.32f : 0.26f)
            : CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.14f);
    }

    private static StyleBoxFlat CreateSelectorPanelStyle(bool selected, bool hovered)
    {
        if (hovered && !selected)
            return CreatePanelStyle(Blend(PanelAltBackground, Accent, 0.08f), Accent.WithAlpha(0.82f), 0);

        return CreatePanelStyle(
            PanelAltBackground,
            selected ? Accent.WithAlpha(0.7f) : BorderColor,
            0);
    }

    private static void SetCenteredStageRect(Control control, float width, float height, float anchorY)
    {
        LayoutContainer.SetAnchorLeft(control, 0.5f);
        LayoutContainer.SetAnchorRight(control, 0.5f);
        LayoutContainer.SetAnchorTop(control, anchorY);
        LayoutContainer.SetAnchorBottom(control, anchorY);
        LayoutContainer.SetMarginLeft(control, -width / 2f);
        LayoutContainer.SetMarginRight(control, width / 2f);
        LayoutContainer.SetMarginTop(control, -height / 2f);
        LayoutContainer.SetMarginBottom(control, height / 2f);
    }

    private static void BindHoverState(Control control, Action<bool> onChanged)
    {
        control.OnMouseEntered += _ => onChanged(true);
        control.OnMouseExited += _ => onChanged(false);
    }

    private static void ApplyButtonTheme(Button button, StyleBoxFlat style, Color fontColor, bool disabled)
    {
        button.StyleBoxOverride = style;
        button.Label.FontColorOverride = disabled ? LabelText : fontColor;
        button.ModulateSelfOverride = Color.White;
    }

    private static Color Blend(Color baseColor, Color accent, float amount)
    {
        amount = Math.Clamp(amount, 0f, 1f);
        return new Color(
            baseColor.R + (accent.R - baseColor.R) * amount,
            baseColor.G + (accent.G - baseColor.G) * amount,
            baseColor.B + (accent.B - baseColor.B) * amount,
            MathF.Max(baseColor.A, accent.A));
    }

