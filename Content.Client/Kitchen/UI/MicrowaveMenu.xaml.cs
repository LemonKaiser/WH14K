        SetSize = new Vector2(796f, 486f);
        MinSize = new Vector2(772f, 466f);

        if (GetChild(0) is PanelContainer windowBackdrop)
            windowBackdrop.PanelOverride = CreatePanelStyle(WindowBackground, BorderStrongColor, 0, 2);

        WindowHeader.PanelOverride = CreateEdgePanelStyle(
            HeaderBackground,
            BorderStrongColor,
            new Thickness(0f, 0f, 0f, 1f),
            0);

        WindowTitle.FontColorOverride = Accent;
        RootFrame.PanelOverride = CreatePanelStyle(WindowBackground, BorderStrongColor, 0);
        HeaderPanel.PanelOverride = CreatePanelStyle(PanelBackground, BorderStrongColor, 0);
        IngredientsPanel.PanelOverride = CreatePanelStyle(PanelBackground, BorderStrongColor, 0);
        ControlPanel.PanelOverride = CreatePanelStyle(PanelBackground, BorderStrongColor, 0);
        StatusPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, BorderColor, 0);
        TimePanel.PanelOverride = CreatePanelStyle(PanelAltBackground, BorderColor, 0);

        FooterDivider.MinSize = new Vector2(0f, 1f);
        FooterDivider.PanelOverride = CreateDividerStyle(BorderStrongColor);

        HeaderSubtitleLabel.SetMessage(Loc.GetString("microwave-menu-header-subtitle"), defaultColor: SecondaryText);
