    public void SetEntity(EntityUid entity)
    {
        this.SetInfoFromEntity(_entityManager, entity);
        EntityView.SetEntity(entity);

        var resolvedName = string.IsNullOrWhiteSpace(Title)
            ? Loc.GetString("battery-menu-window-title")
            : Title;

        _profile = ResolveProfile(resolvedName);
        HeaderTitleLabel.Text = WH40KUiChrome.DecorateTitle(WH40KUiChrome.Cog, resolvedName.ToUpperInvariant());
        RefreshProfileText();
    }

    [MemberNotNull(nameof(_chargeMeterBoxes))]
    private void InitChargeMeter()
    {
        _chargeMeterBoxes = new StyleBoxFlat[StorageColors.Length];

        for (var i = StorageColors.Length - 1; i >= 0; i--)
        {
            var styleBox = new StyleBoxFlat
            {
                BackgroundColor = DimStorageColors[i],
                BorderColor = BorderStrongColor,
                BorderThickness = new Thickness(1),
            };

            _chargeMeterBoxes[i] = styleBox;

            for (var j = 0; j < ChargeMeter.Columns; j++)
            {
                ChargeMeter.AddChild(new PanelContainer
                {
                    Margin = new Thickness(3),
                    PanelOverride = styleBox,
                    HorizontalExpand = true,
                    VerticalExpand = true,
                    MinHeight = 24,
                });
            }
        }
    }

