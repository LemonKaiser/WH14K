    public BatteryMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        InitChargeMeter();
        ApplyTheme();
        WireInteractions();
        ApplyDynamicState(new BatteryBuiState(), 0f);
