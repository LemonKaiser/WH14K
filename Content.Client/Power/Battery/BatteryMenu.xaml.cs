    private void WireInteractions()
    {
        InputOffButton.Group = _inputButtonGroup;
        InputOnButton.Group = _inputButtonGroup;
        InputOffButton.ToggleMode = true;
        InputOnButton.ToggleMode = true;

        OutputOffButton.Group = _outputButtonGroup;
        OutputOnButton.Group = _outputButtonGroup;
        OutputOffButton.ToggleMode = true;
        OutputOnButton.ToggleMode = true;

        InputOffButton.OnPressed += _ =>
        {
            if (_suppressBreakerEvents)
                return;

            OnInBreaker?.Invoke(false);
        };
        InputOnButton.OnPressed += _ =>
        {
            if (_suppressBreakerEvents)
                return;

            OnInBreaker?.Invoke(true);
        };

        OutputOffButton.OnPressed += _ =>
        {
            if (_suppressBreakerEvents)
                return;

            OnOutBreaker?.Invoke(false);
        };
        OutputOnButton.OnPressed += _ =>
        {
            if (_suppressBreakerEvents)
                return;

            OnOutBreaker?.Invoke(true);
        };

        ChargeRateSlider.OnValueChanged += _ =>
        {
            if (!_suppressSliderEvents)
                OnChargeRate?.Invoke(ChargeRateSlider.Value);
        };
        DischargeRateSlider.OnValueChanged += _ =>
        {
            if (!_suppressSliderEvents)
                OnDischargeRate?.Invoke(DischargeRateSlider.Value);
        };

        InputOffButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(ChargePanel, "battery-input-off-hover", DangerAccent.WithAlpha(0.72f), 0.15f);
        InputOnButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(ChargePanel, "battery-input-on-hover", SuccessAccent.WithAlpha(0.72f), 0.15f);
        OutputOffButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(DischargePanel, "battery-output-off-hover", DangerAccent.WithAlpha(0.72f), 0.15f);
        OutputOnButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(DischargePanel, "battery-output-on-hover", Accent.WithAlpha(0.72f), 0.15f);
        CloseButton.OnMouseEntered += _ => WH40KUiChrome.PlayHoverFlash(WindowHeader, "battery-close-hover", BorderStrongColor.WithAlpha(0.86f), 0.18f);
    }

