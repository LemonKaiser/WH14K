    private static void ApplyToggleButtonTheme(Button button, bool active, Color accent, bool disabled)
    {
        var style = disabled
            ? CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.08f)
            : active
                ? CreateButtonStyle(accent.WithAlpha(0.88f), accent, 0.22f)
                : CreateButtonStyle(BorderStrongColor, BorderStrongColor, 0.16f);

        button.StyleBoxOverride = style;
        button.Label.FontColorOverride = disabled ? LabelText : PrimaryText;
        button.ModulateSelfOverride = Color.White;
    }

    private static Color Blend(Color baseColor, Color accent, float amount)
    {
        amount = Math.Clamp(amount, 0f, 1f);
        return new Color(
            baseColor.R + (accent.R - baseColor.R) * amount,
            baseColor.G + (accent.G - baseColor.G) * amount,
            baseColor.B + (accent.B - baseColor.B) * amount,
            MathF.Max(baseColor.A, accent.A));
    }

    private static void SetWrappedText(RichTextLabel label, string text, Color color)
    {
        label.SetMessage(text.Replace("\\n", "\n", StringComparison.Ordinal), defaultColor: color);
    }
