    public void Update(BatteryBuiState msg)
    {
        var inValue = msg.CurrentReceiving;
        var outValue = msg.CurrentSupply;

        var storageDelta = inValue - outValue;
        if (Math.Abs(storageDelta) < msg.Capacity / PrecisionRoundFactor)
            storageDelta = 0;

        _suppressBreakerEvents = true;
        InputOnButton.Pressed = msg.CanCharge;
        InputOffButton.Pressed = !msg.CanCharge;
        OutputOnButton.Pressed = msg.CanDischarge;
        OutputOffButton.Pressed = !msg.CanDischarge;
        _suppressBreakerEvents = false;

        InValue.Text = FormatPower(inValue);
        OutValue.Text = FormatPower(outValue);
        PassthroughValue.Text = FormatPower(Math.Min(msg.CurrentReceiving, msg.CurrentSupply));
        ChargeMaxValue.Text = FormatPower(msg.MaxChargeRate);
        DischargeMaxValue.Text = FormatPower(msg.MaxSupply);
        ChargeCurrentValue.Text = FormatPower(Math.Max(0, storageDelta));
        DischargeCurrentValue.Text = FormatPower(Math.Max(0, -storageDelta));

        _suppressSliderEvents = true;
        ChargeRateSlider.MaxValue = msg.MaxMaxChargeRate;
        ChargeRateSlider.MinValue = msg.MinMaxChargeRate;
        ChargeRateSlider.Value = msg.MaxChargeRate;

        DischargeRateSlider.MaxValue = msg.MaxMaxSupply;
        DischargeRateSlider.MinValue = msg.MinMaxSupply;
        DischargeRateSlider.Value = msg.MaxSupply;
        _suppressSliderEvents = false;

        var storageEtaDiff = storageDelta > 0
            ? (msg.Capacity - msg.Charge) * (1 / msg.Efficiency)
            : -msg.Charge;
        var etaTimeSeconds = storageEtaDiff / storageDelta;
        var etaTimeMinutes = etaTimeSeconds / 60.0;

        EtaLabel.Text = _loc.GetString(
            storageDelta > 0 ? "battery-menu-eta-full" : "battery-menu-eta-empty");
        if (!double.IsFinite(etaTimeMinutes)
            || Math.Abs(etaTimeMinutes) > NotApplicableEtaHighCutoffMinutes
            || Math.Abs(etaTimeMinutes) < NotApplicableEtaLowCutoffMinutes)
        {
            EtaValue.Text = _loc.GetString("battery-menu-eta-value-na");
        }
        else
        {
            EtaValue.Text = _loc.GetString(
                etaTimeMinutes > MaxEtaValueMinutes ? "battery-menu-eta-value-max" : "battery-menu-eta-value",
                ("minutes", Math.Min(Math.Ceiling(etaTimeMinutes), MaxEtaValueMinutes)));
        }

        StoredPercentageValue.Text = _loc.GetString(
            "battery-menu-stored-percent-value",
            ("value", msg.Charge / msg.Capacity));
        StoredEnergyValue.Text = _loc.GetString(
            "battery-menu-stored-energy-value",
            ("value", msg.Charge));

        _storageLevel = ContentHelpers.RoundToNearestLevels(msg.Charge, msg.Capacity, _chargeMeterBoxes.Length);
        _hasStorageDelta = Math.Abs(storageDelta) > 0;

        ApplyDynamicState(msg, storageDelta);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        for (var i = 0; i < _chargeMeterBoxes.Length; i++)
        {
            var box = _chargeMeterBoxes[i];
            box.BackgroundColor = _storageLevel > i ? StorageColors[i] : DimStorageColors[i];
            box.BorderColor = BorderStrongColor;
            box.BorderThickness = new Thickness(1);
        }

        _blinkPulseValue += args.DeltaSeconds;
        if (_blinkPulseValue > 1)
        {
            _blinkPulseValue -= 1;
            _blinkPulse ^= true;
        }

        if (_hasStorageDelta)
        {
            var toBlink = Math.Max(0, _storageLevel - 1);
            _chargeMeterBoxes[toBlink].BackgroundColor =
                _blinkPulse ? StorageColors[toBlink] : DimStorageColors[toBlink];
        }
    }

    private void ApplyDynamicState(BatteryBuiState msg, float storageDelta)
    {
        var hasMsg = msg.Capacity > 0f || msg.MaxMaxChargeRate > 0f || msg.MaxMaxSupply > 0f;

        InputStateLabel.Text = Loc.GetString(ResolveInputStateLocKey(msg, storageDelta));
        InputStateLabel.FontColorOverride = ResolveInputStateColor(msg, storageDelta);
        SetWrappedText(ChargeHintLabel, Loc.GetString(ResolveInputHintLocKey(msg, storageDelta)), SecondaryText);

        OutputStateLabel.Text = Loc.GetString(ResolveOutputStateLocKey(msg, storageDelta));
        OutputStateLabel.FontColorOverride = ResolveOutputStateColor(msg, storageDelta);
        SetWrappedText(DischargeHintLabel, Loc.GetString(ResolveOutputHintLocKey(msg, storageDelta)), SecondaryText);

        SetWrappedText(DeviceHintLabel, Loc.GetString(ResolveDeviceHintLocKey(msg, storageDelta)), SecondaryText);
        SetWrappedText(StorageHintLabel, Loc.GetString(ResolveStorageHintLocKey(msg)), SecondaryText);

        SetWrappedText(FooterLeftLabel, Loc.GetString(ResolveFooterLocKey(msg, storageDelta)), ResolveFooterColor(msg, storageDelta));
        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());

        if (!hasMsg)
        {
            InputStateLabel.Text = Loc.GetString("battery-menu-input-state-off");
            OutputStateLabel.Text = Loc.GetString("battery-menu-output-state-off");
            PassthroughValue.Text = FormatPower(0);
        }

        UpdateSectionStyles(msg, storageDelta);
        UpdateToggleButtonStyles();
    }

    private void UpdateSectionStyles(BatteryBuiState msg, float storageDelta)
    {
        DevicePanel.PanelOverride = CreatePanelStyle(
            PanelBackground,
            storageDelta != 0 ? Accent.WithAlpha(0.7f) : BorderStrongColor,
            0);

        ChargePanel.PanelOverride = CreatePanelStyle(
            msg.CanCharge ? Blend(PanelBackground, SuccessAccent, 0.08f) : PanelBackground,
            ResolveInputStateColor(msg, storageDelta).WithAlpha(0.8f),
            0);

        DischargePanel.PanelOverride = CreatePanelStyle(
            msg.CanDischarge ? Blend(PanelBackground, WarningAccent, 0.08f) : PanelBackground,
            ResolveOutputStateColor(msg, storageDelta).WithAlpha(0.8f),
            0);

        StoragePanel.PanelOverride = CreatePanelStyle(
            PanelBackground,
            ResolveStorageColor(msg).WithAlpha(0.8f),
            0);

        var inputBorder = ResolveInputStateColor(msg, storageDelta).WithAlpha(0.7f);
        ChargeMaxPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, inputBorder, 0);
        ChargeCurrentPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, inputBorder, 0);

        var outputBorder = ResolveOutputStateColor(msg, storageDelta).WithAlpha(0.7f);
        DischargeMaxPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, outputBorder, 0);
        DischargeCurrentPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, outputBorder, 0);

        var storageBorder = ResolveStorageColor(msg).WithAlpha(0.72f);
        StorageReservePanel.PanelOverride = CreatePanelStyle(PanelAltBackground, storageBorder, 0);
        StorageEnergyPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, storageBorder, 0);
        StorageEtaPanel.PanelOverride = CreatePanelStyle(PanelAltBackground, storageBorder, 0);
    }

    private void UpdateToggleButtonStyles()
    {
        ApplyToggleButtonTheme(InputOffButton, !InputOnButton.Pressed, DangerAccent, InputOffButton.Disabled);
        ApplyToggleButtonTheme(InputOnButton, InputOnButton.Pressed, SuccessBorder, InputOnButton.Disabled);
        ApplyToggleButtonTheme(OutputOffButton, !OutputOnButton.Pressed, DangerAccent, OutputOffButton.Disabled);
        ApplyToggleButtonTheme(OutputOnButton, OutputOnButton.Pressed, Accent, OutputOnButton.Disabled);
    }

    private void RefreshProfileText()
    {
        SetWrappedText(HeaderSubtitleLabel, Loc.GetString(GetHeaderSubtitleLocKey()), SecondaryText);
        FooterRightLabel.Text = Loc.GetString(GetFooterRightLocKey());
    }

    private string GetHeaderSubtitleLocKey()
    {
        return _profile switch
        {
            BatteryProfile.Smes => "battery-menu-header-subtitle-smes",
            BatteryProfile.Substation => "battery-menu-header-subtitle-substation",
            _ => "battery-menu-header-subtitle",
        };
    }

    private string GetFooterRightLocKey()
    {
        return _profile switch
        {
            BatteryProfile.Smes => "battery-menu-footer-right-smes",
            BatteryProfile.Substation => "battery-menu-footer-right-substation",
            _ => "battery-menu-footer-right",
        };
    }

    private static BatteryProfile ResolveProfile(string name)
    {
        if (name.Contains("смэс", StringComparison.OrdinalIgnoreCase) ||
            name.Contains("smes", StringComparison.OrdinalIgnoreCase))
        {
            return BatteryProfile.Smes;
        }

        if (name.Contains("подстан", StringComparison.OrdinalIgnoreCase) ||
            name.Contains("substation", StringComparison.OrdinalIgnoreCase))
        {
            return BatteryProfile.Substation;
        }

        return BatteryProfile.Generic;
    }

    private string ResolveInputStateLocKey(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanCharge)
            return "battery-menu-input-state-off";

        if (!msg.SupplyingNetworkHasPower)
            return "battery-menu-input-state-standby";

        return storageDelta > 0
            ? "battery-menu-input-state-active"
            : "battery-menu-input-state-ready";
    }

    private string ResolveInputHintLocKey(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanCharge)
            return "battery-menu-input-note-off";

        if (!msg.SupplyingNetworkHasPower)
            return "battery-menu-input-note-standby";

        return storageDelta > 0
            ? "battery-menu-input-note-active"
            : "battery-menu-input-note-ready";
    }

    private Color ResolveInputStateColor(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanCharge)
            return DangerAccent;

        if (!msg.SupplyingNetworkHasPower)
            return WarningAccent;

        return storageDelta > 0 ? SuccessBorder : Accent;
    }

    private string ResolveOutputStateLocKey(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanDischarge)
            return "battery-menu-output-state-off";

        if (msg.Charge <= 0.001f && !msg.SupplyingNetworkHasPower)
            return "battery-menu-output-state-standby";

        return storageDelta < 0
            ? "battery-menu-output-state-active"
            : "battery-menu-output-state-ready";
    }

    private string ResolveOutputHintLocKey(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanDischarge)
            return "battery-menu-output-note-off";

        if (msg.Charge <= 0.001f && !msg.SupplyingNetworkHasPower)
            return "battery-menu-output-note-empty";

        return storageDelta < 0
            ? "battery-menu-output-note-active"
            : "battery-menu-output-note-ready";
    }

    private Color ResolveOutputStateColor(BatteryBuiState msg, float storageDelta)
    {
        if (!msg.CanDischarge)
            return DangerAccent;

        if (msg.Charge <= 0.001f && !msg.SupplyingNetworkHasPower)
            return WarningAccent;

        return storageDelta < 0 ? Accent : PrimaryText;
    }

    private string ResolveDeviceHintLocKey(BatteryBuiState msg, float storageDelta)
    {
        if (msg.CanCharge && msg.CanDischarge)
        {
            return storageDelta > 0
                ? "battery-menu-device-note-intake"
                : storageDelta < 0
                    ? "battery-menu-device-note-output"
                    : "battery-menu-device-note-balanced";
        }

        if (msg.CanCharge)
            return "battery-menu-device-note-intake";

        if (msg.CanDischarge)
            return "battery-menu-device-note-output";

        return "battery-menu-device-note-locked";
    }

    private string ResolveStorageHintLocKey(BatteryBuiState msg)
    {
        var ratio = msg.Capacity <= 0f ? 0f : msg.Charge / msg.Capacity;
        if (ratio >= 0.95f)
            return "battery-menu-storage-note-full";

        if (ratio >= 0.65f)
            return "battery-menu-storage-note-high";

        if (ratio >= 0.3f)
            return "battery-menu-storage-note-medium";

        return "battery-menu-storage-note-low";
    }

    private Color ResolveStorageColor(BatteryBuiState msg)
    {
        var ratio = msg.Capacity <= 0f ? 0f : msg.Charge / msg.Capacity;
        if (ratio >= 0.95f)
            return SuccessBorder;

        if (ratio >= 0.65f)
            return Accent;

        if (ratio >= 0.3f)
            return WarningAccent;

        return DangerAccent;
    }

    private string ResolveFooterLocKey(BatteryBuiState msg, float storageDelta)
    {
        var ratio = msg.Capacity <= 0f ? 0f : msg.Charge / msg.Capacity;
        if (ratio < 0.15f && msg.CanDischarge)
            return "battery-menu-footer-critical";

        if (storageDelta > 0)
            return "battery-menu-footer-charging";

        if (storageDelta < 0)
            return "battery-menu-footer-discharging";

        if (!msg.CanCharge && !msg.CanDischarge)
            return "battery-menu-footer-locked";

        return "battery-menu-footer-left";
    }

    private Color ResolveFooterColor(BatteryBuiState msg, float storageDelta)
    {
        var ratio = msg.Capacity <= 0f ? 0f : msg.Charge / msg.Capacity;
        if (ratio < 0.15f && msg.CanDischarge)
            return DangerAccent;

        if (storageDelta > 0)
            return SuccessBorder;

        if (storageDelta < 0)
            return Accent;

        if (!msg.CanCharge && !msg.CanDischarge)
            return WarningAccent;

        return SecondaryText;
    }

    private string FormatPower(float value)
    {
        return _loc.GetString("battery-menu-power-value", ("value", value));
    }

    private static Color DimStorageColor(Color color)
    {
        var hsv = Color.ToHsv(color);
        hsv.Z /= 5;
        return Color.FromHsv(hsv);
    }

